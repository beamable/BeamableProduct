	/// <summary>
	/// Default <see cref="IZoneServices"/> — the zone service surface. Currently just the customer directory.
	/// </summary>
	internal class ZoneServices : IZoneServices
	{
		public IZoneCustomerApi Customer { get; }
		public ZoneServices(IZoneCustomerApi customer) => Customer = customer;
	}

	/// <summary>
	/// Customer-directory queries for a zone service, issued over the zone's (cid.zid) requester.
	/// <para>
	/// the gateway routes these over a zone-authenticated microservice connection; if not, this needs a
	/// token-based HTTP requester instead of the websocket <see cref="MicroserviceRequester"/>.
	/// </para>
	/// </summary>
	internal class ZoneCustomerApi : IZoneCustomerApi
	{
		private readonly MicroserviceRequester _requester;
		private readonly IMicroserviceArgs _env;

		public ZoneCustomerApi(MicroserviceRequester requester, IMicroserviceArgs env)
		{
			_requester = requester;
			_env = env;
		}

		public async Promise<List<Realm>> GetRealms()
		{
			var service = new BeamCustomerApi(_requester);
			var view = await service.GetAdminView(_env.CustomerID);
			var realms = view.realms.GetOrElse(new Realm[] { }).ToList();
			return realms;

		}

		public async Promise<List<Zone>> GetZones()
		{
			var service = new BeamCustomerApi(_requester);
			var view = await service.GetAdminView(_env.CustomerID);
			var zones = view.zones.GetOrElse(new Zone[] { }).ToList();
			return zones;
		}
	}

	/// <summary>
	/// Builds a realm (cid.pid) scope from a zone service by forking the zone's root scope and re-applying the
	/// realm SDK (<see cref="MicroserviceStartupUtil.ConfigureRealmServices"/>). The fork shares the live
	/// websocket (SocketRequesterContext) and other common infrastructure with the zone service; only the
	/// realm-specific registrations and the request context (which drives the cid.pid scope) are swapped in.
	/// </summary>
	internal class RealmScopeFactory : IRealmScopeFactory
	{
		private readonly IDependencyProvider _root;
		private readonly StartupContext _startupContext;
		private readonly IMicroserviceArgs _env;

		public RealmScopeFactory(IDependencyProvider root, StartupContext startupContext, IMicroserviceArgs env)
		{
			_root = root;
			_startupContext = startupContext;
			_env = env;
		}

		public UserRequestDataHandler CreateRealmScope(string pid, long gamerTag = 0)
		{
			// Re-target the env to the realm so ConfigureRealmServices registers a cid.pid RequestContext (and
			// scopes its requester to cid.pid) directly, while keeping the zone's secret/host for signing.
			var realmEnv = _env.Copy(a => a.ProjectName = pid);

			// WORKAROUND: the assumed-realm websocket rides the zone's cid.zid connection, so the backend
			// treats the zid as the pid for every request over that socket — realm-scoped calls (stats, etc.)
			// end up hitting the wrong realm. Instead, route the realm SDK's HTTP requests through the signed
			// requester, authenticated as cid.pid with the *realm's* secret (fetched from the customer API).
			// The secret fetch is lazy (Func<Promise<string>>) and cached so it happens at most once per scope.
			// It runs on the first signed request, by which point `realmScope` is assigned — and it must use
			// that scope's requester, not the zone root, because the root has no RequestContext.
			IDependencyProviderScope realmScope = null;
			var realmSecret = new Lazy<Promise<string>>(() => FetchRealmSecret(realmScope, pid));

			realmScope = _root.Fork(builder =>
			{
				// Drop the zone-scoped versions of the shared abstractions before the realm SDK re-registers
				// them (a builder holds one registration per type).
				builder.RemoveIfExists<RequestContext>();
				builder.RemoveIfExists<MicroserviceRequester>();
				builder.RemoveIfExists<IBeamableRequester>();
				builder.RemoveIfExists<IRequester>();

				MicroserviceStartupUtil.ConfigureRealmServices(builder, _startupContext, realmEnv);

				// ConfigureRealmServices derives IRealmInfo from IMicroserviceArgs, which still resolves to the
				// ZONE env in this fork — so the signed requester's Pid (taken from IRealmInfo) would be the
				// zone's, not the realm's. Pin IRealmInfo to the realm so it signs and scopes as cid.pid.
				builder.RemoveIfExists<IRealmInfo>();
				builder.AddScoped<IRealmInfo>(_ => realmEnv);

				// Point the signed requester at the realm secret (ConfigureRealmServices wired it to the zone's
				// secret via realmEnv). The HttpSignedRequester signs as cid.pid using this.
				builder.RemoveIfExists<ISignedRequesterConfig>();
				builder.AddSingleton<ISignedRequesterConfig>(() => new DefaultSignedRequesterConfig
				{
					Host = realmEnv.Host
						.Replace("ws://", "http://")
						.Replace("wss://", "https://")
						.Replace("/socket/", "")
						.Replace("/socket", ""),
					RealmSecretGenerator = () => realmSecret.Value,
				});

				// Resolve the realm SDK's requester to the signed HTTP requester (cid.pid + realm secret)
				// instead of the zone's websocket MicroserviceRequester. Services that need the socket directly
				// (e.g. ContentService) resolve MicroserviceRequester/SocketRequesterContext explicitly and are
				// unaffected; this only redirects the generic IBeamableRequester/IRequester consumers.
				builder.RemoveIfExists<IBeamableRequester>();
				builder.RemoveIfExists<IRequester>();
				builder.AddScoped<IBeamableRequester>(p => p.GetService<HttpSignedRequester>());
				builder.AddScoped<IRequester>(p => p.GetService<HttpSignedRequester>());

				// BeamScheduler is a *common* singleton, so a forked scope resolves it against the zone parent
				// (which lacks the realm-only IBeamSchedulerApi). Re-register it as fork-local scoped so it
				// instantiates here, where ConfigureRealmServices has just registered its dependencies.
				builder.RemoveIfExists<BeamScheduler>();
				builder.AddScoped<BeamScheduler>();

				// Only override the RequestContext when acting on behalf of a specific player; otherwise the
				// cid.pid context ConfigureRealmServices just registered is exactly what we want.
				if (gamerTag > 0)
				{
					builder.RemoveIfExists<RequestContext>();
					builder.AddScoped(new RequestContext(realmEnv.CustomerID, pid, -1, 0, gamerTag, "", "", ""));
				}
			});
			return new UserRequestDataHandler(realmScope);
		}

		/// <summary>
		/// Fetches the realm secret for <paramref name="pid"/> from the customer API. Issued over the given
		/// scope's requester (the realm fork, which has a RequestContext — the zone root does not). Used to
		/// sign realm-scoped requests from an <c>AssumeRealm</c> scope as cid.pid.
		/// </summary>
		private Promise<string> FetchRealmSecret(IDependencyProvider scope, string pid)
		{
			var requester = scope.GetService<MicroserviceRequester>();
			var customerApi = new BeamCustomerApi(requester);
			return customerApi.GetRealms(_env.CustomerID, pid).Map(view =>
			{
				var secret = view.secret.GetOrElse(string.Empty);
				if (string.IsNullOrEmpty(secret))
				{
					throw new Exception(
						$"AssumeRealm could not resolve a realm secret for pid=[{pid}] from the customer API. " +
						$"The zone service may lack permission to read the realm secret.");
				}
				return secret;
			});
		}
	}
}
