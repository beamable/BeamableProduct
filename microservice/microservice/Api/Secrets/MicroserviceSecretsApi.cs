using Beamable.Api.Autogenerated.Models;
using Beamable.Api.Autogenerated.Secrets;
using Beamable.Common;
using Beamable.Common.Content;

namespace Beamable.Server.Api.Secrets
{
	/// <summary>
	/// Default <see cref="IMicroserviceSecretsApi"/>. The generated <see cref="IBeamSecretsApi"/> addresses the
	/// secrets store through the request's scope header, so this works unchanged in realm and zone services.
	/// </summary>
	public class MicroserviceSecretsApi : IMicroserviceSecretsApi
	{
		private readonly IBeamSecretsApi _api;

		public MicroserviceSecretsApi(IBeamSecretsApi api)
		{
			_api = api;
		}

		public async Promise<string> GetSecret(string key)
		{
			var response = await _api.GetValues(key);
			return response.value.Value;
		}

		public async Promise SetSecret(string key, string value)
		{
			await _api.PutValues(key, new PutRealmSecretRequest { value = value });
		}

		public async Promise DeleteSecret(string key)
		{
			await _api.DeleteValues(key);
		}

		public Promise<RealmSecretInfoCursorPagedResult> ListSecrets(string cursor = null)
		{
			// Explicit cast so a null cursor stays an absent Optional (the implicit string conversion would
			// produce one with HasValue = true and a null value, sending an empty cursor).
			Optional<string> page = cursor == null ? null : (Optional<string>)cursor;
			return _api.GetValues(page);
		}
	}
}
