using Beamable.Api.Autogenerated.Models;
using Beamable.Api.Autogenerated.Zones;
using Beamable.Common;

namespace Beamable.Server.Api.Segments
{
	/// <summary>
	/// Default <see cref="IMicroserviceSegmentsApi"/>: the generated <see cref="IBeamZonesApi"/>'s segment routes,
	/// addressed to the zone the service runs in.
	/// </summary>
	public class MicroserviceSegmentsApi : IMicroserviceSegmentsApi
	{
		private readonly IBeamZonesApi _api;
		private readonly IMicroserviceArgs _env;

		public MicroserviceSegmentsApi(IBeamZonesApi api, IMicroserviceArgs env)
		{
			_api = api;
			_env = env;
		}

		public Promise<SegmentResponse> CreateSegment(CreateSegmentRequest request) =>
			_api.PostZonesSegments(_env.CustomerID, _env.Zid, request);

		public Promise<SegmentResponse> UpdateSegment(string segmentId, UpdateSegmentRequest request) =>
			_api.PutZonesSegments(_env.CustomerID, segmentId, _env.Zid, request);

		public Promise<SegmentResultsResponse> SetSegmentStates(SetSegmentStatesRequest request) =>
			_api.PostZonesSegmentsStates(_env.CustomerID, _env.Zid, request);

		public Promise<SegmentOverridesResponse> WriteOverrides(SegmentOverridesRequest request) =>
			_api.PostZonesSegmentsOverrides(_env.CustomerID, _env.Zid, request);

		public Promise<SegmentResponseCursorPagedResult> GetSegments(params string[] segmentIds) =>
			_api.GetZonesSegments(_env.CustomerID, _env.Zid, ids: segmentIds, limit: segmentIds.Length);

		public Promise<MembershipQueryResponse> GetMemberships(SegmentMembershipQueryRequest request) =>
			_api.PostZonesSegmentsMemberships(_env.CustomerID, _env.Zid, request);

		public Promise<SegmentCountsResponse> GetCounts(SegmentCountsRequest request) =>
			_api.PostZonesSegmentsCounts(_env.CustomerID, _env.Zid, request);
	}
}
