using System;
using System.Collections.Generic;
using System.Linq;
using IBeamAuthApi = Beamable.Api.Autogenerated.Auth.IBeamAuthApi;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common;
using Beamable.Common.Api;
using Beamable.Common.Api.Auth;
using Beamable.Serialization.SmallerJSON;
using TokenResponse = Beamable.Common.Api.Auth.TokenResponse;

namespace Beamable.Server.Api
{
   public class ServerAuthApi : AuthApi, IMicroserviceAuthApi
   {
      public const string BASIC_SERVICE = "/basic/accounts";
      public const string OBJECT_SERVICE = "/object/accounts";

      public RequestContext Context { get; }

      private readonly IBeamAuthApi _authApi;

      public ServerAuthApi(IRequester requester, RequestContext context, IBeamAuthApi authApi) : base(requester)
      {
         _requester = requester;
         Context = context;
         _authApi = authApi;
      }

      public Promise<User> GetUser(long gamerTag)
      {
         return Requester.Request<User>(Method.GET, $"{BASIC_SERVICE}", new GetUserRequest
         {
            gamerTag = gamerTag
         });
      }

      public async Promise<AuthV2BatchAccountsResponse> BatchAccounts(AuthV2BatchAccountsRequest request)
      {
         var ids = (request.playerIds ?? Array.Empty<long>()).Distinct().ToList();
         var players = new List<AuthV2BatchAccountsPlayer>();
         var filteredOut = new List<long>();
         var notFound = new List<long>();
         for (var i = 0; i < ids.Count; i += BatchAccountsHelper.MaxPlayersPerRequest)
         {
            var page = await _authApi.PostBatch(new AuthV2BatchAccountsRequest
            {
               playerIds = ids.GetRange(i, Math.Min(BatchAccountsHelper.MaxPlayersPerRequest, ids.Count - i)).ToArray(),
               filter = request.filter,
               includeAccount = request.includeAccount,
               stats = request.stats
            });
            players.AddRange(page.players ?? Array.Empty<AuthV2BatchAccountsPlayer>());
            filteredOut.AddRange(page.filteredOut ?? Array.Empty<long>());
            notFound.AddRange(page.notFound ?? Array.Empty<long>());
         }

         return new AuthV2BatchAccountsResponse
         {
            players = players.ToArray(), filteredOut = filteredOut.ToArray(), notFound = notFound.ToArray()
         };
      }

      public Promise<AccountId> GetAccountId() => 
	      Requester.Request(Method.GET, $"{BASIC_SERVICE}/admin/me",parser: resp =>
	      {
		      var r = (ArrayDict)Json.Deserialize(resp);
		      return new AccountId() { Id = (long)r["id"] };
	      });

      public override Promise<User> GetUser(TokenResponse token)
      {
         throw new NotImplementedException("This version of GetUser is not supported in the Microservice environment!\n" +
                                           $"To get User data, please use {nameof(IMicroserviceAuthApi)}.{nameof(IMicroserviceAuthApi.GetUser)}(userId) instead.\n" +
                                           $"Or, to make calls from the Microservice on behalf of a user with a given Id, " +
                                           $"use Microservice.AssumeUser(userId) and use the returned {nameof(RequestHandlerData)}.{nameof(RequestHandlerData.Services)}.");
      }

      private class GetUserRequest
      {
         public long gamerTag;
      }
   }
}
