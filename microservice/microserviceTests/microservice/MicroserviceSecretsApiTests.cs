using System.Threading.Tasks;
using Beamable.Api.Autogenerated.Models;
using Beamable.Api.Autogenerated.Secrets;
using Beamable.Common;
using Beamable.Common.Api;
using Beamable.Common.Content;
using Beamable.Common.Dependencies;
using Beamable.Server;
using Beamable.Server.Api.Secrets;
using NUnit.Framework;

namespace microserviceTests.microservice
{
	public class MicroserviceSecretsApiTests
	{
		/// <summary>Records what the wrapper sends to the generated client.</summary>
		private class FakeSecretsApi : IBeamSecretsApi
		{
			public string LastKey;
			public PutRealmSecretRequest LastPut;
			public Optional<string> LastCursor;
			public bool ListCalled;
			public string StoredValue = "the-value";

			public Promise<GetRealmSecretResponse> GetValues(string key, bool includeAuthHeader = true)
			{
				LastKey = key;
				return Promise<GetRealmSecretResponse>.Successful(
					new GetRealmSecretResponse { key = key, value = StoredValue });
			}

			public Promise<Acknowledge> PutValues(string key, PutRealmSecretRequest gsReq, bool includeAuthHeader = true)
			{
				LastKey = key;
				LastPut = gsReq;
				return Promise<Acknowledge>.Successful(new Acknowledge());
			}

			public Promise<Acknowledge> DeleteValues(string key, bool includeAuthHeader = true)
			{
				LastKey = key;
				return Promise<Acknowledge>.Successful(new Acknowledge());
			}

			public Promise<RealmSecretInfoCursorPagedResult> GetValues(Optional<string> cursor = null, bool includeAuthHeader = true)
			{
				ListCalled = true;
				LastCursor = cursor;
				return Promise<RealmSecretInfoCursorPagedResult>.Successful(new RealmSecretInfoCursorPagedResult());
			}

			public Promise<RealmDataKeyInfoCursorPagedResult> GetDataKeys(Optional<string> cursor = null, bool includeAuthHeader = true) =>
				throw new System.NotImplementedException();

			public Promise<RotateRealmDataKeyResponse> PostDataKeys(bool includeAuthHeader = true) =>
				throw new System.NotImplementedException();

			public Promise<RealmSecretsAuditInfoCursorPagedResult> GetAuditLogs(Optional<string> AccountId = null,
				Optional<string> PlayerId = null, Optional<string> SecretKey = null, Optional<string> cursor = null,
				bool includeAuthHeader = true) =>
				throw new System.NotImplementedException();
		}

		[Test]
		public async Task GetSecret_ReturnsTheValue()
		{
			var api = new FakeSecretsApi();
			var value = await new MicroserviceSecretsApi(api).GetSecret("a/key");

			Assert.AreEqual("the-value", value);
			Assert.AreEqual("a/key", api.LastKey);
		}

		[Test]
		public async Task SetSecret_SendsTheValue()
		{
			var api = new FakeSecretsApi();
			await new MicroserviceSecretsApi(api).SetSecret("a/key", "new-value");

			Assert.AreEqual("a/key", api.LastKey);
			Assert.IsTrue(api.LastPut.value.HasValue);
			Assert.AreEqual("new-value", api.LastPut.value.Value);
		}

		[Test]
		public async Task DeleteSecret_SendsTheKey()
		{
			var api = new FakeSecretsApi();
			await new MicroserviceSecretsApi(api).DeleteSecret("a/key");

			Assert.AreEqual("a/key", api.LastKey);
		}

		[Test]
		public async Task ListSecrets_WithoutCursor_SendsNoCursor()
		{
			var api = new FakeSecretsApi();
			await new MicroserviceSecretsApi(api).ListSecrets();

			Assert.IsTrue(api.ListCalled);
			// A present-but-null cursor would serialize as an empty `cursor` query parameter.
			Assert.IsFalse(api.LastCursor?.HasValue ?? false);
		}

		[Test]
		public async Task ListSecrets_WithCursor_PassesItThrough()
		{
			var api = new FakeSecretsApi();
			await new MicroserviceSecretsApi(api).ListSecrets("next-page");

			Assert.IsTrue(api.LastCursor.HasValue);
			Assert.AreEqual("next-page", api.LastCursor.Value);
		}

		// The secrets contracts carry no scope attribute, so both containers must accept them. These guard
		// against someone adding [RealmScoped] later, which would break zone services at boot. They also
		// resolve the real BeamSecretsApi, proving the DI can construct the generated client.
		[TestCase(BeamServiceScope.Realm)]
		[TestCase(BeamServiceScope.Zone)]
		public void SecretsApi_IsValidAndResolvableInEveryScope(BeamServiceScope scope)
		{
			var builder = new ScopedDependencyBuilder(scope);
			builder.AddScoped<IBeamableRequester>(_ => null);
			builder.AddScoped<IBeamSecretsApi, BeamSecretsApi>();
			builder.AddScoped<IMicroserviceSecretsApi, MicroserviceSecretsApi>();

			var provider = builder.Build();

			Assert.IsInstanceOf<MicroserviceSecretsApi>(provider.GetService<IMicroserviceSecretsApi>());
		}
	}
}
