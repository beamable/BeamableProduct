using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Net.WebSockets;
using System.Threading.Tasks;
using Beamable.Api.Autogenerated.Models;
using Beamable.Microservice.Tests.Socket;
using Beamable.Server;
using NUnit.Framework;

namespace microserviceTests.microservice.dbmicroservice.BeamableMicroServiceTests
{
	/// <summary>
	/// A connection that can't be set up again must not end the process, which other instances are still serving from
	/// (beamable/BeamableProduct#4958). A service that never started still ends it.
	/// </summary>
	[TestFixture]
	[NonParallelizable]
	public class ReconnectFailureTests : CommonTest
	{
		public enum ReplacementFailure
		{
			NeverAuthenticates,
			RegistrationFails,
			ClosedBeforeSetup
		}

		private readonly List<int> _exits = new List<int>();

		[SetUp]
		public void ObserveExits()
		{
			_exits.Clear();
			BeamableMicroService.ExitProcess = code =>
			{
				lock (_exits) _exits.Add(code);
			};
			allowErrorLogs = true; // a setup that fails is reported as an error.
		}

		[TearDown]
		public void RestoreExits()
		{
			BeamableMicroService.ExitProcess = Environment.Exit;
			BeamableMicroService.SetupAuthorizationTimeout = TimeSpan.FromMinutes(2);
		}

		private int[] Exits()
		{
			lock (_exits) return _exits.ToArray();
		}

		/// <summary>Answers one client callable with id <paramref name="requestId"/>, and reports that it did.</summary>
		private static Task<bool> ExpectReply(TestSocket socket, int requestId)
		{
			var replied = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
			socket.AddMessageHandler(MessageMatcher.WithReqId(requestId).WithStatus(200),
				MessageResponder.Custom(_ =>
				{
					replied.TrySetResult(true);
					return null;
				}), MessageFrequency.OnlyOnce(), requiresAuth: false);
			return replied.Task;
		}

		private static async Task AssertAnswersARequest(TestSocket socket, int requestId, string because)
		{
			var replied = ExpectReply(socket, requestId);
			socket.SendToClient(ClientRequest.ClientCallable("micro_sample", nameof(SimpleMicroservice.Add), requestId, 1, 1, 2));
			Assert.That(await Task.WhenAny(replied, Task.Delay(5000)), Is.SameAs(replied), because);
		}

		private static TestSocket NeverAnswerNonce(TestSocket socket, TaskCompletionSource<bool> asked = null)
		{
			return socket.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/nonce"),
				MessageResponder.Custom(_ =>
				{
					asked?.TrySetResult(true);
					return null;
				}), MessageFrequency.AtLeast(0), "nonce that is never answered", false);
		}

		private static void FailSetup(TestSocket socket, ReplacementFailure failure)
		{
			switch (failure)
			{
				case ReplacementFailure.NeverAuthenticates:
					NeverAnswerNonce(socket);
					break;
				case ReplacementFailure.RegistrationFails:
					// handlers match in the order they were added, so this one answers every registration.
					socket.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/provider").WithPost(),
						MessageResponder.TimeoutFailure(), MessageFrequency.AtLeast(1), "registration the gateway rejects");
					SocketRecoveryTests.AddReconnectHandlers(socket);
					break;
				case ReplacementFailure.ClosedBeforeSetup:
					socket.MockState = WebSocketState.Aborted;
					break;
			}
		}

		[TestCase(ReplacementFailure.NeverAuthenticates)]
		[TestCase(ReplacementFailure.RegistrationFails)]
		[TestCase(ReplacementFailure.ClosedBeforeSetup)]
		[TimeoutWithTeardown(60 * 1000)]
		public async Task ReplacementThatCannotBeSetUp_KeepsTheProcessAndItsOtherInstanceServing(ReplacementFailure failure)
		{
			// two instances; the third connection replaces the second instance's, and its setup fails. Only the case that
			// waits for authentication may take its timeout to fail; the others must fail well before it.
			BeamableMicroService.SetupAuthorizationTimeout =
				TimeSpan.FromSeconds(failure == ReplacementFailure.NeverAuthenticates ? 1 : 30);
			var sockets = new List<TestSocket>();
			var ms = new TestSetup(new TestSocketProvider(socket =>
			{
				sockets.Add(socket);
				switch (sockets.Count)
				{
					case 1:
					case 2:
						socket.AddStandardMessageHandlers(addShutdownResponder: sockets.Count == 1);
						break;
					case 3:
						FailSetup(socket, failure);
						break;
					default:
						SocketRecoveryTests.AddReconnectHandlers(socket);
						break;
				}
			}));
			await ms.Start<SimpleMicroservice>(new TestArgs { BeamInstanceCount = 2 });
			Assert.That(sockets.Count, Is.EqualTo(2));

			// the disconnect callback returns once the connection is replaced, so it can't run on this thread.
			var recovered = Task.Run(() => sockets[1].Fault());
			Assert.That(await SocketRecoveryTests.Eventually(() => sockets.Count >= 3 && sockets[2].AbortReason != null, TimeSpan.FromSeconds(10)),
				Is.True, "a connection whose setup failed must be dropped");

			await AssertAnswersARequest(sockets[0], 1, "the other instance must keep serving while this one can't reconnect");
			Assert.That(Exits(), Is.Empty, "a failed reconnect must not end the process");

			Assert.That(await Task.WhenAny(recovered, Task.Delay(20000)), Is.SameAs(recovered), "the connection must be replaced until one works");
			Assert.That(sockets.Count, Is.EqualTo(4));
			await AssertAnswersARequest(sockets[3], 2, "the instance must serve again once a replacement is set up");
			Assert.That(Exits(), Is.Empty);
			await ms.OnShutdown(this, null);
		}

		[Test]
		[TimeoutWithTeardown(60 * 1000)]
		public async Task ConnectionThatClosesWhileItAuthenticates_IsReplacedWithoutWaitingOutItsSetup()
		{
			// the wait for authentication on the second connection would take 30s to give up. Closing that connection
			// must end the wait at once, and leave nothing behind that could still act for it.
			BeamableMicroService.SetupAuthorizationTimeout = TimeSpan.FromSeconds(30);
			var sockets = new List<TestSocket>();
			var authenticating = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
			var ms = new TestSetup(new TestSocketProvider(socket =>
			{
				sockets.Add(socket);
				switch (sockets.Count)
				{
					case 1:
						socket.AddStandardMessageHandlers(addShutdownResponder: false);
						break;
					case 2:
						NeverAnswerNonce(socket, authenticating);
						break;
					default:
						SocketRecoveryTests.AddReconnectHandlers(socket);
						break;
				}
			}));
			await ms.Start<SimpleMicroservice>(new TestArgs());

			var timer = Stopwatch.StartNew();
			var recovered = Task.Run(() => sockets[0].Fault());
			Assert.That(await Task.WhenAny(authenticating.Task, Task.Delay(5000)), Is.SameAs(authenticating.Task));
			sockets[1].Fault();

			Assert.That(await Task.WhenAny(recovered, Task.Delay(20000)), Is.SameAs(recovered), "the closed connection must be replaced");
			Assert.That(timer.Elapsed, Is.LessThan(BeamableMicroService.SetupAuthorizationTimeout),
				"the wait for authentication must end when its connection closes, not when it times out");
			Assert.That(sockets.Count, Is.EqualTo(3));
			await AssertAnswersARequest(sockets[2], 1, "the replacement must serve");

			Assert.That(Exits(), Is.Empty);
			Assert.That(sockets[1].UnhandledError(), Is.Null, "nothing but authentication may be sent on the closed connection");
			Assert.That(sockets[2].UnhandledError(), Is.Null, "the replacement must be set up exactly once");
			await ms.OnShutdown(this, null);
		}

		[Test]
		[TimeoutWithTeardown(60 * 1000)]
		public void ServiceThatCannotStart_StillEndsTheProcess()
		{
			var ms = new TestSetup(new TestSocketProvider(socket => FailSetup(socket, ReplacementFailure.RegistrationFails)));

			Assert.CatchAsync(() => ms.Start<SimpleMicroservice>(new TestArgs()));

			Assert.That(Exits(), Is.EqualTo(new[] { 12 }), "a service that fails before it has started must exit with code 12");
			Assert.That(ms.HasInitialized, Is.False);
		}

		[Test]
		[TimeoutWithTeardown(60 * 1000)]
		public async Task ConnectionThatClosesWhileTheServiceStarts_IsReplaced()
		{
			BeamableMicroService.SetupAuthorizationTimeout = TimeSpan.FromSeconds(30);
			var sockets = new List<TestSocket>();
			var ms = new TestSetup(new TestSocketProvider(socket =>
			{
				sockets.Add(socket);
				if (sockets.Count == 1) FailSetup(socket, ReplacementFailure.ClosedBeforeSetup);
				else SocketRecoveryTests.AddReconnectHandlers(socket);
			}));

			await ms.Start<SimpleMicroservice>(new TestArgs());

			Assert.That(Exits(), Is.Empty, "a connection lost while starting must not end the process");
			Assert.That(ms.HasInitialized, Is.True);
			Assert.That(sockets.Count, Is.EqualTo(2));
			await AssertAnswersARequest(sockets[1], 1, "the service must serve on the replacement");
			await ms.OnShutdown(this, null);
		}

		[Test]
		[TimeoutWithTeardown(60 * 1000)]
		public void ServiceWhoseConnectionsKeepClosingWhileItStarts_StillEndsTheProcess()
		{
			// a start gets as long as it would have waited for authentication, one second here; the first retry
			// comes five seconds later.
			BeamableMicroService.SetupAuthorizationTimeout = TimeSpan.FromSeconds(1);
			var connections = 0;
			var ms = new TestSetup(new TestSocketProvider(socket =>
			{
				connections++;
				FailSetup(socket, ReplacementFailure.ClosedBeforeSetup);
			}));

			Assert.CatchAsync(() => ms.Start<SimpleMicroservice>(new TestArgs()));

			Assert.That(Exits(), Is.EqualTo(new[] { 12 }));
			Assert.That(connections, Is.EqualTo(2), "the first closed connection is replaced; the second is past the limit");
		}
	}
}
