    // The scoped config clients may issue the second instance's GET on the primary. Gate the
    // actual reply by startup attempt, retaining the sending socket for delivery of a late reply.
    private sealed class Platform : IConnectionProvider
    {
        private readonly ConcurrentDictionary<(int, Reply), TaskCompletionSource<Action>> _held = new();
        public readonly ConcurrentQueue<(BeamableMicroService Service, TestSocket Socket)> Connections = new();

        public Action<int, TestSocket> ConfigureSocket { get; init; }
        public (int Attempt, Reply Step)? Gateway504 { get; init; }
        public int PrimaryPendingBeforeSecondStart { get; private set; }

        public Task<Action> Hold(int attempt, Reply step) =>
            _held.GetOrAdd((attempt, step), _ => new(TaskCreationOptions.RunContinuationsAsynchronously)).Task;

        public IConnection Create(string host, IMicroserviceArgs args)
        {
            if (Connections.Count == 1)
                PrimaryPendingBeforeSecondStart = Connections.First().Service.SocketContext.PendingRequestCount;
            var socket = new TestSocket();
            Connections.Enqueue((args.ServiceScope.GetService<BeamableMicroService>(), socket));
            void Respond(Reply step, TestSocketMessageMatcher matcher, object body, bool requiresAuth = true)
            {
                socket.AddMessageHandler(matcher, MessageResponder.Custom(request =>
                {
                    if (Gateway504 == (Connections.Count, step)) return request.Timeout();
                    var reply = request.Succeed(body);
                    if (_held.TryGetValue((Connections.Count, step), out var held) &&
                        held.TrySetResult(() => socket.SendToClient(reply)))
                        return null;
                    return reply;
                }), MessageFrequency.AtLeast(0), requiresAuth: requiresAuth);
            }

            Respond(Reply.Nonce, MessageMatcher.WithRouteContains("gateway/nonce"),
                new MicroserviceNonceResponse { nonce = "n" }, requiresAuth: false);
            Respond(Reply.Realm, MessageMatcher.WithRouteContains("basic/realms/config").WithGet(),
                new GetRealmConfigResponse { config = new() });
            Respond(Reply.Logging, MessageMatcher.WithRouteContains("services/logs/context").WithGet(),
                new { contexts = Array.Empty<object>() });
            Respond(Reply.BasicProvider, Provider("basic"), new MicroserviceProviderResponse());
            Respond(Reply.EventProvider, Provider("event"), new MicroserviceProviderResponse());
            Respond(Reply.Federation, MessageMatcher.WithRouteContains("federation/traffic").WithPut(), new CommonResponse());
            SocketRecoveryTests.AddReconnectHandlers(socket);
            ConfigureSocket?.Invoke(Connections.Count, socket);
            return socket;
        }

        private static TestSocketMessageMatcher Provider(string type) => MessageMatcher.WithRouteContains("gateway/provider")
            .WithPost().WithBody<MicroserviceServiceProviderRequest>(body => body.type == type);

        public static void Configure(IDependencyBuilder builder)
        {
            builder.RemoveIfExists<IRealmConfigService>();
            builder.AddSingleton<RealmConfigService>();
            builder.AddSingleton<IRealmConfigService>(p => p.GetService<RealmConfigService>());
            builder.RemoveIfExists<ILoggingContextService>();
            builder.AddSingleton<ILoggingContextService, LoggingContextService>();
        }
    }

