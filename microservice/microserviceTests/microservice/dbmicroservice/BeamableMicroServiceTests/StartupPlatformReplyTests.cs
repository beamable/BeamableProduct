        Assert.That(await SocketRecoveryTests.Eventually(() => abandoned.AbortReason != null, TimeSpan.FromSeconds(4)), Is.True);
        await ReconnectFailureTests.AssertAnswersARequest(platform.Connections.First().Socket, 1, "the primary serves through retry");
        await start.WaitAsync(TimeSpan.FromSeconds(12));
        Assert.That(secondary.HasInitialized, Is.True);
        Assert.That(platform.Connections.Count, Is.EqualTo(3));
        await ReconnectFailureTests.AssertAnswersARequest(platform.Connections.Last().Socket, 2, "the replacement serves");
        Assert.That(_exits, Is.Empty);
        await setup.OnShutdown(this, null);
    }

