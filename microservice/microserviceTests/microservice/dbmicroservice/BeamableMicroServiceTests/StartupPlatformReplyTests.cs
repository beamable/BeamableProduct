    [Test]
    [TimeoutWithTeardown(30_000)]
    public async Task RealmConfigChangedSubscriberRunsOutsideThePlatformBudget()
    {
        var platform = new Platform();
        var primaryRegistration = platform.Hold(1, Reply.Federation);
        var setup = new TestSetup(platform);
        var start = setup.Start<SimpleMicroservice>(new TestArgs { BeamInstanceCount = 2 }, Platform.Configure);
        var register = await primaryRegistration.WaitAsync(TimeSpan.FromSeconds(8));
        var realm = setup.Service.Provider.GetService<RealmConfigService>();
        var entered = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
        using var release = new ManualResetEventSlim();
        void OnConfigChanged(RealmConfig _)
        {
            entered.TrySetResult(true);
            release.Wait(TimeSpan.FromSeconds(8));
        }

        // The first realm fetch has finished. The gateway immediately answers the secondary's fetch,
        // but application code handling the resulting config change takes longer than the budget.
        realm.ConfigChanged += OnConfigChanged;
        try
        {
            var releasedPrimary = Task.Run(register);
            await entered.Task.WaitAsync(TimeSpan.FromSeconds(8));
            await Task.Delay(TimeSpan.FromSeconds(2));
            var secondary = platform.Connections.Last();
            Assert.That(platform.Connections.First().Service.HasInitialized, Is.True);
            Assert.That(secondary.Service.HasInitialized, Is.False);
            Assert.That(secondary.Socket.AbortReason, Is.Null);
            release.Set();
            await releasedPrimary.WaitAsync(TimeSpan.FromSeconds(5));
            await start.WaitAsync(TimeSpan.FromSeconds(8));
            Assert.That(secondary.Service.HasInitialized, Is.True);
            Assert.That(platform.Connections.Count, Is.EqualTo(2), "both instances used their original socket");
            Assert.That(_exits, Is.Empty);
            await setup.OnShutdown(this, null);
        }
        finally
        {
            release.Set();
            realm.ConfigChanged -= OnConfigChanged;
        }
    }

    [Test]
    [TimeoutWithTeardown(30_000)]
    public async Task CustomHookCannotSuppressTheTimeoutOfTheBuiltInSubscription()
    {
        var platform = new Platform();
        var eventRequest = platform.Hold(1, Reply.EventProvider);
        var setup = new TestSetup(platform);
        var caught = new TaskCompletionSource<Exception>(TaskCreationOptions.RunContinuationsAsynchronously);
        var finishHook = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
        var hook = new DefaultEventSubscription();
        hook.handler = async args =>
        {
            try { await hook.DefaultHandler(args); }
            catch (Exception error)
            {
                caught.TrySetResult(error);
                await finishHook.Task;
            }
        };

        var start = setup.Start<SimpleMicroservice>(new TestArgs(), builder =>
        {
            Platform.Configure(builder);
            builder.RemoveIfExists<IEventSubscriptionHook>();
            builder.AddSingleton<IEventSubscriptionHook>(_ => hook);
        });
        try
        {
            var lateReply = await eventRequest.WaitAsync(TimeSpan.FromSeconds(8));
            var error = await caught.Task.WaitAsync(TimeSpan.FromSeconds(6));
            Assert.That(error, Is.InstanceOf<TimeoutException>());
            var finished = await Task.WhenAny(start, Task.Delay(TimeSpan.FromSeconds(3)));
            Assert.That(finished, Is.SameAs(start), "startup must act on expiry while the custom hook is still running");
            Assert.CatchAsync(async () => await start);
            Assert.That(_exits, Is.EqualTo(new[] { 12 }));
            lateReply();
            Assert.That(setup.HasInitialized, Is.False);
        }
        finally { finishHook.TrySetResult(true); }
    }

    private sealed class CustomSubscription : IEventSubscriptionHook
    {
        public bool Completed { get; private set; }

        public async Task CreateSubscription(CreateSubscriptionArgs args)
        {
            await Task.Delay(TimeSpan.FromSeconds(2));
            await new DefaultEventSubscription().DefaultHandler(args);
            Completed = true;
        }
    }

    [TestCase(false)]
    [TestCase(true)]
    [TimeoutWithTeardown(30_000)]
    public async Task CustomSubscriptionWorkIsOutsideThePlatformBudget(bool customizedDefaultHandler)
    {
        var subscription = new CustomSubscription();
        IEventSubscriptionHook custom = subscription;
        if (customizedDefaultHandler)
            custom = new DefaultEventSubscription { handler = custom.CreateSubscription };
        var setup = new TestSetup(new TestSocketProvider(socket => SocketRecoveryTests.AddReconnectHandlers(socket)));
        await setup.Start<SimpleMicroservice>(new TestArgs(), builder =>
        {
            builder.RemoveIfExists<IEventSubscriptionHook>();
            builder.AddSingleton<IEventSubscriptionHook>(_ => custom);
        }).WaitAsync(TimeSpan.FromSeconds(12));
        Assert.That(subscription.Completed, Is.True);
        Assert.That(setup.HasInitialized, Is.True);
        Assert.That(_exits, Is.Empty);
        await setup.OnShutdown(this, null);
    }
