    public async Task EnforcedRequesterDeadlineRetriesTheSecondaryButAPlatformErrorStillFailsStartup(bool gatewayReturned504)
    {
        BeamableMicroService.StartupPlatformReplyTimeout = TimeSpan.FromSeconds(30);
        var platform = new Platform { Gateway504 = gatewayReturned504 ? (2, Reply.BasicProvider) : null };
        var held = platform.Hold(2, Reply.BasicProvider);
        var setup = new TestSetup(platform);
        var args = new TestArgs { BeamInstanceCount = 2, EnforceSocketReliability = true, OutboundRequestTimeoutSeconds = 1 };
