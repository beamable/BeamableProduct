using System.Collections.Generic;
using System.Reflection;
using System.Threading.Tasks;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common;
using Beamable.Microservice.Tests.Socket;
using Beamable.Server;
using Beamable.Server.Api.RealmConfig;
using Beamable.Server.Content;
using Microsoft.Extensions.Logging;
using NUnit.Framework;

namespace microserviceTests.microservice.dbmicroservice.BeamableMicroServiceTests;

[Microservice("realm-reconnect", EnableEagerContentLoading = false)]
public class RealmReconnectService : Microservice
{
    public static int InitializationCount;

    [InitializeServices]
    public static void Initialize(IServiceInitializer initializer) => InitializationCount++;
}

[NonParallelizable]
public class RealmConfigReconnectTests : CommonTest
{
    [TestCase(false, true)]
    [TestCase(true, false)]
    public async Task ReconnectRefreshesMissedSettingsWithoutRepeatingInitialization(bool initiallyDisabled, bool disabledAfterReconnect)
    {
        RealmReconnectService.InitializationCount = 0;
        var sockets = new List<TestSocket>();
        var fetches = 0;
        var ms = new TestSetup(new TestSocketProvider(socket =>
        {
            var connection = sockets.Count;
            sockets.Add(socket);
            socket.AddMessageHandler(MessageMatcher.WithRouteContains("nonce"),
                    MessageResponder.Success(new MicroserviceNonceResponse { nonce = "testnonce" }),
                    MessageFrequency.OnlyOnce(), requiresAuth: false)
                .AddMessageHandler(MessageMatcher.WithRouteContains("auth"),
                    MessageResponder.Success(() =>
                    {
                        socket.SetAuthentication(true);
                        return new MicroserviceAuthResponse { result = "ok" };
                    }), MessageFrequency.OnlyOnce(), requiresAuth: false)
                .AddMessageHandler(MessageMatcher.WithRouteContains("realms/config"),
                    MessageResponder.Success(() =>
                    {
                        fetches++;
                        return new GetRealmConfigResponse
                        {
                            config = new Dictionary<string, string>
                            {
                                ["service_content|disable_baked_content"] = (connection == 0 ? initiallyDisabled : disabledAfterReconnect).ToString(),
                                ["service_logs|realm-reconnect"] = connection == 0 ? "debug" : "error"
                            }
                        };
                    }), MessageFrequency.OnlyOnce())
                .AddMessageHandler(MessageMatcher.WithRouteContains("gateway/provider").WithPost(),
                    MessageResponder.Success(new MicroserviceProviderResponse()), MessageFrequency.Exactly(2))
                .AddMessageHandler(MessageMatcher.WithRouteContains("federation/traffic").WithPut(),
                    MessageResponder.Success(new CommonResponse()), MessageFrequency.OnlyOnce());
            if (connection > 0) socket.AddProviderShutdownMessageHandler();
        }));

        await ms.Start<RealmReconnectService>(configurator: builder =>
        {
            builder.RemoveIfExists<IRealmConfigService>();
            builder.RemoveIfExists<IMicroserviceRealmConfigService>();
            builder.AddSingleton<IRealmConfigService, RealmConfigService>();
            builder.AddSingleton<IMicroserviceRealmConfigService>(p => p.GetService<IRealmConfigService>());
        });
        try
        {
            var content = ms.Service.Provider.GetService<ContentService>();
            var realm = (RealmConfigService)ms.Service.Provider.GetService<IRealmConfigService>();
            var bakingEnabled = typeof(ContentService).GetField("_bakedContentEnabled", BindingFlags.Instance | BindingFlags.NonPublic);
            var getLogLevel = typeof(RealmConfigService).GetMethod("GetLogLevel", BindingFlags.Instance | BindingFlags.NonPublic);
            var subscriptions = typeof(RealmConfigService).GetField("ConfigChanged", BindingFlags.Instance | BindingFlags.NonPublic);

            Assert.That(bakingEnabled.GetValue(content), Is.EqualTo(!initiallyDisabled));
            Assert.That(getLogLevel.Invoke(realm, null), Is.EqualTo(LogLevel.Debug));
            Assert.That(sockets[0].AllMocksCalled(), Is.True);

            // No config event is sent: the replacement connection must fetch the missed changes.
            sockets[0].Fault();
            Assert.That(sockets.Count, Is.EqualTo(2));
            Assert.That(fetches, Is.EqualTo(2));
            Assert.That(bakingEnabled.GetValue(content), Is.EqualTo(!disabledAfterReconnect));
            Assert.That(getLogLevel.Invoke(realm, null), Is.EqualTo(LogLevel.Error));
            Assert.That(RealmReconnectService.InitializationCount, Is.EqualTo(1));
            Assert.That(((System.Delegate)subscriptions.GetValue(realm)).GetInvocationList(), Has.Length.EqualTo(1));
        }
        finally
        {
            await ms.OnShutdown(this, null);
        }
        Assert.That(sockets[1].AllMocksCalled(), Is.True);
    }
}
