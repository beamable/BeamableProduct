	[TestFixture]
	public class SocketRecoveryTests : CommonTest
	{
		/// <summary>Auth and provider registration for a replacement connection, whatever its request ids.</summary>
		private static TestSocket AddReconnectHandlers(TestSocket socket, TaskCompletionSource<bool> registered = null)
		{
			return socket
				.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/nonce"),
					MessageResponder.Success(new MicroserviceNonceResponse { nonce = "n" }), MessageFrequency.AtLeast(1), "nonce", false)
				.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/auth"),
					MessageResponder.Success(() =>
					{
						socket.SetAuthentication(true);
						return new MicroserviceAuthResponse { result = "ok" };
					}), MessageFrequency.AtLeast(1), "auth", false)
				.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/provider").WithPost()
						.WithBody<MicroserviceServiceProviderRequest>(b => b.type == "basic"),
					MessageResponder.Success(new MicroserviceProviderResponse()), MessageFrequency.OnlyOnce())
				.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/provider").WithPost()
						.WithBody<MicroserviceServiceProviderRequest>(b => b.type == "event"),
					MessageResponder.Success(new MicroserviceProviderResponse()), MessageFrequency.OnlyOnce())
				.AddMessageHandler(MessageMatcher.WithRouteContains("federation/traffic").WithPut(),
					MessageResponder.Success(() =>
					{
						registered?.TrySetResult(true);
						return new CommonResponse();
					}), MessageFrequency.OnlyOnce())
				.AddProviderShutdownMessageHandler();
		}

		private static int PendingRequestCount(SocketRequesterContext context)
		{
			var field = typeof(SocketRequesterContext).GetField("_pendingMessages", BindingFlags.Instance | BindingFlags.NonPublic);
			return ((ICollection)field!.GetValue(context)!).Count;
		}

		private static async Task<bool> Eventually(Func<bool> condition, TimeSpan limit)
		{
			var deadline = DateTime.UtcNow + limit;
			while (DateTime.UtcNow < deadline)
			{
				if (condition()) return true;
				await Task.Delay(50);
			}

			return condition();
		}

		[Test]
		[NonParallelizable]
		[TimeoutWithTeardown(60 * 1000)]
		public async Task ContentPublish_IsHandledOnAnotherConnection_WhenTheFirstIsBroken()
		{
			// Every connection receives every content publish, but the content cache subscribes on the first instance's
			// context only. With that connection broken, the event arriving on the second connection must still refresh
			// the manifest, and the refresh must go out on a connection that works.
			var sockets = new List<TestSocket>();
			var manifestFetched = new TaskCompletionSource<int>(TaskCreationOptions.RunContinuationsAsynchronously);
			var ms = new TestSetup(new TestSocketProvider(socket =>
			{
				var index = sockets.Count;
				sockets.Add(socket);
				socket.AddStandardMessageHandlers()
					.AddMessageHandler(MessageMatcher.WithRouteContains("basic/content/manifest").WithGet(),
						MessageResponder.Success(() =>
						{
							manifestFetched.TrySetResult(index);
							return new ContentManifest { id = "global", created = 1, references = new List<Beamable.Server.Content.ContentReference>() };
						}), MessageFrequency.AtLeast(0))
					.AddMessageHandler(MessageMatcher.WithReqId(77).WithStatus(200), MessageResponder.NoResponse(), MessageFrequency.AtLeast(0));
			}));
			await ms.Start<SimpleMicroservice>(new TestArgs { BeamInstanceCount = 2 });
			Assert.That(sockets.Count, Is.EqualTo(2));

			ms.Service.SocketContext.ReportUnhealthyConnection(null, "test: the first connection stopped answering");
			var publish = ClientRequest.Event(Constants.Features.Services.CONTENT_UPDATE_EVENT, 77, new { categories = new string[0] });
			publish.headers = new Dictionary<string, string> { ["msgId"] = "publish-1" };
			sockets[1].SendToClient(publish);

			Assert.That(await Task.WhenAny(manifestFetched.Task, Task.Delay(5000)), Is.SameAs(manifestFetched.Task),
				"the content publish must be handled even though it only arrived on the second connection");
			Assert.That(await manifestFetched.Task, Is.EqualTo(1), "the manifest refresh must avoid the broken connection");
			await ms.OnShutdown(this, null);
		}

		[Test]
		[NonParallelizable]
		[TimeoutWithTeardown(60 * 1000)]
		public async Task RepliesToClients_DoNotWaitForReauthentication()
		{
			// The gateway reads replies without checking the session's auth (ThoriumSocket.handleResponse), so a reply
			// must not queue behind a re-authentication that cannot finish.
			TestSocket testSocket = null;
			var replied = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
			var ms = new TestSetup(new TestSocketProvider(socket =>
			{
				testSocket = socket;
				socket.AddStandardMessageHandlers()
					.AddMessageHandler(MessageMatcher.WithReqId(1).WithStatus(200),
						MessageResponder.Custom(_ =>
						{
							replied.TrySetResult(true);
							return null;
						}), MessageFrequency.OnlyOnce(), requiresAuth: false);
			}));
			await ms.Start<SimpleMicroservice>(new TestArgs());

			var daemon = ms.Service.SocketContext.Daemon;
			Interlocked.Exchange(ref daemon.AuthorizationCounter, 1); // a re-authentication that never completes.
			testSocket.SendToClient(ClientRequest.ClientCallable("micro_sample", "Add", 1, 1, 1, 2));
			var finished = await Task.WhenAny(replied.Task, Task.Delay(3000));
			Interlocked.Exchange(ref daemon.AuthorizationCounter, 0);

			Assert.That(finished, Is.SameAs(replied.Task), "the reply must be sent while re-authentication is pending");
			await ms.OnShutdown(this, null);
		}

		[Test]
		[NonParallelizable]
		[TimeoutWithTeardown(60 * 1000)]
		public async Task Disconnect_FailsRequestsSentOnTheDroppedConnection()
		{
			allowErrorLogs = true; // the callable fails when its outbound call is lost.
			var accountsSent = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
			TestSocket first = null;
			var connections = 0;
			var ms = new TestSetup(new TestSocketProvider(socket =>
			{
				if (connections++ == 0)
				{
					first = socket;
					socket.AddStandardMessageHandlers(addShutdownResponder: false)
						.AddMessageHandler(MessageMatcher.WithRouteContains("basic/accounts"),
							MessageResponder.Custom(_ =>
							{
								accountsSent.TrySetResult(true);
								return null; // the gateway never answers on this connection.
							}), MessageFrequency.OnlyOnce());
				}
				else
				{
					AddReconnectHandlers(socket);
				}
			}));
			await ms.Start<SimpleMicroservice>(new TestArgs { EnforceSocketReliability = true });

			first.SendToClient(ClientRequest.ClientCallable("micro_sample", "DelayThenGetEmail", 1, 1, 0, 123));
			Assert.That(await Task.WhenAny(accountsSent.Task, Task.Delay(3000)), Is.SameAs(accountsSent.Task));
			Assert.That(PendingRequestCount(ms.Service.SocketContext), Is.EqualTo(1));

			first.Fault();

			Assert.That(await Eventually(() => PendingRequestCount(ms.Service.SocketContext) == 0, TimeSpan.FromSeconds(3)),
				Is.True, "a request sent on the dropped connection can never be answered, so it must fail");
			Assert.That(connections, Is.EqualTo(2));
			await ms.OnShutdown(this, null);
		}

		[Test]
		[NonParallelizable]
		[TimeoutWithTeardown(60 * 1000)]
		public async Task GatewayRejectingEveryRequestAfterReauth_ReplacesTheConnection()
		{
			// A session the gateway's timeout breaker ended keeps answering 403 "Not Authenticated" even after a
			// successful re-auth. The only way out is a new connection.
			allowErrorLogs = true;
			TestSocket first = null;
			var connections = 0;
			var replaced = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
			var ms = new TestSetup(new TestSocketProvider(socket =>
			{
				if (connections++ == 0)
				{
					first = socket;
					socket.AddStandardMessageHandlers(addShutdownResponder: false)
						.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/nonce"),
							MessageResponder.Success(new MicroserviceNonceResponse { nonce = "n" }), MessageFrequency.AtLeast(0), "nonce again", false)
						.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/auth"),
							MessageResponder.Success(new MicroserviceAuthResponse { result = "ok" }), MessageFrequency.AtLeast(0), "auth again", false)
						.AddMessageHandler(MessageMatcher.WithRouteContains("basic/accounts"),
							MessageResponder.Custom(req => req.AuthFailure()), MessageFrequency.AtLeast(1), "zombie session", false);
				}
				else
				{
					AddReconnectHandlers(socket, replaced);
				}
			}));
			await ms.Start<SimpleMicroservice>(new TestArgs { EnforceSocketReliability = true, OutboundRequestTimeoutSeconds = 5 });

			first.SendToClient(ClientRequest.ClientCallable("micro_sample", "DelayThenGetEmail", 1, 1, 0, 123));

			Assert.That(await Task.WhenAny(replaced.Task, Task.Delay(10000)), Is.SameAs(replaced.Task),
				"a session that rejects every request after a fresh auth must be replaced");
			Assert.That(connections, Is.EqualTo(2));
			Assert.That(first.AbortReason, Does.Contain("rejected"));
			await ms.OnShutdown(this, null);
		}
	}
