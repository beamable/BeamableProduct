    [Test]
    public async Task RecoveredShadowStall_StaysHealthyWhileIdle_AndDetectsSecondStallOnSameSocket()
    {
        void Configure(TestSocket socket) => socket
            .AddMessageHandler(MessageMatcher.WithRouteContains("gateway/auth"),
                MessageResponder.Success(new MicroserviceAuthResponse { result = "ok" }), requiresAuth: false)
            .AddMessageHandler(MessageMatcher.WithRouteContains("basic/ping"), MessageResponder.Success(new CommonResponse()));

        var release = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
        using var sibling = new RequesterHarness(Configure);
        using var affected = new RequesterHarness(socket =>
        {
            Configure(socket);
            socket.AddMessageHandler(MessageMatcher.WithRouteContains("basic/held"), MessageResponder.CustomAsync(async req =>
            {
                await release.Task;
                return req.Succeed(new CommonResponse());
            }), MessageFrequency.Exactly(2));
        });
        var recovery = TimeSpan.FromMilliseconds(100);
        var monitor = new ProcessHealthMonitor(new[] { new Service(sibling.Context), new Service(affected.Context) },
            2, new ProcessHealthOptions { SocketRecovery = recovery });
        ProcessHealthSnapshot Sample()
        {
            monitor.Check(Stopwatch.GetTimestamp());
            return monitor.Snapshot;
        }
        try
        {
            await sibling.AuthRequester.Request<MicroserviceAuthResponse>(Method.POST, "gateway/auth");
            await affected.AuthRequester.Request<MicroserviceAuthResponse>(Method.POST, "gateway/auth");
            Assert.That(Sample().State, Is.EqualTo(ProcessHealthState.Healthy));
            affected.Context.Reliability.StallTimeout = TimeSpan.FromMilliseconds(50);
            var first = affected.Requester.Request<CommonResponse>(Method.GET, "basic/held");
            Assert.That(SpinWait.SpinUntil(() => Sample().State == ProcessHealthState.Degraded, 3000), Is.True);
            release.SetResult(true);
            Assert.That(await first.FinishWithin(TimeSpan.FromSeconds(3), "first reply"), Is.Null);
            await affected.Requester.Request<CommonResponse>(Method.GET, "basic/ping");
            Sample();
            await Task.Delay(recovery + TimeSpan.FromMilliseconds(25));
            await sibling.Requester.Request<CommonResponse>(Method.GET, "basic/ping");
            Assert.That(Sample().State, Is.EqualTo(ProcessHealthState.Healthy), "the recovered socket was only idle");
            Assert.That(monitor.Snapshot.IncidentId, Is.Null);
            Assert.That(affected.Context.GetHealth(Stopwatch.GetTimestamp()).ReportedBroken, Is.True,
                "the socket report is recorded once per connection");

            release = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
            var second = affected.Requester.Request<CommonResponse>(Method.GET, "basic/held");
            Assert.That(SpinWait.SpinUntil(() => Sample().State == ProcessHealthState.Degraded, 3000), Is.True);
            Assert.That(SpinWait.SpinUntil(() => Sample().Reason == "isolated_socket_recovery_exhausted", 3000), Is.True);
            Assert.That(monitor.Snapshot.Instances[1].Generation, Is.EqualTo(1));
            Assert.That(monitor.Snapshot.IncidentId, Is.Not.Null);
            release.SetResult(true);
            Assert.That(await second.FinishWithin(TimeSpan.FromSeconds(3), "second reply"), Is.Null);
            Assert.That(Sample().State, Is.EqualTo(ProcessHealthState.Healthy));
        }
        finally
        {
            release.TrySetResult(true);
            monitor.Stop();
        }
    }

    [Test]
    public async Task ReplacementWithPriorEmptyAuthCounter_RemainsInRecoveryUntilActualAuthReply()
    {
        var args = new TestArgs();
        var first = new TestSocket();
        var second = new TestSocket();
        IConnection current = first;
        var context = new SocketRequesterContext(() => Promise<IConnection>.Successful(current));
        var requester = new MicroserviceRequester(args, null, context, false, new NoopActivityProvider());
        using var cancellation = new CancellationTokenSource();
        (_, context.Daemon) = MicroserviceAuthenticationDaemon.Start(args, requester, cancellation);
        foreach (var socket in new[] { first, second })
        {
            socket.SetAuthentication(true);
            socket.Connect();
            socket.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/auth"),
                MessageResponder.Success(new MicroserviceAuthResponse { result = "ok" }), MessageFrequency.OnlyOnce(), requiresAuth: false);
            socket.OnMessage((_, document, _) =>
            {
                if (document.TryBuildRequestContext(args, out var reply)) _ = context.HandleMessage(null, reply);
            });
        }
        var monitor = new ProcessHealthMonitor(new IBeamableService[] { new Service(context) });
        try
        {
            await requester.Request<MicroserviceAuthResponse>(Method.POST, "gateway/auth");
            monitor.Check(Stopwatch.GetTimestamp());
            Assert.That(monitor.Snapshot.Instances[0].Authenticated, Is.True);
            context.ReportUnhealthyConnection(first, "contract test");
            monitor.Check(Stopwatch.GetTimestamp());
            current = second;
            Assert.That(context.Daemon.NoPendingOrInProgressAuth, Is.True,
                "the prior session's empty counter is still visible on the replacement");
            monitor.Check(Stopwatch.GetTimestamp());
            Assert.That(monitor.Snapshot.Instances[0].Authenticated, Is.False);
            Assert.That(monitor.Snapshot.Instances[0].RecoverySeconds, Is.Not.Null);
            await requester.Request<MicroserviceAuthResponse>(Method.POST, "gateway/auth");
            monitor.Check(Stopwatch.GetTimestamp());
            Assert.That(monitor.Snapshot.Instances[0].Authenticated, Is.True);
            Assert.That(monitor.Snapshot.State, Is.EqualTo(ProcessHealthState.Healthy));
            Assert.That(monitor.Snapshot.Instances[0].Generation, Is.EqualTo(2));
        }
        finally
        {
            cancellation.Cancel();
            context.Daemon.AUTH_THREAD_WAIT_HANDLE.Set();
            monitor.Stop();
        }
    }

    [Test]
    public void BlockedUpstreamStallWarning_CannotBlockHeartbeatSampling()
    {
        using var entered = new ManualResetEventSlim();
        using var release = new ManualResetEventSlim();
        using var harness = new RequesterHarness(socket => socket.AddMessageHandler(
            MessageMatcher.WithRouteContains("basic/silent"), MessageResponder.NoResponse(), MessageFrequency.OnlyOnce()),
            new TestArgs { OutboundRequestTimeoutSeconds = 0 });
        // A separate real context keeps the harness's test-only checker from claiming this stall.
        var context = new SocketRequesterContext(() => Promise<IConnection>.Successful(harness.Socket))
        {
            Daemon = harness.Daemon,
            Reliability = new SocketReliabilityOptions { StallTimeout = TimeSpan.FromMilliseconds(1) }
        };
        var requester = new MicroserviceRequester(harness.Args, null, context, false, new NoopActivityProvider());
        requester.Request<CommonResponse>(Method.GET, "basic/silent").Error(_ => { });
        Thread.Sleep(10);
        var oldLogger = BeamableZLoggerProvider.LogContext.Value;
        BeamableZLoggerProvider.LogContext.Value = new BlockingWarningLogger(entered, release);
        var monitor = new ProcessHealthMonitor(new IBeamableService[] { new Service(context) });
        try
        {
            monitor.Start();
            Assert.That(entered.Wait(3000), Is.True);
            Assert.That(SpinWait.SpinUntil(() => monitor.Snapshot.State != ProcessHealthState.Starting, 2000), Is.True,
                "the watchdog must publish while the upstream warning provider is blocked");
        }
        finally
        {
            release.Set();
            monitor.Stop();
            context.FailAllPending(new Exception("test cleanup"));
            BeamableZLoggerProvider.LogContext.Value = oldLogger;
        }
    }

    [Test]
    public void ThrowingSocketCheck_RecordsFailureWithoutStoppingSampling()
    {
        using var harness = new RequesterHarness(socket => socket.AddMessageHandler(
            MessageMatcher.WithRouteContains("basic/silent"), MessageResponder.NoResponse(), MessageFrequency.OnlyOnce()),
            new TestArgs { OutboundRequestTimeoutSeconds = 0 });
        var context = new SocketRequesterContext(() => Promise<IConnection>.Successful(harness.Socket))
        {
            Daemon = harness.Daemon,
            Reliability = new SocketReliabilityOptions { StallTimeout = TimeSpan.FromMilliseconds(1) }
        };
        var requester = new MicroserviceRequester(harness.Args, null, context, false, new NoopActivityProvider());
        requester.Request<CommonResponse>(Method.GET, "basic/silent").Error(_ => { });
        var oldLogger = BeamableZLoggerProvider.LogContext.Value;
        BeamableZLoggerProvider.LogContext.Value = new ThrowingWarningLogger();
        var monitor = new ProcessHealthMonitor(new IBeamableService[] { new Service(context) }, 1,
            new ProcessHealthOptions { SampleInterval = TimeSpan.FromMilliseconds(10) });
        try
        {
            monitor.Start();
            Assert.That(SpinWait.SpinUntil(() =>
                ((long?)JObject.FromObject(monitor.Snapshot)["SocketCheckFailures"] ?? 0) > 0, 2000), Is.True,
                "a failed socket check must be visible in the cached process-health response");
            var snapshot = JObject.FromObject(monitor.Snapshot);
            Assert.That((string)snapshot["LastSocketCheckErrorType"], Is.EqualTo("InvalidOperationException"));
            Assert.That(snapshot.ToString(), Does.Not.Contain("private failure detail"));
            Assert.That(monitor.Snapshot.Instances[0].ReportedBroken, Is.True);
        }
        finally
        {
            monitor.Stop();
            context.FailAllPending(new Exception("test cleanup"));
            BeamableZLoggerProvider.LogContext.Value = oldLogger;
        }
    }

    private sealed class ThrowingWarningLogger : ILogger
    {
        public IDisposable BeginScope<TState>(TState state) => null;
        public bool IsEnabled(LogLevel level) => true;
        public void Log<TState>(LogLevel level, EventId id, TState state, Exception error, Func<TState, Exception, string> formatter)
        {
            if (level == LogLevel.Warning) throw new InvalidOperationException("private failure detail");
        }
    }

    [Test]
    public void BlockedProcessDiagnosticSink_DoesNotSuppressExistingSocketRecovery()
    {
        using var entered = new ManualResetEventSlim();
        using var release = new ManualResetEventSlim();
        using var harness = new RequesterHarness(socket => socket.AddMessageHandler(
            MessageMatcher.WithRouteContains("basic/silent"), MessageResponder.NoResponse(), MessageFrequency.OnlyOnce()),
            new TestArgs { OutboundRequestTimeoutSeconds = 0 });
        var context = new SocketRequesterContext(() => Promise<IConnection>.Successful(harness.Socket))
        {
            Daemon = harness.Daemon,
            Reliability = new SocketReliabilityOptions { StallTimeout = TimeSpan.FromMilliseconds(1), Enforce = true }
        };
        var requester = new MicroserviceRequester(harness.Args, null, context, false, new NoopActivityProvider());
        using var diagnostics = new ProcessHealthDiagnostics((_, _) => { entered.Set(); release.Wait(); });
        using var recovered = new ManualResetEventSlim();
        context.ConnectionUnhealthy += (_, _) => recovered.Set();
        var monitor = new ProcessHealthMonitor(new IBeamableService[] { new Service(context) }, 1,
            new ProcessHealthOptions(), diagnostics: diagnostics);
        try
        {
            monitor.Start();
            Assert.That(entered.Wait(3000), Is.True);
            requester.Request<CommonResponse>(Method.GET, "basic/silent").Error(_ => { });
            Assert.That(recovered.Wait(3000), Is.True,
                "existing socket recovery remains scheduled while the new diagnostic sink is blocked");
        }
        finally
        {
            release.Set();
            monitor.Stop();
            context.FailAllPending(new Exception("test cleanup"));
        }
    }

    private sealed class Service : IBeamableService
    {
        public Service(SocketRequesterContext context) => SocketContext = context;
        public SocketRequesterContext SocketContext { get; }
        public bool HasInitialized => true;
        public IDependencyProvider Provider => null;
        public Task OnShutdown(object sender, EventArgs args) => Task.CompletedTask;
    }

    private sealed class BlockingWarningLogger : ILogger
    {
        private readonly ManualResetEventSlim _entered;
        private readonly ManualResetEventSlim _release;
        public BlockingWarningLogger(ManualResetEventSlim entered, ManualResetEventSlim release)
        { _entered = entered; _release = release; }
        public IDisposable BeginScope<TState>(TState state) => null;
        public bool IsEnabled(LogLevel logLevel) => true;
        public void Log<TState>(LogLevel level, EventId id, TState state, Exception error, Func<TState, Exception, string> formatter)
        {
            if (level != LogLevel.Warning) return;
            _entered.Set();
            _release.Wait();
        }
    }
