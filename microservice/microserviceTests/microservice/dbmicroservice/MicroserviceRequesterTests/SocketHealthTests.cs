	/// <summary>
	/// Connection health detection and connection selection (beamable/BeamableProduct#4834).
	/// </summary>
	[TestFixture]
	public class SocketHealthTests : CommonTest
	{
		private const string Route = "basic/test/thing";

		private class FakeService : IBeamableService
		{
			public SocketRequesterContext SocketContext { get; set; }
			public Task OnShutdown(object sender, EventArgs args) => Task.CompletedTask;
			public bool HasInitialized => true;
			public IDependencyProvider Provider => null;
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task RequestsGoingUnanswered_ReportTheConnection()
		{
			var args = new TestArgs { OutboundRequestTimeoutSeconds = 0, EnforceSocketReliability = true };
			using var h = new RequesterHarness(s => s.AddMessageHandler(
				MessageMatcher.WithRouteContains(Route), MessageResponder.NoResponse(), MessageFrequency.AtLeast(1)), args);
			h.Context.Reliability = new SocketReliabilityOptions { StallTimeout = TimeSpan.FromSeconds(1), Enforce = true };
			var reported = new TaskCompletionSource<string>(TaskCreationOptions.RunContinuationsAsynchronously);
			h.Context.ConnectionUnhealthy += (_, reason) => reported.TrySetResult(reason);

			_ = h.Requester.Request<CommonResponse>(Method.GET, Route);

			Assert.That(await Task.WhenAny(reported.Task, Task.Delay(5000)), Is.SameAs(reported.Task));
			Assert.That(await reported.Task, Does.StartWith("no reply"));
			Assert.That(h.Context.IsHealthy, Is.False, "a connection reported broken must not be picked for new requests");
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task OneSlowRequest_DoesNotCondemnAConnectionThatStillAnswers()
		{
			var args = new TestArgs { OutboundRequestTimeoutSeconds = 0, EnforceSocketReliability = true };
			using var h = new RequesterHarness(s => s
				.AddMessageHandler(MessageMatcher.WithRouteContains("basic/slow"), MessageResponder.NoResponse(), MessageFrequency.OnlyOnce())
				.AddMessageHandler(MessageMatcher.WithRouteContains(Route),
					MessageResponder.Custom(req => req.Succeed(new CommonResponse { result = "ok" })), MessageFrequency.AtLeast(1)), args);
			h.Context.Reliability = new SocketReliabilityOptions { StallTimeout = TimeSpan.FromSeconds(1), Enforce = true };
			var reported = false;
			h.Context.ConnectionUnhealthy += (_, _) => reported = true;

			_ = h.Requester.Request<CommonResponse>(Method.GET, "basic/slow");
			for (var i = 0; i < 8; i++)
			{
				await Task.Delay(250);
				await h.Requester.Request<CommonResponse>(Method.GET, Route);
			}

			Assert.That(reported, Is.False, "replies keep arriving, so the connection works");
		}

		[Test]
		public void HealthySelection_SkipsAConnectionReportedBroken()
		{
			using var first = new RequesterHarness(_ => { });
			using var second = new RequesterHarness(_ => { });
			var services = new List<IBeamableService>
			{
				new FakeService { SocketContext = first.Context },
				new FakeService { SocketContext = second.Context }
			};

			Assert.That(SocketContextSelector.SelectHealthy(services), Is.SameAs(first.Context));

			first.Context.ReportUnhealthyConnection(null, "no reply for a while");

			Assert.That(SocketContextSelector.SelectHealthy(services), Is.SameAs(second.Context));
			Assert.That(SocketContextSelector.PreferHealthy(first.Context, services)(), Is.SameAs(second.Context));
			Assert.That(SocketContextSelector.PreferHealthy(second.Context, services)(), Is.SameAs(second.Context));
		}

		private static MicroserviceRequestContext Event(long id, string messageId) =>
			new MicroserviceRequestContext("cid", "pid", id, 200, 1, "event/test", "post", "1", new HashSet<string>())
			{
				BodyElement = JsonElement.Parse("1"),
				HeaderElement = JsonElement.Parse($"{{\"msgId\":\"{messageId}\"}}")
			};

		[Test]
		public async Task AnEventDeliveredTwice_IsHandledOnce()
		{
			var context = new SocketRequesterContext(() => throw new NotImplementedException());
			var handled = 0;
			context.Subscribe<int>("test", _ => handled++);

			await context.HandleMessage(null, Event(1, "message-1"));
			await context.HandleMessage(null, Event(2, "message-1"));

			Assert.That(handled, Is.EqualTo(1));
		}

		[Test]
		public async Task FailedEventDelivery_CanBeRetriedWithTheSameGatewayMessageId()
		{
			// A failed handler gets a 500 ack, and the gateway redelivers the event with the same message id.
			var context = new SocketRequesterContext(() => throw new NotImplementedException());
			var calls = 0;
			context.Subscribe<int>("test", _ =>
			{
				if (++calls == 1) throw new InvalidOperationException("the first delivery fails");
			});

			Assert.ThrowsAsync<InvalidOperationException>(() => context.HandleMessage(null, Event(1, "message-1")));
			await context.HandleMessage(null, Event(2, "message-1"));

			Assert.That(calls, Is.EqualTo(2), "the redelivery must run the handler again");
		}

		[Test]
		[TimeoutWithTeardown(10 * 1000)]
		public async Task ConcurrentDuplicateEvent_DoesNotSucceedBeforeTheOriginal()
		{
			var context = new SocketRequesterContext(() => throw new NotImplementedException());
			var outcome = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
			var calls = 0;
			context.Subscribe<int>("test", async _ =>
			{
				Interlocked.Increment(ref calls);
				if (!await outcome.Task) throw new InvalidOperationException("the delivery failed");
			});

			var original = context.HandleMessage(null, Event(1, "message-1"));
			await Task.Delay(100);
			var duplicate = context.HandleMessage(null, Event(2, "message-1"));
			await Task.Delay(200);

			Assert.That(duplicate.IsCompleted, Is.False, "a duplicate must not be acknowledged before the original delivery finishes");
			outcome.SetResult(false);
			Assert.ThrowsAsync<InvalidOperationException>(async () => await original);
			Assert.ThrowsAsync<InvalidOperationException>(async () => await duplicate,
				"a duplicate of a failed delivery fails too, so the gateway retries it");
			Assert.That(calls, Is.EqualTo(1));
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task ExpiredLastRequest_StillTriggersLongerStallDeadline()
		{
			var args = new TestArgs { OutboundRequestTimeoutSeconds = 1, EnforceSocketReliability = true };
			using var h = new RequesterHarness(s => s.AddMessageHandler(
				MessageMatcher.WithRouteContains(Route), MessageResponder.NoResponse(), MessageFrequency.OnlyOnce()), args);
			h.Context.Reliability = new SocketReliabilityOptions { StallTimeout = TimeSpan.FromSeconds(3), Enforce = true };
			var reported = new TaskCompletionSource<string>(TaskCreationOptions.RunContinuationsAsynchronously);
			h.Context.ConnectionUnhealthy += (_, reason) => reported.TrySetResult(reason);

			var ex = await h.Requester.Request<CommonResponse>(Method.GET, Route)
				.FinishWithin(TimeSpan.FromSeconds(5), "a request with no reply");
			Assert.That(ex, Is.InstanceOf<RequestTimeoutException>());
			Assert.That(h.Context.PendingRequestCount, Is.Zero);

			Assert.That(await Task.WhenAny(reported.Task, Task.Delay(4500)), Is.SameAs(reported.Task),
				"the connection still never answered, so it must be reported once the stall limit passes");
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task ReplyTimeoutOverride_AppliesOnlyInsideItsScope()
		{
			using var h = new RequesterHarness(s => s.AddMessageHandler(
				MessageMatcher.WithRouteContains(Route), MessageResponder.SuccessWithDelay(1500, new CommonResponse { result = "slow" }),
				MessageFrequency.Exactly(2)), new TestArgs { OutboundRequestTimeoutSeconds = 1, EnforceSocketReliability = true });

			Exception insideScope;
			using (MicroserviceRequester.OverrideReplyTimeout(TimeSpan.FromSeconds(5)))
			{
				insideScope = await h.Requester.Request<CommonResponse>(Method.GET, Route)
					.FinishWithin(TimeSpan.FromSeconds(5), "a request with a longer deadline");
			}
			var outsideScope = await h.Requester.Request<CommonResponse>(Method.GET, Route)
				.FinishWithin(TimeSpan.FromSeconds(5), "a request with the default deadline");

			Assert.That(insideScope, Is.Null, "the slow reply arrives within the overridden deadline");
			Assert.That(outsideScope, Is.InstanceOf<RequestTimeoutException>());
		}
	}
