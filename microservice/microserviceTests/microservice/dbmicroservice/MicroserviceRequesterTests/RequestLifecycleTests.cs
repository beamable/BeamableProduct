using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Beamable.Common;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common.Api;
using Beamable.Microservice.Tests.Socket;
using Beamable.Server;
using microserviceTests.microservice.Util;
using Microsoft.Extensions.Logging;
using NUnit.Framework;

namespace microserviceTests.microservice.dbmicroservice.MicroserviceRequesterTests
{
	/// <summary>
	/// The lifecycle of one outbound platform request (beamable/BeamableProduct#4834): every request ends exactly once,
	/// within its deadline, and the auth daemon's request accounting stays balanced whichever way it ends.
	/// </summary>
	[TestFixture]
	public class RequestLifecycleTests : CommonTest
	{
		private const string Route = "basic/test/thing";

		private static TestArgs EnforcedArgs(int timeoutSeconds = 1) => new TestArgs
		{
			OutboundRequestTimeoutSeconds = timeoutSeconds,
			EnforceSocketReliability = true
		};

		private static Promise<CommonResponse> Get(RequesterHarness h) =>
			h.Requester.Request<CommonResponse>(Method.GET, Route);

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task MissingReply_FailsWithinDeadline_AndRemovesListener()
		{
			using var h = new RequesterHarness(s => s.AddMessageHandler(
				MessageMatcher.WithRouteContains(Route), MessageResponder.NoResponse(), MessageFrequency.OnlyOnce()),
				EnforcedArgs());

			var ex = await Get(h).FinishWithin(TimeSpan.FromSeconds(5), "a request whose reply never arrives");

			Assert.That(ex, Is.InstanceOf<RequesterException>());
			Assert.That(((RequesterException)ex).Status, Is.EqualTo(504));
			Assert.That(h.Context.TryGetListener(-1, out _), Is.False, "the expired listener must be removed");
			Assert.That(h.Accounting.processed, Is.EqualTo(h.Accounting.sent), "request accounting must balance");
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task MissingReply_InShadowMode_KeepsWaitingButWarns()
		{
			var args = new TestArgs { OutboundRequestTimeoutSeconds = 1, EnforceSocketReliability = false };
			using var h = new RequesterHarness(s => s.AddMessageHandler(
				MessageMatcher.WithRouteContains(Route), MessageResponder.NoResponse(), MessageFrequency.OnlyOnce()),
				args);

			var request = Get(h);
			await Task.Delay(2500);

			Assert.That(request.IsCompleted, Is.False, "shadow mode must not fail the caller");
			Assert.That(GetLogs().Any(l => l.LogInfo.LogLevel == LogLevel.Warning && l.ToString().Contains("exceeded its deadline")),
				Is.True, "shadow mode must report the request that would have expired");
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task StuckSend_StillFailsCallerWithinDeadline()
		{
			var neverSent = new TaskCompletionSource<object>();
			using var h = new RequesterHarness(s => s.AddMessageHandler(
				MessageMatcher.WithRouteContains(Route), MessageResponder.CustomAsync(_ => neverSent.Task), MessageFrequency.OnlyOnce()),
				EnforcedArgs());

			var ex = await Get(h).FinishWithin(TimeSpan.FromSeconds(5), "a request stuck in the send path");

			Assert.That(ex, Is.InstanceOf<RequesterException>());
			Assert.That(((RequesterException)ex).Status, Is.EqualTo(504));
			Assert.That(h.Accounting.processed, Is.EqualTo(h.Accounting.sent));
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task TerminalSendFailure_RemovesListener_AndBalancesAccounting()
		{
			allowErrorLogs = true; // SendMessageSafely logs each failed attempt.
			using var h = new RequesterHarness(_ => { }, EnforcedArgs(timeoutSeconds: 30));
			h.Socket.MockIsConnectionOpen = false;

			var ex = await Get(h).FinishWithin(TimeSpan.FromSeconds(10), "a request whose sends all fail");

			Assert.That(ex, Is.InstanceOf<SocketClosedException>());
			Assert.That(h.Context.TryGetListener(-1, out _), Is.False, "a request that was never sent must not leave a listener");
			Assert.That(h.Accounting.processed, Is.EqualTo(h.Accounting.sent));
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task LateReply_AfterExpiry_IsNotAnError()
		{
			using var h = new RequesterHarness(s => s.AddMessageHandler(
				MessageMatcher.WithRouteContains(Route),
				MessageResponder.SuccessWithDelay(2000, new CommonResponse { result = "late" }),
				MessageFrequency.OnlyOnce()), EnforcedArgs());

			var ex = await Get(h).FinishWithin(TimeSpan.FromSeconds(5), "a request whose reply is late");
			Assert.That(ex, Is.InstanceOf<RequesterException>(), "the request must fail at its 1s deadline, before the reply");
			Assert.That(((RequesterException)ex).Status, Is.EqualTo(504));

			await Task.Delay(2000); // let the late reply arrive.
			Assert.That(GetBadLogs(), Is.Empty, "an expected late reply must not log at error level");
		}

		[Test]
		[TimeoutWithTeardown(60 * 1000)]
		public async Task ReplyRacingExpiry_CompletesEachRequestOnce()
		{
			const int count = 200;
			var random = new Random(4834);
			using var h = new RequesterHarness(s => s.AddMessageHandler(
				MessageMatcher.WithRouteContains(Route),
				MessageResponder.CustomAsync(async req =>
				{
					int delay;
					lock (random) delay = random.Next(800, 1200);
					await Task.Delay(delay);
					return req.Succeed(new CommonResponse { result = "ok" });
				}),
				MessageFrequency.Exactly(count)), EnforcedArgs());

			var completions = new int[count];
			var requests = Enumerable.Range(0, count).Select(i =>
			{
				var p = Get(h);
				p.Then(_ => Interlocked.Increment(ref completions[i]));
				p.Error(_ => Interlocked.Increment(ref completions[i]));
				return p;
			}).ToList();

			foreach (var request in requests)
			{
				await request.FinishWithin(TimeSpan.FromSeconds(10), "a request racing its deadline");
			}
			await Task.Delay(1500); // let any reply that lost the race arrive.

			Assert.That(completions, Is.All.EqualTo(1), "each request completes exactly once");
			Assert.That(GetBadLogs().Where(l => l.ToString().Contains("could not be removed")), Is.Empty);
			Assert.That(h.Accounting.processed, Is.EqualTo(h.Accounting.sent));
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task GatewayRejectsAfterFreshAuth_FailsFast_AndBalancesAccounting()
		{
			// After the gateway's timeout breaker ends a session it never re-validates it: every request gets a gateway
			// 403 even though nonce/auth still succeed (BeamableBackend ThoriumSocket.scala end() / checkAuth).
			allowErrorLogs = true;
			using var h = new RequesterHarness(s => s
					.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/nonce"),
						MessageResponder.Success(new MicroserviceNonceResponse { nonce = "n" }), MessageFrequency.AtLeast(0), "nonce", false)
					.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/auth"),
						MessageResponder.Success(new MicroserviceAuthResponse { result = "ok" }), MessageFrequency.AtLeast(0), "auth", false)
					.AddMessageHandler(MessageMatcher.WithRouteContains(Route),
						MessageResponder.Custom(req => req.AuthFailure()), MessageFrequency.AtLeast(1), "zombie", false),
				EnforcedArgs(timeoutSeconds: 5));

			var ex = await Get(h).FinishWithin(TimeSpan.FromSeconds(8), "a request the gateway always rejects");

			Assert.That(ex, Is.InstanceOf<UnauthenticatedException>());
			await Task.Delay(500);
			Assert.That(h.Accounting.processed, Is.EqualTo(h.Accounting.sent));
		}

		[Test]
		[TimeoutWithTeardown(30 * 1000)]
		public async Task LostNonceReply_AuthDaemonRetries_AndRecovers()
		{
			allowErrorLogs = true; // the daemon logs the failed attempt.
			using var h = new RequesterHarness(s => s
					.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/nonce"),
						MessageResponder.NoResponse(), MessageFrequency.OnlyOnce(), "lost nonce", false)
					.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/nonce"),
						MessageResponder.Success(new MicroserviceNonceResponse { nonce = "n" }), MessageFrequency.AtLeast(1), "nonce", false)
					.AddMessageHandler(MessageMatcher.WithRouteContains("gateway/auth"),
						MessageResponder.Success(new MicroserviceAuthResponse { result = "ok" }), MessageFrequency.AtLeast(1), "auth", false),
				EnforcedArgs(), authenticated: false);

			h.Daemon.WakeAuthThread();
			var waited = h.Context.WaitForAuthorization(TimeSpan.FromSeconds(8), "test").ToPromise();
			var ex = await waited.FinishWithin(TimeSpan.FromSeconds(10), "re-authentication after a lost nonce reply");

			Assert.That(ex, Is.Null, "the daemon must retry after the lost nonce reply and finish authenticating");
		}
	}
}
