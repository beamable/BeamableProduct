using System.Threading.Tasks;
using Beamable.Api.Autogenerated.Models;
using Beamable.Api.Autogenerated.Zones;
using Beamable.Common;
using Beamable.Common.Content;
using Beamable.Server;
using Beamable.Server.Api.Segments;
using NUnit.Framework;

namespace microserviceTests.microservice
{
	public class MicroserviceSegmentsApiTests
	{
		/// <summary>Records what the wrapper sends to the generated client.</summary>
		private class FakeZonesApi : BeamZonesApi
		{
			public string LastCustomerId;
			public string LastZoneId;
			public string LastSegmentId;
			public object LastRequest;
			public Optional<string[]> LastIds;
			public Optional<int> LastLimit;

			public FakeZonesApi() : base(null) { }

			private Promise<T> Record<T>(string customerId, string zoneId, object request, T response)
			{
				LastCustomerId = customerId;
				LastZoneId = zoneId;
				LastRequest = request;
				return Promise<T>.Successful(response);
			}

			public override Promise<SegmentResponse> PostZonesSegments(string customerId, string zoneId,
				CreateSegmentRequest gsReq, bool includeAuthHeader = true) =>
				Record(customerId, zoneId, gsReq, new SegmentResponse { segmentId = "seg-1" });

			public override Promise<SegmentResponse> PutZonesSegments(string customerId, string segmentId, string zoneId,
				UpdateSegmentRequest gsReq, bool includeAuthHeader = true)
			{
				LastSegmentId = segmentId;
				return Record(customerId, zoneId, gsReq, new SegmentResponse { segmentId = segmentId });
			}

			public override Promise<SegmentResultsResponse> PostZonesSegmentsStates(string customerId, string zoneId,
				SetSegmentStatesRequest gsReq, bool includeAuthHeader = true) =>
				Record(customerId, zoneId, gsReq, new SegmentResultsResponse());

			public override Promise<SegmentOverridesResponse> PostZonesSegmentsOverrides(string customerId, string zoneId,
				SegmentOverridesRequest gsReq, bool includeAuthHeader = true) =>
				Record(customerId, zoneId, gsReq, new SegmentOverridesResponse());

			public override Promise<SegmentResponseCursorPagedResult> GetZonesSegments(string customerId, string zoneId,
				Optional<string> cursor = null, Optional<string[]> ids = null, Optional<string> include = null,
				Optional<int> limit = null, Optional<string> managedBy = null, Optional<SegmentState> state = null,
				Optional<string[]> tags = null, bool includeAuthHeader = true)
			{
				LastIds = ids;
				LastLimit = limit;
				return Record(customerId, zoneId, null, new SegmentResponseCursorPagedResult());
			}

			public override Promise<MembershipQueryResponse> PostZonesSegmentsMemberships(string customerId, string zoneId,
				SegmentMembershipQueryRequest gsReq, bool includeAuthHeader = true) =>
				Record(customerId, zoneId, gsReq, new MembershipQueryResponse());

			public override Promise<SegmentCountsResponse> PostZonesSegmentsCounts(string customerId, string zoneId,
				SegmentCountsRequest gsReq, bool includeAuthHeader = true) =>
				Record(customerId, zoneId, gsReq, new SegmentCountsResponse());
		}

		private static readonly MicroserviceArgs Zone = new MicroserviceArgs { CustomerID = "1234", Zid = "ZONE_5678" };

		private static void AssertZone(FakeZonesApi api)
		{
			Assert.AreEqual("1234", api.LastCustomerId);
			Assert.AreEqual("ZONE_5678", api.LastZoneId);
		}

		[Test]
		public async Task CreateSegment_SendsTheRequestToTheServicesZone()
		{
			var api = new FakeZonesApi();
			var request = new CreateSegmentRequest { displayName = "Agent", managedBy = "vip" };
			var created = await new MicroserviceSegmentsApi(api, Zone).CreateSegment(request);

			Assert.AreEqual("seg-1", created.segmentId);
			Assert.AreSame(request, api.LastRequest);
			AssertZone(api);
		}

		[Test]
		public async Task UpdateSegment_SendsTheSegmentAndRequest()
		{
			var api = new FakeZonesApi();
			var request = new UpdateSegmentRequest { tags = new OptionalArrayOfString(new[] { "vip" }) };
			await new MicroserviceSegmentsApi(api, Zone).UpdateSegment("seg-2", request);

			Assert.AreEqual("seg-2", api.LastSegmentId);
			Assert.AreSame(request, api.LastRequest);
			AssertZone(api);
		}

		[Test]
		public async Task WritesAndQueries_SendTheirRequestsToTheServicesZone()
		{
			var api = new FakeZonesApi();
			var segments = new MicroserviceSegmentsApi(api, Zone);
			var states = new SetSegmentStatesRequest { segmentIds = new[] { "seg-1" }, managedBy = "vip" };
			var overrides = new SegmentOverridesRequest { items = new SegmentOverridesItem[0], managedBy = "vip" };
			var memberships = new SegmentMembershipQueryRequest { realmId = "DE_1", playerIds = new[] { 1L } };
			var counts = new SegmentCountsRequest { segmentIds = new[] { "seg-1" } };

			await segments.SetSegmentStates(states);
			Assert.AreSame(states, api.LastRequest);
			await segments.WriteOverrides(overrides);
			Assert.AreSame(overrides, api.LastRequest);
			await segments.GetMemberships(memberships);
			Assert.AreSame(memberships, api.LastRequest);
			await segments.GetCounts(counts);
			Assert.AreSame(counts, api.LastRequest);
			AssertZone(api);
		}

		[Test]
		public async Task GetSegments_AsksForAllTheIdsInOnePage()
		{
			var api = new FakeZonesApi();
			await new MicroserviceSegmentsApi(api, Zone).GetSegments("seg-1", "seg-2");

			Assert.AreEqual(new[] { "seg-1", "seg-2" }, api.LastIds.Value);
			Assert.AreEqual(2, api.LastLimit.Value);
			AssertZone(api);
		}
	}
}
