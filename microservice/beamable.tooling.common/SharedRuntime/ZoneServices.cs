using Beamable.Common;
using System.Collections.Generic;
using Beamable.Api.Autogenerated.Models;

namespace Beamable.Server
{
	/// <summary>
	/// The zone (<c>cid.zid</c>) analog of <see cref="IBeamableServices"/>. A zone runs above realms and has
	/// no player/realm SDK surface; instead it exposes customer-directory queries — what realms and zones
	/// exist for the customer — via <see cref="Customer"/>. Resolve it from a <see cref="ZoneMicroservice"/>
	/// through its <c>Services</c> accessor.
	/// </summary>
	public interface IZoneServices
	{
		/// <summary>Query the customer this zone belongs to for its realms and zones.</summary>
		IZoneCustomerApi Customer { get; }
	}

	/// <summary>
	/// Read-only directory of the customer's realms and zones, callable from a zone-scoped service.
	/// </summary>
	public interface IZoneCustomerApi
	{
		/// <summary>Lists every realm (project) that belongs to the customer, including its zone binding.</summary>
		Promise<List<Realm>> GetRealms();

		/// <summary>Lists every zone that belongs to the customer.</summary>
		Promise<List<Zone>> GetZones();
	}
	
	/// <summary>
	/// Builds a realm (<c>cid.pid</c>) scoped dependency scope on demand from within a zone service. The
	/// implementation lives in the microservice runtime (which knows how to register the realm SDK); the
	/// interface lives here so <see cref="ZoneMicroservice"/> can depend on it. See
	/// <see cref="ZoneMicroservice.AssumeRealm"/>.
	/// </summary>
	public interface IRealmScopeFactory
	{
		/// <summary>
		/// Creates a disposable realm-scoped handle (the full realm SDK, scoped to <paramref name="pid"/> and,
		/// optionally, acting on behalf of <paramref name="gamerTag"/>).
		/// </summary>
		UserRequestDataHandler CreateRealmScope(string pid, long gamerTag = 0);
	}
}
