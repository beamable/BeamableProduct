using Beamable.Api.Autogenerated.Models;
using Beamable.Common;

namespace Beamable.Server.Api.Segments
{
	/// <summary>
	/// %Microservice entry point for the zone's segments: player groups defined by a rule over stats, or by
	/// explicit per-realm includes and excludes, evaluated across the zone's realms.
	///
	/// <para>
	/// A service writes segments as its own system by setting <c>managedBy</c> on a request (<c>vip</c>, for
	/// one). A segment created that way is the system's: people may still change its labels from the portal,
	/// but its rule, realms, state and overrides change only through requests naming that system.
	/// </para>
	/// </summary>
	[ZoneScoped]
	public interface IMicroserviceSegmentsApi
	{
		/// <summary>Creates a segment. Set <c>managedBy</c> to make it the service's system's.</summary>
		/// <param name="request">The new segment.</param>
		Promise<SegmentResponse> CreateSegment(CreateSegmentRequest request);

		/// <summary>
		/// Changes a segment. Only the fields set on the request change; a change to its rule, realms, tenure or
		/// properties creates a new version.
		/// </summary>
		/// <param name="segmentId">The segment to change.</param>
		/// <param name="request">The changes.</param>
		Promise<SegmentResponse> UpdateSegment(string segmentId, UpdateSegmentRequest request);

		/// <summary>Moves segments to a state (enabled, disabled or archived), each with its own result.</summary>
		/// <param name="request">The segments and the state to move them to.</param>
		Promise<SegmentResultsResponse> SetSegmentStates(SetSegmentStatesRequest request);

		/// <summary>
		/// Includes, excludes or clears players in segments, per realm, applied in order. Each item has its own
		/// result; a refused item carries its error.
		/// </summary>
		/// <param name="request">The overrides to write.</param>
		Promise<SegmentOverridesResponse> WriteOverrides(SegmentOverridesRequest request);

		/// <summary>Gets segments by id. Ids that don't exist are left out.</summary>
		/// <param name="segmentIds">The segments to get.</param>
		Promise<SegmentResponseCursorPagedResult> GetSegments(params string[] segmentIds);

		/// <summary>Which of the segments each player is in, in one realm.</summary>
		/// <param name="request">The realm, the players and, optionally, the segments to check.</param>
		Promise<MembershipQueryResponse> GetMemberships(SegmentMembershipQueryRequest request);

		/// <summary>The segments' member counts.</summary>
		/// <param name="request">The segments to count.</param>
		Promise<SegmentCountsResponse> GetCounts(SegmentCountsRequest request);
	}
}
