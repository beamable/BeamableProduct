using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common.Api.Stats;
using Beamable.Common.Content;

namespace Beamable.Server.Api
{
	/// <summary>
	/// Builds the pieces of an <see cref="IMicroserviceAuthApi.BatchAccounts"/> request and reads its stat values back.
	/// </summary>
	public static class BatchAccountsHelper
	{
		/// <summary>
		/// How many players <see cref="IMicroserviceAuthApi.BatchAccounts"/> sends per request; larger requests are paged.
		/// </summary>
		public const int MaxPlayersPerRequest = 500;

		/// <summary>
		/// A request for <paramref name="playerIds"/>. Leave <paramref name="filter"/> null to keep every player, see
		/// <see cref="StatsFilter"/>; <paramref name="stats"/> are the stat values to return, see <see cref="Stats"/>.
		/// </summary>
		public static AuthV2BatchAccountsRequest Request(IEnumerable<long> playerIds,
			AuthV2StatsSearchRequest filter = null, bool includeAccount = true, params AuthV2BatchAccountsStats[] stats)
		{
			var request = new AuthV2BatchAccountsRequest
			{
				playerIds = new List<long>(playerIds).ToArray(),
				includeAccount = new OptionalBool(includeAccount)
			};
			if (filter != null)
			{
				request.filter = new OptionalAuthV2StatsSearchRequest(filter);
			}

			if (stats != null && stats.Length > 0)
			{
				request.stats = new OptionalArrayOfAuthV2BatchAccountsStats(stats);
			}

			return request;
		}

		/// <summary>
		/// A filter keeping only the players whose stats in the namespace satisfy every criterion. A player with no stats
		/// in the namespace never matches. The filter's item type is always <c>player</c>: the platform requires it on
		/// every stats search, and a batch lookup only accepts players.
		/// </summary>
		/// <param name="domain">The stats domain, sent as <c>game</c> or <c>client</c>.</param>
		/// <param name="access">The stats visibility, sent as <c>Public</c> or <c>Private</c>.</param>
		/// <param name="criteria">The comparisons every kept player satisfies, see <see cref="Eq"/> and its siblings.</param>
		public static AuthV2StatsSearchRequest StatsFilter(StatsDomainType domain, StatsAccessType access,
			params AuthV2StatsSearchCriteria[] criteria) => new AuthV2StatsSearchRequest
		{
			domain = Domain(domain),
			visibility = Visibility(access),
			itemType = "player",
			criteria = new OptionalArrayOfAuthV2StatsSearchCriteria(criteria)
		};

		/// <summary>
		/// One stat comparison. Prefer the helper for the operator (<see cref="Eq"/>, <see cref="Neq"/>, <see cref="Lt"/>,
		/// <see cref="Lte"/>, <see cref="Gt"/>, <see cref="Gte"/>, <see cref="In{T}"/>, <see cref="Nin{T}"/>,
		/// <see cref="Nonexistent"/>). Comparisons are type-exact, so a string stat only equals a string value.
		/// </summary>
		/// <param name="stat">
		/// The stat key, e.g. <c>email_delivery_enabled</c>; not a full stats object id. The namespace comes from the
		/// filter's domain and visibility.
		/// </param>
		/// <param name="rel">
		/// <c>eq</c> (or <c>equal</c>), <c>neq</c> (<c>notequal</c>), <c>lt</c> (<c>lessthan</c>), <c>lte</c>
		/// (<c>lessthanequal</c>), <c>gt</c> (<c>greaterthan</c>), <c>gte</c> (<c>greaterthanequal</c>), <c>in</c>,
		/// <c>nin</c> (<c>notin</c>) or <c>nonexistent</c>.
		/// </param>
		/// <param name="value">A string, integer, floating point number, bool, or a list of those (for in and nin).</param>
		public static AuthV2StatsSearchCriteria Criteria(string stat, string rel, object value) =>
			new AuthV2StatsSearchCriteria { stat = stat, rel = rel, value = ToStatsValue(value) };

		/// <summary>The stat equals <paramref name="value"/>.</summary>
		public static AuthV2StatsSearchCriteria Eq(string stat, object value) => Criteria(stat, "eq", value);

		/// <summary>The stat differs from <paramref name="value"/>.</summary>
		public static AuthV2StatsSearchCriteria Neq(string stat, object value) => Criteria(stat, "neq", value);

		/// <summary>The stat is less than <paramref name="value"/>.</summary>
		public static AuthV2StatsSearchCriteria Lt(string stat, object value) => Criteria(stat, "lt", value);

		/// <summary>The stat is less than or equal to <paramref name="value"/>.</summary>
		public static AuthV2StatsSearchCriteria Lte(string stat, object value) => Criteria(stat, "lte", value);

		/// <summary>The stat is greater than <paramref name="value"/>.</summary>
		public static AuthV2StatsSearchCriteria Gt(string stat, object value) => Criteria(stat, "gt", value);

		/// <summary>The stat is greater than or equal to <paramref name="value"/>.</summary>
		public static AuthV2StatsSearchCriteria Gte(string stat, object value) => Criteria(stat, "gte", value);

		/// <summary>The stat equals one of <paramref name="values"/>.</summary>
		public static AuthV2StatsSearchCriteria In<T>(string stat, params T[] values) => Criteria(stat, "in", values);

		/// <summary>The stat equals none of <paramref name="values"/>.</summary>
		public static AuthV2StatsSearchCriteria Nin<T>(string stat, params T[] values) => Criteria(stat, "nin", values);

		/// <summary>The player has no value for the stat.</summary>
		public static AuthV2StatsSearchCriteria Nonexistent(string stat) => Criteria(stat, "nonexistent", null);

		/// <summary>The stat values to return for each player.</summary>
		/// <param name="domain">The stats domain, sent as <c>game</c> or <c>client</c>.</param>
		/// <param name="access">The stats visibility, sent as <c>Public</c> or <c>Private</c>.</param>
		/// <param name="keys">The stat keys to return. None returns every stat in the namespace.</param>
		public static AuthV2BatchAccountsStats Stats(StatsDomainType domain, StatsAccessType access, params string[] keys) =>
			new AuthV2BatchAccountsStats
			{
				domain = Domain(domain),
				visibility = Visibility(access),
				keys = new OptionalArrayOfString(keys)
			};

		/// <summary>
		/// A requested stat value as text (numbers in the invariant culture, booleans as <c>true</c>/<c>false</c>, lists as
		/// JSON), or null when the player has none.
		/// </summary>
		public static string GetStat(this AuthV2BatchAccountsPlayer player, StatsDomainType domain, StatsAccessType access,
			string key)
		{
			if (player.stats == null || !player.stats.HasValue)
			{
				return null;
			}

			var domainName = Domain(domain);
			var visibility = Visibility(access);
			foreach (var stat in player.stats.Value)
			{
				if (stat.domain != domainName || stat.visibility != visibility || stat.key != key)
				{
					continue;
				}

				switch (stat.value?.ToRawValue())
				{
					case null: return null;
					case string text: return text;
					case bool flag: return flag ? "true" : "false";
					case IFormattable number: return number.ToString(null, CultureInfo.InvariantCulture);
					default: return stat.value.ToJson();
				}
			}

			return null;
		}

		/// <summary>The player's account email, or null when the account wasn't requested or has none.</summary>
		public static string GetEmail(this AuthV2BatchAccountsPlayer player) =>
			player.account != null && player.account.HasValue && player.account.Value.email != null &&
			player.account.Value.email.HasValue
				? player.account.Value.email.Value
				: null;

		private static string Domain(StatsDomainType domain) => domain.ToString().ToLowerInvariant();

		private static AuthV2StatsVisibility Visibility(StatsAccessType access) =>
			access == StatsAccessType.Public ? AuthV2StatsVisibility.Public : AuthV2StatsVisibility.Private;

		private static AuthV2StatsValue ToStatsValue(object value)
		{
			switch (value)
			{
				case null: return new AuthV2StatsValue();
				case string text: return new AuthV2StatsValue { StringValue = new OptionalString(text) };
				case bool flag: return new AuthV2StatsValue { BoolValue = new OptionalBool(flag) };
				case int _:
				case long _:
				case short _:
				case byte _:
					return new AuthV2StatsValue { IntValue = new OptionalLong(Convert.ToInt64(value)) };
				case float _:
				case double _:
				case decimal _:
					return new AuthV2StatsValue { DoubleValue = Convert.ToDouble(value) };
				case IEnumerable items:
					var values = new List<AuthV2StatsValue>();
					foreach (var item in items)
					{
						values.Add(ToStatsValue(item));
					}

					return new AuthV2StatsValue { ArrayValue = new OptionalArrayOfAuthV2StatsValue(values.ToArray()) };
				default:
					throw new ArgumentException(
						$"A stat value must be a string, number, bool or a list of those, got {value.GetType().Name}.",
						nameof(value));
			}
		}
	}
}
