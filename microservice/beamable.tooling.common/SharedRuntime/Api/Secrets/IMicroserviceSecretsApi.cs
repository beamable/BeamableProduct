using Beamable.Api.Autogenerated.Models;
using Beamable.Common;

namespace Beamable.Server.Api.Secrets
{
	/// <summary>
	/// %Microservice entry point for the Secrets feature: an encrypted key/value store.
	///
	/// <para>
	/// Secrets are scoped to the scope the service runs in. In a realm <see cref="Microservice"/> they are the
	/// realm's (<c>cid.pid</c>) secrets; in a <see cref="ZoneMicroservice"/> they are the zone's (<c>cid.zid</c>)
	/// secrets. To reach a realm's secrets from a zone service, use <c>AssumeRealm(pid)</c> and its
	/// <c>Services.Secrets</c>.
	/// </para>
	///
	/// <para>
	/// Keys are at most 512 characters and values at most 64 KiB. The <c>beamable/</c> key prefix is reserved.
	/// </para>
	/// </summary>
	// Deliberately carries neither [RealmScoped] nor [ZoneScoped]: the same contract is registered in both
	// containers, and acts on whichever scope the request runs in.
	public interface IMicroserviceSecretsApi
	{
		/// <summary>
		/// Gets the value of a secret. Fails with a 404 <c>SecretNotFound</c> error when the key does not exist.
		/// </summary>
		/// <param name="key">The secret's key.</param>
		Promise<string> GetSecret(string key);

		/// <summary>
		/// Creates the secret, or replaces its value if it already exists.
		/// </summary>
		/// <param name="key">The secret's key.</param>
		/// <param name="value">The value to store.</param>
		Promise SetSecret(string key, string value);

		/// <summary>
		/// Deletes a secret.
		/// </summary>
		/// <param name="key">The secret's key.</param>
		Promise DeleteSecret(string key);

		/// <summary>
		/// Lists one page of secret metadata (key, data key, algorithm, last update). Values are never listed.
		/// </summary>
		/// <param name="cursor">
		/// The <c>nextCursor</c> of a previous page, or null for the first page.
		/// </param>
		Promise<RealmSecretInfoCursorPagedResult> ListSecrets(string cursor = null);
	}
}
