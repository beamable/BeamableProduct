using System;
using System.Collections.Generic;
using System.Text;
using Beamable.Api.Autogenerated.Models;
using Beamable.Serialization;
using Beamable.Serialization.SmallerJSON;
using Beamable.Server.Common;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using NUnit.Framework;

namespace tests;

public class GeneratedTransportSerializationTests
{
	public static IEnumerable<TestCaseData> NestedJsonCases()
	{
		foreach (var model in new[] { "ContentMeta", "SupportedFederation", "FederationInfo" })
		foreach (var json in new[] { null, "null", "{}", "{\"enabled\":true,\"count\":42,\"nested\":{\"items\":[\"a\",null,3]}}" })
			yield return new TestCaseData(model, json);
	}

	[TestCaseSource(nameof(NestedJsonCases))]
	public void ExplicitJsonPreservesNestedPayloadAndOptionalPresence(string model, string? nestedJson)
	{
		var value = Create(model);
		var field = value.GetType().GetField(model == "ContentMeta" ? "data" : "settings")!;
		field.SetValue(value, nestedJson == null ? new OptionalJsonString() : new OptionalJsonString(JsonString.FromJson(nestedJson)));
		var json = JsonSerializable.ToJson(value);
		var payload = JObject.Parse(json);
		Assert.That(payload.ContainsKey(field.Name), Is.EqualTo(nestedJson != null));
		if (nestedJson != null) Assert.That(JToken.DeepEquals(payload[field.Name], JToken.Parse(nestedJson)), Is.True);
		var restored = Read(model, json);
		Assert.That(((OptionalJsonString)field.GetValue(restored)!).HasValue, Is.EqualTo(nestedJson != null));
		Assert.That(JToken.DeepEquals(JObject.Parse(JsonSerializable.ToJson(restored)), payload), Is.True);
	}

	[TestCaseSource(nameof(NestedJsonCases))]
	public void ReflectionJsonKeepsOptionalFields(string model, string? nestedJson)
	{
		var value = Create(model);
		var field = value.GetType().GetField(model == "ContentMeta" ? "data" : "settings")!;
		field.SetValue(value, nestedJson == null ? new OptionalJsonString() : new OptionalJsonString(JsonString.FromJson(nestedJson)));
		var smaller = JObject.Parse(Json.Serialize(value, new StringBuilder()));
		Assert.That(smaller.ContainsKey(field.Name), Is.True);
		Assert.That((bool)smaller[field.Name]!["HasValue"]!, Is.EqualTo(nestedJson != null));
		// Reflection JSON preserves the wrapper, but does not encode JsonString's private data.
		Assert.That(smaller[field.Name]!["Value"]!.Type, Is.EqualTo(nestedJson == null ? JTokenType.Null : JTokenType.Object));
		var newtonsoft = JObject.Parse(JsonConvert.SerializeObject(value, UnitySerializationSettings.Instance));
		Assert.That(newtonsoft.ContainsKey(field.Name), Is.EqualTo(nestedJson != null));
		if (nestedJson != null) Assert.That(newtonsoft[field.Name]!.ToString(Formatting.None), Is.EqualTo("{}"));
	}

	[TestCase("[]")]
	[TestCase("[[],[\"segment.a\"],[\"segment.b\",\"quote\\\"value\"]]")]
	public void AudienceRowsPreservePayloadsAndExistingReadback(string rows)
	{
		var request = new AudienceRequest { include = JsonConvert.DeserializeObject<string[][]>(rows)! };
		var explicitJson = JsonSerializable.ToJson(request);
		var smallerJson = Json.Serialize(request, new StringBuilder());
		var newtonsoftJson = JsonConvert.SerializeObject(request, UnitySerializationSettings.Instance);
		foreach (var json in new[] { explicitJson, smallerJson, newtonsoftJson })
			Assert.That(JToken.DeepEquals(JObject.Parse(json)["include"], JToken.Parse(rows)), Is.True);
		// The explicit loader currently restores all inner arrays as null.
		Assert.That(JsonSerializable.FromJson<AudienceRequest>(explicitJson).include,
			Is.EqualTo(new string[request.include.Length][]));
		Assert.That(Json.Deserialize<AudienceRequest>(smallerJson).include, Is.EqualTo(request.include));
		Assert.That(JsonConvert.DeserializeObject<AudienceRequest>(newtonsoftJson, UnitySerializationSettings.Instance)!.include,
			Is.EqualTo(request.include));
		Assert.That(JObject.Parse(explicitJson).ContainsKey("exclude"), Is.False);
	}

	private static JsonSerializable.ISerializable Create(string model) => model switch
	{
		"ContentMeta" => new ContentMeta(),
		"SupportedFederation" => new SupportedFederation(),
		"FederationInfo" => new FederationInfo { namespaceKey = "inventory", service = "items" },
		_ => throw new ArgumentException(model)
	};

	private static JsonSerializable.ISerializable Read(string model, string json) => model switch
	{
		"ContentMeta" => JsonSerializable.FromJson<ContentMeta>(json),
		"SupportedFederation" => JsonSerializable.FromJson<SupportedFederation>(json),
		"FederationInfo" => JsonSerializable.FromJson<FederationInfo>(json),
		_ => throw new ArgumentException(model)
	};
}
