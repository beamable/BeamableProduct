using System;
using System.IO;
using System.Linq;
using System.Text.Json;
using System.Threading.Tasks;
using Beamable.Api.Autogenerated.Content;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common;
using Beamable.Common.Content;
using Beamable.Common.Dependencies;
using cli;
using cli.Content;
using cli.Services;
using Moq;
using NUnit.Framework;

namespace tests;

public class ContentPsNoAutoSyncTests
{
    private string root = null!, folder = null!;
    private ContentService service = null!;
    private ContentPsCommandArgs args = null!;
    private ClientManifestJsonResponse before = null!, after = null!;

    [SetUp]
    public void SetUp()
    {
        root = Path.Combine(Path.GetTempPath(), "beam-content-observe-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Path.Combine(root, ConfigService.CFG_FOLDER));
        var config = new ConfigService(null);
        config.SetWorkingDir(root);
        var api = new Mock<IContentApi>(MockBehavior.Strict);
        api.Setup(x => x.GetManifestPublicJson(It.IsAny<Optional<string>>(), It.IsAny<Optional<bool>>(), It.IsAny<Optional<string>>(), true))
            .Returns((Optional<string> id, Optional<bool> omit, Optional<string> uid, bool auth) =>
                Promise<ClientManifestJsonResponse>.Successful(uid != null && uid.HasValue && uid.Value == "before" ? before : after));
        var requester = new CliRequester(new RequesterInfo(Guid.NewGuid().ToString("N"), "test-pid", "fake", "fake", "http://127.0.0.1:1"));
        service = new ContentService(requester, config, api.Object, null!, null!, null!, null!);
        folder = service.EnsureContentPathForRealmExists(out _, "test-pid", "global");
        var context = new Mock<IAppContext>();
        context.SetupGet(x => x.Cid).Returns("test-cid");
        context.SetupGet(x => x.Pid).Returns("test-pid");
        var dependencies = new Mock<IDependencyProvider>();
        dependencies.Setup(x => x.GetService<ContentService>()).Returns(service);
        var provider = new Mock<IServiceProvider>();
        provider.Setup(x => x.GetService(typeof(IDependencyProvider))).Returns(dependencies.Object);
        provider.Setup(x => x.GetService(typeof(IAppContext))).Returns(context.Object);
        provider.Setup(x => x.GetService(typeof(AppLifecycle))).Returns(new AppLifecycle());
        args = new ContentPsCommandArgs { NoAutoSync = true, ManifestId = "global", Provider = provider.Object };
    }

    [TearDown]
    public void TearDown() => Directory.Delete(root, true);

    [TestCase(true)]
    [TestCase(false)]
    public async Task Startup_preserves_local_tags_and_reference_when_auto_sync_is_disabled(bool noAutoSync)
    {
        var props = JsonSerializer.SerializeToElement(new { damage = new { data = 10 } });
        var file = new ContentFile { Id = "items.sword", Properties = props,
            Tags = JsonSerializer.SerializeToElement(new[] { "designer-local" }), FetchedFromManifestUid = "before" };
        await service.SaveContentFile(folder, file);
        var entry = new ClientContentInfoJson { contentId = file.Id, version = "v1",
            checksum = ContentService.CalculateChecksum(in file), tags = new[] { "published" }, uri = "http://127.0.0.1:1/unused" };
        before = new ClientManifestJsonResponse { uid = "before", entries = new[] { entry } };
        after = new ClientManifestJsonResponse { uid = "after", entries = new[] { entry } };
        var path = Path.Combine(folder, file.Id + ".json");
        var original = File.ReadAllBytes(path);
        args.NoAutoSync = noAutoSync;

        var command = new CapturingCommand();
        await command.Handle(args);

        Assert.That(command.Result!.RelevantManifestsAgainstLatest.Single().Entries.Single().FullId, Is.EqualTo(file.Id));
        if (noAutoSync)
            Assert.That(File.ReadAllBytes(path), Is.EqualTo(original));
        else
        {
            using var saved = JsonDocument.Parse(File.ReadAllText(path));
            Assert.That(saved.RootElement.GetProperty("tags")[0].GetString(), Is.EqualTo("published"));
            Assert.That(saved.RootElement.GetProperty("referenceManifestId").GetString(), Is.EqualTo("after"));
        }
    }

    [Test]
    public async Task Startup_does_not_populate_a_new_folder_when_auto_sync_is_disabled()
    {
        Directory.Delete(folder);
        before = new ClientManifestJsonResponse { uid = "before", entries = Array.Empty<ClientContentInfoJson>() };
        after = new ClientManifestJsonResponse { uid = "after", entries = new[] {
            new ClientContentInfoJson { contentId = "items.remote", version = "v1", checksum = "remote",
                tags = Array.Empty<string>(), uri = "http://127.0.0.1:1/must-not-download" } } };
        var command = new CapturingCommand();

        await command.Handle(args);

        Assert.That(Directory.GetFiles(folder), Is.Empty);
        Assert.That(command.Result!.RelevantManifestsAgainstLatest.Single().Entries.Single().FullId, Is.EqualTo("items.remote"));
        Assert.That(command.Result.SyncReports, Is.Empty);
    }

    private sealed class CapturingCommand : ContentPsCommand
    {
        public ContentPsCommandEvent? Result;
        protected override void LogResult(object result) => Result = (ContentPsCommandEvent)result;
    }
}
