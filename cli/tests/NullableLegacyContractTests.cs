using System.Collections.Generic;
using System.Text;
using Beamable.Common.Api.Tournaments;
using Beamable.Experimental.Api.Lobbies;
using Beamable.Serialization.SmallerJSON;
using Newtonsoft.Json.Linq;
using NUnit.Framework;

namespace tests;

public class NullableLegacyContractTests
{
    [TestCase(null)]
    [TestCase(0)]
    [TestCase(8)]
    public void LobbyRequestJsonRetainsNullableValues(int? value)
    {
        var create = new CreateLobbyRequest("room", "description", "Open", "game_types.duel", new List<Tag>(), value, value);
        var update = new UpdateLobbyRequest("room", "description", "Open", "42", "game_types.duel", value);
        var created = JObject.Parse(Json.Serialize(create, new StringBuilder()));
        var updated = JObject.Parse(Json.Serialize(update, new StringBuilder()));
        Assert.That(created["maxPlayers"], Is.EqualTo(value.HasValue ? new JValue(value.Value) : JValue.CreateNull()));
        Assert.That(created["passcodeLength"], Is.EqualTo(value.HasValue ? new JValue(value.Value) : JValue.CreateNull()));
        Assert.That(updated["maxPlayers"], Is.EqualTo(value.HasValue ? new JValue(value.Value) : JValue.CreateNull()));
        Assert.That((string)created["name"], Is.EqualTo("room"));
        Assert.That((string)updated["newHost"], Is.EqualTo("42"));
    }

    [TestCase(null)]
    [TestCase(-2)]
    [TestCase(0)]
    [TestCase(3)]
    public void TournamentConversionKeepsUnknownDistinctFromZero(int? value)
    {
        var source = new Beamable.Api.Autogenerated.Models.TournamentEntry { playerId = 42 };
        if (value.HasValue)
        {
            source.nextStageChange.SetValue(value.Value);
            source.previousStageChange.SetValue(value.Value);
        }
        var result = TournamentEntry.FromOpenApi(source);
        Assert.That(result.nextStageChange, Is.EqualTo(value));
        Assert.That(result.previousStageChange, Is.EqualTo(value));
        Assert.That(result.playerId, Is.EqualTo(42));
        var restored = Newtonsoft.Json.JsonConvert.DeserializeObject<TournamentEntry>(Json.Serialize(result, new StringBuilder()));
        Assert.That(restored.nextStageChange, Is.EqualTo(value));
        Assert.That(restored.previousStageChange, Is.EqualTo(value));
    }
}
