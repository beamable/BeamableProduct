	private const string PID = "test-pid";
	private const string MANIFEST_ID = "global";

	[Test]
	public async Task A_content_file_deleted_during_read_does_not_block_the_scan()
	{
		var testRoot = Path.Combine(Path.GetTempPath(), $"beam-content-watcher-{Guid.NewGuid():N}");
		Directory.CreateDirectory(Path.Combine(testRoot, ConfigService.CFG_FOLDER));

		try
		{
			var config = new ConfigService(null);
			config.SetWorkingDir(testRoot);
			var requester = new CliRequester(new RequesterInfo(
				"test-cid",
				PID,
				"test-access-token",
				"test-refresh-token",
				"http://localhost"));
			var contentService = new ContentService(requester, config, null!, null!, null!, null!, null!);
			var contentFolder = contentService.EnsureContentPathForRealmExists(out _, PID, MANIFEST_ID);
			var contentFilePath = Path.Combine(contentFolder, "items.deleted-during-read.json");
			await File.WriteAllTextAsync(contentFilePath, "");

			var scan = contentService.GetAllContentFiles(
				new ClientManifestJsonResponse
				{
					entries = Array.Empty<ClientContentInfoJson>(),
					uid = new OptionalString("test-manifest")
				},
				MANIFEST_ID,
				ContentFilterType.ExactIds,
				new[] { "items.deleted-during-read" },
				getLocalStateOnly: true);
			Assert.That(scan.IsCompleted, Is.False, "the scanner must have observed the empty file before it is deleted");

			await DeleteWithRetryAsync(contentFilePath);

			var result = await scan.WaitAsync(TimeSpan.FromSeconds(1));
			Assert.That(result.ContentFiles, Is.Empty);
		}
		finally
		{
			if (Directory.Exists(testRoot))
			{
				Directory.Delete(testRoot, true);
			}
		}
	}

	[Test]
	public async Task A_content_file_deleted_after_it_is_read_is_represented_once_as_deleted()
	{
		var testRoot = Path.Combine(Path.GetTempPath(), $"beam-content-watcher-{Guid.NewGuid():N}");
		Directory.CreateDirectory(Path.Combine(testRoot, ConfigService.CFG_FOLDER));

		try
		{
			var config = new ConfigService(null);
			config.SetWorkingDir(testRoot);
			var requester = new CliRequester(new RequesterInfo(
				"test-cid",
				PID,
				"test-access-token",
				"test-refresh-token",
				"http://localhost"));
			var contentService = new ContentService(requester, config, null!, null!, null!, null!, null!);
			var contentFolder = contentService.EnsureContentPathForRealmExists(out _, PID, MANIFEST_ID);
			const string contentId = "items.item_0959";
			var contentFilePath = Path.Combine(contentFolder, $"{contentId}.json");
			await File.WriteAllTextAsync(contentFilePath,
				"{\"properties\":{},\"tags\":[],\"referenceManifestId\":\"test-manifest\"}");

			// Keep the remote-file reconciliation busy after the local read starts. This models the
			// large manifest from the reported failure and makes the delete/read race deterministic.
			var unrelatedEntry = ManifestEntry("items.unrelated");
			var manifestEntries = Enumerable.Repeat(unrelatedEntry, 1_000_000)
				.Append(ManifestEntry(contentId))
				.ToArray();

			var scan = Task.Run(() => contentService.GetAllContentFiles(
				new ClientManifestJsonResponse
				{
					entries = manifestEntries,
					uid = new OptionalString("test-manifest")
				},
				MANIFEST_ID,
				ContentFilterType.ExactIds,
				new[] { contentId },
				getLocalStateOnly: true));

			await Task.Delay(25);
			await DeleteWithRetryAsync(contentFilePath);

			var result = await scan.WaitAsync(TimeSpan.FromSeconds(30));
			var matchingEntries = result.ContentFiles.Where(contentFile => contentFile.Id == contentId).ToArray();
			Assert.Multiple(() =>
			{
				Assert.That(matchingEntries, Has.Length.EqualTo(1));
				Assert.That(matchingEntries[0].LocalFilePath, Is.Empty);
				Assert.That(result.PerIdContentFiles[contentId].LocalFilePath, Is.Empty);
			});
		}
		finally
		{
			if (Directory.Exists(testRoot))
			{
				Directory.Delete(testRoot, true);
			}
		}
	}

	[Test]
	public async Task An_internal_buffer_overflow_reconciles_from_disk_and_emits_a_full_rebuild()
	{
		var recognized = ContentService.TryCreateWatcherRecoveryChange(
			new InternalBufferOverflowException("test overflow"),
			PID,
			MANIFEST_ID,
			out var recoveryChange);
		var batch = ContentService.BatchLocalFileChanges(new[] { recoveryChange, recoveryChange }, PID, MANIFEST_ID);
		var rescanCount = 0;

		var result = await ContentPsCommand.CreateFullRebuildEventIfRequired(
			batch,
			() =>
			{
				rescanCount++;
				return Task.FromResult(new LocalContentFiles
				{
					ContentFiles = new List<ContentFile> { DeletedContentFile("items.sword") }
				});
			},
			"test-cid",
			PID,
			MANIFEST_ID);

		Assert.That(result, Is.Not.Null);
		Assert.Multiple(() =>
		{
			Assert.That(recognized, Is.True);
			Assert.That(batch.RequiresFullRescan, Is.True);
			Assert.That(batch.AllFileChanges, Is.Empty,
				"the overflow sentinel must not be processed as a content-file delta");
			Assert.That(rescanCount, Is.EqualTo(1));
			Assert.That(result.EventType, Is.EqualTo(ContentPsCommandEvent.EVT_TYPE_FullRebuild));
			Assert.That(result.RelevantManifestsAgainstLatest, Has.Count.EqualTo(1));
			Assert.That(result.RelevantManifestsAgainstLatest.Single().OwnerCid, Is.EqualTo("test-cid"));
			Assert.That(result.RelevantManifestsAgainstLatest.Single().OwnerPid, Is.EqualTo(PID));
			Assert.That(result.RelevantManifestsAgainstLatest.Single().ManifestId, Is.EqualTo(MANIFEST_ID));
			Assert.That(result.RelevantManifestsAgainstLatest.Single().Entries.Select(entry => entry.FullId),
				Is.EqualTo(new[] { "items.sword" }));
			Assert.That(result.ToRemoveLocalEntries, Is.Empty,
				"a full rebuild replaces state and must not carry an incremental removal list");
		});
	}

	[Test]
	public void A_non_overflow_watcher_error_does_not_request_a_full_rescan()
	{
		var recognized = ContentService.TryCreateWatcherRecoveryChange(
			new IOException("watch root disappeared"),
			PID,
			MANIFEST_ID,
			out var recoveryChange);

		Assert.Multiple(() =>
		{
			Assert.That(recognized, Is.False);
			Assert.That(recoveryChange.RequiresFullRescan, Is.False);
		});
	}

	[Test]
	public void A_recoverable_watcher_overflow_is_logged_as_a_warning_and_queues_recovery()
	{
		var logger = new RecordingLogger();
		var changes = Channel.CreateUnbounded<ChangedContentFile>();

		ContentService.HandleWatcherError(
			new InternalBufferOverflowException("test overflow"),
			PID,
			MANIFEST_ID,
			logger,
			changes.Writer);

		Assert.Multiple(() =>
		{
			Assert.That(logger.Levels, Is.EqualTo(new[] { LogLevel.Warning }));
			Assert.That(changes.Reader.TryRead(out var recoveryChange), Is.True);
			Assert.That(recoveryChange.RequiresFullRescan, Is.True);
		});
	}

	[Test]
	public void An_unrecognized_watcher_failure_is_logged_as_an_error_without_queuing_recovery()
	{
		var logger = new RecordingLogger();
		var changes = Channel.CreateUnbounded<ChangedContentFile>();

		ContentService.HandleWatcherError(
			new IOException("watch root disappeared"),
			PID,
			MANIFEST_ID,
			logger,
			changes.Writer);

		Assert.Multiple(() =>
		{
			Assert.That(logger.Levels, Is.EqualTo(new[] { LogLevel.Error }));
			Assert.That(changes.Reader.TryRead(out _), Is.False);
		});
	}

	[Test]
	public async Task A_normal_file_change_does_not_run_the_expensive_full_rescan()
	{
		var batch = ContentService.BatchLocalFileChanges(new[]
		{
			new ChangedContentFile
			{
				OwnerPid = PID,
				OwnerManifestId = MANIFEST_ID,
				ContentId = "items.sword",
				FullFilePath = "items.sword.json",
				OldFullFilePath = "items.sword.json"
			}
		}, PID, MANIFEST_ID);
		var rescanCount = 0;

		var result = await ContentPsCommand.CreateFullRebuildEventIfRequired(
			batch,
			() =>
			{
				rescanCount++;
				return Task.FromResult(new LocalContentFiles());
			},
			"test-cid",
			PID,
			MANIFEST_ID);

		Assert.Multiple(() =>
		{
			Assert.That(batch.RequiresFullRescan, Is.False);
			Assert.That(batch.AllFileChanges, Has.Count.EqualTo(1));
			Assert.That(rescanCount, Is.Zero);
			Assert.That(result, Is.Null);
		});
	}

	[Test]
	public void A_recovery_request_for_another_manifest_is_not_consumed_by_this_watcher()
	{
		ContentService.TryCreateWatcherRecoveryChange(
			new InternalBufferOverflowException("test overflow"),
			PID,
			"other-manifest",
			out var recoveryChange);

		var batch = ContentService.BatchLocalFileChanges(new[] { recoveryChange }, PID, MANIFEST_ID);

		Assert.Multiple(() =>
		{
			Assert.That(batch.RequiresFullRescan, Is.False);
			Assert.That(batch.AllFileChanges, Is.Empty);
		});
	}

	private static ContentFile DeletedContentFile(string contentId)
	{
		using var tags = JsonDocument.Parse("[]");
		return new ContentFile
		{
			Id = contentId,
			LocalFilePath = "",
			PropertiesChecksum = "local-checksum",
			ReferenceContent = new ClientContentInfoJson
			{
				contentId = contentId,
				checksum = "remote-checksum",
				createdAt = 123L,
				tags = Array.Empty<string>()
			},
			Tags = tags.RootElement.Clone(),
			FetchedFromManifestUid = "reference-manifest"
		};
	}

	private static ClientContentInfoJson ManifestEntry(string contentId)
	{
		return new ClientContentInfoJson
		{
			contentId = contentId,
			checksum = "remote-checksum",
			createdAt = 123L,
			tags = Array.Empty<string>(),
			version = "remote-version"
		};
	}

	private static async Task DeleteWithRetryAsync(string path)
	{
		for (var attempt = 0; attempt < 100; attempt++)
		{
			try
			{
				File.Delete(path);
				return;
			}
			catch (IOException)
			{
				await Task.Delay(5);
			}
		}

		Assert.Fail($"Could not delete the test content file: {path}");
	}

	private sealed class RecordingLogger : ILogger
	{
		public List<LogLevel> Levels { get; } = new();

		public IDisposable? BeginScope<TState>(TState state) where TState : notnull => NullScope.Instance;

		public bool IsEnabled(LogLevel logLevel) => true;

		public void Log<TState>(LogLevel logLevel, EventId eventId, TState state, Exception? exception,
			Func<TState, Exception?, string> formatter)
		{
			Levels.Add(logLevel);
		}

		private sealed class NullScope : IDisposable
		{
			public static readonly NullScope Instance = new();

			public void Dispose()
			{
			}
		}
	}
}
