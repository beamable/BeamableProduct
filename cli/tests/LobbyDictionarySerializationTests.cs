using System.Collections.Generic;
using System.Text;
using Beamable.Experimental.Api.Lobbies;
using Beamable.Serialization;
using Beamable.Serialization.SmallerJSON;
using Beamable.Server.Common;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using NUnit.Framework;
using ApiLobby = Beamable.Api.Autogenerated.Models.Lobby;

namespace tests;

public class LobbyDictionarySerializationTests
{
	[TestCase("null")]
	[TestCase("empty")]
	[TestCase("populated")]
	public void SmallerJsonPreservesNestedDictionaries(string state)
	{
		var response = Response(state);
		var json = Json.Serialize(response, new StringBuilder());
		AssertPayload(json, response.results[0]);
		var payload = JObject.Parse(json);
		// DateTime's existing reflection format cannot round-trip through SmallerJSON.
		((JObject)payload["results"]![0]!["players"]![0]!).Remove("joined");
		var restored = Json.Deserialize<LobbyQueryResponse>(payload.ToString()).results[0];
		// SmallerJSON reads null dictionaries as empty collections.
		Assert.That(restored.data, Is.EqualTo(response.results[0].data ?? new Dictionary<string, string>()));
		Assert.That(restored.players[0].stats, Is.EqualTo(response.results[0].players[0].stats ?? new Dictionary<string, string>()));
		Assert.That(restored.lobbyId, Is.EqualTo("lobby-1"));
		Assert.That(restored.players[0].playerId, Is.EqualTo("42"));
	}

	[TestCase("null")]
	[TestCase("empty")]
	[TestCase("populated")]
	public void UnityCompatibleNewtonsoftPreservesNestedDictionaries(string state)
	{
		var response = Response(state);
		var json = JsonConvert.SerializeObject(response, UnitySerializationSettings.Instance);
		AssertPayload(json, response.results[0]);
		var restored = JsonConvert.DeserializeObject<LobbyQueryResponse>(json, UnitySerializationSettings.Instance)!.results[0];
		Assert.That(restored.data, Is.EqualTo(response.results[0].data));
		Assert.That(restored.players[0].stats, Is.EqualTo(response.results[0].players[0].stats));
		Assert.That(restored.lobbyId, Is.EqualTo("lobby-1"));
		Assert.That(restored.players[0].playerId, Is.EqualTo("42"));
	}

	[TestCase("{}")]
	[TestCase("{\"map\":\"arena\",\"mode\":\"teams\"}")]
	public void GeneratedResponseConversionPreservesLobbyData(string data)
	{
		var json = "{\"lobbyId\":\"lobby-1\",\"restriction\":\"Open\",\"data\":" + data
			+ ",\"players\":[{\"playerId\":\"42\",\"tags\":[{\"name\":\"team\",\"value\":\"blue\"}]}]}";
		var generated = JsonSerializable.FromJson<ApiLobby>(json);
		var lobby = generated.ConvertLobbyType();
		Assert.That(JToken.DeepEquals(JObject.Parse(Json.Serialize(lobby.data, new StringBuilder())), JObject.Parse(data)), Is.True);
		Assert.That(lobby.lobbyId, Is.EqualTo("lobby-1"));
		Assert.That(lobby.players[0].playerId, Is.EqualTo("42"));
		Assert.That(lobby.players[0].tags[0].value, Is.EqualTo("blue"));
		// The generated response has no player-stats field; conversion currently leaves it null.
		Assert.That(lobby.players[0].stats, Is.Null);
	}

	[Test]
	public void MissingDictionariesKeepExistingDefaults()
	{
		const string json = "{\"lobbyId\":\"lobby-1\",\"players\":[{\"playerId\":\"42\"}]}";
		var smaller = Json.Deserialize<Lobby>(json);
		Assert.That(smaller.data, Is.Empty);
		Assert.That(smaller.players[0].stats, Is.Empty);
		var newtonsoft = JsonConvert.DeserializeObject<Lobby>(json, UnitySerializationSettings.Instance)!;
		Assert.That(newtonsoft.data, Is.Null);
		Assert.That(newtonsoft.players[0].stats, Is.Null);
	}

	private static LobbyQueryResponse Response(string state) => new()
	{
		results = new List<Lobby>
		{
			new()
			{
				lobbyId = "lobby-1", name = "Arena", restriction = "Open", maxPlayers = 4,
				data = Values(state), players = new List<LobbyPlayer>
				{
					new() { playerId = "42", tags = new List<Tag>(), stats = Values(state) }
				}
			}
		}
	};

	private static Dictionary<string, string>? Values(string state) => state == "null" ? null : state == "empty"
		? new Dictionary<string, string>() : new Dictionary<string, string>
		{
			["skill"] = "9001", ["empty"] = "", ["escaped"] = "quote\" and newline\n", ["unicode"] = "café"
		};

	private static void AssertPayload(string json, Lobby expected)
	{
		var lobby = (JObject)JObject.Parse(json)["results"]![0]!;
		var player = (JObject)lobby["players"]![0]!;
		Assert.That(lobby.ContainsKey("data"), Is.True);
		Assert.That(player.ContainsKey("stats"), Is.True);
		Assert.That(JToken.DeepEquals(lobby["data"], JToken.Parse(JsonConvert.SerializeObject(expected.data))), Is.True);
		Assert.That(JToken.DeepEquals(player["stats"], JToken.Parse(JsonConvert.SerializeObject(expected.players[0].stats))), Is.True);
	}
}
