using System;
using System.Collections.Generic;
using System.IO;
using System.Text.Json;
using System.Threading.Tasks;
using Beamable.Api.Autogenerated.Models;
using cli;
using cli.Content;
using NUnit.Framework;

namespace tests;

public class ContentFileReadRetryTests
{
    [TestCase(false)]
    [TestCase(true)]
    public void Persistent_empty_reads_or_io_errors_stop_after_five_attempts(bool ioFailure)
    {
        var reads = 0;
        var delays = new List<int>();
        var cause = new IOException("sharing violation");
        var error = Assert.ThrowsAsync<IOException>(() => ContentService.ReadContentFileTextAsync(
            "/cache/items.bad.json",
            _ => { reads++; return ioFailure ? Task.FromException<string>(cause) : Task.FromResult(""); },
            ms => { delays.Add(ms); return Task.CompletedTask; }));

        Assert.Multiple(() =>
        {
            Assert.That(reads, Is.EqualTo(5));
            Assert.That(delays, Is.EqualTo(new[] { 250, 250, 250, 250 }));
            Assert.That(error!.Message, Does.Contain("/cache/items.bad.json").And.Contain("5 attempts"));
            Assert.That(error.InnerException, Is.SameAs(ioFailure ? cause : null));
        });
    }

    [Test]
    public async Task Empty_and_locked_reads_can_recover_on_the_final_attempt()
    {
        var reads = 0;
        var delays = 0;
        var text = await ContentService.ReadContentFileTextAsync("file.json",
            _ => ++reads switch
            {
                1 or 3 => Task.FromResult(""),
                2 or 4 => Task.FromException<string>(new IOException("locked")),
                _ => Task.FromResult("{}")
            },
            _ => { delays++; return Task.CompletedTask; });
        Assert.That(text, Is.EqualTo("{}"));
        Assert.That(reads, Is.EqualTo(5));
        Assert.That(delays, Is.EqualTo(4));
    }

    [Test]
    public async Task A_nonempty_read_returns_without_delay()
    {
        var text = await ContentService.ReadContentFileTextAsync("file.json",
            _ => Task.FromResult("invalid JSON"),
            _ => throw new AssertionException("No delay expected"));
        Assert.That(text, Is.EqualTo("invalid JSON"));
    }

    [TestCase(typeof(FileNotFoundException))]
    [TestCase(typeof(DirectoryNotFoundException))]
    [TestCase(typeof(UnauthorizedAccessException))]
    public void Nonretryable_errors_are_preserved(Type errorType)
    {
        var cause = (Exception)Activator.CreateInstance(errorType)!;
        var reads = 0;
        var error = Assert.CatchAsync<Exception>(() => ContentService.ReadContentFileTextAsync("file.json",
            _ => { reads++; return Task.FromException<string>(cause); },
            _ => throw new AssertionException("No delay expected")));
        Assert.That(error, Is.SameAs(cause));
        Assert.That(reads, Is.EqualTo(1));
    }

    private string root = null!;
    private ContentService service = null!;
    private const string ContentJson = "{\"properties\":{},\"tags\":[],\"referenceManifestId\":\"uid\"}";
    private const string ChangelistJson = "{\"manifestUid\":\"uid\",\"publishedAt\":1,\"added\":{},\"modified\":{},\"removed\":{}}";
    private const string EntryJson = "{\"manifestUid\":\"uid\",\"createdDate\":1,\"publishedBy\":\"test\",\"publishedByName\":\"Test\"}";

    [SetUp]
    public void SetUp()
    {
        root = Path.Combine(Path.GetTempPath(), "beam-file-read-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Path.Combine(root, ConfigService.CFG_FOLDER));
        var config = new ConfigService(null);
        config.SetWorkingDir(root);
        var requester = new CliRequester(new RequesterInfo("cid", "pid", "fake", "fake", "http://127.0.0.1:1"));
        service = new ContentService(requester, config, null!, null!, null!, null!, null!);
    }

    [TearDown]
    public void TearDown() => Directory.Delete(root, true);

    private (string path, string valid, Func<Task> load) Prepare(string kind)
    {
        var manifest = new ClientManifestJsonResponse { entries = Array.Empty<ClientContentInfoJson>(), uid = "uid" };
        switch (kind)
        {
            case "scan":
            case "snapshot":
                var local = service.EnsureContentPathForRealmExists(out _, "pid", "global");
                return (Path.Combine(local, "items.bad.json"), ContentJson, kind == "scan"
                    ? () => service.GetAllContentFiles(manifest, getLocalStateOnly: true)
                    : () => service.SnapshotLocalContent("test", true));
            case "entries":
                var entries = service.EnsureContentHistoryEntriesFolderExists(out _, "pid");
                return (Path.Combine(entries, "1¬uid.json"), EntryJson,
                    () => service.GetAllContentHistoryLocalEntries("pid"));
            case "changelists":
                var changes = service.EnsureContentHistoryChangelistsFolderExists(out _, "pid");
                return (Path.Combine(changes, "uid.json"), ChangelistJson,
                    () => service.GetAllContentHistoryLocalChangelists("pid"));
            case "history-content":
                var changelists = service.EnsureContentHistoryChangelistsFolderExists(out _, "pid");
                File.WriteAllText(Path.Combine(changelists, "uid.json"), ChangelistJson);
                var history = Path.Combine(service.EnsureContentHistoryContentFolderExists(out _, "pid"), "uid");
                Directory.CreateDirectory(history);
                return (Path.Combine(history, "items.bad.json"), ContentJson,
                    () => service.GetAllContentHistoryLocalContent("pid", manifestUid: "uid"));
            default: throw new ArgumentException(kind);
        }
    }

    [TestCase("scan")]
    [TestCase("snapshot")]
    [TestCase("entries")]
    [TestCase("changelists")]
    [TestCase("history-content")]
    public async Task Empty_file_fails_with_path_and_releases_locks(string kind)
    {
        var (path, valid, load) = Prepare(kind);
        await File.WriteAllTextAsync(path, "");
        var error = Assert.CatchAsync<Exception>(() => load().WaitAsync(TimeSpan.FromSeconds(5)));
        Assert.That(error, Is.Not.InstanceOf<TimeoutException>());
        Assert.That(error!.Message, Does.Contain(path).And.Contain("5 attempts"));

        if (kind != "snapshot")
        {
            await File.WriteAllTextAsync(path, valid);
            await load().WaitAsync(TimeSpan.FromSeconds(5));
        }
    }

    [TestCase("scan")]
    [TestCase("snapshot")]
    [TestCase("entries")]
    [TestCase("changelists")]
    [TestCase("history-content")]
    public async Task Malformed_nonempty_files_still_fail_parsing(string kind)
    {
        var (path, _, load) = Prepare(kind);
        await File.WriteAllTextAsync(path, "{");
        var error = Assert.CatchAsync<Exception>(() => load().WaitAsync(TimeSpan.FromSeconds(5)));
        if (kind == "snapshot")
            Assert.That(error, Is.InstanceOf<CliException>());
        else
            Assert.That(error, Is.InstanceOf<JsonException>());
    }

    [Test]
    public async Task Scanner_recovers_when_an_empty_file_is_populated_during_retry()
    {
        var (path, valid, load) = Prepare("scan");
        await File.WriteAllTextAsync(path, "");
        var scan = load();
        Assert.That(scan.IsCompleted, Is.False);
        await File.WriteAllTextAsync(path, valid);
        await scan.WaitAsync(TimeSpan.FromSeconds(5));
    }
}
