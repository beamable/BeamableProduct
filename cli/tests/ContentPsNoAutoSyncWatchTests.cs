    private static JsonElement Props(int damage) => JsonSerializer.SerializeToElement(new { damage = new { data = damage } });
    private sealed class EventReporter : IDataReporterService
    {
        private readonly Channel<ContentPsCommandEvent> events = Channel.CreateUnbounded<ContentPsCommandEvent>();
        private readonly Channel<ContentHistoryCommandEvent> historyEvents = Channel.CreateUnbounded<ContentHistoryCommandEvent>();
        public void Report<T>(string type, T data)
        {
            if (data is ContentPsCommandEvent notification) events.Writer.TryWrite(notification);
            if (data is ContentHistoryCommandEvent history) historyEvents.Writer.TryWrite(history);
        }
        public async Task NextHistoryEntry(string uid)
        {
            using var timeout = new CancellationTokenSource(Timeout);
            while (true)
            {
                var notification = await historyEvents.Reader.ReadAsync(timeout.Token);
                if (notification.EntriesPage?.Entries.Any(entry => entry.ManifestUid == uid) == true) return;
            }
        }
        public async Task<ContentPsCommandEvent> Next(int type) {
            using var timeout = new CancellationTokenSource(Timeout);
            while (true) { var notification = await events.Reader.ReadAsync(timeout.Token); if (notification.EventType == type) return notification; }
        }
    }
    // Small protocol fixture: real ClientWebSocket handshake/auth/subscription, never a Beamable endpoint.
    private sealed class LoopbackServer : IAsyncDisposable
    {
        private readonly TcpListener listener = new(System.Net.IPAddress.Loopback, 0);
        private readonly CancellationTokenSource stop = new();
        private readonly Task accept;
        private readonly List<Task> connections = new();
        private WebSocket? socket;
        private int downloads;
        public int Downloads => downloads;
        public bool Published { get; private set; }
        public string Host { get; }
        public readonly TaskCompletionSource Ready = new(TaskCreationOptions.RunContinuationsAsynchronously);
        public LoopbackServer() {
            listener.Start(); Host = "http://127.0.0.1:" + ((System.Net.IPEndPoint)listener.LocalEndpoint).Port;
            accept = Task.Run(async () => { try { while (!stop.IsCancellationRequested) { var client = await listener.AcceptTcpClientAsync(stop.Token); connections.Add(Serve(client)); } } catch (OperationCanceledException) { } });
        }
        private async Task Serve(TcpClient client)
        {
            using (client) {
                await using var stream = client.GetStream();
                var request = new StringBuilder(); var single = new byte[1];
                while (!request.ToString().EndsWith("\r\n\r\n", StringComparison.Ordinal)) { await stream.ReadExactlyAsync(single, stop.Token); request.Append((char)single[0]); if (request.Length > 16384) throw new IOException("Unexpected HTTP headers"); }
                if (request.ToString().StartsWith("GET /content ", StringComparison.Ordinal)) {
                    Interlocked.Increment(ref downloads); var body = Encoding.UTF8.GetBytes("{\"properties\":{\"damage\":{\"data\":20}}}");
                    await stream.WriteAsync(Encoding.ASCII.GetBytes($"HTTP/1.1 200 OK\r\nContent-Length: {body.Length}\r\nConnection: close\r\n\r\n")); await stream.WriteAsync(body); return;
                }
                var key = request.ToString().Split("\r\n").Single(x => x.StartsWith("Sec-WebSocket-Key:", StringComparison.OrdinalIgnoreCase)).Split(':', 2)[1].Trim();
                var handshake = Convert.ToBase64String(SHA1.HashData(Encoding.ASCII.GetBytes(key + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11")));
                await stream.WriteAsync(Encoding.ASCII.GetBytes($"HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Accept: {handshake}\r\n\r\n"));
                using var ws = WebSocket.CreateFromStream(stream, true, null, TimeSpan.FromSeconds(30)); socket = ws;
                var buffer = new byte[16384];
                try {
                    await ws.ReceiveAsync(buffer, stop.Token); await Send("{\"id\":2,\"status\":200}");
                    await ws.ReceiveAsync(buffer, stop.Token); await Send("{\"id\":3,\"status\":200}"); Ready.TrySetResult();
                    while (!stop.IsCancellationRequested) await ws.ReceiveAsync(buffer, stop.Token);
                } catch (OperationCanceledException) { } catch (WebSocketException) { }
            }
        }
        private Task Send(string json) => socket!.SendAsync(new ArraySegment<byte>(Encoding.UTF8.GetBytes(json)), WebSocketMessageType.Text, true, stop.Token);
        public Task Publish()
        {
            Published = true;
            return Send("{\"id\":4,\"path\":\"content.manifest\",\"body\":{\"categories\":[],\"manifest\":{\"id\":\"global\",\"uid\":\"after\",\"checksum\":\"fixture\",\"created\":2000,\"publisherAccountId\":0}}}");
        }
        public async ValueTask DisposeAsync() { stop.Cancel(); listener.Stop(); socket?.Abort(); await accept.WaitAsync(Timeout); await Task.WhenAll(connections).WaitAsync(Timeout); stop.Dispose(); }
    }
