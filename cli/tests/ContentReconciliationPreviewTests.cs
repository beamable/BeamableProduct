    [Test]
    public async Task Guarded_apply_requires_publication_and_preserves_file_on_cancel()
    {
        await Seed();
        var preview = await service.PreviewReconciliation("global", Id, "reviewed");
        var original = File.ReadAllText(FilePath);
        var args = CommandArgs(); args.Use = "realm"; args.ExpectedLocalRevision = preview.LocalRevision; args.ExpectedManifestUid = null!;
        Assert.ThrowsAsync<CliException>(() => new ContentResolveConflictCommand().GetResult(args));
        using var cancelled = new CancellationTokenSource(); cancelled.Cancel();
        Assert.CatchAsync<OperationCanceledException>(() => service.ReconcileReviewedContent("global", Id, false,
            preview.ManifestUid, preview.LocalRevision, cancelled.Token));
        Assert.That(File.ReadAllText(FilePath), Is.EqualTo(original));
    }

    [TestCase(false, "update")]
    [TestCase(true, "update")]
    [TestCase(false, "addition")]
    [TestCase(true, "addition")]
    [TestCase(false, "deletion")]
    [TestCase(true, "deletion")]
    public async Task Reviewed_choice_applies_only_the_selected_values_and_preserves_absence(bool keepLocal, string change)
    {
        if (change != "addition") await Seed("[\"local\"]");
        var other = Path.Combine(folder, "currency.other.json");
        await File.WriteAllTextAsync(other, "unrelated");
        using var server = new ScriptedServer(_ => Task.FromResult("{\"properties\":{\"startingAmount\":{\"data\":20}}}"));
        if (change != "deletion") SetRemote(server.Url);
        var preview = await service.PreviewReconciliation("global", Id, "reviewed");
        Assert.That(preview.LocalExists, Is.EqualTo(change != "addition"));
        Assert.That(preview.RealmExists, Is.EqualTo(change != "deletion"));
        if (change != "update") Assert.That(preview.Differences, Is.Empty);
        var resolved = await Apply(preview, keepLocal);
        Assert.That(resolved, Is.EqualTo(new[] { Id }));
        Assert.That(File.ReadAllText(other), Is.EqualTo("unrelated"));
        bool exists = keepLocal ? change != "addition" : change != "deletion";
        Assert.That(File.Exists(FilePath), Is.EqualTo(exists));
        if (exists)
        {
            using var saved = JsonDocument.Parse(File.ReadAllText(FilePath));
            Assert.That(saved.RootElement.GetProperty("properties").GetProperty("startingAmount").GetProperty("data").GetInt32(), Is.EqualTo(keepLocal ? 10 : 20));
            Assert.That(saved.RootElement.GetProperty("tags")[0].GetString(), Is.EqualTo(keepLocal ? "local" : "realm"));
            Assert.That(saved.RootElement.GetProperty("referenceManifestId").GetString(), Is.EqualTo("reviewed"));
        }
        // Round-trip through the real status consumer, not merely through the preview's serializer:
        // acknowledgement must clear incoming/conflict while preserving an intentional local edit/deletion.
        var scanned = await service.GetAllContentFiles(latest, "global", ContentFilterType.ExactIds, new[] { Id });
        if (!keepLocal && change == "deletion")
            Assert.That(scanned.ContentFiles, Is.Empty, "Accepting realm deletion must not leave a reconciliation placeholder.");
        else
        {
            var current = scanned.ContentFiles.Single();
            Assert.That(current.IsInConflict, Is.False);
            Assert.That(current.ChangeKind, Is.EqualTo(keepLocal ? ContentChangeKind.LocalEdit : ContentChangeKind.UpToDate));
            Assert.That(current.FetchedFromManifestUid, Is.EqualTo("reviewed"));
            Assert.That(current.ReferenceIsUnknown, Is.False);
            if (!keepLocal) Assert.That(current.GetStatus(), Is.EqualTo(ContentStatus.UpToDate));
            else Assert.That(current.GetStatus(), Is.EqualTo(change == "addition" ? ContentStatus.Deleted : change == "deletion" ? ContentStatus.Created : ContentStatus.Modified));
        }
    }

    [TestCase(false, "properties")]
    [TestCase(true, "tags")]
    [TestCase(false, "baseline")]
    [TestCase(true, "reference")]
    [TestCase(false, "absence")]
    public async Task Apply_rejects_local_changes_since_review(bool keepLocal, string changed)
    {
        await Seed();
        using var server = new ScriptedServer(_ => Task.FromResult("{\"properties\":{\"startingAmount\":{\"data\":20}}}"));
        SetRemote(server.Url);
        var preview = await service.PreviewReconciliation("global", Id, "reviewed");
        var text = File.ReadAllText(FilePath);
        switch (changed)
        {
            case "properties": await File.WriteAllTextAsync(FilePath, text.Replace("10", "30")); break;
            case "tags": await File.WriteAllTextAsync(FilePath, text.Replace("[]", "[\"new\"]")); break;
            case "baseline": await File.WriteAllTextAsync(FilePath, text.Replace("original@v1", "new@v1")); break;
            case "reference": await File.WriteAllTextAsync(FilePath, text.Replace("before", "elsewhere")); break;
            case "absence": File.Delete(FilePath); break;
        }
        var changedText = File.Exists(FilePath) ? File.ReadAllText(FilePath) : null;
        Assert.ThrowsAsync<CliException>(() => Apply(preview, keepLocal));
        Assert.That(File.Exists(FilePath) ? File.ReadAllText(FilePath) : null, Is.EqualTo(changedText));
    }

    [TestCase("local")]
    [TestCase("realm")]
    [TestCase("payload")]
    public async Task Apply_rechecks_state_after_download_and_never_overwrites_a_newer_edit(string changed)
    {
        await Seed();
        using var server = new ScriptedServer(async count =>
        {
            if (count == 2 && changed == "local") await Seed("[\"edited during download\"]");
            if (count == 2 && changed == "realm") latest.uid = "newer";
            return "{\"properties\":{\"startingAmount\":{\"data\":" + (count == 2 && changed == "payload" ? "30" : "20") + "}}}";
        });
        SetRemote(server.Url);
        var preview = await service.PreviewReconciliation("global", Id, "reviewed");
        Assert.ThrowsAsync<CliException>(() => Apply(preview, false));
        using var saved = JsonDocument.Parse(File.ReadAllText(FilePath));
        Assert.That(saved.RootElement.GetProperty("properties").GetProperty("startingAmount").GetProperty("data").GetInt32(), Is.EqualTo(10));
        Assert.That(saved.RootElement.GetProperty("referenceManifestId").GetString(), Is.EqualTo("before"));
    }

    [Test]
    public async Task Diff_contains_only_changed_fields_and_preserves_json_types_and_array_order()
    {
        await File.WriteAllTextAsync(FilePath, """{"properties":{"same":{"data":1},"type":{"data":"1"},"missing":{"data":null},"array":{"data":[1,2]},"nested":{"data":{"b":2,"a":1}},"wrapped":{"data":1,"other":true}},"tags":["a","b"],"referenceManifestId":"before"}""");
        using var server = new ScriptedServer(_ => Task.FromResult("""{"properties":{"same":{"data":1},"type":{"data":1},"added":{"data":null},"array":{"data":[2,1]},"nested":{"data":{"a":1,"b":2}},"wrapped":{"data":2,"other":true}}}"""));
        SetRemote(server.Url); latest.entries[0].tags = new[] { "b", "a" };
        var preview = await service.PreviewReconciliation("global", Id, "reviewed");
        Assert.That(preview.Differences.Select(d => d.Property), Is.EqualTo(new[] { "added", "array", "missing", "type", "wrapped" }));
        var rows = preview.Differences.ToDictionary(d => d.Property);
        Assert.That(rows["added"].LocalValue, Is.EqualTo("Not present"));
        Assert.That(rows["added"].RealmValue, Is.EqualTo("null"));
        Assert.That(rows["missing"].RealmValue, Is.EqualTo("Not present"));
        Assert.That(rows["type"].LocalValue, Is.EqualTo("\"1\""));
        Assert.That(rows["type"].RealmValue, Is.EqualTo("1"));
        Assert.That(rows["array"].LocalValue, Is.EqualTo("[1,2]"));
        Assert.That(rows["wrapped"].LocalValue, Does.Contain("\"other\":true"));
    }

    [Test]
    public async Task Diff_keeps_large_values_and_reports_tag_set_changes()
    {
        var longValue = new string('x', 5000);
        await Seed("[\"local\"]");
        using var server = new ScriptedServer(_ => Task.FromResult(JsonSerializer.Serialize(new { properties = new { description = new { data = longValue } } })));
        SetRemote(server.Url);
        var preview = await service.PreviewReconciliation("global", Id, "reviewed");
        Assert.That(preview.Differences.Single(d => d.Property == "description").RealmValue, Is.EqualTo("\"" + longValue + "\""));
        var tags = preview.Differences.Single(d => d.Property == "Tags");
        Assert.That(tags.LocalValue, Is.EqualTo("[\"local\"]"));
        Assert.That(tags.RealmValue, Is.EqualTo("[\"realm\"]"));
    }

    private sealed class ScriptedServer : IDisposable
    {
        private readonly TcpListener listener = new(System.Net.IPAddress.Loopback, 0);
        private readonly CancellationTokenSource stop = new();
        public string Url { get; }
        private readonly Task run;
        public ScriptedServer(Func<int, Task<string>> response)
        {
            listener.Start();
            Url = $"http://127.0.0.1:{((IPEndPoint)listener.LocalEndpoint).Port}/content";
            run = Task.Run(async () =>
            {
                int count = 0;
                try
                {
                    while (!stop.IsCancellationRequested)
                    {
                        using var client = await listener.AcceptTcpClientAsync(stop.Token);
                        await using var stream = client.GetStream();
                        using var reader = new StreamReader(stream, Encoding.ASCII, false, 1024, true);
                        while (!string.IsNullOrEmpty(await reader.ReadLineAsync(stop.Token))) { }
                        var bytes = Encoding.UTF8.GetBytes(await response(++count));
                        await stream.WriteAsync(Encoding.ASCII.GetBytes($"HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {bytes.Length}\r\nConnection: close\r\n\r\n"));
                        await stream.WriteAsync(bytes);
                    }
                }
                catch (OperationCanceledException) when (stop.IsCancellationRequested) { }
                catch (SocketException) when (stop.IsCancellationRequested) { }
            });
        }
        public void Dispose() { stop.Cancel(); listener.Stop(); run.GetAwaiter().GetResult(); stop.Dispose(); }
    }
