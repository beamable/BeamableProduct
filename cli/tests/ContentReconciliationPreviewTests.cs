    [SetUp]
    public void SetUp()
    {
        root = Path.Combine(Path.GetTempPath(), "beam-preview-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Path.Combine(root, ConfigService.CFG_FOLDER));
        var config = new ConfigService(null); config.SetWorkingDir(root);
        var requester = new CliRequester(new RequesterInfo("preview-cid", "preview-pid", "fake", "fake", "http://127.0.0.1:1"));
        var api = new Mock<IContentApi>(MockBehavior.Strict);
        latest = new ClientManifestJsonResponse { uid = "reviewed", entries = Array.Empty<ClientContentInfoJson>() };
        api.Setup(x => x.GetManifestPublicJson(It.IsAny<Optional<string>>(), It.IsAny<Optional<bool>>(), It.IsAny<Optional<string>>(), true))
            .Returns(() => Promise<ClientManifestJsonResponse>.Successful(latest));
        service = new ContentService(requester, config, api.Object, null!, null!, null!, null!);
        folder = service.EnsureContentPathForRealmExists(out _, "preview-pid");
    }

    [TearDown]
    public void TearDown() => Directory.Delete(root, true);

    private string FilePath => Path.Combine(folder, Id + ".json");
    private async Task Seed(string tags = "[]") => await File.WriteAllTextAsync(FilePath,
        "{\"properties\":{\"startingAmount\":{\"data\":10}},\"tags\":" + tags + ",\"referenceManifestId\":\"before\",\"baseline\":\"original@v1\"}");

    [Test]
    public async Task Preview_reads_both_values_without_changing_content_or_acknowledgement()
    {
        await Seed("[\"mine\"]");
        using var server = new ContentLocal4866ReproTests.OneResponseServer("{\"properties\":{\"startingAmount\":{\"data\":20}}}");
        latest.entries = new[] { new ClientContentInfoJson { contentId = Id, version = "v2", uri = server.Url, tags = new[] { "theirs" } } };
        var filesBefore = Directory.GetFiles(root, "*", SearchOption.AllDirectories).ToDictionary(p => p, File.ReadAllText);
        var result = await service.PreviewReconciliation("global", Id, "reviewed");
        var json = JsonSerializer.SerializeToElement(result, new JsonSerializerOptions { IncludeFields = true });
        Assert.That(json.GetProperty("LocalExists").GetBoolean(), Is.True);
        Assert.That(json.GetProperty("RealmExists").GetBoolean(), Is.True);
        using var local = JsonDocument.Parse(json.GetProperty("LocalJson").GetString()!);
        using var realm = JsonDocument.Parse(json.GetProperty("RealmJson").GetString()!);
        Assert.That(local.RootElement.GetProperty("properties").GetProperty("startingAmount").GetProperty("data").GetInt32(), Is.EqualTo(10));
        Assert.That(realm.RootElement.GetProperty("properties").GetProperty("startingAmount").GetProperty("data").GetInt32(), Is.EqualTo(20));
        Assert.That(realm.RootElement.GetProperty("tags")[0].GetString(), Is.EqualTo("theirs"));
        Assert.That(local.RootElement.TryGetProperty("baseline", out _), Is.False);
        Assert.That(Directory.GetFiles(root, "*", SearchOption.AllDirectories), Is.EquivalentTo(filesBefore.Keys));
        foreach (var file in filesBefore) Assert.That(File.ReadAllText(file.Key), Is.EqualTo(file.Value));
    }

    private Task<string[]> Apply(ContentReconciliationPreview preview, bool keepLocal)
    {
        return service.ReconcileReviewedContent("global", Id, keepLocal, preview.ManifestUid, preview.LocalRevision);
    }

    private void SetRemote(string url) => latest.entries = new[]
        { new ClientContentInfoJson { contentId = Id, version = "v2", uri = url, tags = new[] { "realm" } } };

    private ContentResolveConflictCommandArgs CommandArgs()
    {
        var provider = new Mock<IServiceProvider>();
        provider.Setup(p => p.GetService(typeof(ContentService))).Returns(service);
        provider.Setup(p => p.GetService(typeof(AppLifecycle))).Returns(new AppLifecycle());
        return new ContentResolveConflictCommandArgs { Provider = provider.Object, ManifestIdsToReset = new[] { "global" },
            FilterType = ContentFilterType.ExactIds, Filter = new[] { Id }, ExpectedManifestUid = "reviewed" };
    }

    private static void SetPreview(ContentResolveConflictCommandArgs args)
    {
        args.Preview = true;
    }

