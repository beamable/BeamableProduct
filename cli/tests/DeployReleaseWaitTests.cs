using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Beamable.Api.Autogenerated.Models;
using cli;
using cli.DeploymentCommands;
using cli.Deployment.Services;
using NUnit.Framework;
using BeamoServiceStatus = Beamable.Api.Autogenerated.Models.ServiceStatus;

namespace tests;

/// <summary>
/// Tests for the polling behind `deploy release --wait`. The status source, delay and clock are all faked,
/// so nothing here touches the network or actually sleeps.
/// </summary>
public class DeployReleaseWaitTests
{
	private static readonly TimeSpan Poll = TimeSpan.FromSeconds(5);

	private static BeamoServiceStatus Status(string name, bool running, bool isCurrent)
		=> new BeamoServiceStatus { serviceName = name, running = running, isCurrent = isCurrent, imageId = "img-" + name };

	private static GetStatusResponse Response(params BeamoServiceStatus[] services)
		=> new GetStatusResponse { services = services };

	/// <summary>
	/// A fake clock: each delay advances the elapsed time by the requested amount, and the status source
	/// returns the queued responses in order (repeating the last one).
	/// </summary>
	private class FakePoller
	{
		public TimeSpan Elapsed;
		public int FetchCount;
		public List<TimeSpan> Delays = new List<TimeSpan>();
		private readonly Queue<GetStatusResponse> _responses;
		private GetStatusResponse _last = Response();

		public FakePoller(params GetStatusResponse[] responses)
		{
			_responses = new Queue<GetStatusResponse>(responses);
		}

		public Task<GetStatusResponse> Fetch()
		{
			FetchCount++;
			if (_responses.Count > 0)
			{
				_last = _responses.Dequeue();
			}
			return Task.FromResult(_last);
		}

		public Task Delay(TimeSpan time, CancellationToken token)
		{
			Delays.Add(time);
			Elapsed += time;
			return Task.CompletedTask;
		}

		public Task<ReleaseWaitResult> Wait(IReadOnlyCollection<string> services, TimeSpan timeout)
			=> ReleaseWaitUtil.WaitForServices(services, Fetch, timeout, Poll, Delay, () => Elapsed);
	}

	[Test]
	public async Task AllServicesBecomeReady_ReturnsStatuses()
	{
		var poller = new FakePoller(
			Response(Status("a", running: false, isCurrent: false)),
			Response(Status("a", running: true, isCurrent: false), Status("b", running: true, isCurrent: true)),
			Response(Status("a", running: true, isCurrent: true), Status("b", running: true, isCurrent: true)));

		var result = await poller.Wait(new[] { "a", "b" }, TimeSpan.FromSeconds(600));

		Assert.That(result.allReady, Is.True);
		Assert.That(result.timedOut, Is.False);
		Assert.That(poller.FetchCount, Is.EqualTo(3));
		Assert.That(poller.Delays, Is.EqualTo(new[] { Poll, Poll }));
		Assert.That(result.services.Select(s => s.service), Is.EqualTo(new[] { "a", "b" }));
		Assert.That(result.services.All(s => s.ready && s.running && s.isCurrent), Is.True);
		Assert.That(result.services.All(s => s.status == ReleasedServiceStatus.STATUS_READY), Is.True);
		Assert.That(result.services[0].imageId, Is.EqualTo("img-a"));

		Assert.DoesNotThrow(() => ReleaseWaitUtil.ThrowIfNotReady(result));
	}

	[Test]
	public async Task Timeout_ReportsNotReadyServices_AndThrows()
	{
		var poller = new FakePoller(
			Response(Status("a", running: true, isCurrent: true), Status("b", running: true, isCurrent: false)));

		var result = await poller.Wait(new[] { "a", "b", "c" }, TimeSpan.FromSeconds(12));

		Assert.That(result.allReady, Is.False);
		Assert.That(result.timedOut, Is.True);
		// polls at 0s, 5s, 10s, then clamps the last delay to the 2s left and polls once more at 12s.
		Assert.That(poller.Delays, Is.EqualTo(new[] { Poll, Poll, TimeSpan.FromSeconds(2) }));
		Assert.That(poller.FetchCount, Is.EqualTo(4));
		Assert.That(result.elapsedSeconds, Is.EqualTo(12));

		var byName = result.services.ToDictionary(s => s.service);
		Assert.That(byName["a"].status, Is.EqualTo(ReleasedServiceStatus.STATUS_READY));
		Assert.That(byName["b"].status, Is.EqualTo(ReleasedServiceStatus.STATUS_NOT_CURRENT));
		Assert.That(byName["c"].status, Is.EqualTo(ReleasedServiceStatus.STATUS_MISSING));

		var ex = Assert.Throws<CliException>(() => ReleaseWaitUtil.ThrowIfNotReady(result));
		Assert.That(ex?.Message, Does.Contain("b (not-current)"));
		Assert.That(ex?.Message, Does.Contain("c (missing)"));
		Assert.That(ex?.Message, Does.Not.Contain("a ("));
	}

	[Test]
	public async Task StatusForServicesNotInRelease_IsIgnored()
	{
		// "removed" is still reported (and stuck), but it was not part of the release, so it must not block.
		var poller = new FakePoller(
			Response(Status("a", running: true, isCurrent: true), Status("removed", running: false, isCurrent: false)));

		var result = await poller.Wait(new[] { "a" }, TimeSpan.FromSeconds(600));

		Assert.That(result.allReady, Is.True);
		Assert.That(poller.FetchCount, Is.EqualTo(1));
		Assert.That(result.services.Select(s => s.service), Is.EqualTo(new[] { "a" }));
	}

	[Test]
	public void NotRunning_IsReportedAsNotRunning()
	{
		var result = ReleaseWaitUtil.BuildResult(new[] { "a" }, Response(Status("a", running: false, isCurrent: true)));

		Assert.That(result.allReady, Is.False);
		Assert.That(result.services[0].status, Is.EqualTo(ReleasedServiceStatus.STATUS_NOT_RUNNING));
	}

	[Test]
	public void DuplicateStatusEntries_PreferTheReadyOne()
	{
		// mid-roll the status can carry both the old and the new instance of a service.
		var result = ReleaseWaitUtil.BuildResult(new[] { "a" }, Response(
			Status("a", running: true, isCurrent: false),
			Status("a", running: true, isCurrent: true)));

		Assert.That(result.allReady, Is.True);
	}

	[Test]
	public async Task NoServicesToWaitOn_ReturnsImmediatelyWithoutFetching()
	{
		var poller = new FakePoller();

		var result = await poller.Wait(Array.Empty<string>(), TimeSpan.FromSeconds(600));

		Assert.That(result.allReady, Is.True);
		Assert.That(result.services, Is.Empty);
		Assert.That(poller.FetchCount, Is.EqualTo(0));
	}

	[Test]
	public void GetServicesToWaitOn_OnlyEnabledNonArchivedServices()
	{
		var plan = new DeployablePlan
		{
			manifest = new ManifestView
			{
				manifest = new[]
				{
					new BeamoBasicServiceReference { serviceName = "live", enabled = true },
					// the manifest can carry archived history next to the live entry of the same name
					new BeamoBasicServiceReference { serviceName = "live", enabled = false, archived = true },
					new BeamoBasicServiceReference { serviceName = "disabled", enabled = false },
					new BeamoBasicServiceReference { serviceName = "removed", enabled = true, archived = true },
					new BeamoBasicServiceReference { serviceName = "other", enabled = true },
				}
			}
		};

		var services = ReleaseWaitUtil.GetServicesToWaitOn(plan);

		Assert.That(services, Is.EqualTo(new[] { "live", "other" }));
	}
}
