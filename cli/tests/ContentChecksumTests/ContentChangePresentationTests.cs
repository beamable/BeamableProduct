using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common.BeamCli.Contracts;
using cli.Content;
using NUnit.Framework;

namespace tests.ContentChecksumTests;

public class ContentChangePresentationTests
{
    private string path;

    [SetUp]
    public void SetUp()
    {
        path = Path.Combine(Path.GetTempPath(), Guid.NewGuid() + ".json");
        File.WriteAllText(path, "{}");
    }

    [TearDown]
    public void TearDown() => File.Delete(path);

    // Wire values: Unknown=0, UpToDate=1, LocalEdit=2, IncomingChange=3, Conflict=4.
    [TestCase(40, 40, 50, 3, true, false)]
    [TestCase(12, 10, 10, 2, false, false)]
    [TestCase(25, 20, 30, 4, false, true)]
    [TestCase(50, 40, 50, 1, false, false)]
    [TestCase(40, 40, 40, 1, false, false)]
    public void Projection_explains_change_without_changing_sync_policy(
        int local, int saved, int published, int expected, bool autoSync, bool conflict)
    {
        var files = CreateFiles(local, saved, published);
        ContentService.ComputeCorrectSyncOp(files, false, false, new HashSet<string>(),
            out var conflicts, out var downloads, out _);

        Assert.That(conflicts.Contains("currency.coins"), Is.EqualTo(conflict));
        Assert.That(downloads.Contains("currency.coins"), Is.EqualTo(autoSync));
        AssertKind(ContentService.ContentFileToLocalContentManifestEntries(files.ContentFiles).Single(), expected);
        var json = JsonSerializer.Serialize(files.ContentFiles.Single(), ContentService.GetContentFileSerializationOptions(false));
        Assert.That(json, Does.Not.Contain("ChangeKind"));
        Assert.That(json, Does.Not.Contain("changeKind"));
    }

    [TestCase(true, 2)]
    [TestCase(false, 3)]
    public void Tags_use_the_existing_reference_comparison(bool localTagChanged, int expected)
    {
        var files = CreateFiles(40, 40, 40);
        if (localTagChanged)
        {
            var file = files.ContentFiles[0];
            file.Tags = JsonSerializer.SerializeToElement(new[] { "designer" });
            files.ContentFiles[0] = file;
        }
        else files.TargetManifest.entries[0].tags = new[] { "published" };
        ContentService.ComputeCorrectSyncOp(files, false, false, new HashSet<string>(), out _, out _, out _);
        AssertKind(ContentService.ContentFileToLocalContentManifestEntries(files.ContentFiles).Single(), expected);
    }

    [TestCase(true)]
    [TestCase(false)]
    public void Creation_or_deletion_does_not_guess_change_direction(bool missingOnRemote)
    {
        var files = CreateFiles(40, 40, 40);
        var file = files.ContentFiles[0];
        if (missingOnRemote) file.ReferenceContent = null;
        else file.LocalFilePath = "";
        files.ContentFiles[0] = file;
        ContentService.ComputeCorrectSyncOp(files, false, false, new HashSet<string>(), out _, out _, out _);
        AssertKind(ContentService.ContentFileToLocalContentManifestEntries(files.ContentFiles).Single(), 0);
    }

    [Test]
    public void Old_payload_has_unknown_presentation()
    {
        var entry = JsonSerializer.Deserialize<LocalContentManifestEntry>(
            """{"FullId":"currency.coins","CurrentStatus":4}""", new JsonSerializerOptions { IncludeFields = true });
        AssertKind(entry, 0);
    }

    private static void AssertKind(LocalContentManifestEntry entry, int expected)
    {
        // Reflection keeps the red test compilable before the additive wire field exists.
        var field = typeof(LocalContentManifestEntry).GetField("ChangeKind");
        Assert.That(field, Is.Not.Null, "CLI status is missing the local-versus-published presentation metadata.");
        Assert.That(Convert.ToInt32(field.GetValue(entry)), Is.EqualTo(expected));
    }

    private LocalContentFiles CreateFiles(int local, int saved, int published)
    {
        ContentFile Payload(int amount) => new()
        {
            Id = "currency.coins", LocalFilePath = path, FetchedFromManifestUid = "saved",
            Properties = JsonSerializer.SerializeToElement(new { startingAmount = new { data = amount } }),
            Tags = JsonSerializer.SerializeToElement(Array.Empty<string>())
        };
        ClientContentInfoJson Entry(int amount)
        {
            var payload = Payload(amount);
            return new ClientContentInfoJson
            {
                contentId = payload.Id, checksum = ContentService.CalculateChecksum(in payload),
                version = "version-" + amount, tags = Array.Empty<string>(), uri = "https://example.invalid/unused"
            };
        }
        var original = Entry(saved);
        var target = Entry(published);
        var file = Payload(local);
        file.PropertiesChecksum = ContentService.CalculateChecksum(in file);
        file.ReferenceContent = target;
        file.Baseline = new ContentBaseline(original.checksum.Value, original.version);
        return new LocalContentFiles
        {
            ContentFiles = new List<ContentFile> { file },
            TargetManifest = new ClientManifestJsonResponse { uid = "latest", entries = new[] { target } },
            ReferenceManifests = new Dictionary<string, ClientManifestJsonResponse>
            {
                ["saved"] = new() { uid = "saved", entries = new[] { original } }
            }
        };
    }
}
