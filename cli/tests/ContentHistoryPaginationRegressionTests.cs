using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Beamable.Api.Autogenerated.Content;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common;
using Beamable.Common.Content;
using cli;
using cli.Content;
using Moq;
using NUnit.Framework;

namespace tests;

public class ContentHistoryPaginationRegressionTests
{
    [TestCase(0, 0, 1)]
    [TestCase(1, 0, 1)]
    [TestCase(99, 0, 1)]
    [TestCase(100, 0, 1)]
    [TestCase(101, 0, 2)]
    [TestCase(200, 0, 2)]
    [TestCase(201, 0, 3)]
    [TestCase(101, 100, 2)]
    [TestCase(201, 101, 3)]
    [TestCase(200, 200, 2)]
    public async Task History_sync_loads_all_pages_and_preserves_cached_entries(int total, int cachedCount, int expectedPages)
    {
        var root = Path.Combine(Path.GetTempPath(), "beam-history-pages-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Path.Combine(root, ConfigService.CFG_FOLDER));
        using var stop = new CancellationTokenSource(TimeSpan.FromSeconds(10));
        try
        {
            var config = new ConfigService(null);
            config.SetWorkingDir(root);
            var created = DateTimeOffset.UtcNow.AddMinutes(-1).ToUnixTimeMilliseconds();
            var entries = Enumerable.Range(0, total).Select(i => new ManifestDiffSummary
            {
                manifestUid = "publish-" + i, createdDate = created + i, affectedContentIds = Array.Empty<string>()
            }).ToArray();
            var available = entries.Take(cachedCount).ToArray();
            var offsets = new List<int>();
            var api = new Mock<IContentApi>(MockBehavior.Strict);
            api.Setup(x => x.GetManifestDiffs("global", null, null, It.IsAny<Optional<int>>(), It.IsAny<Optional<int>>(), It.IsAny<Optional<long>>(), null, true))
                .Returns((string manifestId, Optional<long> fromDate, Optional<string> fromUid,
                    Optional<int> limit, Optional<int> offset, Optional<long> toDate, Optional<string> toUid, bool auth) =>
                {
                    // BackendMain 740ba329 ContentService.scala:98-109,139-154 and
                    // ManifestRepository.scala:287-307: toDate alone uses offset pagination.
                    var start = offset?.Value ?? 0;
                    var count = Math.Min(limit?.Value ?? 50, 100);
                    offsets.Add(start);
                    // Bound a broken loop without allowing cancellation to masquerade as successful completion.
                    if (offsets.Count > expectedPages + 1) stop.Cancel();
                    return Promise<GetManifestDiffsResponse>.Successful(new GetManifestDiffsResponse
                    {
                        diffs = available.Skip(start).Take(count).ToArray(),
                        totalCount = available.Length, hasMore = start + count < available.Length
                    });
                });
            var requester = new CliRequester(new RequesterInfo(Guid.NewGuid().ToString("N"), "pid", "fake", "fake", "http://127.0.0.1:1"));
            var service = new ContentService(requester, config, api.Object, null!, null!, null!, null!);

            if (cachedCount > 0)
                await service.SyncContentHistoryEntries("pid", "global", cancellationToken: stop.Token);
            var cachePath = service.EnsureContentHistoryEntriesFolderExists(out _, "pid", "global");
            var originalFiles = Directory.GetFiles(cachePath).ToDictionary(path => path, File.ReadAllBytes);
            Assert.That(originalFiles.Count, Is.EqualTo(cachedCount), "Seed through the production cache writer");
            offsets.Clear();
            available = entries;

            var report = await service.SyncContentHistoryEntries("pid", "global", cancellationToken: stop.Token);
            var cached = await service.GetAllContentHistoryLocalEntries("pid", "global");

            TestContext.Out.WriteLine("Requested offsets: " + string.Join(", ", offsets));
            Assert.Multiple(() =>
            {
                Assert.That(stop.IsCancellationRequested, Is.False, "Sync must finish without the bounded-loop guard");
                Assert.That(cached.Entries.Select(entry => entry.ManifestUid), Is.EquivalentTo(entries.Select(entry => entry.manifestUid)));
                Assert.That(report.Entries.Count, Is.EqualTo(total - cachedCount), "Only newly cached entries belong in the report");
                Assert.That(offsets.Count, Is.EqualTo(expectedPages), "Stop at the final page, including exact page boundaries");
                foreach (var original in originalFiles)
                    Assert.That(File.ReadAllBytes(original.Key), Is.EqualTo(original.Value), "Preserve cached file bytes");
            });
        }
        finally
        {
            Directory.Delete(root, true);
        }
    }
}
