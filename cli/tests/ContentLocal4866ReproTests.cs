// Regression coverage for the original Local Content reproductions.
public class ContentLocal4866ReproTests
{
    private string root = null!, folder = null!;
    private ContentService service = null!;
    private Mock<IContentApi> api = null!;
    private ClientManifestJsonResponse before = null!, after = null!;
    private const string Id = "items.sword";
    [SetUp] public void SetUp()
    {
        root = Path.Combine(Path.GetTempPath(), "beam4866-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Path.Combine(root, ConfigService.CFG_FOLDER));
        var config = new ConfigService(null); config.SetWorkingDir(root);
        var requester = new CliRequester(new RequesterInfo(Guid.NewGuid().ToString("N"), "test-pid", "fake", "fake", "http://127.0.0.1:1"));
        api = new Mock<IContentApi>(MockBehavior.Strict);
        api.Setup(x => x.GetManifestPublicJson(It.IsAny<Optional<string>>(), It.IsAny<Optional<bool>>(), It.IsAny<Optional<string>>(), true))
            .Returns((Optional<string> id, Optional<bool> omit, Optional<string> uid, bool auth) => Promise<ClientManifestJsonResponse>.Successful(uid != null && uid.HasValue && uid.Value == "before" ? before : after));
        service = new ContentService(requester, config, api.Object, null!, null!, null!, null!);
        folder = service.EnsureContentPathForRealmExists(out _, "test-pid", "global");
    }
    [TearDown] public void TearDown() { if (Directory.Exists(root)) Directory.Delete(root, true); }
    private static JsonElement Props(int damage) => JsonSerializer.SerializeToElement(new { damage = new { data = damage } });
    private static ClientContentInfoJson Entry(string id, int damage, string version, string[]? tags = null)
    {
        var f = new ContentFile { Properties = Props(damage) };
        return new ClientContentInfoJson { contentId = id, version = version, checksum = ContentService.CalculateChecksum(in f), tags = tags ?? Array.Empty<string>(), uri = "http://127.0.0.1:1/never" };
    }
    private static ClientManifestJsonResponse Manifest(string uid, params ClientContentInfoJson[] entries) => new() { uid = uid, entries = entries };
    private async Task Seed(int damage, params string[] tags)
    {
        var f = new ContentFile { Id = Id, Properties = Props(damage), Tags = JsonSerializer.SerializeToElement(tags), FetchedFromManifestUid = "before" };
        await service.SaveContentFile(folder, f);
    }
    private string PathFor(string id = Id) => Path.Combine(folder, id + ".json");
    private Task<ContentSyncReport> AutoSync(CancellationToken token = default) => service.SyncLocalContent(after, "global", syncCreated: false, syncModified: false, forceSyncConflicts: false, syncDeleted: false, cancellationToken: token);

    [Test] public async Task Selective_sync_downloads_remote_changes_to_an_unchanged_local_file()
    {
        before = Manifest("before", Entry(Id, 10, "v1")); after = Manifest("after", Entry(Id, 20, "v2")); await Seed(10);
        using var server = new OneResponseServer("{\"properties\":{\"damage\":{\"data\":20}}}"); after.entries[0].uri = server.Url;
        var oldBytes = File.ReadAllBytes(PathFor()); var report = await AutoSync(); await server.Finished;
        Assert.That(report.AutoSynchedContents, Does.Contain(Id));
        Assert.That(File.ReadAllBytes(PathFor()), Is.Not.EqualTo(oldBytes));
        Assert.That(JsonDocument.Parse(File.ReadAllText(PathFor())).RootElement.GetProperty("properties").GetProperty("damage").GetProperty("data").GetInt32(), Is.EqualTo(20));
    }
    [Test] public async Task Selective_sync_preserves_a_conflicting_local_file_byte_for_byte()
    {
        before = Manifest("before", Entry(Id, 10, "v1")); after = Manifest("after", Entry(Id, 20, "v2")); await Seed(30);
        var oldBytes = File.ReadAllBytes(PathFor()); var report = await AutoSync();
        Assert.That(report.ConflictingContents, Does.Contain(Id)); Assert.That(File.ReadAllBytes(PathFor()), Is.EqualTo(oldBytes));
    }
    [Test] public async Task Remote_deletion_does_not_delete_the_local_file_in_selective_sync()
    {
        before = Manifest("before", Entry(Id, 10, "v1")); after = Manifest("after"); await Seed(10);
        var oldBytes = File.ReadAllBytes(PathFor()); await AutoSync(); Assert.That(File.ReadAllBytes(PathFor()), Is.EqualTo(oldBytes));
    }
    [Test] public async Task Reference_advance_preserves_local_properties_and_tags()
    {
        before = Manifest("before", Entry(Id, 10, "v1", new[] { "published" })); after = Manifest("after", Entry(Id, 10, "v1", new[] { "published" })); await Seed(30, "local-only");
        var report = await AutoSync(); var data = JsonDocument.Parse(File.ReadAllText(PathFor())).RootElement;
        Assert.That(report.ReferenceUpdatedContents, Does.Contain(Id));
        Assert.That(data.GetProperty("properties").GetProperty("damage").GetProperty("data").GetInt32(), Is.EqualTo(30));
        Assert.That(data.GetProperty("tags").EnumerateArray().Select(x => x.GetString()), Is.EqualTo(new[] { "local-only" }));
        Assert.That(data.GetProperty("referenceManifestId").GetString(), Is.EqualTo("after"));
    }
    [Test] public async Task Publish_blocks_a_remote_item_that_was_never_local()
    {
        before = Manifest("before", Entry(Id, 10, "v1")); after = Manifest("after", Entry(Id, 10, "v1"), Entry("items.unseen", 99, "v2")); await Seed(10);
        SaveContentRequest? sentContent = null; SaveManifestRequest? sentManifest = null;
        api.Setup(x => x.Post(It.IsAny<SaveContentRequest>(), true)).Returns((SaveContentRequest req, bool auth) => {
            sentContent = req; return Promise<SaveContentResponse>.Successful(new SaveContentResponse { content = req.content.Select(c => new ContentReference { id = c.id, version = "saved", checksum = c.checksum, tags = Array.Empty<string>(), uri = "http://127.0.0.1:1/fake" }).ToArray() }); });
        api.Setup(x => x.PostManifest(It.IsAny<SaveManifestRequest>(), true)).Returns((SaveManifestRequest req, bool auth) => { sentManifest = req; return Promise<SaveManifestResponse>.Successful(new SaveManifestResponse()); });
        Assert.ThrowsAsync<CliException>(() => service.PublishContent(AutoSnapshotType.None, 0));
        Assert.That(sentContent, Is.Null);
        Assert.That(sentManifest, Is.Null);
        Assert.That(after.entries.Select(c => c.contentId), Does.Contain("items.unseen"));
    }
    [Test] public async Task Cancellation_after_download_is_reported_without_saving_the_download()
    {
        before = Manifest("before", Entry(Id, 10, "v1")); after = Manifest("after", Entry(Id, 20, "v2")); await Seed(10);
        using var server = new OneResponseServer("{\"properties\":{\"damage\":{\"data\":20}}}"); after.entries[0].uri = server.Url;
        using var cancel = new CancellationTokenSource(); var oldBytes = File.ReadAllBytes(PathFor());
        Assert.That(async () => await service.SyncLocalContent(after, "global", syncCreated: false, syncModified: false, forceSyncConflicts: false, syncDeleted: false,
            cancellationToken: cancel.Token, onContentSyncProgressUpdate: progress => {
                if (progress.EventType == ContentProgressUpdateData.EVT_TYPE_SyncComplete) cancel.Cancel();
            }), Throws.InstanceOf<OperationCanceledException>());
        await server.Finished;
        Assert.That(cancel.IsCancellationRequested, Is.True);

        Assert.That(File.ReadAllBytes(PathFor()), Is.EqualTo(oldBytes));
    }
    [Test] public async Task Production_scan_and_decision_select_a_known_remote_addition_without_sync_deleted()
    {
        before = Manifest("before", Entry(Id, 10, "v1")); after = before; await Seed(10);
        await service.GetAllContentFiles(before, "global");
        after = Manifest("after", Entry(Id, 10, "v1"), Entry("items.unseen", 99, "v2"));
        var files = await service.GetAllContentFiles(after, "global");
        // The real history endpoint normally supplies this set. This test isolates its decision consumer.
        ContentService.ComputeCorrectSyncOp(files, false, false, new System.Collections.Generic.HashSet<string> { "items.unseen" }, out var conflicts, out var downloads, out _);
        Assert.That(conflicts, Is.Empty); Assert.That(downloads, Does.Contain("items.unseen"));
        Assert.That(File.Exists(PathFor("items.unseen")), Is.False);
    }
    [Test] public async Task Content_ps_even_without_watch_downloads_changes_at_startup()
    {
        before = Manifest("before", Entry(Id, 10, "v1")); after = Manifest("after", Entry(Id, 20, "v2")); await Seed(10);
        using var server = new OneResponseServer("{\"properties\":{\"damage\":{\"data\":20}}}"); after.entries[0].uri = server.Url;
        var context = new Mock<IAppContext>(); context.SetupGet(x => x.Cid).Returns("test-cid"); context.SetupGet(x => x.Pid).Returns("test-pid");
        var dependencies = new Mock<Beamable.Common.Dependencies.IDependencyProvider>();
        dependencies.Setup(x => x.GetService<ContentService>()).Returns(service);
        var provider = new Mock<IServiceProvider>();
        provider.Setup(x => x.GetService(typeof(Beamable.Common.Dependencies.IDependencyProvider))).Returns(dependencies.Object);
        provider.Setup(x => x.GetService(typeof(IAppContext))).Returns(context.Object);
        provider.Setup(x => x.GetService(typeof(cli.Services.AppLifecycle))).Returns(new cli.Services.AppLifecycle());
        await new ContentPsCommand().Handle(new ContentPsCommandArgs { Watch = false, ManifestId = "global", Provider = provider.Object });
        await server.Finished;
        Assert.That(JsonDocument.Parse(File.ReadAllText(PathFor())).RootElement.GetProperty("properties").GetProperty("damage").GetProperty("data").GetInt32(), Is.EqualTo(20));
    }
    internal sealed class OneResponseServer : IDisposable
    {
        private readonly TcpListener listener;
        public string Url { get; }
        public Task Finished { get; }
        public OneResponseServer(string json)
        {
            listener = new TcpListener(System.Net.IPAddress.Loopback, 0); listener.Start();
            Url = $"http://127.0.0.1:{((IPEndPoint)listener.LocalEndpoint).Port}/content";
            Finished = Task.Run(async () => { using var client = await listener.AcceptTcpClientAsync(); await using var stream = client.GetStream();
                var buffer = new byte[8192]; await stream.ReadAsync(buffer); var bytes = Encoding.UTF8.GetBytes(json);
                var headers = Encoding.ASCII.GetBytes($"HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {bytes.Length}\r\nConnection: close\r\n\r\n");
                await stream.WriteAsync(headers); await stream.WriteAsync(bytes); });
        }
        public void Dispose() => listener.Stop();
    }
}





