/// <summary>
/// Unit tests for how a deploy declares bundle component overrides: reading <c>beam.override.json</c> and the
/// checkout's remote (<see cref="DeployUtil.ReadOverrideDeclarations"/>), and checking declarations and
/// <c>--end-override</c> against what the site runs (<see cref="DeployUtil.CheckOverrides"/>).
/// </summary>
public class OverrideDeclarationTests
{
	private static readonly Guid Connection = Guid.Parse("6f1c0000-0000-0000-0000-000000000001");
	private static readonly Guid OtherConnection = Guid.Parse("6f1c0000-0000-0000-0000-000000000002");

	private string _root;

	[SetUp]
	public void SetUp()
	{
		_root = Path.Combine(Path.GetTempPath(), "beam-override-tests-" + Guid.NewGuid().ToString("N"));
		Directory.CreateDirectory(_root);
	}

	[TearDown]
	public void TearDown()
	{
		try
		{
			foreach (var file in Directory.EnumerateFiles(_root, "*", SearchOption.AllDirectories))
				File.SetAttributes(file, FileAttributes.Normal);
			Directory.Delete(_root, true);
		}
		catch (IOException)
		{
			// a git process may still hold the folder on Windows; it's a temp folder
		}
	}

	private BeamoServiceDefinition Service(string name, string overrideJson = null)
	{
		var dir = Path.Combine(_root, "services", name);
		Directory.CreateDirectory(dir);
		File.WriteAllText(Path.Combine(dir, name + ".csproj"), "<Project />");
		if (overrideJson != null)
			File.WriteAllText(Path.Combine(dir, "beam.override.json"), overrideJson);
		return new BeamoServiceDefinition
		{
			BeamoId = name,
			Protocol = BeamoProtocolType.HttpMicroservice,
			ProjectPath = $"services/{name}/{name}.csproj",
			AbsoluteProjectPath = Path.Combine(dir, name + ".csproj"),
		};
	}

	private void GitInit(string remote)
	{
		Assert.That(StartProcessUtil.Run("git", "init -q", workingDirectoryPath: _root).WaitForResult().exit, Is.EqualTo(0));
		if (remote != null)
			Assert.That(StartProcessUtil.Run("git", $"remote add origin {remote}", workingDirectoryPath: _root).WaitForResult().exit, Is.EqualTo(0));
	}

	private static string OverrideJson(string component, Guid? connection = null, string kind = "service") =>
		$"{{ \"bundle\": \"@acme/leaderboards\", \"version\": 3, \"component\": \"{component}\", \"kind\": \"{kind}\", \"connectionId\": \"{connection ?? Connection}\" }}";

	private static BeamoLocalManifest Manifest(params BeamoServiceDefinition[] definitions) =>
		new BeamoLocalManifest { ServiceDefinitions = new List<BeamoServiceDefinition>(definitions) };

	// ---- ReadOverrideDeclarations ----

	[Test]
	public void Read_DeclaredProject_TakesTheFileAndTheRemote()
	{
		GitInit("https://github.com/acme/game.git");
		var manifest = Manifest(Service("Scores", OverrideJson("Scores")), Service("Inventory"));

		var declarations = DeployUtil.ReadOverrideDeclarations(manifest, DeployScope.Realm, null);

		Assert.That(declarations.Select(d => d.component), Is.EqualTo(new[] { "Scores" }), "a project without the file is the org's own");
		var scores = declarations.Single();
		Assert.That(scores.bundle, Is.EqualTo("@acme/leaderboards"));
		Assert.That(scores.version, Is.EqualTo(3));
		Assert.That(scores.kind, Is.EqualTo("service"));
		Assert.That(scores.connectionId, Is.EqualTo(Connection.ToString()));
		Assert.That(scores.remote, Is.EqualTo("https://github.com/acme/game.git"));
	}

	[Test]
	public void Read_FileForAnotherComponent_MeansTheProjectWasRenamed()
	{
		GitInit("https://github.com/acme/game.git");
		var ex = Assert.Throws<CliException>(() => DeployUtil.ReadOverrideDeclarations(Manifest(Service("Scores2", OverrideJson("Scores"))), DeployScope.Realm, null));
		Assert.That(ex.Message, Does.Contain("renamed"));
	}

	[Test]
	public void Read_WithoutARemote_CantBeAnOverride()
	{
		GitInit(remote: null);
		var ex = Assert.Throws<CliException>(() => DeployUtil.ReadOverrideDeclarations(Manifest(Service("Scores", OverrideJson("Scores"))), DeployScope.Realm, null));
		Assert.That(ex.Message, Does.Contain("Git checkout with a remote"));
	}

	[Test]
	public void Read_KindOfAnotherProjectType_Throws()
	{
		GitInit("https://github.com/acme/game.git");
		var ex = Assert.Throws<CliException>(() => DeployUtil.ReadOverrideDeclarations(Manifest(Service("Scores", OverrideJson("Scores", kind: "storage"))), DeployScope.Realm, null));
		Assert.That(ex.Message, Does.Contain("Only services and portal extensions"));
	}

	[Test]
	public void Read_OnlyTheDeploysScope_AndTheBuildsComponents()
	{
		GitInit("https://github.com/acme/game.git");
		var zoneService = Service("ZoneScores", OverrideJson("ZoneScores"));
		zoneService.ServiceScope = "zone";
		var manifest = Manifest(Service("Scores", OverrideJson("Scores")), zoneService);

		Assert.That(DeployUtil.ReadOverrideDeclarations(manifest, DeployScope.Realm, null).Select(d => d.component), Is.EqualTo(new[] { "Scores" }));
		Assert.That(DeployUtil.ReadOverrideDeclarations(manifest, DeployScope.Zone, null).Select(d => d.component), Is.EqualTo(new[] { "ZoneScores" }));
		Assert.That(DeployUtil.ReadOverrideDeclarations(manifest, DeployScope.Realm, new HashSet<string> { "Other" }), Is.Empty);
	}

	// ---- CheckOverrides ----

	private static BeamoV2Manifest Site(params (string name, string bundle, Guid? overriddenFrom)[] services) => new BeamoV2Manifest
	{
		serviceReferences = new OptionalArrayOfBeamoV2ServiceReference(services.Select(s => new BeamoV2ServiceReference
		{
			serviceName = s.name,
			origin = s.bundle == null
				? new OptionalBeamoV2ComponentOrigin()
				: new OptionalBeamoV2ComponentOrigin(new BeamoV2ComponentOrigin
				{
					bundle = s.bundle,
					version = 3,
					@override = s.overriddenFrom.HasValue
						? new OptionalBeamoV2ComponentOverride(new BeamoV2ComponentOverride { connectionId = s.overriddenFrom.Value })
						: new OptionalBeamoV2ComponentOverride(),
				}),
		}).ToArray()),
	};

	private static OverrideDeclarationPlan Declared(string component, Guid? connection = null) => new OverrideDeclarationPlan
	{
		component = component, bundle = "@acme/leaderboards", version = 3, kind = "service",
		connectionId = (connection ?? Connection).ToString(), remote = "https://github.com/acme/game.git",
	};

	[Test]
	public void Check_ComponentOfTheInstalledBundle_IsAccepted()
	{
		var kept = DeployUtil.CheckOverrides(new List<OverrideDeclarationPlan> { Declared("Scores") }, new List<string>(),
			Site(("Scores", "@acme/leaderboards", null), ("Inventory", null, null)));
		Assert.That(kept, Is.Empty);
	}

	[Test]
	public void Check_BundleNotInstalledHere_Throws()
	{
		var ex = Assert.Throws<CliException>(() => DeployUtil.CheckOverrides(new List<OverrideDeclarationPlan> { Declared("Scores") }, new List<string>(),
			Site(("Scores", null, null))));
		Assert.That(ex.Message, Does.Contain("nothing to override"));
	}

	[Test]
	public void Check_OverriddenFromAnotherRepository_Throws()
	{
		var ex = Assert.Throws<CliException>(() => DeployUtil.CheckOverrides(new List<OverrideDeclarationPlan> { Declared("Scores") }, new List<string>(),
			Site(("Scores", "@acme/leaderboards", OtherConnection))));
		Assert.That(ex.Message, Does.Contain("another repository"));
	}

	[Test]
	public void Check_SameRepositoryAgain_IsAccepted()
	{
		Assert.DoesNotThrow(() => DeployUtil.CheckOverrides(new List<OverrideDeclarationPlan> { Declared("Scores") }, new List<string>(),
			Site(("Scores", "@acme/leaderboards", Connection))));
	}

	[Test]
	public void Check_UndeclaredOverride_IsKeptAndReported()
	{
		var kept = DeployUtil.CheckOverrides(new List<OverrideDeclarationPlan>(), new List<string>(),
			Site(("Scores", "@acme/leaderboards", OtherConnection), ("Seasons", "@acme/leaderboards", null)));
		Assert.That(kept.Single(), Does.StartWith("Scores: overridden here"));
	}

	[Test]
	public void Check_EndingAnOverride_NeedsOneHere()
	{
		Assert.That(DeployUtil.CheckOverrides(new List<OverrideDeclarationPlan>(), new List<string> { "Scores" },
			Site(("Scores", "@acme/leaderboards", Connection))), Is.Empty, "an ended override isn't reported as kept");

		var ex = Assert.Throws<CliException>(() => DeployUtil.CheckOverrides(new List<OverrideDeclarationPlan>(), new List<string> { "Seasons" },
			Site(("Seasons", "@acme/leaderboards", null))));
		Assert.That(ex.Message, Does.Contain("isn't overridden on this site"));
	}

	// ---- remotes (the same cases as the server's RepositoryRemotes tests) ----

	[TestCase("https://github.com/acme/game.git", "https://github.com/acme/game")]
	[TestCase("git@github.com:acme/game.git", "https://github.com/acme/game")]
	[TestCase("ssh://git@github.com/acme/game.git", "https://github.com/acme/game.git")]
	[TestCase("ssh://git@github.com:22/acme/game", "https://github.com/acme/game")]
	[TestCase("https://someone@GitHub.com/Acme/Game/", "https://github.com/acme/game")]
	[TestCase(" https://github.com./acme/game ", "https://github.com/acme/game")]
	public void Remotes_NamingTheSameRepository_AreTheSame(string remote, string url)
	{
		Assert.That(DeployUtil.SameRemote(remote, url), Is.True);
	}

	[TestCase("git@github.com:someone/game.git", "https://github.com/acme/game")]
	[TestCase("https://gitlab.com/acme/game", "https://github.com/acme/game")]
	[TestCase("https://github.com/acme/game-fork", "https://github.com/acme/game")]
	[TestCase("https://github.com/acme/game/sub", "https://github.com/acme/game")]
	[TestCase("../game", "https://github.com/acme/game")]
	[TestCase(@"C:\repos\game", "https://github.com/acme/game")]
	[TestCase("https://github.com/", "https://github.com/")]
	[TestCase("", "")]
	public void Remotes_NamingAnotherRepository_OrNone_AreNotTheSame(string remote, string url)
	{
		Assert.That(DeployUtil.SameRemote(remote, url), Is.False);
	}

	// ---- CheckOverrideConnections ----

	private static IDependencyProvider SourceControl(Action<Mock<IBeamSourcecontrolApi>> configure)
	{
		var mock = new Mock<IBeamSourcecontrolApi>();
		configure(mock);
		var builder = new DependencyBuilder();
		builder.AddSingleton<IBeamSourcecontrolApi>(mock.Object);
		return builder.Build();
	}

	private static ScmConnection Connected(string url, bool hasMyToken) => new ScmConnection
	{
		id = Connection, name = "game", url = url, hasMyToken = hasMyToken,
	};

	[Test]
	public void Connections_TheConnectionsRepositoryWithAToken_IsAccepted()
	{
		var provider = SourceControl(m => m.Setup(x => x.GetConnections(Connection, It.IsAny<bool>()))
			.ReturnsPromise(Connected("https://github.com/acme/game", hasMyToken: true)));

		Assert.DoesNotThrowAsync(() => DeployUtil.CheckOverrideConnections(provider, new List<OverrideDeclarationPlan> { Declared("Scores") }));
	}

	[Test]
	public void Connections_AForksRemote_IsRefusedBeforeBuilding()
	{
		var provider = SourceControl(m => m.Setup(x => x.GetConnections(Connection, It.IsAny<bool>()))
			.ReturnsPromise(Connected("https://github.com/acme/game", hasMyToken: true)));
		var fork = Declared("Scores");
		fork.remote = "git@github.com:someone/game.git";

		var ex = Assert.ThrowsAsync<CliException>(() => DeployUtil.CheckOverrideConnections(provider, new List<OverrideDeclarationPlan> { fork }));
		Assert.That(ex.Message, Does.Contain("this checkout's remote is git@github.com:someone/game.git"));
	}

	[Test]
	public void Connections_WithoutAConnectionOrHostToken_IsRefused()
	{
		var provider = SourceControl(m =>
		{
			m.Setup(x => x.GetConnections(Connection, It.IsAny<bool>())).ReturnsPromise(Connected("https://github.com/acme/game", hasMyToken: false));
			m.Setup(x => x.GetHostsToken("github.com", It.IsAny<bool>())).ReturnsPromise(new ScmHostTokenResponse { host = "github.com", hasMyToken = false });
		});

		var ex = Assert.ThrowsAsync<CliException>(() => DeployUtil.CheckOverrideConnections(provider, new List<OverrideDeclarationPlan> { Declared("Scores") }));
		Assert.That(ex.Message, Does.Contain("you have no token"));
	}

	[Test]
	public void Connections_AHostToken_IsEnough()
	{
		var provider = SourceControl(m =>
		{
			m.Setup(x => x.GetConnections(Connection, It.IsAny<bool>())).ReturnsPromise(Connected("git@github.com:acme/game.git", hasMyToken: false));
			m.Setup(x => x.GetHostsToken("github.com", It.IsAny<bool>())).ReturnsPromise(new ScmHostTokenResponse { host = "github.com", hasMyToken = true });
		});

		Assert.DoesNotThrowAsync(() => DeployUtil.CheckOverrideConnections(provider, new List<OverrideDeclarationPlan> { Declared("Scores") }));
	}

	[Test]
	public void Connections_NotTheZones_IsRefused()
	{
		var provider = SourceControl(m => m.Setup(x => x.GetConnections(Connection, It.IsAny<bool>()))
			.Returns(Promise<ScmConnection>.Failed(new RequesterException("Beamable", "GET", "/api/scm/connections", 404, "{}"))));

		var ex = Assert.ThrowsAsync<CliException>(() => DeployUtil.CheckOverrideConnections(provider, new List<OverrideDeclarationPlan> { Declared("Scores") }));
		Assert.That(ex.Message, Does.Contain("isn't one of this zone's repository connections"));
	}

	[Test]
	public void Check_DeclaringAndEndingTheSameComponent_Throws()
	{
		var ex = Assert.Throws<CliException>(() => DeployUtil.CheckOverrides(new List<OverrideDeclarationPlan> { Declared("Scores") }, new List<string> { "Scores" },
			Site(("Scores", "@acme/leaderboards", Connection))));
		Assert.That(ex.Message, Does.Contain("can't also be ended"));
	}
}
