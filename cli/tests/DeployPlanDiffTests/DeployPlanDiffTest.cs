using System.Collections.Generic;
using System.Linq;
using Beamable.Api.Autogenerated.Models;
using cli.Deployment.Services;
using NUnit.Framework;

namespace tests.DeployPlanDiffTests;

/// <summary>
/// Regression tests for the phantom-diff bug in `beam deploy plan`: the realm's current manifest can
/// carry several entries per name (archived history + the live one), and portal-extension/service refs
/// were diffed against an arbitrary (archived) duplicate — reporting already-deployed components as
/// changed/removed. See projects/deploy-plan-phantom-diff-plan.md.
/// </summary>
public class DeployPlanDiffTest
{
	private static PortalExtensionPlanReference Pe(string name, string checksum, bool enabled = true, bool archived = false)
		=> new PortalExtensionPlanReference { name = name, checksum = checksum, enabled = enabled, archived = archived };

	[Test]
	public void CollapseByName_DedupesAndPrefersLiveEntry_PreservingOrder()
	{
		// mirrors the real manifest: two identical archived copies, an older archived copy, and the live one.
		var refs = new List<PortalExtensionPlanReference>
		{
			Pe("sample", "archivedA", enabled: false, archived: true),
			Pe("sample", "archivedA", enabled: false, archived: true),
			Pe("nav", "navLive"),
			Pe("sample", "archivedB", enabled: false, archived: true),
			Pe("sample", "live", enabled: true, archived: false),
		};

		var collapsed = DeployUtil.CollapseByName(refs, r => r.name, r => r.archived);

		Assert.That(collapsed.Select(r => r.name), Is.EqualTo(new[] { "sample", "nav" }));
		var sample = collapsed.Single(r => r.name == "sample");
		Assert.That(sample.checksum, Is.EqualTo("live"));
		Assert.That(sample.archived, Is.False);
	}

	[Test]
	public void CollapseByName_AllArchived_KeepsOne()
	{
		var refs = new List<PortalExtensionPlanReference>
		{
			Pe("x", "a1", enabled: false, archived: true),
			Pe("x", "a2", enabled: false, archived: true),
		};

		var collapsed = DeployUtil.CollapseByName(refs, r => r.name, r => r.archived);

		Assert.That(collapsed.Count, Is.EqualTo(1));
		Assert.That(collapsed[0].archived, Is.True);
	}

	[Test]
	public void CollapseByName_WorksForServiceReferences()
	{
		var services = new[]
		{
			new BeamoBasicServiceReference { serviceName = "A", archived = true, imageId = "old" },
			new BeamoBasicServiceReference { serviceName = "A", archived = false, imageId = "current" },
			new BeamoBasicServiceReference { serviceName = "B", archived = false, imageId = "b" },
		};

		var collapsed = DeployUtil.CollapseByName(services, s => s.serviceName, s => s.archived);

		Assert.That(collapsed.Select(s => s.serviceName), Is.EqualTo(new[] { "A", "B" }));
		Assert.That(collapsed.Single(s => s.serviceName == "A").imageId, Is.EqualTo("current"));
	}

	[Test]
	public void DiffReferences_UnchangedExtension_AgainstCollapsedRemote_ReportsNoChange()
	{
		// after collapsing, remote has one live entry that matches next — nothing should be reported.
		var remote = new List<PortalExtensionPlanReference> { Pe("sample", "live") };
		var next = new List<PortalExtensionPlanReference> { Pe("sample", "live") };
		var diff = new DeploymentDiffSummary();

		DeployUtil.DiffReferences(remote, next, new Dictionary<string, string>(), new Dictionary<string, string>(), diff);

		Assert.That(diff.changedPortalExtensions, Is.Empty);
		Assert.That(diff.addedPortalExtensions, Is.Empty);
		Assert.That(diff.removedPortalExtensions, Is.Empty);
	}

	[Test]
	public void DiffReferences_WithoutCollapse_MisreportsPhantomChange()
	{
		// documents the bug: a non-collapsed remote (archived duplicate first) makes an unchanged
		// extension look "changed" because it's compared against the wrong (archived) copy.
		var remoteRaw = new List<PortalExtensionPlanReference>
		{
			Pe("sample", "archived", enabled: false, archived: true),
			Pe("sample", "live"),
		};
		var next = new List<PortalExtensionPlanReference> { Pe("sample", "live") };
		var diff = new DeploymentDiffSummary();

		DeployUtil.DiffReferences(remoteRaw, next, new Dictionary<string, string>(), new Dictionary<string, string>(), diff);

		Assert.That(diff.changedPortalExtensions, Does.Contain("sample"),
			"pre-collapse behavior: comparing against an archived duplicate yields a phantom change");
	}

	[Test]
	public void DiffReferences_ArchivedInNext_ReportsRemovedOnce_ThenConverges()
	{
		// a genuine removal (e.g. Replace mode archiving an extension that no longer exists locally, and
		// which is NOT a bundle component — bundle components are excluded before DiffReferences runs):
		// next is archived while remote is still live → reported removed exactly once.
		var remoteLive = new List<PortalExtensionPlanReference> { Pe("gone", "c1") };
		var nextArchived = new List<PortalExtensionPlanReference> { Pe("gone", "c1", enabled: false, archived: true) };
		var diff = new DeploymentDiffSummary();

		DeployUtil.DiffReferences(remoteLive, nextArchived, new Dictionary<string, string>(), new Dictionary<string, string>(), diff);

		Assert.That(diff.removedPortalExtensions, Is.EqualTo(new[] { "gone" }));
		Assert.That(diff.changedPortalExtensions, Is.Empty);

		// once the realm reports it archived, the same plan produces no diff (converged).
		var remoteArchived = new List<PortalExtensionPlanReference> { Pe("gone", "c1", enabled: false, archived: true) };
		var convergedDiff = new DeploymentDiffSummary();

		DeployUtil.DiffReferences(remoteArchived, nextArchived, new Dictionary<string, string>(), new Dictionary<string, string>(), convergedDiff);

		Assert.That(convergedDiff.removedPortalExtensions, Is.Empty);
		Assert.That(convergedDiff.changedPortalExtensions, Is.Empty);
	}

	[Test]
	public void DiffReferences_ExcludedBundleComponent_ProducesNoInlineDiff()
	{
		// Option A: a component delivered by a referenced bundle is stripped from BOTH the remote and next
		// sets in Plan before DiffReferences runs, so it never shows as an inline add/change/remove — only
		// its bundle pin does. Simulate that post-strip state: the component is absent from both lists.
		var remote = new List<PortalExtensionPlanReference> { Pe("keep", "k1") };
		var next = new List<PortalExtensionPlanReference> { Pe("keep", "k1") };
		var pins = new Dictionary<string, string> { ["@beamable/defaults"] = "sha256:abc" };
		var diff = new DeploymentDiffSummary();

		DeployUtil.DiffReferences(remote, next, new Dictionary<string, string>(), pins, diff);

		Assert.That(diff.addedPortalExtensions, Is.Empty);
		Assert.That(diff.changedPortalExtensions, Is.Empty);
		Assert.That(diff.removedPortalExtensions, Is.Empty);
		// the bundle pin is the only thing reported for the bundle's contents.
		Assert.That(diff.addedBundleReferences.Select(b => b.bundle), Is.EqualTo(new[] { "@beamable/defaults" }));
	}

	[Test]
	public void DiffReferences_BundleReferencePins_StillDiffedByChecksum()
	{
		var remotePins = new Dictionary<string, string>
		{
			["@a/keep"] = "sha256:same",
			["@a/change"] = "sha256:old",
			["@a/drop"] = "sha256:gone",
		};
		var nextPins = new Dictionary<string, string>
		{
			["@a/keep"] = "sha256:same",
			["@a/change"] = "sha256:new",
			["@a/add"] = "sha256:fresh",
		};
		var diff = new DeploymentDiffSummary();

		DeployUtil.DiffReferences(new List<PortalExtensionPlanReference>(), new List<PortalExtensionPlanReference>(),
			remotePins, nextPins, diff);

		Assert.That(diff.addedBundleReferences.Select(b => b.bundle), Is.EqualTo(new[] { "@a/add" }));
		Assert.That(diff.changedBundleReferences.Select(b => b.bundle), Is.EqualTo(new[] { "@a/change" }));
		Assert.That(diff.removedBundleReferences.Select(b => b.bundle), Is.EqualTo(new[] { "@a/drop" }));
		// an unchanged pin (same checksum) is never reported.
		Assert.That(diff.changedBundleReferences.Select(b => b.bundle), Does.Not.Contain("@a/keep"));
	}
}
