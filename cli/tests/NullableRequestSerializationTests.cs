using System.Linq;
using System.Reflection;
using System.Text;
using Beamable.Common;
using Beamable.Common.Api;
using Beamable.Common.Api.Groups;
using Beamable.Common.Api.Inventory;
using Beamable.Serialization;
using Beamable.Serialization.SmallerJSON;
using Beamable.Server.Common;
using Moq;
using Newtonsoft.Json;
using NUnit.Framework;
using InventoryRequest = Beamable.Api.Autogenerated.Models.InventoryUpdateRequest;

namespace tests;

public class NullableRequestSerializationTests
{
	[TestCase(null)]
	[TestCase(false)]
	[TestCase(true)]
	public void InventoryNetworkJsonPreservesOptionalVipBonus(bool? value)
	{
		var builder = new InventoryUpdateBuilder { applyVipBonus = value };
		var json = InventoryUpdateBuilderSerializer.ToNetworkJson(builder, "transaction");
		var payload = (ArrayDict)Json.Deserialize(json);
		AssertOptional(payload, "applyVipBonus", value);
		Assert.That(payload["transaction"], Is.EqualTo("transaction"));
		Assert.That(InventoryUpdateBuilderSerializer.FromNetworkJson(json).Item1.applyVipBonus, Is.EqualTo(value));
	}

	[TestCase(null)]
	[TestCase(false)]
	[TestCase(true)]
	public void InventoryApiConversionPreservesOptionalVipBonus(bool? value)
	{
		var builder = new InventoryUpdateBuilder { applyVipBonus = value };
		builder.currencies.Add("currency.coins", 5);
		var method = typeof(AbsInventoryApi).GetMethod("ToInventoryUpdateRequest", BindingFlags.Instance | BindingFlags.NonPublic)!;
		var request = (InventoryRequest)method.Invoke(new InventoryApiStub(), new object[] { builder, "transaction" })!;
		var payload = (ArrayDict)Json.Deserialize(JsonSerializable.ToJson(request));
		AssertOptional(payload, "applyVipBonus", value);
		Assert.That(payload["transaction"], Is.EqualTo("transaction"));
		Assert.That(((ArrayDict)payload["currencies"])["currency.coins"], Is.EqualTo(5));
	}

	[TestCase(null)]
	[TestCase(false)]
	[TestCase(true)]
	public void InventoryReflectionJsonPreservesVipBonus(bool? value)
	{
		var builder = new InventoryUpdateBuilder { applyVipBonus = value };
		var json = Json.Serialize(builder, new StringBuilder());
		var payload = (ArrayDict)Json.Deserialize(json);
		Assert.That(payload.ContainsKey("applyVipBonus"), Is.True);
		Assert.That(payload["applyVipBonus"], Is.EqualTo(value));
		Assert.That(Json.Deserialize<InventoryUpdateBuilder>(json).applyVipBonus, Is.EqualTo(value));
	}

	[TestCase(null)]
	[TestCase(false)]
	[TestCase(true)]
	public void InventoryUnityCompatibleJsonPreservesVipBonus(bool? value)
	{
		var builder = new InventoryUpdateBuilder { applyVipBonus = value };
		builder.currencies.Add("currency.coins", 5);
		var json = JsonConvert.SerializeObject(builder, UnitySerializationSettings.Instance);
		var restored = JsonConvert.DeserializeObject<InventoryUpdateBuilder>(json, UnitySerializationSettings.Instance)!;
		Assert.That(restored.applyVipBonus, Is.EqualTo(value));
		Assert.That(restored.currencies["currency.coins"], Is.EqualTo(5));
	}

	[TestCase(null)]
	[TestCase(0L)]
	[TestCase(42L)]
	[TestCase(long.MaxValue)]
	public void GroupRequestPreservesOptionalRequirement(long? value)
	{
		var requester = new Mock<IBeamableRequester>();
		var api = new GroupsApi(null!, requester.Object);
		api.SetGroupProps(7, new GroupUpdateProperties { requirement = value, name = "Guild", motd = "" });
		var call = requester.Invocations.Single();
		Assert.That(call.Arguments[0], Is.EqualTo(Method.PUT));
		Assert.That(call.Arguments[1], Is.EqualTo("/object/groups/7"));
		var payload = (ArrayDict)Json.Deserialize((string)call.Arguments[2]);
		AssertOptional(payload, "requirement", value);
		Assert.That(payload["name"], Is.EqualTo("Guild"));
		Assert.That(payload["motd"], Is.EqualTo(""));
	}

	[TestCase(null)]
	[TestCase(0L)]
	[TestCase(42L)]
	[TestCase(long.MaxValue)]
	public void GroupReflectionJsonKeepsExistingPayloadAndReadback(long? value)
	{
		var props = new GroupUpdateProperties { requirement = value, name = "Guild" };
		var json = Json.Serialize(props, new StringBuilder());
		var payload = (ArrayDict)Json.Deserialize(json);
		Assert.That(payload.ContainsKey("requirement"), Is.True);
		Assert.That(payload["requirement"], Is.EqualTo(value));
		// SmallerJSON currently reads a null nullable long as zero.
		Assert.That(Json.Deserialize<GroupUpdateProperties>(json).requirement, Is.EqualTo(value ?? 0));
	}

	private static void AssertOptional<T>(ArrayDict payload, string key, T? value) where T : struct
	{
		Assert.That(payload.ContainsKey(key), Is.EqualTo(value.HasValue));
		if (value.HasValue) Assert.That(payload[key], Is.EqualTo(value.Value));
	}

	private class InventoryApiStub : AbsInventoryApi
	{
		public InventoryApiStub() : base(null!, null!) { }
		public override Promise<InventoryView> GetCurrent(string scope = "") => Promise<InventoryView>.Successful(new InventoryView());
	}
}
