	public async Promise<string> GetDockerImageRegistryUri()
	{
		var uri = await GetDockerImageRegistry();
		if (!uri.Contains("://"))
		{
			uri = $"https://{uri}"; // add an https protocol if there is no protocol present.
		}
		if (!Uri.TryCreate(uri, UriKind.RelativeOrAbsolute, out var parsedUri))
		{
			throw new CliException($"Invalid registry URI uri=[{uri}]");
		}

		// Host (drop port): pushes go through the :443 nginx ingress that accepts x-ks-* auth, not the raw
		// registry port reported by the endpoint (which 401s that scheme).
		return $"{parsedUri.Scheme}://{parsedUri.Host}/v2/";
	}

	/// <summary>
	/// Resolves the Docker registry URI and, per service, the canonical repository name the image must be
	/// pushed to <b>for the caller's scope</b> — via the V2 <c>/api/beamo/registry-uri</c> endpoint. Because
	/// this rides the scoped requester, a zone deploy (<c>cid.zid</c>) gets the zone's repository names, which
	/// is what the server's <c>PostManifest</c> checks against (fixes <c>DockerImagesNotAvailable</c> for zone
	/// services). The returned <c>repositoryNames</c> is empty if the server does not provide them (older
	/// backends); callers fall back to the legacy client-side repo hash in that case.
	/// </summary>
	public async Promise<(string registryUri, Dictionary<string, string> repositoryNames)> GetImageUploadTargets(
		IEnumerable<string> serviceNames)
	{
		var names = serviceNames?.Where(n => !string.IsNullOrEmpty(n)).Distinct().ToArray() ?? Array.Empty<string>();
		// The generated GetRegistryUri serializes the serviceName[] query incorrectly (string[].ToString()),
		// so build the repeated-param query by hand.
		var query = names.Length > 0
			? "?" + string.Join("&", names.Select(n => $"serviceName={Uri.EscapeDataString(n)}"))
			: string.Empty;

		var scope = string.IsNullOrEmpty(Requester.Pid) ? Requester.Cid : $"{Requester.Cid}.{Requester.Pid}";
		Log.Information($"Resolving docker image registry via GET /api/beamo/registry-uri{query} " +
		                $"(X-BEAM-SCOPE via requester cid.pid=[{scope}]; a zone deploy overrides this to cid.zid)");

		var resp = await Requester.Request<BeamoV2UriResponse>(Method.GET, $"/api/beamo/registry-uri{query}")
			.RecoverFrom40x(_ => new BeamoV2UriResponse());

		var rawUri = resp.uri.GetOrElse(string.Empty);
		var uri = rawUri;
		if (!string.IsNullOrEmpty(uri))
		{
			if (!uri.Contains("://"))
			{
				uri = $"https://{uri}"; // add an https protocol if there is no protocol present.
			}
			if (!Uri.TryCreate(uri, UriKind.RelativeOrAbsolute, out var parsedUri))
			{
				throw new CliException($"Invalid registry URI uri=[{uri}]");
			}
			// Use Host (drop any port). The registry-uri endpoint reports the registry's raw/internal port
			// (e.g. :5001), but pushes must go through the :443 nginx ingress that accepts the x-ks-* auth
			// headers — the raw registry port 401s that scheme. (Pushing to :5001 was a regression.)
			uri = $"{parsedUri.Scheme}://{parsedUri.Host}/v2/";
		}

		var repos = new Dictionary<string, string>();
		if (resp.repositoryNames.HasValue && resp.repositoryNames.Value != null)
		{
			foreach (var kvp in resp.repositoryNames.Value)
			{
				repos[kvp.Key] = kvp.Value;
			}
		}

		Log.Information($"Docker image registry resolved: rawUri=[{rawUri}] normalizedUri=[{uri}]");
		if (repos.Count > 0)
		{
			Log.Information($"Per-service canonical repositories from server: " +
			                $"{string.Join(", ", repos.Select(kv => $"{kv.Key}=>{kv.Value}"))}");
		}
		else
		{
			Log.Warning("Server returned NO per-service repositoryNames for /api/beamo/registry-uri. " +
			            "Falling back to the legacy client-side repo hash (cid_pid_beamoId), which is realm-only — " +
			            "a zone deploy will push to the wrong repository. Check that the request scope and the " +
			            "serviceName query are what the backend expects.");
		}

		return (uri, repos);
	}

