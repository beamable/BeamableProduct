/// <summary>One file a release carries, named by its hashes. <see cref="path"/> is where it is on disk.</summary>
public class BundleFile : JsonSerializable.ISerializable
{
	public string path;
	public string sha256;
	public string md5;
	public string contentType;

	public void Serialize(JsonSerializable.IStreamSerializer s)
	{
		s.Serialize(nameof(path), ref path);
		s.Serialize(nameof(sha256), ref sha256);
		s.Serialize(nameof(md5), ref md5);
		s.Serialize(nameof(contentType), ref contentType);
	}
}

/// <summary>
/// The local side of a release: the deploy plan built for each site the bundle has components on, the
/// bundle's components as the catalog stores them, and every file the release uploads.
/// </summary>
public class BundleBuildResult : JsonSerializable.ISerializable
{
	/// <summary>Null when the bundle has no realm components.</summary>
	public DeployablePlan realmPlan;

	/// <summary>Null when the bundle has no zone components.</summary>
	public DeployablePlan zonePlan;

	public List<BundleComponent> components = new List<BundleComponent>();
	public List<BundleFile> files = new List<BundleFile>();

	public IEnumerable<(DeployScope scope, DeployablePlan plan)> Plans()
	{
		if (realmPlan != null) yield return (DeployScope.Realm, realmPlan);
		if (zonePlan != null) yield return (DeployScope.Zone, zonePlan);
	}

	public void Serialize(JsonSerializable.IStreamSerializer s)
	{
		s.Serialize(nameof(realmPlan), ref realmPlan);
		s.Serialize(nameof(zonePlan), ref zonePlan);
		s.SerializeList(nameof(components), ref components);
		s.SerializeList(nameof(files), ref files);
	}
}

/// <summary>
/// Shared build/catalog helpers for <c>bundles plan</c> and <c>bundles publish</c> so the two can't
/// drift. A bundle can have components on the zone and on realms; the deploy build handles one scope at
/// a time, so each site is built on its own and the results are combined.
/// </summary>
public static class BundleBuild
{
	private static readonly (string name, string contentType)[] ExtensionAssets =
	{
		("index.js", "application/javascript"),
		("style.css", "text/css"),
		("metadata.json", "application/json"),
	};

	/// <summary>Validate the bundle against the workspace's projects before the (potentially expensive) build.</summary>
	public static void ValidateComponentsExist(BeamoLocalManifest localManifest, BundleConfigFile bundle)
	{
		if (bundle.components.Count == 0)
			throw new CliException($"Bundle=[{bundle.name}] has no components. Add some to {Path.GetFileName(bundle.filePath)}.");
		BundleWorkspace.ValidateAgainstProjects(localManifest, bundle);
	}

	/// <summary>
	/// Build every site the bundle has components on, restricted to those components so an unrelated
	/// service can't fail (or slow down) the build, and turn the results into catalog components.
	/// </summary>
	public static async Task<BundleBuildResult> Build<T, TArgs>(T command, TArgs args, BundleConfigFile bundle)
		where T : AppCommand<TArgs>
		, IResultSteam<RunProjectBuildErrorStreamChannel, RunProjectBuildErrorStream>
		, IResultSteam<PlanReleaseProgressChannel, PlanReleaseProgress>
		where TArgs : CommandArgs, IHasDeployPlanArgs
	{
		var manifest = args.BeamoLocalSystem.BeamoManifest;
		var result = new BundleBuildResult();
		foreach (var scope in new[] { DeployScope.Realm, DeployScope.Zone })
		{
			var site = scope == DeployScope.Zone ? BundleWorkspace.SITE_ZONE : BundleWorkspace.SITE_REALM;
			var ids = bundle.ComponentNames.Where(c => BundleWorkspace.SiteOf(manifest, bundle, c) == site).ToHashSet();
			if (ids.Count == 0) continue;

			args.Scope = scope;
			using var scopeHandle = await DeployArgs.ApplyDeployScopeAsync(args, scope);
			// Bundle plan/publish operate on exactly these components, so they're not excluded as authored.
			var (plan, _) = await command.InteractivePlan(args.DependencyProvider, args,
				excludeAuthoredBundleComponents: false, savePlanToTemp: false, includeOnlyBeamoIds: ids);
			if (scope == DeployScope.Zone) result.zonePlan = plan;
			else result.realmPlan = plan;
		}

		Collect(manifest, bundle, result);
		PackSource(manifest, bundle, result, Path.Combine(args.ConfigService.ConfigDirectoryPath, "temp", "bundles-source"));
		return result;
	}

	/// <summary>Turn the built plans into catalog components and hash the files they carry.</summary>
	public static void Collect(BeamoLocalManifest manifest, BundleConfigFile bundle, BundleBuildResult result)
	{
		var built = new HashSet<string>();
		foreach (var (scope, plan) in result.Plans())
		{
			var site = scope == DeployScope.Zone ? BundleSite.Zone : BundleSite.Realm;
			foreach (var service in (plan.manifest.manifest ?? Array.Empty<BeamoBasicServiceReference>())
			         .Where(s => bundle.components.ContainsKey(s.serviceName)))
			{
				result.components.Add(Component(bundle, service.serviceName, BundleComponentKind.Service, site,
					c => c.service = new OptionalServiceReference(service.ConvertToBundleReference())));
				built.Add(service.serviceName);
			}

			foreach (var storage in plan.manifest.storageReference.GetOrElse(Array.Empty<BeamoBasicServiceStorageReference>())
			         .Where(s => bundle.components.ContainsKey(s.id)))
			{
				result.components.Add(Component(bundle, storage.id, BundleComponentKind.Storage, site,
					c => c.storage = new OptionalServiceStorageReference(storage.ConvertToBundleReference())));
				built.Add(storage.id);
			}

			foreach (var extension in plan.portalExtensionReferences.Where(e => bundle.components.ContainsKey(e.name)))
			{
				var definition = manifest.ServiceDefinitions.First(d => d.BeamoId == extension.name).PortalExtensionDefinition;
				var files = ExtensionAssets.Select(a => Hash(Path.Combine(definition.AbsolutePath, "assets", a.name), a.contentType)).ToList();
				foreach (var file in files.Where(f => result.files.All(x => x.sha256 != f.sha256)))
					result.files.Add(file);

				var reference = PortalExtensionPlanReference.ToBundleReference(extension);
				// Marketplace files are stored by SHA-256, and the content id is the key the server signs.
				reference.files = new OptionalArrayOfExtensionContentReference(ExtensionAssets.Select((a, i) => new ExtensionContentReference
				{
					name = new OptionalString(a.name),
					version = new OptionalString(files[i].sha256),
					contentId = new OptionalString(files[i].sha256),
				}).ToArray());

				result.components.Add(Component(bundle, extension.name, BundleComponentKind.Extension, site, c =>
				{
					c.extension = new OptionalPortalExtensionReference(reference);
					c.mounts = new OptionalArrayOfBundleMount((definition.Properties?.Mounts ?? new List<PortalExtensionMountProperties>())
						.Select(m => new BundleMount
						{
							page = string.IsNullOrEmpty(m.Page) ? new OptionalString() : new OptionalString(m.Page),
							selector = string.IsNullOrEmpty(m.Selector) ? new OptionalString() : new OptionalString(m.Selector),
						}).ToArray());
				}));
				built.Add(extension.name);
			}
		}

		var missing = bundle.ComponentNames.Where(c => !built.Contains(c)).ToList();
		if (missing.Count > 0)
			throw new CliException($"Bundle=[{bundle.name}] lists components that weren't built as local services, storages or extensions: {string.Join(", ", missing)}");
	}

	private static BundleComponent Component(BundleConfigFile bundle, string name, BundleComponentKind kind, BundleSite site, Action<BundleComponent> entry)
	{
		var component = new BundleComponent
		{
			name = new OptionalString(name),
			kind = new OptionalBundleComponentKind(kind),
			site = new OptionalBundleSite(site),
			sourceAvailable = new OptionalBool(bundle.components[name].source),
		};
		entry(component);
		return component;
	}

	/// <summary>A file's SHA-256 (its key in the marketplace store) and MD5, both lowercase hex.</summary>
	public static BundleFile Hash(string path, string contentType)
	{
		if (!File.Exists(path))
			throw new CliException($"Expected the built file [{path}], but it doesn't exist.");
		var bytes = File.ReadAllBytes(path);
		return new BundleFile
		{
			path = path,
			sha256 = Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant(),
			md5 = Convert.ToHexString(MD5.HashData(bytes)).ToLowerInvariant(),
			contentType = contentType,
		};
	}

	// The server's limits for one component's source (SourceArchives / ScmPublishPlan in BeamableAPI).
	private const int MaxSourceFiles = 999;
	private const long MaxSourceFileBytes = 10L * 1024 * 1024;
	private const long MaxSourceTotalBytes = 25L * 1024 * 1024 - 64 * 1024;
	private const long MaxSourceArchiveBytes = 32L * 1024 * 1024;
	private const int MaxSourcePathLength = 640;
	private static readonly string[] NeverPublished = { ".git", "bin", "obj", "node_modules", ".beamable/temp", ".beamable/local", ".wingman" };
	public const string OVERRIDE_FILE_NAME = "beam.override.json";

	/// <summary>
	/// Pack the project folder of every component whose source is available into a tar.gz, add it to the
	/// release's files and set the component's <c>sourceArchive</c>. Entries are sorted, timestamped at the
	/// epoch and gzipped without a timestamp, so unchanged source always hashes to the same key and a
	/// republish of it makes no new version. Folders the server never publishes and any
	/// <c>beam.override.json</c> are left out; the server's limits are checked before anything is uploaded.
	/// </summary>
	public static void PackSource(BeamoLocalManifest manifest, BundleConfigFile bundle, BundleBuildResult result, string outputDir)
	{
		Directory.CreateDirectory(outputDir);
		foreach (var component in result.components.Where(c => c.sourceAvailable.GetOrElse(false)))
		{
			var name = component.name.GetOrElse("");
			var definition = manifest.ServiceDefinitions.First(d => d.BeamoId == name);
			var root = definition.Protocol == BeamoProtocolType.PortalExtension
				? definition.PortalExtensionDefinition.AbsolutePath
				: definition.AbsoluteProjectDirectory;

			var entries = SourceEntries(root).ToList();
			var problems = new List<string>();
			if (entries.Count > MaxSourceFiles)
				problems.Add($"it has {entries.Count} files; the limit is {MaxSourceFiles}");
			problems.AddRange(entries.Where(e => e.length > MaxSourceFileBytes).Select(e => $"[{e.relative}] is over 10 MB"));
			problems.AddRange(entries.Where(e => e.relative.Length > MaxSourcePathLength).Select(e => $"[{e.relative}] is a path over {MaxSourcePathLength} characters"));
			var total = entries.Sum(e => e.length);
			if (total > MaxSourceTotalBytes)
				problems.Add($"it unpacks to {total / (1024 * 1024)} MB; the limit is 25 MB less 64 KB");
			if (problems.Count > 0)
				throw new CliException($"The source of [{name}] can't be published: {string.Join("; ", problems)}.");

			var archivePath = Path.Combine(outputDir, $"{bundle.name}-{name}.tar.gz");
			using (var file = File.Create(archivePath))
			using (var gzip = new GZipStream(file, CompressionLevel.SmallestSize))
			using (var tar = new TarWriter(gzip, TarEntryFormat.Pax, leaveOpen: false))
			{
				foreach (var entry in entries)
				{
					var tarEntry = new PaxTarEntry(TarEntryType.RegularFile, entry.relative)
					{
						ModificationTime = DateTimeOffset.UnixEpoch,
						Mode = UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.GroupRead | UnixFileMode.OtherRead,
						DataStream = File.OpenRead(entry.path),
					};
					tar.WriteEntry(tarEntry);
					tarEntry.DataStream.Dispose();
				}
			}

			if (new FileInfo(archivePath).Length > MaxSourceArchiveBytes)
				throw new CliException($"The source of [{name}] compresses to over 32 MB, the limit for one component.");

			var archive = Hash(archivePath, "application/gzip");
			if (result.files.All(f => f.sha256 != archive.sha256))
				result.files.Add(archive);
			component.sourceArchive = new OptionalString(archive.sha256);
		}
	}

	private static IEnumerable<(string path, string relative, long length)> SourceEntries(string root)
	{
		return Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories)
			.Select(path => (path, relative: Path.GetRelativePath(root, path).Replace('\\', '/')))
			.Where(e => e.relative != OVERRIDE_FILE_NAME)
			.Where(e => !NeverPublished.Any(skip => ("/" + e.relative).Contains("/" + skip + "/", StringComparison.OrdinalIgnoreCase)
			                                        || e.relative.StartsWith(skip + "/", StringComparison.OrdinalIgnoreCase)))
			.Select(e => (e.path, e.relative, new FileInfo(e.path).Length))
			.OrderBy(e => e.relative, StringComparer.Ordinal);
	}

	/// <summary>The component groups as the catalog stores them (the server calls them features).</summary>
	public static BundleFeature[] ComponentGroups(BundleConfigFile bundle) => bundle.componentGroups
		.Select(f => new BundleFeature
		{
			name = new OptionalString(f.Key),
			title = new OptionalString(f.Value.title),
			description = new OptionalString(f.Value.description),
			components = new OptionalArrayOfString(f.Value.components.ToArray()),
			enabledByDefault = new OptionalBool(f.Value.enabledByDefault),
		}).ToArray();

	/// <summary>The bundle dependencies as the catalog stores them.</summary>
	public static BundleDep[] Dependencies(BundleConfigFile bundle) => bundle.dependencies
		.Select(d => new BundleDep
		{
			name = new OptionalString(d.Key),
			kind = new OptionalBundleDependencyKind(d.Value.IsHard ? BundleDependencyKind.Hard : BundleDependencyKind.Soft),
			min = new OptionalLong(d.Value.min),
			max = d.Value.max.HasValue ? new OptionalLong(d.Value.max.Value) : new OptionalLong(),
		}).ToArray();

	/// <summary>
	/// The bundle's latest release and its content, or nulls when the bundle has no release yet. A
	/// bundle name that doesn't exist yet is the same as one without releases: <c>bundles create</c> makes it.
	/// </summary>
	public static async Task<(BundleRelease release, BundleContentView content)> FetchLatestPublished(IBeamBeamobundleApi api, string fullName)
	{
		try
		{
			var releases = await api.GetReleases(new Optional<long>(), (Optional<int>)1, (Optional<string>)fullName);
			var latest = releases.tags.GetOrElse(new MapOfLong()).TryGetValue("latest", out var v) ? v : 0;
			if (latest <= 0) return (null, null);
			var content = await api.GetReleasesContent((Optional<string>)fullName, (Optional<long>)latest);
			return (content.release.GetOrElse((BundleRelease)null), content.content.GetOrElse((BundleContentView)null));
		}
		catch (RequesterException e) when (e.Status == 404)
		{
			return (null, null);
		}
	}
}
