using Beamable.Api.Autogenerated.Models;
using Beamable.Serialization;
using Beamable.Server;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace cli.Services.Bundles;

/// <summary>One change between a locally-built bundle and its latest release.</summary>
public class BundleComponentChange : JsonSerializable.ISerializable
{
	public string name;
	public string kind;   // "service" | "storage" | "extension" | "schema" | "componentGroup" | "dependency"
	public string change; // "Added" | "Removed" | "Changed"
	public string local = "";
	public string published = "";

	public void Serialize(JsonSerializable.IStreamSerializer s)
	{
		s.Serialize(nameof(name), ref name);
		s.Serialize(nameof(kind), ref kind);
		s.Serialize(nameof(change), ref change);
		s.Serialize(nameof(local), ref local);
		s.Serialize(nameof(published), ref published);
	}
}

public class BundleDiffResult : JsonSerializable.ISerializable
{
	/// <summary>True when the built bundle is the same as the latest release (publishing makes no new version).</summary>
	public bool isNoOp;

	/// <summary>The latest release's version, or 0 when the bundle has no release yet.</summary>
	public long publishedVersion;

	public List<BundleComponentChange> changes = new List<BundleComponentChange>();

	public void Serialize(JsonSerializable.IStreamSerializer s)
	{
		s.Serialize(nameof(isNoOp), ref isNoOp);
		s.Serialize(nameof(publishedVersion), ref publishedVersion);
		s.SerializeList(nameof(changes), ref changes);
	}
}

/// <summary>
/// Diffs a locally-built bundle against its latest release: each component by what a release changes
/// in it (its site, source flag, image or files, and mounts), then the component groups and dependencies, which
/// are part of the release's content too.
/// </summary>
public static class BundleDiff
{
	public static BundleDiffResult Compute(BundleBuildResult local, BundleConfigFile bundle, BundleRelease publishedRelease, BundleContentView published)
	{
		var result = new BundleDiffResult { publishedVersion = publishedRelease?.version.GetOrElse(0) ?? 0 };

		var publishedComponents = (published?.components.GetOrElse(Array.Empty<BundleComponent>()) ?? Array.Empty<BundleComponent>())
			.ToDictionary(c => c.name.GetOrElse(""));
		var localComponents = local.components.ToDictionary(c => c.name.GetOrElse(""));
		foreach (var kind in new[] { BundleComponentKind.Service, BundleComponentKind.Storage, BundleComponentKind.Extension, BundleComponentKind.Schema })
		{
			DiffSide(result, KindName(kind),
				localComponents.Where(c => KindOf(c.Value) == kind).ToDictionary(c => c.Key, c => Fingerprint(c.Value)),
				publishedComponents.Where(c => KindOf(c.Value) == kind).ToDictionary(c => c.Key, c => Fingerprint(c.Value)));
		}

		DiffSide(result, "componentGroup",
			BundleBuild.ComponentGroups(bundle).ToDictionary(f => f.name.GetOrElse(""), Fingerprint),
			(published?.features.GetOrElse(Array.Empty<BundleFeature>()) ?? Array.Empty<BundleFeature>())
				.ToDictionary(f => f.name.GetOrElse(""), Fingerprint));

		DiffSide(result, "dependency",
			BundleBuild.Dependencies(bundle).ToDictionary(d => d.name.GetOrElse(""), Fingerprint),
			(published?.dependencies.GetOrElse(Array.Empty<BundleDep>()) ?? Array.Empty<BundleDep>())
				.ToDictionary(d => d.name.GetOrElse(""), Fingerprint));

		result.isNoOp = result.changes.Count == 0;
		return result;
	}

	private static BundleComponentKind? KindOf(BundleComponent c) => c.kind.HasValue ? c.kind.Value : null;

	private static string KindName(BundleComponentKind kind) => kind switch
	{
		BundleComponentKind.Service => "service",
		BundleComponentKind.Storage => "storage",
		BundleComponentKind.Extension => "extension",
		_ => "schema",
	};

	private static string Fingerprint(BundleComponent c)
	{
		var entry = KindOf(c) switch
		{
			BundleComponentKind.Service => $"image {c.service.GetOrElse((Beamable.Api.Autogenerated.Models.ServiceReference)null)?.imageId.GetOrElse("")}",
			BundleComponentKind.Storage => $"type {c.storage.GetOrElse((Beamable.Api.Autogenerated.Models.ServiceStorageReference)null)?.storageType.GetOrElse("")}",
			BundleComponentKind.Extension => "files " + string.Join(",", (c.extension.GetOrElse((PortalExtensionReference)null)?.files
					.GetOrElse(Array.Empty<ExtensionContentReference>()) ?? Array.Empty<ExtensionContentReference>())
				.OrderBy(f => f.name.GetOrElse(""), StringComparer.Ordinal)
				.Select(f => $"{f.name.GetOrElse("")}:{Short(f.version.GetOrElse(""))}")),
			_ => $"version {c.schema.GetOrElse((SchemaReference)null)?.version.GetOrElse("")}",
		};
		var mounts = string.Join(",", c.mounts.GetOrElse(Array.Empty<BundleMount>())
			.Select(m => $"{m.page.GetOrElse("")}>{m.extension.GetOrElse("")}>{m.selector.GetOrElse("")}")
			.OrderBy(m => m, StringComparer.Ordinal));
		var site = c.site.HasValue ? c.site.Value.ToString().ToLowerInvariant() : "";
		var source = c.sourceAvailable.GetOrElse(false) ? $", source {Short(c.sourceArchive.GetOrElse(""))}" : "";
		return $"{site}, {entry}{source}" + (mounts.Length > 0 ? $", mounts {mounts}" : "");
	}

	private static string Fingerprint(BundleFeature f) =>
		$"{f.title.GetOrElse("")}: {string.Join(", ", f.components.GetOrElse(Array.Empty<string>()).OrderBy(c => c, StringComparer.Ordinal))}" +
		(f.enabledByDefault.GetOrElse(false) ? " (on by default)" : "") +
		$" | {f.description.GetOrElse("")}";

	private static string Fingerprint(BundleDep d) =>
		$"{(d.kind.HasValue ? d.kind.Value.ToString().ToLowerInvariant() : "")} {BundleDependencyConfig.FormatRange(d.min.GetOrElse(0), d.max.HasValue ? d.max.Value : null)}";

	private static string Short(string sha) => sha.Length > 12 ? sha.Substring(0, 12) : sha;

	private static void DiffSide(BundleDiffResult result, string kind, Dictionary<string, string> local, Dictionary<string, string> published)
	{
		foreach (var (name, fingerprint) in local)
		{
			if (!published.TryGetValue(name, out var pub))
				result.changes.Add(new BundleComponentChange { name = name, kind = kind, change = "Added", local = fingerprint });
			else if (pub != fingerprint)
				result.changes.Add(new BundleComponentChange { name = name, kind = kind, change = "Changed", local = fingerprint, published = pub });
		}

		foreach (var (name, fingerprint) in published)
		{
			if (!local.ContainsKey(name))
				result.changes.Add(new BundleComponentChange { name = name, kind = kind, change = "Removed", published = fingerprint });
		}
	}

	/// <summary>
	/// Log a human-readable summary of the diff, using the same grouped layout as
	/// <see cref="cli.Deployment.Services.DeployUtil.PrintPlanInfo"/> ("Adding 2 services\n - x\n - y").
	/// </summary>
	public static void Print(BundleDiffResult diff, string bundleName)
	{
		var detectedChangeCount = 0;
		foreach (var kind in new[] { ("service", "service"), ("storage", "storage"), ("extension", "portal extension"), ("schema", "schema"), ("componentGroup", "component group"), ("dependency", "bundle dependency") })
		{
			foreach (var (change, verb) in new[] { ("Added", "Adding"), ("Removed", "Removing"), ("Changed", "Updating") })
			{
				var items = diff.changes.Where(c => c.change == change && c.kind == kind.Item1).ToList();
				if (items.Count == 0) continue;
				var sb = new StringBuilder();
				sb.AppendLine($"{verb} {items.Count} {(items.Count == 1 ? kind.Item2 : kind.Item2 + "s")}");
				foreach (var item in items)
				{
					sb.AppendLine(change == "Changed"
						? $" - {item.name}: {item.published} -> {item.local}"
						: $" - {item.name}: {(change == "Added" ? item.local : item.published)}");
				}
				Log.Warning(sb.ToString());
				detectedChangeCount += items.Count;
			}
		}

		if (detectedChangeCount == 0)
			Log.Information(diff.publishedVersion > 0
				? $"There are no changes. [{bundleName}] is the same as its latest release, v{diff.publishedVersion}."
				: $"[{bundleName}] has no components to publish.");
		else if (diff.publishedVersion == 0)
			Log.Information($"[{bundleName}] has no release yet; publishing creates v1.");
		else
			Log.Information(detectedChangeCount == 1
				? $"This plan has 1 change against v{diff.publishedVersion}."
				: $"This plan has {detectedChangeCount} changes against v{diff.publishedVersion}.");
	}
}
