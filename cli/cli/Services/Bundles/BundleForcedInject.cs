using Beamable.Api.Autogenerated.Beamobundle;
using Beamable.Api.Autogenerated.Beamoforcedbundle;
using Beamable.Api.Autogenerated.Models;
using cli.BundleCommands;
using Microsoft.Extensions.DependencyInjection;
using System.Threading.Tasks;

namespace cli.Services.Bundles;

/// <summary>The outcome of a forced-bundle override set/clear.</summary>
public class BundleForcedInjectResult
{
	public string bundleName;
	public string cid;
	public string realmId;
	public string checksum;
	public bool removed;
}

/// <summary>
/// Set (or clear) a forced-bundle override — the admin escape hatch used by Beamable's
/// portal-extension PR-preview workflow (UC13). When <paramref name="realmId"/> is passed the override
/// is scoped to that realm; otherwise it is applied CID-wide as the default for every realm.
/// Requires a Beamable SuperAdmin server token; a customer admin token is insufficient server-side.
/// This is the logic behind <c>bundles install --force</c> (set) and <c>bundles uninstall --force</c>
/// (clear).
/// </summary>
public static class BundleForcedInject
{
	public static async Task<BundleForcedInjectResult> Apply(
		CommandArgs args, string bundleName, string explicitNs, string cid, string realmId, string checksum, bool unset)
	{
		BundleWorkspace.ValidateName(bundleName);
		var name = bundleName;
		var ns = string.IsNullOrEmpty(explicitNs) ? await BundleNamespace.Get(args) : BundleNamespace.FromAlias(explicitNs);
		var fullName = BundleNamespace.Qualify(ns, name);
		var targetCid = string.IsNullOrEmpty(cid) ? args.AppContext.Cid : cid;
		var isRealmScoped = !string.IsNullOrEmpty(realmId);
		var api = args.Provider.GetService<IBeamBeamoforcedbundleApi>();

		if (unset)
		{
			if (isRealmScoped)
			{
				await api.DeleteRealmsForcedBundles(name, targetCid, ns, realmId);
			}
			else
			{
				await api.DeleteCidsForcedBundles(name, targetCid, ns);
			}

			return new BundleForcedInjectResult
			{
				bundleName = fullName, cid = targetCid, realmId = realmId, removed = true
			};
		}

		if (string.IsNullOrEmpty(checksum))
		{
			var bundleApi = args.Provider.GetService<IBeamBeamobundleApi>();
			var latest = await bundleApi.GetBundles(name, ns);
			checksum = BundleInfo.FromBundle(latest?.bundle)?.checksum;
			if (string.IsNullOrEmpty(checksum))
			{
				throw new CliException($"Could not resolve the latest published checksum for [{fullName}]; pass --checksum explicitly.");
			}
		}

		if (isRealmScoped)
		{
			await api.PutRealmsForcedBundles(name, targetCid, ns, realmId, new SetForcedBundleRequest { checksum = checksum });
		}
		else
		{
			await api.PutCidsForcedBundles(name, targetCid, ns, new SetForcedBundleRequest { checksum = checksum });
		}

		return new BundleForcedInjectResult
		{
			bundleName = fullName, cid = targetCid, realmId = realmId, checksum = checksum, removed = false
		};
	}
}
