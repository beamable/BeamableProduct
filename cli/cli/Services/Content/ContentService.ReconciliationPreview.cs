using Beamable.Api.Autogenerated.Models;
using Beamable.Common.BeamCli.Contracts;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace cli.Content;

public partial class ContentService
{
    /// <summary>Read a selected working file and the exact reviewed realm publication without acknowledging either.</summary>
    public async Task<ContentReconciliationPreview> PreviewReconciliation(string manifestId, string contentId,
        string expectedManifestUid = null, CancellationToken token = default)
    {
        var manifest = await GetReviewedManifest(manifestId, expectedManifestUid);
        var remote = await ReadReviewedRealm(manifest, contentId, token);
        var path = GetPathForContentId(contentId, manifestId);
        var local = await ReadReviewedLocal(path, token);
        return CreateReconciliationPreview(manifestId, contentId, manifest, local, remote);
    }

    /// <summary>Apply one choice only if both sides still match the immutable preview.</summary>
    public async Task<string[]> ReconcileReviewedContent(string manifestId, string contentId, bool useLocal,
        string expectedManifestUid, string expectedLocalRevision, CancellationToken token = default)
    {
        if (string.IsNullOrEmpty(expectedManifestUid) || string.IsNullOrEmpty(expectedLocalRevision))
            throw new CliException("A reviewed publication and local revision are required.");
        var manifest = await GetReviewedManifest(manifestId, expectedManifestUid);
        var remote = await ReadReviewedRealm(manifest, contentId, token);
        // Downloading can take time; reject a publication that arrived during that interval too.
        await GetReviewedManifest(manifestId, expectedManifestUid);
        var path = GetPathForContentId(contentId, manifestId);
        await _fileSystemOperationSemaphore.WaitAsync(token);
        try
        {
            var localText = await ReadReviewedLocal(path, token);
            var current = CreateReconciliationPreview(manifestId, contentId, manifest, localText, remote);
            if (!string.Equals(current.LocalRevision, expectedLocalRevision, StringComparison.Ordinal))
                throw StaleReconciliation("The local file or realm values changed after this item was reviewed.");
            token.ThrowIfCancellationRequested();
            var file = localText == null ? new ContentFile() : JsonSerializer.Deserialize<ContentFile>(localText, GetContentFileSerializationOptions());
            file.Id = contentId;
            file.LocalFilePath = path;
            file.FetchedFromManifestUid = expectedManifestUid;
            file.ReferenceIsUnknown = false;
            if (!useLocal && remote.HasValue)
            {
                file.ReferenceContent = manifest.entries.Single(e => e.contentId == contentId);
                file.Properties = remote.Value.GetProperty(ContentFile.JSON_NAME_PROPERTIES);
                file.Tags = remote.Value.GetProperty(ContentFile.JSON_NAME_TAGS);
                file.PropertiesChecksum = CalculateChecksum(in file);
                file.Baseline = new ContentBaseline(file.PropertiesChecksum, file.ReferenceContent.version);
            }
            // This coordinates writers using this service's semaphore. External editors/processes and
            // writers outside that semaphore can still race the final read and file replacement.
            if (useLocal ? localText != null : remote.HasValue)
                await SaveContentFile(Path.GetDirectoryName(path)!, file, token);
            else if (!useLocal && localText != null)
                File.Delete(path);
            await RememberReferences(manifestId, new[] { file }, expectedManifestUid, confirmed: true);
            return new[] { contentId };
        }
        finally { _fileSystemOperationSemaphore.Release(); }
    }

    private async Task<ClientManifestJsonResponse> GetReviewedManifest(string manifestId, string expectedUid)
    {
        var manifest = await GetManifest(manifestId, replaceLatest: true);
        if (!string.IsNullOrEmpty(expectedUid) && manifest.uid.GetOrElse("") != expectedUid)
            throw StaleReconciliation("The realm changed after this item was reviewed.");
        return manifest;
    }

    private static CliException StaleReconciliation(string reason) => new(
        reason + " Refresh and review it again before reconciling.", ERR_CODE_PUBLISH_FAILED_INVALID_REFERENCE_MANIFEST, true);

    private async Task<JsonElement?> ReadReviewedRealm(ClientManifestJsonResponse manifest, string id, CancellationToken token)
    {
        var entry = manifest.entries.SingleOrDefault(e => e.contentId == id);
        if (entry == null) return null;
        var downloaded = await DownloadContentFile(new ContentFile { Id = id, ReferenceContent = entry }, token);
        return ContentEnvelope(downloaded.GetProperty(ContentFile.JSON_NAME_PROPERTIES),
            JsonSerializer.SerializeToElement(entry.tags ?? Array.Empty<string>()));
    }

    private static async Task<string> ReadReviewedLocal(string path, CancellationToken token)
    {
        try { return await File.ReadAllTextAsync(path, token); }
        catch (FileNotFoundException) { return null; }
        catch (DirectoryNotFoundException) { return null; }
    }

    private static JsonElement ContentEnvelope(JsonElement properties, JsonElement tags) =>
        JsonSerializer.SerializeToElement(new { properties, tags });

    private ContentReconciliationPreview CreateReconciliationPreview(string manifestId, string id,
        ClientManifestJsonResponse manifest, string localText, JsonElement? remote)
    {
        JsonElement? local = null;
        if (localText != null)
        {
            var parsed = JsonSerializer.Deserialize<JsonElement>(localText, GetContentFileSerializationOptions());
            local = ContentEnvelope(parsed.GetProperty(ContentFile.JSON_NAME_PROPERTIES), parsed.GetProperty(ContentFile.JSON_NAME_TAGS));
        }
        var uid = manifest.uid.GetOrElse("");
        // Framed JSON avoids ambiguous concatenation. Raw local JSON also protects baseline/reference changes.
        var review = JsonSerializer.Serialize(new { cid = _requester.Cid, pid = _requester.Pid, manifestId, id, uid,
            localText, remote = remote.HasValue ? JsonSerializer.Serialize(remote.Value, GetContentFileSerializationOptions(false)) : null });
        return new ContentReconciliationPreview
        {
            ContentId = id, ManifestUid = uid, LocalExists = local.HasValue, RealmExists = remote.HasValue,
            LocalJson = local.HasValue ? JsonSerializer.Serialize(local.Value, GetContentFileSerializationOptions()) : null,
            RealmJson = remote.HasValue ? JsonSerializer.Serialize(remote.Value, GetContentFileSerializationOptions()) : null,
            LocalRevision = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(review))).ToLowerInvariant(),
            Differences = local.HasValue && remote.HasValue ? ReconciliationDifferences(local.Value, remote.Value) : Array.Empty<ContentReconciliationDifference>()
        };
    }

    private static ContentReconciliationDifference[] ReconciliationDifferences(JsonElement local, JsonElement realm)
    {
        var localProperties = local.GetProperty(ContentFile.JSON_NAME_PROPERTIES);
        var realmProperties = realm.GetProperty(ContentFile.JSON_NAME_PROPERTIES);
        var names = localProperties.EnumerateObject().Select(p => p.Name)
            .Union(realmProperties.EnumerateObject().Select(p => p.Name)).OrderBy(n => n, StringComparer.Ordinal);
        var differences = new List<ContentReconciliationDifference>();
        foreach (var name in names)
        {
            bool hasLocal = localProperties.TryGetProperty(name, out var localValue);
            bool hasRealm = realmProperties.TryGetProperty(name, out var realmValue);
            if (hasLocal && hasRealm && CanonicalValue(localValue) == CanonicalValue(realmValue)) continue;
            differences.Add(new ContentReconciliationDifference { Property = name,
                LocalValue = hasLocal ? DisplayValue(localValue) : "Not present",
                RealmValue = hasRealm ? DisplayValue(realmValue) : "Not present" });
        }
        var localTags = local.GetProperty(ContentFile.JSON_NAME_TAGS).EnumerateArray().Select(t => t.GetString()).ToHashSet();
        var realmTags = realm.GetProperty(ContentFile.JSON_NAME_TAGS).EnumerateArray().Select(t => t.GetString()).ToHashSet();
        if (!localTags.SetEquals(realmTags))
            differences.Add(new ContentReconciliationDifference { Property = "Tags",
                LocalValue = JsonSerializer.Serialize(localTags.OrderBy(t => t, StringComparer.Ordinal)),
                RealmValue = JsonSerializer.Serialize(realmTags.OrderBy(t => t, StringComparer.Ordinal)) });
        return differences.ToArray();
    }

    private static string CanonicalValue(JsonElement value) => JsonSerializer.Serialize(value, GetContentFileSerializationOptions(false));

    private static string DisplayValue(JsonElement value)
    {
        if (value.ValueKind == JsonValueKind.Object && value.EnumerateObject().Count() == 1 && value.TryGetProperty("data", out var data))
            value = data;
        return CanonicalValue(value);
    }
}
