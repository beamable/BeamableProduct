using Beamable.Api.Autogenerated.Models;
using Beamable.Common.BeamCli.Contracts;
using Beamable.Common.Content;
using System.Text.Json;

namespace cli.Content;

public partial class ContentService
{
	// Keep this outside the content JSON directory: it is workspace bookkeeping, never published content.
	private string ReconciliationPath(string manifestId) => Path.Combine(
		_config.GetConfigPath(ConfigService.LOCAL_FOLDER_NAME), "content-reconciliation",
		_requester.Cid, _requester.Pid, manifestId + ".json");

	private sealed class ReconciliationState
	{
		// Observation proves only that later additions were absent, not that existing items were downloaded.
		public string ObservedManifestUid { get; set; }
		public Dictionary<string, string> References { get; set; } = new();
		public HashSet<string> PendingPublishIds { get; set; } = new();
	}

	private async Task<ReconciliationState> UpdateReconciliation(string manifestId,
		Func<ReconciliationState, bool> update, CancellationToken token = default)
	{
		var path = ReconciliationPath(manifestId);
		Directory.CreateDirectory(Path.GetDirectoryName(path)!);
		// A short file lease also coordinates separate CLI invocations in the same workspace.
		FileStream lease = null;
		for (var attempt = 0; lease == null; attempt++)
		{
			token.ThrowIfCancellationRequested();
			try { lease = new FileStream(path + ".lock", FileMode.OpenOrCreate, FileAccess.ReadWrite, FileShare.None); }
			catch (IOException) when (attempt < 40) { await Task.Delay(25, token); }
		}
		using (lease)
		{
			var state = File.Exists(path)
				? JsonSerializer.Deserialize<ReconciliationState>(await File.ReadAllTextAsync(path, token))
				: new ReconciliationState();
			if (state?.References == null) throw new IOException("Content reconciliation history is unreadable: " + path);
			if (update(state))
			{
				var temporary = path + ".tmp";
				try
				{
					await File.WriteAllTextAsync(temporary, JsonSerializer.Serialize(state), token);
					token.ThrowIfCancellationRequested();
					File.Move(temporary, path, true);
				}
				finally { if (File.Exists(temporary)) File.Delete(temporary); }
			}
			return state;
		}
	}

	private Task<ReconciliationState> RememberReferences(string manifestId, IEnumerable<ContentFile> files,
		string observedUid, CancellationToken token = default, ISet<string> remoteIds = null, bool confirmed = false) => UpdateReconciliation(manifestId, state =>
	{
		bool changed = false;
		if (string.IsNullOrEmpty(state.ObservedManifestUid))
		{
			// Start at the actual observation. Surviving files cannot prove the history of missing files.
			state.ObservedManifestUid = observedUid;
			changed = true;
		}
		foreach (var file in files)
		{
			if (string.IsNullOrEmpty(file.FetchedFromManifestUid) || file.ReferenceIsUnknown) continue;
			if (confirmed && state.PendingPublishIds.Remove(file.Id)) changed = true;
			if (!state.References.TryGetValue(file.Id, out var previous) || previous != file.FetchedFromManifestUid)
			{
				state.References[file.Id] = file.FetchedFromManifestUid;
				changed = true;
			}
		}
		if (remoteIds != null)
		{
			var localIds = files.Select(file => file.Id).ToHashSet();
			// Both sides absent is already reconciled. Retain that absence so a later re-addition is incoming.
			foreach (var id in state.References.Keys.ToArray())
				if (!localIds.Contains(id) && !remoteIds.Contains(id) && state.References[id] != observedUid)
				{
					state.References[id] = observedUid;
					changed = true;
				}
		}
		return changed;
	}, token);

	private static bool SamePublishedEntry(ClientContentInfoJson left, ClientContentInfoJson right)
	{
		if (left == null || right == null) return left == right;
		return left.checksum.GetOrElse("") == right.checksum.GetOrElse("") &&
			new HashSet<string>(left.tags ?? Array.Empty<string>()).SetEquals(right.tags ?? Array.Empty<string>());
	}

	private static ContentChangeKind ClassifyChange(ContentFile local, ContentFile original)
	{
		if (local.ReferenceIsUnknown) return ContentChangeKind.Unknown;
		var targetStatus = local.GetStatus();
		if (targetStatus == ContentStatus.UpToDate) return ContentChangeKind.UpToDate;
		bool exists = !string.IsNullOrEmpty(local.LocalFilePath) && File.Exists(local.LocalFilePath);
		bool localChanged = exists
			? original.ReferenceContent == null || original.GetStatus() != ContentStatus.UpToDate
			: original.ReferenceContent != null;
		bool remoteChanged = !SamePublishedEntry(original.ReferenceContent, local.ReferenceContent);
		if (localChanged && remoteChanged) return ContentChangeKind.Conflict;
		if (remoteChanged)
			return local.ReferenceContent == null ? ContentChangeKind.IncomingDeletion
				: original.ReferenceContent == null ? ContentChangeKind.IncomingAddition : ContentChangeKind.IncomingChange;
		return localChanged ? ContentChangeKind.LocalEdit : ContentChangeKind.UpToDate;
	}

	private static bool NeedsReconciliation(ContentFile file) => file.ChangeKind is
		ContentChangeKind.Unknown or ContentChangeKind.IncomingChange or ContentChangeKind.IncomingAddition or ContentChangeKind.IncomingDeletion;

	private static void RequireReconciled(LocalContentFiles files)
	{
		var pending = files.ContentFiles.Where(NeedsReconciliation).ToArray();
		if (pending.Length == 0) return;
		throw new CliException("Publishing blocked. Reconcile incoming content or unverified local deletions before publishing. " +
			string.Join("; ", pending.Select(c => $"{c.Id} ({c.ChangeKind})")),
			ERR_CODE_PUBLISH_FAILED_INVALID_REFERENCE_MANIFEST, true);
	}

	/// <summary>Explicit, selected-item reconciliation. Observation and cancellation never acknowledge a choice.</summary>
	public async Task<string[]> ReconcileContent(string manifestId, string[] ids, bool useLocal, CancellationToken token = default, string expectedManifestUid = null)
	{
		if (ids == null || ids.Length == 0) throw new CliException("Select content IDs to reconcile.");
		var latest = await GetManifest(manifestId, replaceLatest: true);
		if (!string.IsNullOrEmpty(expectedManifestUid) && expectedManifestUid != latest.uid.GetOrElse(""))
			throw new CliException("The realm changed after this item was reviewed. Refresh and review it again before reconciling.", ERR_CODE_PUBLISH_FAILED_INVALID_REFERENCE_MANIFEST, true);
		var files = await GetAllContentFiles(latest, manifestId, ContentFilterType.ExactIds, ids);
		var pending = files.ContentFiles.Where(c => c.IsInConflict || NeedsReconciliation(c)).ToArray();
		if (pending.Length == 0) return Array.Empty<string>();
		var folder = EnsureContentPathForRealmExists(out _, _requester.Pid, manifestId);
		if (!useLocal)
		{
			await SyncLocalContent(latest, manifestId, ContentFilterType.ExactIds, pending.Select(c => c.Id).ToArray(),
				syncCreated: true, syncModified: true, forceSyncConflicts: true, syncDeleted: true, cancellationToken: token);
		}
		else
		{
			var completed = new List<ContentFile>();
			token.ThrowIfCancellationRequested();
			await _fileSystemOperationSemaphore.WaitAsync(token);
			try
			{
				foreach (var file in pending)
				{
					token.ThrowIfCancellationRequested();
					var acknowledged = file;
					acknowledged.FetchedFromManifestUid = latest.uid.GetOrElse("");
					acknowledged.ReferenceIsUnknown = false;
					if (!string.IsNullOrEmpty(file.LocalFilePath) && File.Exists(file.LocalFilePath))
						await SaveContentFile(folder, acknowledged, token);
					completed.Add(acknowledged);
				}
			}
			finally
			{
				// Persist the batch once, including successful items before a failure or cancellation.
				try
				{
					if (completed.Count > 0) await RememberReferences(manifestId, completed, latest.uid.GetOrElse(""), confirmed: true);
				}
				finally { _fileSystemOperationSemaphore.Release(); }
			}
		}
		return pending.Select(c => c.Id).ToArray();
	}
}
