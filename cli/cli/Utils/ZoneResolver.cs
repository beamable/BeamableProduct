using Beamable.Api.Autogenerated.Customer;
using Beamable.Common;
using Beamable.Common.Dependencies;

namespace cli;

/// <summary>
/// Shared resolution of the "effective" zone id for a workspace, used by both <c>beam config</c> and
/// <c>project generate-env</c> so the two never drift.
/// </summary>
public static class ZoneResolver
{
	/// <summary>
	/// Resolves the effective zone id.
	/// <para>
	/// When a <paramref name="pid"/> is selected, the realm's zone binding is authoritative: it wins over any
	/// local zid, and a realm bound to no zone resolves to <c>null</c> ("no zone") regardless of
	/// <paramref name="localZid"/>. When no pid is selected, the local zid (from the .beamable config) is used.
	/// </para>
	/// </summary>
	/// <param name="provider">Dependency provider used to resolve the customer API.</param>
	/// <param name="cid">Numeric customer id (alias-resolved) for the realm lookup.</param>
	/// <param name="pid">The currently selected realm, or null/empty when none is selected.</param>
	/// <param name="localZid">The zid stored in the .beamable config, used only when no pid is selected.</param>
	public static async Promise<string> ResolveZid(IDependencyProvider provider, string cid, string pid, string localZid)
	{
		if (!string.IsNullOrEmpty(pid))
		{
			var customerApi = provider.GetService<IBeamCustomerApi>();
			var realmView = await customerApi.GetRealms(cid, pid);
			return (realmView.zoneId != null && realmView.zoneId.HasValue) ? realmView.zoneId.Value : null;
		}

		return string.IsNullOrEmpty(localZid) ? null : localZid;
	}
}
