using Beamable.Common.BeamCli;
using Beamable.Common.BeamCli.Contracts;
using Beamable.Common.Content;
using Beamable.Server.Content;
using System.CommandLine;
using System.Text.Json;

namespace cli.Content;

/// <summary>
/// Shared baking entry point for service images and Unity. The source and output format
/// are independent so the Unity editor can later replace its baker with this command.
/// </summary>
public class ContentBakeCommand : AtomicCommand<ContentBakeCommandArgs, ContentBakeResult>, ISkipManifest
{
	public ContentBakeCommand() : base("bake", "Bake content and its manifest for a service or Unity build") { }

	public override void Configure()
	{
		AddOption(new Option<string>("--source", () => "published", "published or local"), (args, value) => args.Source = value);
		AddOption(new Option<string>("--format", () => "server", "server or unity"), (args, value) => args.Format = value);
		AddOption(new Option<string>("--manifest-id", () => "global", "Manifest to bake"), (args, value) => args.ManifestId = value);
		AddOption(new Option<string>("--output-dir", "Directory for bakedContent.bytes and bakedManifest.bytes"), (args, value) => args.OutputDir = value);
		AddOption(new Option<string>("--local-changes", () => "fail", "fail or skip when local content differs from the published manifest"), (args, value) => args.LocalChanges = value);
		AddOption(new Option<string>("--compression", () => "gzip", "gzip or none"), (args, value) => args.Compression = value);
	}

	public override async Task<ContentBakeResult> GetResult(ContentBakeCommandArgs args)
	{
		if (args.Source is not ("published" or "local")) throw new CliException("--source must be published or local.");
		if (args.Format is not ("server" or "unity")) throw new CliException("--format must be server or unity.");
		if (args.LocalChanges is not ("fail" or "skip")) throw new CliException("--local-changes must be fail or skip.");
		if (args.Compression is not ("gzip" or "none")) throw new CliException("--compression must be gzip or none.");
		if (string.IsNullOrWhiteSpace(args.OutputDir)) throw new CliException("--output-dir is required.");
		if (string.IsNullOrWhiteSpace(args.ManifestId)) throw new CliException("--manifest-id cannot be empty.");

		var manifest = await args.ContentService.GetManifest(args.ManifestId, replaceLatest: true);
		var allReferences = manifest.entries ?? Array.Empty<Beamable.Api.Autogenerated.Models.ClientContentInfoJson>();
		var references = allReferences
			.Where(entry => entry.type.ToString() == "Content")
			.OrderBy(entry => entry.contentId, StringComparer.Ordinal)
			.ToArray();
		var archive = new BakedContentArchive
		{
			cid = args.Requester.Cid,
			pid = args.Requester.Pid,
			manifestId = args.ManifestId,
			manifestUid = manifest.uid.GetOrElse("")
		};

		if (args.Source == "local")
		{
			// getLocalStateOnly prevents baking from synchronizing or modifying editor content.
			var files = await args.ContentService.GetAllContentFiles(manifest, args.ManifestId, getLocalStateOnly: true);
			var byId = files.ContentFiles.ToDictionary(file => file.Id, StringComparer.Ordinal);
			var publishedIds = allReferences.Select(reference => reference.contentId).ToHashSet(StringComparer.Ordinal);
			if (args.LocalChanges == "fail" && files.ContentFiles.Any(file => !publishedIds.Contains(file.Id)))
				throw new CliException("Local content contains items that are not in the published manifest.");
			foreach (var reference in references)
			{
				if (!byId.TryGetValue(reference.contentId, out var file) || file.GetStatus() != ContentStatus.UpToDate)
				{
					if (args.LocalChanges == "fail") throw new CliException($"Local content is not up to date: {reference.contentId}");
					continue;
				}
				var data = JsonSerializer.Serialize(new
				{
					id = reference.contentId,
					version = reference.version,
					properties = file.Properties
				});
				ValidateContent(data, reference.contentId, reference.version);
				archive.content.Add(new BakedContentEntry { contentId = reference.contentId, contentVersion = reference.version, data = data });
			}
		}
		else
		{
			using var concurrency = new SemaphoreSlim(16);
			var downloads = references.Select(async reference =>
			{
				await concurrency.WaitAsync(args.Lifecycle.CancellationToken);
				try
				{
					var data = await args.ContentService.DownloadPublishedContent(reference, args.Lifecycle.CancellationToken);
					ValidateContent(data, reference.contentId, reference.version);
					return new BakedContentEntry { contentId = reference.contentId, contentVersion = reference.version, data = data };
				}
				finally { concurrency.Release(); }
			});
			archive.content.AddRange(await Task.WhenAll(downloads));
		}

		var clientManifest = new ClientManifest
		{
			uid = archive.manifestUid,
			entries = allReferences.OrderBy(reference => reference.contentId, StringComparer.Ordinal).Select(reference => new ClientContentInfo
			{
				contentId = reference.contentId,
				version = reference.version,
				uri = reference.uri,
				type = reference.type.ToString(),
				tags = reference.tags,
				manifestID = args.ManifestId
			}).ToList()
		};

		var outputDir = Path.GetFullPath(args.OutputDir);
		Directory.CreateDirectory(outputDir);
		var contentPath = Path.Combine(outputDir, BakedContentArchive.ContentFileName);
		var manifestPath = Path.Combine(outputDir, BakedContentArchive.ManifestFileName);
		var compress = args.Compression == "gzip";
		// The Unity format retains the exact ContentDataInfoWrapper root shape.
		var contentValue = args.Format == "unity" ? (object)new { content = archive.content } : archive;
		await WriteFile(contentPath, BakedContentArchive.Encode(contentValue, compress));
		await WriteFile(manifestPath, BakedContentArchive.Encode(clientManifest, compress));
		return new ContentBakeResult { ContentPath = contentPath, ManifestPath = manifestPath, Count = archive.content.Count };
	}

	private static void ValidateContent(string data, string id, string version)
	{
		using var document = JsonDocument.Parse(data);
		var root = document.RootElement;
		if (root.ValueKind != JsonValueKind.Object ||
		    !root.TryGetProperty("id", out var actualId) || actualId.GetString() != id ||
		    !root.TryGetProperty("version", out var actualVersion) || actualVersion.GetString() != version ||
		    !root.TryGetProperty("properties", out _))
			throw new CliException($"Baked content does not match published manifest: {id}");
	}

	private static async Task WriteFile(string path, byte[] data)
	{
		var temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
		try
		{
			await File.WriteAllBytesAsync(temporary, data);
			File.Move(temporary, path, true);
		}
		finally
		{
			if (File.Exists(temporary)) File.Delete(temporary);
		}
	}
}

[CliContractType, Serializable]
public class ContentBakeCommandArgs : ContentCommandArgs
{
	public string Source;
	public string Format;
	public string ManifestId;
	public string OutputDir;
	public string LocalChanges;
	public string Compression;
}

[CliContractType, Serializable]
public class ContentBakeResult
{
	public string ContentPath;
	public string ManifestPath;
	public int Count;
}
