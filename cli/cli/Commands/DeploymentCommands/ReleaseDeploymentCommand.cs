public class ReleaseDeploymentCommand 
	: AppCommand<ReleaseDeploymentCommandArgs>
	, IResultSteam<DefaultStreamResultChannel, DeploymentPlanMetadata>
	, IResultSteam<RunProjectBuildErrorStreamChannel, RunProjectBuildErrorStream>
	, IResultSteam<PlanReleaseProgressChannel, PlanReleaseProgress>
	, IResultSteam<ReleaseWaitResultChannel, ReleaseWaitResult>
{
	public ReleaseDeploymentCommand() : base("release", "Perform a release, this will modify remote running services")
	{
		AddAlias("fire");
	}

	public override void Configure()
	{
		DeployArgs.AddPlanOptions(this);
		DeployArgs.AddScopeOption(this);
		AddOption(new Option<string>(new string[] { "--from-plan", "--plan", "-p" }, "The file path to a pre-generated plan file using the `deploy plan` command"),
			(args, i) => args.fromPlanFile = i);
		SolutionCommandArgs.ConfigureSolutionFlag(this, _ => throw new CliException("Must have a valid .beamable folder"));

		// TODO: is this really helpful?
		AddOption(new Option<bool>(new string[]{"--from-latest-plan", "--latest-plan", "--last-plan", "-lp"}, "Use the most recent plan generated from the plan command"), (args, i) => args.fromLastPlan = i);

		AddOption(new Option<bool>("--wait", "After releasing, poll the remote status until every released service is running and current, or until --wait-timeout expires"),
			(args, i) => args.wait = i);
		AddOption(new Option<int>("--wait-timeout", () => ReleaseWaitUtil.DEFAULT_TIMEOUT_SECONDS, "The maximum number of seconds --wait will poll before failing"),
			(args, i) => args.waitTimeoutSeconds = i);
	}

	public override async Task Handle(ReleaseDeploymentCommandArgs args)
	{
		DeployablePlan plan = null;
		string planPath = null;

		// Resolve the plan source before touching scope: a plan loaded from disk carries its own scope
		// (realm/zone), and that scope — not the CLI flag — must drive the whole release, since the plan's
		// manifest and checksum were built under it.
		var isLoadingPlan = !string.IsNullOrEmpty(args.fromPlanFile);
		if (args.fromLastPlan)
		{
			if (isLoadingPlan)
			{
				throw new CliException("cannot specify both --from-latest-plan and --plan");
			}
			args.fromPlanFile = DeployUtil.GetLatestPlanFilePath(args.DependencyProvider);
			if (args.fromPlanFile == null)
			{
				throw new CliException(
					"cannot use --from-latest-plan, because there are no plan files. Please run `dotnet beam deploy plan`");
			}

			isLoadingPlan = true;
		}
		var isLoadingManifest = !string.IsNullOrEmpty(args.FromManifestFile);

		if (isLoadingPlan && isLoadingManifest)
		{
			throw new CliException("Cannot specify both --from-plan and --from-manifest");
		}

		if (isLoadingPlan)
		{
			Log.Information($"Loading release plan from file=[{args.fromPlanFile}]");
			var json = await File.ReadAllTextAsync(args.fromPlanFile);

			// before deserializing it as a plan, check the fields to make sure its a valid plan.
			var data = Json.Deserialize(json) as IDictionary<string, object>;
			if (!DeployUtil.IsJsonAPlan(data))
			{
				// do a special check to see if this looks like a manifest view...
				if (DeployUtil.IsJsonAManifest(data))
				{
					throw new CliException(
						$"The file {args.fromPlanFile} appears to contain a manifest, but should contain a plan." +
						$" Use `dotnet beam deploy release --from-manifest {args.fromPlanFile}` to create a plan.");
				}
				throw new CliException(
					$"The file {args.fromPlanFile} does not contain a valid plan. Use the `dotnet beam deploy plan` command to create a plan.");
			}
			plan = JsonSerializable.FromJson<DeployablePlan>(json);

			// The plan's scope is authoritative — adopt it so the requester and downstream operations
			// target the manifest (realm vs zone) the plan was built against.
			if (args.Scope != plan.scope)
			{
				Log.Information($"Releasing with scope [{plan.scope}] from the loaded plan.");
				args.Scope = plan.scope;
			}
		}

		// For `--scope zone` (from the flag or the loaded plan), pin the requester to the zone (cid.zid)
		// before any manifest fetch/publish so the whole release targets the zone manifest; realm is a no-op.
		using var scopeHandle = await DeployArgs.ApplyDeployScopeAsync(args, args.Scope);

		var remoteManifestTask = DeployUtil.CreateReleaseManifestViewFromRealmV2(args.DependencyProvider.GetService<IBeamBeamoApi>());

		if (!isLoadingPlan)
		{
			Log.Information("Generating release plan...");
			(plan, planPath) = await this.InteractivePlan(
				args.DependencyProvider,
				args);
		}

		var remoteManifest = await remoteManifestTask;
		if (remoteManifest.checksum != plan.builtFromRemoteChecksum)
		{
			throw new CliException(
				"The given deployment plan was created with a different configuration of remote services than exists now. Please create a new plan and try again.");
		}
		
		
		DeployUtil.PrintPlanInfo(plan, args, out var hasChanges);
		this.ApplyDeployComments(plan, args);
		if (!string.IsNullOrEmpty(planPath))
		{
			Log.Information("Saved plan: " + planPath);
		}
		this.SendResults<DefaultStreamResultChannel, DeploymentPlanMetadata>(new DeploymentPlanMetadata
		{
			success = true,
			plan = plan,
			planPath = planPath
		});

		Log.Information(@$"Releasing plan to target:
 HOST={args.AppContext.Host}
 CID={args.AppContext.Cid}
 PID={args.AppContext.Pid}");
		var confirmationText = hasChanges
			? "Are you sure you want to release the changes?"
			: "You can still deploy the services, which will roll existing services. Do you want to continue?";

		confirmationText += "\nType 'yes' to continue.";
		var confirm = args.Quiet || string.Equals("yes", AnsiConsole.Prompt(new TextPrompt<string>(confirmationText)), StringComparison.InvariantCultureIgnoreCase);
		if (!confirm)
		{
			return;
		}

		var progressReporter = (IResultSteam<PlanReleaseProgressChannel, PlanReleaseProgress>)this;
		await AnsiConsole
			.Progress()
			.StartAsync(async ctx =>
			{

				var progressTasks = new Dictionary<string, ProgressTask>();
			
				await DeployUtil.Deploy(
					plan,
					args.DependencyProvider,
					progressHandler: (name, progress, isKnownLength, serviceName) =>
					{
						if (!progressTasks.TryGetValue(name, out var progressTask))
						{
							progressTasks[name] = progressTask = ctx.AddTask(name, maxValue: 1);
						}

						if (!isKnownLength && progress > 0)
						{
							progressTask.IsIndeterminate = true;
						}

						progressReporter.SendResults(new PlanReleaseProgress
						{
							ratio = progress,
							name = name,
							isKnownLength = isKnownLength,
							serviceName = serviceName
						});

						progressTask.Value = progress;
					},
					args.Lifecycle.Source,
					remoteManifestTask,
					maxConcurrentUploads: args.MaxConcurrentUploads);
	
			});

		if (args.wait)
		{
			await WaitForRelease(plan, args);
		}
	}

	async Task WaitForRelease(DeployablePlan plan, ReleaseDeploymentCommandArgs args)
	{
		var services = ReleaseWaitUtil.GetServicesToWaitOn(plan);
		var timeout = TimeSpan.FromSeconds(Math.Max(0, args.waitTimeoutSeconds));
		Log.Information($"Waiting up to {timeout.TotalSeconds}s for released services to be ready: [{string.Join(", ", services)}]");

		var api = args.DependencyProvider.GetService<IBeamoApi>();
		var lastReadyCount = -1;
		var result = await ReleaseWaitUtil.WaitForServices(
			services,
			() => ShowCurrentBeamoStatusCommand.FetchStatus(api, showArchived: false),
			timeout,
			ReleaseWaitUtil.DefaultPollInterval,
			onPoll: poll =>
			{
				var readyCount = poll.services.Count(x => x.ready);
				if (readyCount == lastReadyCount)
				{
					return;
				}
				lastReadyCount = readyCount;
				Log.Information($"Released services ready: {readyCount}/{poll.services.Count}");
			},
			token: args.Lifecycle.CancellationToken);

		foreach (var service in result.services)
		{
			Log.Information($"  {service.service}: {service.status} (running={service.running}, isCurrent={service.isCurrent})");
		}

		this.SendResults<ReleaseWaitResultChannel, ReleaseWaitResult>(result);
		ReleaseWaitUtil.ThrowIfNotReady(result);
		Log.Information("All released services are running and current.");
	}
}

public class ReleaseWaitResultChannel : IResultChannel
{
	public string ChannelName => "waitResult";
}

/// <summary>
/// The outcome of <c>deploy release --wait</c>: the last polled status of every released service.
/// </summary>
public class ReleaseWaitResult
{
	/// <summary>True when every released service is running and current.</summary>
	public bool allReady;
	/// <summary>True when --wait-timeout expired before every released service was ready.</summary>
	public bool timedOut;
	public double timeoutSeconds;
	public double elapsedSeconds;
	public List<ReleasedServiceStatus> services = new List<ReleasedServiceStatus>();
}

public class ReleasedServiceStatus
{
	public const string STATUS_READY = "ready";
	public const string STATUS_NOT_CURRENT = "not-current";
	public const string STATUS_NOT_RUNNING = "not-running";
	public const string STATUS_MISSING = "missing";

	public string service;
	public bool running;
	public bool isCurrent;
	/// <summary>running and isCurrent</summary>
	public bool ready;
	/// <summary>One of "ready", "not-current", "not-running" or "missing" (not yet reported by the remote status)</summary>
	public string status;
	public string imageId;
}

public static class ReleaseWaitUtil
{
	public const int DEFAULT_TIMEOUT_SECONDS = 600;
	public static readonly TimeSpan DefaultPollInterval = TimeSpan.FromSeconds(5);

	/// <summary>
	/// The services that will be running after the plan is released: enabled, non-archived entries of the
	/// plan's manifest. Services the release removes or disables are not waited on.
	/// </summary>
	public static List<string> GetServicesToWaitOn(DeployablePlan plan)
	{
		var entries = plan?.manifest?.manifest;
		if (entries == null)
		{
			return new List<string>();
		}
		return entries
			.Where(x => x.enabled && !x.archived && !string.IsNullOrEmpty(x.serviceName))
			.Select(x => x.serviceName)
			.Distinct()
			.ToList();
	}

	/// <summary>
	/// Poll <paramref name="fetchStatus"/> until every service in <paramref name="serviceNames"/> is running
	/// and current, or until <paramref name="timeout"/> elapses. Statuses for services not in
	/// <paramref name="serviceNames"/> are ignored. This never throws on timeout; see <see cref="ThrowIfNotReady"/>.
	/// </summary>
	/// <param name="delay">Injectable for tests; defaults to <see cref="Task.Delay(TimeSpan, CancellationToken)"/></param>
	/// <param name="getElapsed">Injectable for tests; defaults to a <see cref="Stopwatch"/> started on entry</param>
	public static async Task<ReleaseWaitResult> WaitForServices(
		IReadOnlyCollection<string> serviceNames,
		Func<Task<BeamoStatusResponse>> fetchStatus,
		TimeSpan timeout,
		TimeSpan pollInterval,
		Func<TimeSpan, CancellationToken, Task> delay = null,
		Func<TimeSpan> getElapsed = null,
		Action<ReleaseWaitResult> onPoll = null,
		CancellationToken token = default)
	{
		delay ??= Task.Delay;
		if (getElapsed == null)
		{
			var stopwatch = Stopwatch.StartNew();
			getElapsed = () => stopwatch.Elapsed;
		}

		while (true)
		{
			token.ThrowIfCancellationRequested();
			var status = serviceNames.Count > 0 ? await fetchStatus() : null;
			var result = BuildResult(serviceNames, status);
			var elapsed = getElapsed();
			result.timeoutSeconds = timeout.TotalSeconds;
			result.elapsedSeconds = elapsed.TotalSeconds;
			onPoll?.Invoke(result);

			if (result.allReady)
			{
				return result;
			}

			if (elapsed >= timeout)
			{
				result.timedOut = true;
				return result;
			}

			var remaining = timeout - elapsed;
			await delay(remaining < pollInterval ? remaining : pollInterval, token);
		}
	}

	/// <summary>
	/// Map a remote status response onto the given services, in the given order.
	/// </summary>
	public static ReleaseWaitResult BuildResult(IEnumerable<string> serviceNames, BeamoStatusResponse status)
	{
		var result = new ReleaseWaitResult();
		var remote = status?.services ?? Array.Empty<BeamoServiceStatus>();
		foreach (var name in serviceNames)
		{
			// the status may carry more than one entry per service (e.g. mid-roll), so prefer the most-ready one.
			var match = remote
				.Where(x => x.serviceName == name)
				.OrderByDescending(x => x.running && x.isCurrent)
				.ThenByDescending(x => x.isCurrent)
				.ThenByDescending(x => x.running)
				.FirstOrDefault();

			var entry = new ReleasedServiceStatus { service = name };
			if (match == null)
			{
				entry.status = ReleasedServiceStatus.STATUS_MISSING;
			}
			else
			{
				entry.running = match.running;
				entry.isCurrent = match.isCurrent;
				entry.imageId = match.imageId;
				entry.ready = match.running && match.isCurrent;
				entry.status = entry.ready
					? ReleasedServiceStatus.STATUS_READY
					: !match.running
						? ReleasedServiceStatus.STATUS_NOT_RUNNING
						: ReleasedServiceStatus.STATUS_NOT_CURRENT;
			}
			result.services.Add(entry);
		}

		result.allReady = result.services.All(x => x.ready);
		return result;
	}

	/// <summary>
	/// Fail the command with the services that did not become ready, if any.
	/// </summary>
	public static void ThrowIfNotReady(ReleaseWaitResult result)
	{
		if (result.allReady)
		{
			return;
		}
		var notReady = result.services.Where(x => !x.ready).Select(x => $"{x.service} ({x.status})");
		throw new CliException(
			$"Timed out after {result.timeoutSeconds}s waiting for released services to be running and current. " +
			$"Not ready: {string.Join(", ", notReady)}. Use `dotnet beam deploy ps` to keep checking their status.");
	}
}
