using Beamable.Api.Autogenerated.Auth;
using Beamable.Api.Autogenerated.Models;
using Beamable.Api.Autogenerated.Realms;
using Beamable.Common.BeamCli;
using Beamable.Common.Content;
using cli.Utils;
using Newtonsoft.Json;
using System.CommandLine;
using System.CommandLine.Binding;
using System.Net.WebSockets;
using System.Text.RegularExpressions;
using Beamable.Server;

namespace cli.Notifications;

public class NotificationPlayerCommandArgs : CommandArgs
{
	public string contextRegexStr;
	public bool guest;
	public bool probe;
	public int probeSeconds;
}

public class NotificationPlayerOutput
{
	public string context;
	public string payload;
}

class NotificationPlayerModel
{
	public string messageFull;
	public string context;

	public NotificationPlayerModel() { }
	public NotificationPlayerModel(string messageFull, string context)
	{
		this.messageFull = messageFull;
		this.context = context;
	}
}

public class ListenPlayerProbeResultChannel : IResultChannel
{
	public string ChannelName => "probe";
}

public class NotificationPlayerCommand : StreamCommand<NotificationPlayerCommandArgs, NotificationPlayerOutput>
	, IResultSteam<ListenPlayerProbeResultChannel, ListenPlayerProbeResult>
{
	public NotificationPlayerCommand()
		: base("player", "Listen for player notifications")
	{
	}

	public override void Configure()
	{
		AddOption(new Option<string>(new string[] { "--context", "-c" }, () => ".*",
			"A regex to filter for notification channels"), (args, s) => args.contextRegexStr = s);
		AddOption(new Option<bool>("--guest", "Authenticate as a newly created guest player instead of the logged-in identity. --probe uses a guest unless --refresh-token is passed"),
			(args, b) => args.guest = b);
		AddOption(new Option<bool>("--probe", "Instead of listening, open one realtime session the way the Web SDK does, report the handshake, session-start and frames on the probe channel, then exit"),
			(args, b) => args.probe = b);
		AddOption(new Option<int>("--probe-seconds", () => ListenPlayerProbe.DEFAULT_PROBE_SECONDS, "How many seconds --probe listens for frames after the socket opens"),
			(args, i) => args.probeSeconds = i);
	}

	public override async Task Handle(NotificationPlayerCommandArgs args)
	{
		if (args.probe)
		{
			await HandleProbe(args);
			return;
		}

		var regex = new Regex(args.contextRegexStr);


		var ws = new ClientWebSocket();
		var cancelToken = new CancellationToken();
		var config = await args.DependencyProvider.GetService<IRealmsApi>().GetClientDefaults();

		Log.Debug($"provider=[{config.websocketConfig.provider}] url=[{config.websocketConfig.uri.Value}]");

		var unsupportedMessage = ListenPlayerProbe.GetUnsupportedProviderMessage(config.websocketConfig.provider);
		if (unsupportedMessage != null)
		{
			throw new CliException(unsupportedMessage);
		}


		var accessToken = await GetRealtimeAccessToken(args, args.guest);

		ws.Options.SetRequestHeader("Authorization", $"Bearer {accessToken}");
		await ws.ConnectAsync(new Uri(config.websocketConfig.uri + "/connect"), cancelToken);

		while (ws.State != WebSocketState.Closed)
		{
			var content = await WebsocketUtil.ReadMessage(ws, cancelToken);
			var message = JsonConvert.DeserializeObject<NotificationPlayerModel>(content);
			if (!regex.IsMatch(message.context)) continue;
			Log.Information($"{message.context} -- {message.messageFull}");
			SendResults(new NotificationPlayerOutput
			{
				context = message.context,
				payload = message.messageFull
			});
		}

	}

	/// <summary>
	/// Exchanges a refresh token at /api/auth/tokens/refresh-token for the JWT the realtime socket accepts.
	/// The opaque token from /basic/auth/token is rejected by the socket with a 401.
	/// </summary>
	static async Task<string> GetRealtimeAccessToken(NotificationPlayerCommandArgs args, bool useGuest)
	{
		var refreshToken = args.AppContext.RefreshToken;
		if (useGuest)
		{
			var guest = await args.DependencyProvider.GetService<IAuthApi>()
				.PostToken(new TokenRequestWrapper { grant_type = "guest" }, includeAuthHeader: false);
			refreshToken = guest.refresh_token;
		}

		var authApi = args.DependencyProvider.GetService<IBeamAuthApi>();
		var tokenAuthResult = await authApi.PostRefreshToken(new AuthV2RefreshTokenAuthRequest
		{
			customerId = new OptionalString(args.AppContext.Cid),
			realmId = new OptionalString(args.AppContext.Pid),
			refreshToken = new OptionalString(refreshToken)
		}, includeAuthHeader: !useGuest);
		return tokenAuthResult.accessToken.Value;
	}

	async Task HandleProbe(NotificationPlayerCommandArgs args)
	{
		if (args.probeSeconds < 0)
		{
			throw new CliException("--probe-seconds must be zero or more");
		}

		// Default to a new guest, like a Web SDK client: a developer login often has no player on the realm,
		// which the socket rejects. An explicit --refresh-token probes as that player instead.
		var explicitRefreshToken = args.DependencyProvider.GetService<BindingContext>().ParseResult
			.GetValueForOption(args.DependencyProvider.GetService<RefreshTokenOption>());
		var useGuest = args.guest || string.IsNullOrEmpty(explicitRefreshToken);
		var result = new ListenPlayerProbeResult
		{
			identity = useGuest ? "guest" : "current",
			listenSeconds = args.probeSeconds,
			connectTimeoutSeconds = ListenPlayerProbe.CONNECT_TIMEOUT_SECONDS
		};

		try
		{
			var config = await args.DependencyProvider.GetService<IRealmsApi>().GetClientDefaults();
			result.provider = config.websocketConfig.provider;
			result.socketUri = config.websocketConfig.uri?.Value;
		}
		catch (Exception ex)
		{
			FailProbe(result, ListenPlayerProbeResult.STAGE_REALM_CONFIG, ex,
				"Could not read the realm's client defaults (/basic/realms/client/defaults), so the socket URL is unknown");
		}

		var unsupportedMessage = ListenPlayerProbe.GetUnsupportedProviderMessage(result.provider);
		if (unsupportedMessage != null)
		{
			FailProbe(result, ListenPlayerProbeResult.STAGE_REALM_CONFIG, null, unsupportedMessage);
		}
		if (string.IsNullOrEmpty(result.socketUri))
		{
			FailProbe(result, ListenPlayerProbeResult.STAGE_REALM_CONFIG, null,
				"The realm's client defaults have no websocketConfig.uri, so there is no realtime socket to connect to");
		}

		string accessToken = null;
		try
		{
			accessToken = await GetRealtimeAccessToken(args, useGuest);
		}
		catch (Exception ex)
		{
			FailProbe(result, ListenPlayerProbeResult.STAGE_TOKEN, ex, useGuest
				? "Could not create a guest player and exchange its refresh token at /api/auth/tokens/refresh-token"
				: "Could not exchange the given refresh token at /api/auth/tokens/refresh-token. Check the token, or drop --refresh-token to probe as a new guest");
		}
		if (string.IsNullOrEmpty(accessToken))
		{
			FailProbe(result, ListenPlayerProbeResult.STAGE_TOKEN, null,
				"/api/auth/tokens/refresh-token returned no access token");
		}

		Log.Information($"Probing the realtime socket at {result.socketUri} as {(useGuest ? "a new guest" : "the logged-in player")}...");
		await ListenPlayerProbe.RunSocketProbe(result, result.socketUri, accessToken,
			TimeSpan.FromSeconds(ListenPlayerProbe.CONNECT_TIMEOUT_SECONDS),
			TimeSpan.FromSeconds(args.probeSeconds),
			args.Lifecycle.CancellationToken);
		ListenPlayerProbe.Interpret(result);

		Log.Information($"handshake=[{result.handshakeStatusCode}] opened=[{result.opened}] timeToOpenMs=[{result.timeToOpenMs}] " +
		                $"sessionStartSent=[{result.sessionStartSent}] frames=[{result.framesReceived}] closedByServer=[{result.closedByServer}]");
		foreach (var frame in result.frames)
		{
			Log.Information($"  frame: {frame}");
		}

		this.SendResults<ListenPlayerProbeResultChannel, ListenPlayerProbeResult>(result);
		if (!result.success)
		{
			throw new CliException(result.message);
		}
		Log.Information(result.message);
	}

	/// <summary>
	/// Reports a probe that failed before the socket part started, then throws.
	/// </summary>
	void FailProbe(ListenPlayerProbeResult result, string stage, Exception ex, string message)
	{
		result.success = false;
		result.failedStage = stage;
		if (ex != null)
		{
			var status = ListenPlayerProbe.FindRequestStatus(ex);
			result.error = ex.Message;
			message = $"{message} ({(status != 0 ? $"HTTP {status}: " : "")}{ex.Message})";
		}
		result.message = message;
		this.SendResults<ListenPlayerProbeResultChannel, ListenPlayerProbeResult>(result);
		throw new CliException(message);
	}
}
