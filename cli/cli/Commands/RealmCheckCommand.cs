using Beamable.Api.Autogenerated.Beamo;
using Beamable.Api.Autogenerated.Content;
using Beamable.Common.BeamCli;
using Beamable.Common.BeamCli.Contracts;
using Beamable.Server;
using cli.DeploymentCommands;
using System.CommandLine;
using ClientDefaultsApi = Beamable.Api.Autogenerated.Realms.IRealmsApi;

namespace cli;

public class RealmCheckCommandArgs : CommandArgs
{
	public string target;
	public bool fix;
}

[CliContractType, Serializable]
public class RealmCheckResult
{
	/// <summary>What the realm was checked for (currently always "web").</summary>
	public string target;
	/// <summary>True when no check failed.</summary>
	public bool ok;
	public List<RealmCheckEntry> checks = new();
}

[CliContractType, Serializable]
public class RealmCheckEntry
{
	/// <summary>A stable id: notification-publisher, global-manifest, services, realtime-socket.</summary>
	public string id;
	/// <summary>pass, fail, fixed or skipped.</summary>
	public string status;
	public string message;
	/// <summary>The command that fixes a failed check, when there is one.</summary>
	public string fixCommand;
}

/// <summary>
/// Everything <see cref="RealmCheck"/> needs from the realm, so the checks can be tested without a network.
/// </summary>
public interface IRealmCheckEnvironment
{
	/// <summary>The realtime provider and socket uri from the realm's client defaults (what the Web SDK reads).</summary>
	Task<(string provider, string uri)> GetWebsocketConfig();
	Task SetRealmConfig(string namespaceKey, string value);
	Task<bool> HasPublishedManifest(string manifestId);
	Task PublishManifest(string manifestId);
	/// <summary>Deployed services with their running/current state.</summary>
	Task<List<(string name, bool running, bool isCurrent)>> GetServiceStatuses();
	/// <summary>Null when the socket host answered; otherwise why it couldn't be reached.</summary>
	Task<string> CheckSocketReachable(string websocketUri);
}

/// <summary>
/// Checks that a realm is ready for the Web SDK: <c>Beam.init</c> needs the <c>beamable</c> realtime publisher,
/// a published <c>global</c> content manifest and a reachable realtime socket, and a game needs its services running.
/// </summary>
public static class RealmCheck
{
	public const string Pass = "pass";
	public const string Fail = "fail";
	public const string Fixed = "fixed";
	public const string Skipped = "skipped";

	public const string PublisherKey = "notification|publisher";
	public const string PublisherFixCommand = "beam config realm set --key-values 'notification|publisher::beamable'";
	public const string ManifestFixCommand = "beam content publish";
	public const string ServicesFixCommand = "beam deploy release --merge --wait";

	public static async Task<RealmCheckResult> RunWeb(IRealmCheckEnvironment env, bool fix)
	{
		var result = new RealmCheckResult { target = "web" };

		// 1. realtime publisher
		var (provider, uri) = await env.GetWebsocketConfig();
		var publisher = CheckPublisher(provider);
		if (publisher.status == Fail && fix)
		{
			await env.SetRealmConfig(PublisherKey, "beamable");
			(provider, uri) = await env.GetWebsocketConfig();
			publisher = CheckPublisher(provider);
			if (publisher.status == Pass)
			{
				publisher.status = Fixed;
				publisher.message = $"Set realm config {PublisherKey}=beamable.";
			}
			else
			{
				publisher.message = $"Set realm config {PublisherKey}=beamable, but the realm still reports provider '{provider}'. " + publisher.message;
			}
		}
		result.checks.Add(publisher);

		// 2. global content manifest
		var manifest = await CheckManifest(env);
		if (manifest.status == Fail && fix)
		{
			await env.PublishManifest("global");
			manifest = await CheckManifest(env);
			if (manifest.status == Pass)
			{
				manifest.status = Fixed;
				manifest.message = "Published the 'global' content manifest.";
			}
		}
		result.checks.Add(manifest);

		// 3. deployed services
		result.checks.Add(CheckServices(await env.GetServiceStatuses()));

		// 4. realtime socket
		result.checks.Add(await CheckSocket(env, uri));

		result.ok = result.checks.All(c => c.status != Fail);
		return result;
	}

	public static RealmCheckEntry CheckPublisher(string provider)
	{
		if (string.Equals(provider, "beamable", StringComparison.OrdinalIgnoreCase))
		{
			return new RealmCheckEntry { id = "notification-publisher", status = Pass, message = "The realm uses the 'beamable' realtime publisher." };
		}

		return new RealmCheckEntry
		{
			id = "notification-publisher",
			status = Fail,
			message = $"The realm uses the '{provider ?? "unknown"}' realtime publisher, which the Web SDK doesn't support: Beam.init fails with 'Unsupported websocket provider'.",
			fixCommand = PublisherFixCommand,
		};
	}

	private static async Task<RealmCheckEntry> CheckManifest(IRealmCheckEnvironment env)
	{
		if (await env.HasPublishedManifest("global"))
		{
			return new RealmCheckEntry { id = "global-manifest", status = Pass, message = "The 'global' content manifest is published." };
		}

		return new RealmCheckEntry
		{
			id = "global-manifest",
			status = Fail,
			message = "No 'global' content manifest is published, so Beam.init fails with a 404 on /basic/content/manifest/public/json?id=global. Publishing works even with no content.",
			fixCommand = ManifestFixCommand,
		};
	}

	public static RealmCheckEntry CheckServices(List<(string name, bool running, bool isCurrent)> services)
	{
		if (services.Count == 0)
		{
			return new RealmCheckEntry { id = "services", status = Skipped, message = "No services are deployed to this realm." };
		}

		var notReady = services
			.Where(s => !s.running || !s.isCurrent)
			.Select(s => $"{s.name} ({(!s.running ? "not running" : "not current")})")
			.ToList();
		if (notReady.Count == 0)
		{
			return new RealmCheckEntry { id = "services", status = Pass, message = $"All deployed services are running and current: {string.Join(", ", services.Select(s => s.name))}." };
		}

		return new RealmCheckEntry
		{
			id = "services",
			status = Fail,
			message = $"Deployed services that are not ready: {string.Join(", ", notReady)}. Check `beam deploy ps` and `beam project remote-logs`.",
			fixCommand = ServicesFixCommand,
		};
	}

	private static async Task<RealmCheckEntry> CheckSocket(IRealmCheckEnvironment env, string uri)
	{
		if (string.IsNullOrWhiteSpace(uri))
		{
			return new RealmCheckEntry { id = "realtime-socket", status = Fail, message = "The realm's client defaults have no websocket uri." };
		}

		var problem = await env.CheckSocketReachable(uri);
		if (problem == null)
		{
			return new RealmCheckEntry { id = "realtime-socket", status = Pass, message = $"The realtime socket host {HostOf(uri)} is reachable." };
		}

		return new RealmCheckEntry
		{
			id = "realtime-socket",
			status = Fail,
			message = $"Could not reach the realtime socket host {HostOf(uri)}: {problem}. If other requests work, a proxy or firewall may be blocking it; Beam.init will time out.",
		};
	}

	public static string HostOf(string uri) => Uri.TryCreate(uri, UriKind.Absolute, out var parsed) ? parsed.Host : uri;

	/// <summary>The https(s) url a ws(s) socket uri's handshake is served from.</summary>
	public static string ToHttpUrl(string websocketUri)
	{
		var trimmed = websocketUri.TrimEnd('/');
		if (trimmed.StartsWith("wss://", StringComparison.OrdinalIgnoreCase)) return "https://" + trimmed.Substring(6) + "/connect";
		if (trimmed.StartsWith("ws://", StringComparison.OrdinalIgnoreCase)) return "http://" + trimmed.Substring(5) + "/connect";
		return trimmed + "/connect";
	}
}

public class LiveRealmCheckEnvironment : IRealmCheckEnvironment
{
	private readonly CommandArgs _args;

	public LiveRealmCheckEnvironment(CommandArgs args)
	{
		_args = args;
	}

	public async Task<(string provider, string uri)> GetWebsocketConfig()
	{
		var defaults = await _args.DependencyProvider.GetService<ClientDefaultsApi>().GetClientDefaults();
		return (defaults.websocketConfig.provider, defaults.websocketConfig.uri.GetOrElse(""));
	}

	public async Task SetRealmConfig(string namespaceKey, string value)
	{
		var config = await _args.RealmsApi.GetRealmConfig();
		config.Config[namespaceKey] = value;
		await _args.RealmsApi.UpdateRealmConfig(config.Config);
	}

	public async Task<bool> HasPublishedManifest(string manifestId)
	{
		var checksums = await _args.DependencyProvider.GetService<IContentApi>().GetManifestChecksums();
		return checksums.manifests.Any(m => m.id == manifestId && !m.archived);
	}

	public Task PublishManifest(string manifestId) =>
		_args.ContentService.PublishContent(AutoSnapshotType.None, 20, manifestId);

	public async Task<List<(string name, bool running, bool isCurrent)>> GetServiceStatuses()
	{
		var status = await ShowCurrentBeamoStatusCommand.FetchStatus(_args.DependencyProvider.GetService<IBeamoApi>(), false);
		return (status.services ?? Array.Empty<Beamable.Api.Autogenerated.Models.ServiceStatus>())
			.Select(s => (s.serviceName, s.running, s.isCurrent))
			.ToList();
	}

	public async Task<string> CheckSocketReachable(string websocketUri)
	{
		// Any HTTP answer (typically 400/401 without a token) proves the host is reachable; the
		// session itself is checked by `beam listen player --probe`.
		using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(10) };
		try
		{
			using var response = await http.GetAsync(RealmCheck.ToHttpUrl(websocketUri));
			return null;
		}
		catch (Exception ex) when (ex is HttpRequestException or TaskCanceledException)
		{
			return ex is TaskCanceledException ? "the request timed out" : ex.Message;
		}
	}
}

public class RealmCheckCommand : AtomicCommand<RealmCheckCommandArgs, RealmCheckResult>, ISkipManifest
{
	private static readonly string[] Targets = { "web" };
	private RealmCheckResult _result;

	public RealmCheckCommand() : base("check", "Check that the realm is ready for a client SDK (e.g. the Web SDK's realtime publisher, global content manifest, services and socket)") { }

	public override void Configure()
	{
		AddOption(new Option<string>("--for", () => "web", "The client to check the realm for. Valid values are: `web`"),
			(args, i) => args.target = i);
		AddOption(new Option<bool>("--fix", "Fix what can be fixed: set the realtime publisher to beamable and publish the global content manifest"),
			(args, i) => args.fix = i);
	}

	public override async Task Handle(RealmCheckCommandArgs args)
	{
		await base.Handle(args);
		if (_result is { ok: false })
		{
			var failed = _result.checks.Where(c => c.status == RealmCheck.Fail).Select(c => c.id);
			throw new CliException($"Realm check failed: {string.Join(", ", failed)}. See the fixCommand of each failed check{(args.fix ? "" : ", or run again with --fix")}.");
		}
	}

	public override async Task<RealmCheckResult> GetResult(RealmCheckCommandArgs args)
	{
		var target = string.IsNullOrWhiteSpace(args.target) ? "web" : args.target.Trim().ToLowerInvariant();
		if (!Targets.Contains(target))
			throw new CliException($"Unsupported --for value [{args.target}]. Valid values are: {string.Join(", ", Targets)}.");

		_result = await RealmCheck.RunWeb(new LiveRealmCheckEnvironment(args), args.fix);
		foreach (var check in _result.checks)
		{
			var line = $"[{check.status}] {check.id}: {check.message}";
			if (check.status == RealmCheck.Fail) Log.Warning(line + (check.fixCommand != null ? $" Fix: {check.fixCommand}" : ""));
			else Log.Information(line);
		}
		return _result;
	}
}
