using Beamable.Api.Autogenerated.Beamobundle;
using Beamable.Server;
using cli.Commands.Project;
using cli.Deployment.Services;
using cli.DeploymentCommands;
using cli.Services.Bundles;
using System.Collections.Generic;
using System.CommandLine;

namespace cli.BundleCommands;

public class BundlePlanCommandArgs : CommandArgs, IHasDeployPlanArgs
{
	public string bundleName;

	// IHasDeployPlanArgs (mirrors ReleaseDeploymentCommandArgs / PublishBundleCommandArgs)
	public string Comment { get; set; }
	public string[] ServiceComments { get; set; }
	public string FromManifestFile { get; set; }
	public string ManifestId { get; set; }
	public bool UseLatestDeployedManifest { get; set; }
	public DeployMode DeployMode { get; set; }
	public bool RunHealthChecks { get; set; }
	public bool UseSequentialBuild { get; set; }
	public int MaxParallelTask { get; set; }
	public int MaxConcurrentUploads { get; set; }
	public DeployScope Scope { get; set; }
	public string SlnFilePath;

	public string SolutionFilePath
	{
		get => SlnFilePath;
		set => SlnFilePath = value;
	}
}

public class BundlePlanCommandOutput
{
	public string name;
	public bool isNoOp;

	/// <summary>The latest release's version the plan was diffed against, or 0 when there is none.</summary>
	public long publishedVersion;
	public List<BundleComponentChange> changes = new List<BundleComponentChange>();

	/// <summary>Path of the saved plan file, usable with `bundles publish --from-plan`.</summary>
	public string planPath;
}

public class BundlePlanCommand
	: AppCommand<BundlePlanCommandArgs>
	, IResultSteam<DefaultStreamResultChannel, BundlePlanCommandOutput>
	, IResultSteam<RunProjectBuildErrorStreamChannel, RunProjectBuildErrorStream>
	, IResultSteam<PlanReleaseProgressChannel, PlanReleaseProgress>
{
	public override bool AutoLogOutput => false;

	public BundlePlanCommand() : base("plan", "Build an authored bundle and diff it against its latest release")
	{
	}

	public override void Configure()
	{
		DeployArgs.AddPlanOptions(this);
		SolutionCommandArgs.ConfigureSolutionFlag(this, _ => throw new CliException("Must have a valid .beamable folder"));
		AddArgument(new Argument<string>("bundle-name", "The bundle name"),
			(args, i) => args.bundleName = i);
	}

	public override async Task Handle(BundlePlanCommandArgs args)
	{
		var provider = args.DependencyProvider;
		var bundle = BundleWorkspace.Require(args.ConfigService, args.bundleName);
		BundleBuild.ValidateComponentsExist(args.BeamoLocalSystem.BeamoManifest, bundle);

		var ns = await BundleNamespace.Get(args);
		var fullName = BundleNamespace.Qualify(ns, bundle.name);

		Log.Information($"Building bundle=[{fullName}] to compute its diff...");
		var build = await BundleBuild.Build(this, args, bundle);

		var (release, content) = await BundleBuild.FetchLatestPublished(provider.GetService<IBeamBeamobundleApi>(), fullName);
		var diff = BundleDiff.Compute(build, bundle, release, content);
		BundleDiff.Print(diff, fullName);

		var planPath = await BundlePlanUtil.SaveBundlePlanToTempFolder(provider, new BundlePlanFile
		{
			bundleName = bundle.name,
			publishedVersion = diff.publishedVersion,
			build = build,
			diff = diff,
		});
		BundlePlanUtil.PrintBundlePlanNextSteps(planPath, bundle.name, hasChanges: !diff.isNoOp);
		Log.Information("Saved plan: " + planPath);

		this.SendResults<DefaultStreamResultChannel, BundlePlanCommandOutput>(new BundlePlanCommandOutput
		{
			name = fullName,
			isNoOp = diff.isNoOp,
			publishedVersion = diff.publishedVersion,
			changes = diff.changes,
			planPath = planPath,
		});
	}
}
