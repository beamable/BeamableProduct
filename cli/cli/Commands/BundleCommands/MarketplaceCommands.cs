public class SearchMarketplaceCommandArgs : CommandArgs
{
	public string query;
	public string category;
	public string cursor;
	public int limit;
}

public class SearchMarketplaceCommandOutput
{
	public BundleSummaryInfo[] bundles = Array.Empty<BundleSummaryInfo>();

	/// <summary>Pass as --cursor for the next page; null on the last.</summary>
	public string nextCursor;
}

/// <summary>Search the marketplace: public bundles that have a release.</summary>
public class SearchMarketplaceCommand : AtomicCommand<SearchMarketplaceCommandArgs, SearchMarketplaceCommandOutput>, ISkipManifest
{
	public SearchMarketplaceCommand() : base("search", "Search the marketplace's public bundles by name and category")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("query", () => null, "Text to match in bundle names"),
			(args, i) => args.query = i);
		AddOption(new Option<string>("--category", "Only bundles in this category"),
			(args, i) => args.category = i);
		AddOption(new Option<string>("--cursor", "The cursor a previous search returned, for its next page"),
			(args, i) => args.cursor = i);
		AddOption(new Option<int>("--limit", () => 50, "How many bundles per page"),
			(args, i) => args.limit = i);
	}

	public override async Task<SearchMarketplaceCommandOutput> GetResult(SearchMarketplaceCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamobundleApi>();
		var response = await api.GetMarketplace(
			string.IsNullOrEmpty(args.category) ? new Optional<string>() : args.category,
			string.IsNullOrEmpty(args.cursor) ? new Optional<string>() : args.cursor,
			args.limit,
			string.IsNullOrEmpty(args.query) ? new Optional<string>() : args.query);
		var output = new SearchMarketplaceCommandOutput
		{
			bundles = response.bundles.GetOrElse(Array.Empty<BundleSummaryView>()).Select(BundleSummaryInfo.FromSummary).ToArray(),
			nextCursor = response.nextCursor.GetOrElse((string)null),
		};
		if (output.nextCursor != null)
			Log.Information($"More bundles: run again with --cursor {output.nextCursor}");
		return output;
	}

	protected override void LogResult(object result)
	{
		if (result is not SearchMarketplaceCommandOutput output)
		{
			base.LogResult(result);
			return;
		}

		var table = new Table();
		table.AddColumn("Bundle");
		table.AddColumn("About");
		table.AddColumn("Latest");
		table.AddColumn("Categories");
		foreach (var b in output.bundles)
		{
			table.AddRow(
				Markup.Escape(b.name),
				Markup.Escape((string.IsNullOrEmpty(b.displayName) ? "" : b.displayName + ": ") + b.summary + (b.autoUpdateRequired ? " (auto-update required)" : "")),
				Markup.Escape($"v{b.latestVersion}"),
				Markup.Escape(string.Join(", ", b.categories)));
		}
		AnsiConsole.Write(table);
	}
}

public class BundleInfoCommandArgs : CommandArgs
{
	public string bundleName;
}

public class BundleInfoCommandOutput
{
	public BundleSummaryInfo bundle;
	public string description = "";
	public string docsUrl;
	public BundleReleaseInfo latestRelease;

	/// <summary>The latest release's components, component groups and dependencies.</summary>
	public BundleContentInfo latestContent;

	/// <summary>Each component group's title and description, by group name.</summary>
	public Dictionary<string, string> componentGroupDescriptions = new Dictionary<string, string>();
}

/// <summary>A bundle's marketplace page: listing, latest release, component groups and dependencies.</summary>
public class BundleInfoCommand : AtomicCommand<BundleInfoCommandArgs, BundleInfoCommandOutput>, ISkipManifest
{
	public BundleInfoCommand() : base("info", "Show a bundle's listing, latest release, component groups and dependencies")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
	}

	public override async Task<BundleInfoCommandOutput> GetResult(BundleInfoCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamobundleApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		var response = await api.GetMarketplaceBundle(fullName);
		var summary = response.bundle.GetOrElse((BundleSummaryView)null);
		var listing = summary?.listing.GetOrElse((BundleListing)null);
		var release = response.latestRelease.GetOrElse((BundleRelease)null);
		var content = response.latestContent.GetOrElse((BundleContentView)null);
		return new BundleInfoCommandOutput
		{
			bundle = BundleSummaryInfo.FromSummary(summary),
			description = listing?.description.GetOrElse("") ?? "",
			docsUrl = listing?.docsUrl.GetOrElse((string)null),
			latestRelease = BundleReleaseInfo.FromRelease(release),
			latestContent = content == null ? null : BundleContentInfo.FromContent(release?.version.GetOrElse(0) ?? 0, content),
			componentGroupDescriptions = (content?.features.GetOrElse(Array.Empty<BundleFeature>()) ?? Array.Empty<BundleFeature>())
				.ToDictionary(f => f.name.GetOrElse(""), f =>
					$"{f.title.GetOrElse("")}{(f.enabledByDefault.GetOrElse(false) ? " (on by default)" : "")}: {f.description.GetOrElse("")}"),
		};
	}

	protected override void LogResult(object result)
	{
		if (result is not BundleInfoCommandOutput output || output.bundle == null)
		{
			base.LogResult(result);
			return;
		}

		var b = output.bundle;
		AnsiConsole.MarkupLine($"[bold]{Markup.Escape(string.IsNullOrEmpty(b.displayName) ? b.name : b.displayName)}[/] {Markup.Escape(b.name)} · {Markup.Escape(b.visibility)} · latest v{b.latestVersion}{(b.autoUpdateRequired ? " · auto-update required" : "")}");
		if (!string.IsNullOrEmpty(b.summary)) AnsiConsole.MarkupLine(Markup.Escape(b.summary));
		if (!string.IsNullOrEmpty(output.description)) AnsiConsole.MarkupLine(Markup.Escape(output.description));
		if (!string.IsNullOrEmpty(output.docsUrl)) AnsiConsole.MarkupLine($"Docs: {Markup.Escape(output.docsUrl)}");
		foreach (var notice in b.notices) AnsiConsole.MarkupLine($"[yellow]Notice[/]: {Markup.Escape(notice.Describe())}");
		foreach (var (group, description) in output.componentGroupDescriptions)
			AnsiConsole.MarkupLine($"Component group [bold]{Markup.Escape(group)}[/]: {Markup.Escape(description)} ({Markup.Escape(string.Join(", ", output.latestContent?.componentGroups.GetValueOrDefault(group) ?? Array.Empty<string>()))})");
		foreach (var (dependency, range) in output.latestContent?.dependencies ?? new Dictionary<string, string>())
			AnsiConsole.MarkupLine($"Depends on {Markup.Escape(dependency)} ({Markup.Escape(range)})");
	}
}

public class PlacementsCommandArgs : CommandArgs
{
	public List<string> pages = new List<string>();
	public List<string> mounts = new List<string>();
}

[Serializable]
public class PlacedBundleInfo
{
	/// <summary>The page, or the host extension and selector, as asked.</summary>
	public string place;
	public string bundle;
	public long latestVersion;
	public bool acquired;
	public bool owned;

	/// <summary>The latest release's component groups with an extension that mounts there.</summary>
	public string[] componentGroups = Array.Empty<string>();

	/// <summary>The installed version on your zone, and which of those component groups it has on; null when not installed.</summary>
	public string installation;
}

public class PlacementsCommandOutput
{
	public PlacedBundleInfo[] bundles = Array.Empty<PlacedBundleInfo>();
}

/// <summary>The bundles Beamable lists for portal pages, or for selectors inside other extensions.</summary>
public class PlacementsCommand : AtomicCommand<PlacementsCommandArgs, PlacementsCommandOutput>, ISkipManifest
{
	public PlacementsCommand() : base("placements", "Find the Beamable-listed bundles that add something to a portal page or extension mount")
	{
	}

	public override void Configure()
	{
		AddOption(new Option<List<string>>("--page", "A portal page, e.g. players/list (repeatable)") { AllowMultipleArgumentsPerToken = true },
			(args, i) => args.pages = i ?? new List<string>());
		AddOption(new Option<List<string>>("--mount", "A host extension and selector, Extension>selector, or just Extension (repeatable)") { AllowMultipleArgumentsPerToken = true },
			(args, i) => args.mounts = i ?? new List<string>());
	}

	public override async Task<PlacementsCommandOutput> GetResult(PlacementsCommandArgs args)
	{
		if (args.pages.Count + args.mounts.Count == 0)
			throw new CliException("Give at least one --page or --mount.");
		var api = args.Provider.GetService<IBeamBeamobundleApi>();
		var response = await api.GetMarketplacePlacements(
			args.mounts.Count > 0 ? args.mounts.ToArray() : new Optional<string[]>(),
			args.pages.Count > 0 ? args.pages.ToArray() : new Optional<string[]>());
		return new PlacementsCommandOutput
		{
			bundles = response.places.GetOrElse(Array.Empty<PlacementBundles>()).SelectMany(p =>
			{
				var place = p.place.GetOrElse((Placement)null);
				var label = place?.page.GetOrElse((string)null)
				            ?? $"{place?.extension.GetOrElse("")}{(place?.selector.HasValue == true ? ">" + place.selector.Value : "")}";
				return p.bundles.GetOrElse(Array.Empty<PlacedBundle>()).Select(b =>
				{
					var installation = b.installation.GetOrElse((PlacedInstallation)null);
					return new PlacedBundleInfo
					{
						place = label,
						bundle = b.name.GetOrElse(""),
						latestVersion = b.latestVersion.GetOrElse(0),
						acquired = b.acquired.GetOrElse(false),
						owned = b.owned.GetOrElse(false),
						componentGroups = b.features.GetOrElse(Array.Empty<PlacedFeature>()).Select(f => f.title.GetOrElse(f.name.GetOrElse(""))).ToArray(),
						installation = installation == null
							? null
							: $"v{installation.version.GetOrElse(0)} on {installation.zoneId.GetOrElse("")}, on: {string.Join(", ", installation.featuresOn.GetOrElse(Array.Empty<string>()))}",
					};
				});
			}).ToArray(),
		};
	}
}
