using Beamable.Api.Autogenerated.Beamobundle;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common.Content;
using Beamable.Server;
using cli.Services.Bundles;
using System;
using System.Collections.Generic;
using System.CommandLine;
using System.Linq;

namespace cli.BundleCommands;

public class BundleListingCommandArgs : CommandArgs
{
	public string bundleName;
	public string visibility;
	public string displayName;
	public string summary;
	public string description;
	public List<string> categories;
	public string iconUrl;
	public string docsUrl;
	public bool? autoUpdateRequired;

	/// <summary>The listing fields that were given, or null when none was.</summary>
	public BundleListing Listing(BundleListing current = null)
	{
		if (displayName == null && summary == null && description == null && categories == null && iconUrl == null && docsUrl == null)
			return null;
		return new BundleListing
		{
			displayName = displayName ?? current?.displayName.GetOrElse("") ?? "",
			summary = summary ?? current?.summary.GetOrElse("") ?? "",
			description = description ?? current?.description.GetOrElse("") ?? "",
			categories = new OptionalArrayOfString((categories ?? current?.categories.GetOrElse(Array.Empty<string>()).ToList() ?? new List<string>()).ToArray()),
			iconUrl = iconUrl ?? current?.iconUrl.GetOrElse((string)null),
			docsUrl = docsUrl ?? current?.docsUrl.GetOrElse((string)null),
		};
	}

	public OptionalBundleVisibility Visibility() => visibility?.Trim().ToLowerInvariant() switch
	{
		null => new OptionalBundleVisibility(),
		"private" => new OptionalBundleVisibility(BundleVisibility.Private),
		"public" => new OptionalBundleVisibility(BundleVisibility.Public),
		_ => throw new CliException($"--visibility=[{visibility}] must be 'private' or 'public'."),
	};

	public static void AddListingOptions<TArgs>(AppCommand<TArgs> command) where TArgs : BundleListingCommandArgs
	{
		command.AddOption(new Option<string>("--visibility", "Private (only your org) or public (listed in the marketplace once it has a release)"),
			(args, i) => args.visibility = i);
		command.AddOption(new Option<string>("--display-name", "The name the marketplace shows"),
			(args, i) => args.displayName = i);
		command.AddOption(new Option<string>("--summary", "One line about what the bundle does"),
			(args, i) => args.summary = i);
		command.AddOption(new Option<string>("--description", "The marketplace description"),
			(args, i) => args.description = i);
		command.AddOption(new Option<List<string>>("--category", "A marketplace category (repeatable)") { AllowMultipleArgumentsPerToken = true },
			(args, i) => args.categories = i?.Count > 0 ? i : null);
		command.AddOption(new Option<string>("--icon-url", "An icon for the listing"),
			(args, i) => args.iconUrl = i);
		command.AddOption(new Option<string>("--docs-url", "A link to the bundle's documentation"),
			(args, i) => args.docsUrl = i);
		command.AddOption(new Option<bool?>("--auto-update-required", "Require auto-update on every new installation of this bundle"),
			(args, i) => args.autoUpdateRequired = i);
	}
}

public class CreateBundleCommandArgs : BundleListingCommandArgs
{
}

public class BundleListingCommandOutput
{
	public BundleSummaryInfo bundle;
}

/// <summary>
/// Create a bundle name in the org's namespace. A bundle has no releases until it is published, and
/// publishing needs the name to exist first. Admins only.
/// </summary>
public class CreateBundleCommand : AtomicCommand<CreateBundleCommandArgs, BundleListingCommandOutput>, ISkipManifest
{
	public CreateBundleCommand() : base("create", "Create a bundle name in your org's namespace, so it can be published")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		BundleListingCommandArgs.AddListingOptions(this);
	}

	public override async Task<BundleListingCommandOutput> GetResult(CreateBundleCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamobundleApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		var request = new CreateBundleRequest
		{
			name = fullName,
			visibility = args.Visibility(),
			autoUpdateRequired = args.autoUpdateRequired ?? false,
		};
		var listing = args.Listing();
		if (listing != null) request.listing = new OptionalBundleListing(listing);

		var summary = await api.PostBundles(request);
		return new BundleListingCommandOutput { bundle = BundleSummaryInfo.FromSummary(summary) };
	}
}

public class UpdateBundleCommandArgs : BundleListingCommandArgs
{
}

/// <summary>
/// Edit a bundle's listing, visibility or required auto-update. Fields that aren't given keep their
/// value; listing fields are merged into the current listing. Admins of the owning org only.
/// </summary>
public class UpdateBundleCommand : AtomicCommand<UpdateBundleCommandArgs, BundleListingCommandOutput>, ISkipManifest
{
	public UpdateBundleCommand() : base("update", "Edit a bundle's listing, visibility or required auto-update")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		BundleListingCommandArgs.AddListingOptions(this);
	}

	public override async Task<BundleListingCommandOutput> GetResult(UpdateBundleCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamobundleApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);

		var request = new UpdateBundleRequest
		{
			name = fullName,
			visibility = args.Visibility(),
			autoUpdateRequired = args.autoUpdateRequired.HasValue ? new OptionalBool(args.autoUpdateRequired.Value) : new OptionalBool(),
		};
		if (args.Listing() != null)
		{
			// The server replaces the listing whole, so merge the given fields into the current one.
			var current = (await api.GetBundles()).records.GetOrElse(Array.Empty<BundleSummaryView>())
				.FirstOrDefault(b => b.name.GetOrElse("") == fullName)?.listing.GetOrElse((BundleListing)null);
			request.listing = new OptionalBundleListing(args.Listing(current));
		}

		var summary = await api.PutBundles(request);
		return new BundleListingCommandOutput { bundle = BundleSummaryInfo.FromSummary(summary) };
	}
}
