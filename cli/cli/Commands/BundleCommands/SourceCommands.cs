/// <summary>A bundle component's source, delivered as a pull request into one of your connected repositories.</summary>
public class BundleSourceCommand : CommandGroup
{
	public BundleSourceCommand() : base("source", "Get a bundle component's source as a pull request into one of your connected repositories")
	{
	}
}

[Serializable]
public class SourceDeliveryInfo
{
	public string id;
	public string bundle;
	public long version;
	public string[] components = Array.Empty<string>();
	public string connectionId;
	public string workspace;

	/// <summary>"requested", "working", "opened" (a pull request), "pushed" (the branch only) or "failed".</summary>
	public string state;
	public string branch;
	public string pullRequestUrl;
	public string reviewUrl;
	public string error;
	public DateTime createdAt;

	public static SourceDeliveryInfo From(SourceDeliveryView v)
	{
		var error = v.error.GetOrElse((SourceDeliveryError)null);
		return new SourceDeliveryInfo
		{
			id = v.id.GetOrElse(""),
			bundle = v.bundle.GetOrElse(""),
			version = v.version.GetOrElse(0),
			components = v.components.GetOrElse(Array.Empty<string>()),
			connectionId = v.connectionId.HasValue ? v.connectionId.Value.ToString() : "",
			workspace = v.workspace.GetOrElse(""),
			state = v.state.HasValue ? v.state.Value.ToString().ToLowerInvariant() : "",
			branch = v.branch.GetOrElse((string)null),
			pullRequestUrl = v.pullRequestUrl.GetOrElse((string)null),
			reviewUrl = v.reviewUrl.GetOrElse((string)null),
			error = error == null ? null : $"{(error.kind.HasValue ? error.kind.Value.ToString().ToLowerInvariant() + ": " : "")}{error.reason.GetOrElse("")}",
			createdAt = v.createdAt.GetOrElse(default(DateTime)),
		};
	}
}

public class RequestSourceCommandArgs : CommandArgs
{
	public string bundleName;
	public List<string> components = new List<string>();
	public string repository;
	public long version;
	public string workspace;
}

public class RequestSourceCommandOutput
{
	public SourceDeliveryInfo delivery;
}

/// <summary>
/// Ask for components' source. It lands in one of the zone's connected repositories as a pull request,
/// made with your own token, with a <c>beam.override.json</c> beside each project: deploying the project
/// from that repository then runs your build in place of the bundle's. The storages the services use come along.
/// </summary>
public class RequestSourceCommand : AtomicCommand<RequestSourceCommandArgs, RequestSourceCommandOutput>, ISkipManifest
{
	public RequestSourceCommand() : base("request", "Ask for components' source as a pull request into a connected repository. The storages they use come along")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddArgument(new Argument<List<string>>("components", "The services and portal extensions whose source you want") { Arity = ArgumentArity.OneOrMore },
			(args, i) => args.components = i);
		AddOption(new Option<string>("--repository", "The repository connection (its id) the pull request goes to") { IsRequired = true },
			(args, i) => args.repository = i);
		AddOption(new Option<long>("--version", "The release to take the source from. Defaults to the one installed on the zone, else latest"),
			(args, i) => args.version = i);
		AddOption(new Option<string>("--workspace", "The connection's workspace (folder) the source goes in. Defaults to its first"),
			(args, i) => args.workspace = i);
	}

	public override async Task<RequestSourceCommandOutput> GetResult(RequestSourceCommandArgs args)
	{
		if (!Guid.TryParse(args.repository, out var connectionId))
			throw new CliException($"--repository=[{args.repository}] must be a repository connection id.");
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		var request = new SourceDeliveryRequest
		{
			name = fullName,
			components = new OptionalArrayOfString(args.components.ToArray()),
			connectionId = connectionId,
		};
		if (args.version > 0) request.version = args.version;
		if (!string.IsNullOrEmpty(args.workspace)) request.workspace = args.workspace;

		var delivery = SourceDeliveryInfo.From(await api.PostSourceDeliveries(request));
		Log.Information($"Requested the source of {string.Join(", ", delivery.components)} from [{fullName}] v{delivery.version} (delivery {delivery.id}). " +
		                "`beam bundles source list` shows when its pull request is open.");
		return new RequestSourceCommandOutput { delivery = delivery };
	}
}

public class ListSourceDeliveriesCommandArgs : CommandArgs
{
	public int limit;
}

public class ListSourceDeliveriesCommandOutput
{
	public SourceDeliveryInfo[] deliveries = Array.Empty<SourceDeliveryInfo>();
}

/// <summary>Your org's source requests, newest first, with each one's state and pull request.</summary>
public class ListSourceDeliveriesCommand : AtomicCommand<ListSourceDeliveriesCommandArgs, ListSourceDeliveriesCommandOutput>, ISkipManifest
{
	public ListSourceDeliveriesCommand() : base("list", "Show your org's source requests, newest first, with each one's state and pull request")
	{
	}

	public override void Configure()
	{
		AddOption(new Option<int>("--limit", () => 20, "How many requests to show"),
			(args, i) => args.limit = i);
	}

	public override async Task<ListSourceDeliveriesCommandOutput> GetResult(ListSourceDeliveriesCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var response = await api.GetSourceDeliveries(args.limit);
		return new ListSourceDeliveriesCommandOutput
		{
			deliveries = response.deliveries.GetOrElse(Array.Empty<SourceDeliveryView>()).Select(SourceDeliveryInfo.From).ToArray(),
		};
	}

	protected override void LogResult(object result)
	{
		if (result is not ListSourceDeliveriesCommandOutput output)
		{
			base.LogResult(result);
			return;
		}

		var table = new Table();
		table.AddColumn("Requested");
		table.AddColumn("Bundle");
		table.AddColumn("Components");
		table.AddColumn("State");
		table.AddColumn("Pull request");
		foreach (var d in output.deliveries)
		{
			table.AddRow(
				Markup.Escape(d.createdAt.ToLocalTime().ToString("yyyy-MM-dd HH:mm")),
				Markup.Escape($"{d.bundle} v{d.version}"),
				Markup.Escape(string.Join(", ", d.components)),
				Markup.Escape(d.state + (d.error == null ? "" : $" ({d.error})")),
				Markup.Escape(d.pullRequestUrl ?? d.branch ?? "-"));
		}
		AnsiConsole.Write(table);
	}
}
