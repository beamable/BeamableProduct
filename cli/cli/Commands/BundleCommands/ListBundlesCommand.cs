using Beamable.Api.Autogenerated.Beamobundle;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common.Api;
using Beamable.Server;
using cli.Services.Bundles;
using Spectre.Console;
using System;
using System.Linq;

namespace cli.BundleCommands;

public class ListBundlesCommandArgs : CommandArgs
{
}

public class ListBundlesCommandOutput
{
	/// <summary>The org's own bundles in the catalog, private ones included.</summary>
	public BundleSummaryInfo[] published = Array.Empty<BundleSummaryInfo>();

	/// <summary>Bundles authored in this workspace (they may have no release yet).</summary>
	public BundleInfo[] local = Array.Empty<BundleInfo>();
}

public class ListBundlesCommand : AtomicCommand<ListBundlesCommandArgs, ListBundlesCommandOutput>
{
	public ListBundlesCommand() : base("list", "List the bundles authored in this workspace and your org's bundles in the catalog")
	{
	}

	public override void Configure()
	{
	}

	public override async Task<ListBundlesCommandOutput> GetResult(ListBundlesCommandArgs args)
	{
		// Resolved best-effort so the local list still works when the namespace can't be resolved.
		var ns = await BundleNamespace.TryGet(args);
		if (ns == null)
			Log.Warning("Could not resolve the bundle namespace (customer alias); showing local bundle names without it.");

		// Discover, not DiscoverAndValidate, so a partition conflict doesn't prevent listing.
		var local = BundleWorkspace.Discover(args.ConfigService)
			.Select(b => BundleInfo.FromLocalBundle(b, args.BeamoLocalSystem.BeamoManifest, ns == null ? b.name : BundleNamespace.Qualify(ns, b.name)))
			.ToArray();

		BundleSummaryInfo[] published;
		try
		{
			var response = await args.Provider.GetService<IBeamBeamobundleApi>().GetBundles();
			published = response.records.GetOrElse(Array.Empty<BundleSummaryView>())
				.Select(BundleSummaryInfo.FromSummary).ToArray();
		}
		catch (RequesterException e)
		{
			Log.Warning($"Could not fetch your org's bundles from the catalog (status={e.Status}); showing local bundles only.");
			published = Array.Empty<BundleSummaryInfo>();
		}

		return new ListBundlesCommandOutput { published = published, local = local };
	}

	protected override void LogResult(object result)
	{
		if (result is not ListBundlesCommandOutput output)
		{
			base.LogResult(result);
			return;
		}

		var published = new Table().Title("Your org's bundles");
		published.AddColumn("Name");
		published.AddColumn("Visibility");
		published.AddColumn("Latest");
		published.AddColumn("Tags");
		published.AddColumn("Notices");
		foreach (var bundle in output.published)
		{
			published.AddRow(
				Markup.Escape(bundle.name),
				Markup.Escape(bundle.visibility),
				Markup.Escape(bundle.latestVersion > 0 ? $"v{bundle.latestVersion}" : "no release"),
				Markup.Escape(bundle.FormatTags()),
				Markup.Escape(bundle.notices.Length == 0 ? "-" : string.Join("\n", bundle.notices.Select(n => $"{n.id} {n.description}"))));
		}
		AnsiConsole.Write(published);

		var local = new Table().Title("In this workspace");
		local.AddColumn("Name");
		local.AddColumn("Components");
		local.AddColumn("Component groups");
		local.AddColumn("Path");
		foreach (var bundle in output.local)
		{
			local.AddRow(
				Markup.Escape(bundle.name),
				Markup.Escape(string.Join(", ", bundle.components.Select(c => $"{c.name} ({c.kind}, {c.site}{(c.source ? ", source" : "")})"))),
				Markup.Escape(string.Join(", ", bundle.componentGroups.Keys)),
				Markup.Escape(bundle.filePath));
		}
		AnsiConsole.Write(local);
	}
}
