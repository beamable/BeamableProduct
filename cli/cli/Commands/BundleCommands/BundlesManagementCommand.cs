using Beamable.Api.Autogenerated.Accounts;
using Beamable.Server;
using cli.Commands.Project;
using cli.Portal;
using cli.Services;
using cli.Services.Bundles;
using cli.Utils;
using System.CommandLine;

namespace cli.BundleCommands;

public class BundlesManagementCommandArgs : CommandArgs
{
	public bool noBrowser;
	public string extension;
}

/// <summary>
/// Serves the bundles management API on 127.0.0.1 (<see cref="BundlesManagementServer"/>), serves the Bundles page
/// extension from the workspace (it ships in no bundle), and opens the page already connected to the API. The page
/// drives every bundle operation through this CLI. Runs until stopped.
/// </summary>
public class BundlesManagementCommand : AppCommand<BundlesManagementCommandArgs>, IEmptyResult
{
	public const string DEFAULT_EXTENSION = "dev-bundles-management";

	public override bool IsForInternalUse => true;

	public BundlesManagementCommand() : base("management",
		"Manage bundles from the portal: list, pin, plan, publish, tag, yank and deploy pins from the zone's Bundles page, executed by this CLI against this workspace. Runs until stopped")
	{
	}

	public override void Configure()
	{
		AddOption(new Option<bool>(new[] { "--no-browser" }, "Do not open the portal; print its url instead"),
			(args, i) => args.noBrowser = i);
		AddOption(new Option<string>(new[] { "--extension" }, () => DEFAULT_EXTENSION,
				"The portal extension in this workspace that renders the Bundles page; it is served from here, like `project run`. Pass an empty value to serve only the API"),
			(args, i) => args.extension = i);
	}

	public override async Task Handle(BundlesManagementCommandArgs args)
	{
		var cid = args.AppContext.Cid;
		var pid = args.AppContext.Pid;
		var localZid = args.ConfigService.GetConfigString(ConfigService.CFG_JSON_FIELD_ZID);
		var zid = await ZoneResolver.ResolveZid(args.DependencyProvider, cid, pid, localZid);
		if (string.IsNullOrEmpty(zid))
		{
			throw new CliException(string.IsNullOrEmpty(pid)
				? "No realm is selected and no 'zid' is set in the .beamable config, so there is no zone to manage bundles from."
				: $"The selected realm [{pid}] is not bound to a zone. Bind it to a zone (Portal > Zone Management) and retry.");
		}

		var me = await args.DependencyProvider.GetService<IAccountsApi>().GetAdminMe();
		var portal = PortalCommand.GetPortalBaseUrl(args, PortalType.Console);
		var server = new BundlesManagementServer(new BundlesManagementContext
		{
			Cid = cid,
			Pid = pid,
			Zid = zid,
			Host = args.AppContext.Host,
			OwnerAccountId = me.id,
			OwnerEmail = me.email.GetOrElse((string)null),
			ConfigService = args.ConfigService,
			Jobs = new BundleJobRunner(new[] { "--cid", cid, "--pid", pid, "--host", args.AppContext.Host }),
		}, portal);
		server.Start();
		var serving = server.Serve(args.Lifecycle.CancellationToken);

		// The page is a zone extension, so it needs the zone's secret to be served from here.
		await ServeExtension(args, cid, pid, zid, await RunScopeIdentity.FetchZoneSecret(args, cid, zid));

		var url = BuildManagementUrl(args, portal, zid, server);
		Log.Information($"Bundles management API on http://127.0.0.1:{server.Port} for zone [{zid}] as [{me.email.GetOrElse((string)null)}]. Press Ctrl+C to stop.");
		Log.Information($"Portal (the link carries this session's secret, don't share it): {url}");
		if (!args.noBrowser)
		{
			MachineHelper.OpenBrowser(url);
		}

		await serving;
	}

	/// <summary>
	/// Serves the page's extension in this process, as `project run --ids &lt;extension&gt;` would, and returns once it is
	/// ready (or failed), so the browser doesn't open on a page that isn't there yet. A workspace without the extension
	/// still gets the API; someone else must serve the page then.
	/// </summary>
	static async Task ServeExtension(BundlesManagementCommandArgs args, string cid, string pid, string zid, string zoneSecret)
	{
		if (string.IsNullOrWhiteSpace(args.extension))
		{
			return;
		}

		var definition = args.BeamoLocalSystem.BeamoManifest.ServiceDefinitions.FirstOrDefault(d =>
			d.Protocol == BeamoProtocolType.PortalExtension && d.BeamoId == args.extension);
		if (definition == null)
		{
			Log.Warning($"Portal extension [{args.extension}] is not in this workspace, so only the API runs. " +
			            "Serve the Bundles page with `dotnet beam project run --ids <extension>`, or pass --extension.");
			return;
		}

		var identity = RunScopeIdentity.BuildIdentities(new[] { (definition.BeamoId, definition.IsZoneScoped) },
			cid, pid, zid, RunScopeIdentity.GetSocketHost(args.AppContext.Host), null, null, zoneSecret)[definition.BeamoId];
		var ready = new TaskCompletionSource();
		var serving = args.BeamoLocalSystem.RunLocalPortalExtension(definition, args.BeamoLocalSystem,
			args.ConfigService.LoadPortalExtensionConfig(), args.AppContext, args.Provider.GetService<BeamActivity>(), identity,
			portalBaseUrl: PortalCommand.GetPortalBaseUrl(args, PortalType.Console),
			onProgress: (progress, _) =>
			{
				if (progress >= 1) ready.TrySetResult();
			},
			token: args.Lifecycle.CancellationToken);

		Log.Information($"Serving the Bundles page from portal extension [{definition.BeamoId}]...");
		if (await Task.WhenAny(ready.Task, serving) == serving)
		{
			// RunLocalPortalExtension only returns when the extension failed to build or start.
			try
			{
				await serving;
			}
			catch (Exception ex)
			{
				Log.Error($"Could not serve portal extension [{definition.BeamoId}], so the Bundles page won't load: {ex.Message}");
			}
		}
	}

	/// <summary>
	/// The zone Bundles page, signed in with this CLI's refresh token. The API's address and session secret go in
	/// the fragment, which browsers never send to a server.
	/// </summary>
	static string BuildManagementUrl(CommandArgs args, string portal, string zid, BundlesManagementServer server)
	{
		return $"{portal}/{args.AppContext.Cid}/zones/{zid}/bundles" +
		       $"?refresh_token={Uri.EscapeDataString(args.AppContext.RefreshToken)}" +
		       $"#cli=127.0.0.1:{server.Port}&token={server.Token}";
	}
}
