/// <summary>Arguments shared by the commands that act on the installations of one zone.</summary>
public class ZoneInstallationArgs : CommandArgs
{
	public string bundleName;

	/// <summary>The zone to act on; the workspace's zone when empty.</summary>
	public string targetZone;

	public static void AddTargetZoneOption<TArgs>(AppCommand<TArgs> command) where TArgs : ZoneInstallationArgs =>
		command.AddOption(new Option<string>("--target-zone", "The zone to act on (its zone id). Defaults to the workspace's zone"),
			(args, i) => args.targetZone = i);

	/// <summary>Pin the requests to the zone: installation routes act on the zone in X-BEAM-SCOPE.</summary>
	public System.Threading.Tasks.Task<IDisposable> ZoneScope() => DeployArgs.ApplyDeployScopeAsync(this, DeployScope.Zone, targetZone);
}

public class InstallBundleCommandArgs : ZoneInstallationArgs
{
	public long version;
	public string tag;
	public List<string> componentGroups;
	public string realms;
	public List<string> realmIds;
	public bool? autoUpdate;
	public List<string> detach;
	public bool uninstall;

	public InstallationRequest Request(string fullName)
	{
		var request = new InstallationRequest
		{
			name = fullName,
			uninstall = uninstall,
		};
		if (version > 0 && !string.IsNullOrEmpty(tag))
			throw new CliException("Give --version or --tag, not both.");
		if (version > 0) request.version = version;
		if (!string.IsNullOrEmpty(tag)) request.tag = tag;
		if (componentGroups != null) request.features = new OptionalArrayOfString(componentGroups.ToArray());
		if (autoUpdate.HasValue) request.autoUpdate = autoUpdate.Value;
		if (detach?.Count > 0) request.detach = new OptionalArrayOfString(detach.ToArray());

		var mode = realms?.Trim().ToLowerInvariant();
		if (realmIds?.Count > 0)
		{
			if (mode != null)
				throw new CliException("Give --realms all|none, or --realm for each realm, not both.");
			request.realms = new OptionalInstalledBundleRealms(new InstalledBundleRealms
			{
				mode = new OptionalInstallationRealmMode(InstallationRealmMode.Some),
				ids = new OptionalArrayOfString(realmIds.ToArray()),
			});
		}
		else if (mode != null)
		{
			request.realms = new OptionalInstalledBundleRealms(new InstalledBundleRealms
			{
				mode = new OptionalInstallationRealmMode(mode switch
				{
					"all" => InstallationRealmMode.All,
					"none" => InstallationRealmMode.None,
					_ => throw new CliException($"--realms=[{realms}] must be 'all' or 'none'; use --realm <realm id> for chosen realms."),
				}),
				ids = new OptionalArrayOfString(Array.Empty<string>()),
			});
		}

		return request;
	}

	public static ApplyInstallationRequest Apply(InstallationRequest r, string hash) => new ApplyInstallationRequest
	{
		name = r.name, version = r.version, tag = r.tag, features = r.features, realms = r.realms,
		autoUpdate = r.autoUpdate, uninstall = r.uninstall, detach = r.detach, hash = hash,
	};
}

public class InstallBundleCommandOutput
{
	public InstallationPlanInfo plan;

	/// <summary>False when the plan was refused or the change wasn't confirmed.</summary>
	public bool applied;

	/// <summary>Per manifest (the zone, then each realm): applied, pending or failed, and why.</summary>
	public SiteResultInfo[] results = Array.Empty<SiteResultInfo>();

	public string[] warnings = Array.Empty<string>();
}

/// <summary>
/// Install a bundle on a zone, or change its installation: release, component groups, realms, auto-update. The
/// server plans the change; the plan is shown, and applied by its hash once confirmed, so nothing that
/// moved since it was shown is applied. A failed realm is retried by running the same command again.
/// </summary>
public class InstallBundleCommand : AtomicCommand<InstallBundleCommandArgs, InstallBundleCommandOutput>, ISkipManifest
{
	public InstallBundleCommand() : base("install", "Install a bundle on a zone, or change its release, component groups, realms or auto-update")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddOption(new Option<long>("--version", "The release to run. Defaults to latest on a new install, and to the installed one on a change"),
			(args, i) => args.version = i);
		AddOption(new Option<string>("--tag", "Run the release this tag points at, instead of --version"),
			(args, i) => args.tag = i);
		AddOption(new Option<List<string>>("--component-groups", "The component groups to turn on, comma separated or repeated. Defaults to the ones on by default") { AllowMultipleArgumentsPerToken = true },
			(args, i) => args.componentGroups = i?.Count > 0 ? i.SelectMany(f => f.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)).ToList() : null);
		AddOption(new Option<string>("--realms", "Which realms get the realm components: all (every realm of the zone, including later ones) or none (zone components only). Defaults to all"),
			(args, i) => args.realms = i);
		AddOption(new Option<List<string>>("--realm", "A realm (its id) to get the realm components; repeat for each. Instead of --realms") { AllowMultipleArgumentsPerToken = true },
			(args, i) => args.realmIds = i?.Count > 0 ? i : null);
		AddOption(new Option<bool?>("--auto-update", "Apply compatible releases automatically. Defaults to your org's setting on a new install"),
			(args, i) => args.autoUpdate = i);
		AddOption(new Option<List<string>>("--detach", "An overridden component to keep as your own when this change takes it off a site, instead of archiving it") { AllowMultipleArgumentsPerToken = true },
			(args, i) => args.detach = i);
		ZoneInstallationArgs.AddTargetZoneOption(this);
	}

	public override async Task<InstallBundleCommandOutput> GetResult(InstallBundleCommandArgs args) => await Run(args);

	public static async Task<InstallBundleCommandOutput> Run(InstallBundleCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		var request = args.Request(fullName);
		using var zone = await args.ZoneScope();

		for (var attempt = 1; ; attempt++)
		{
			var plan = InstallationPlanInfo.From(await api.PostInstallationsPlan(request));
			plan.Print();

			var output = new InstallBundleCommandOutput { plan = plan };
			if (plan.refusals.Length > 0)
			{
				Log.Error($"The plan is refused, so nothing was applied:\n - {string.Join("\n - ", plan.refusals)}");
				return output;
			}
			if (plan.sites.All(s => s.changes.Length == 0) && plan.change != "AutoUpdate")
			{
				Log.Information("Nothing to change.");
				return output;
			}

			var confirm = args.Quiet || string.Equals("yes",
				AnsiConsole.Prompt(new TextPrompt<string>($"Apply this plan to zone [{Markup.Escape(plan.zoneId)}]?\nType 'yes' to continue.")),
				StringComparison.InvariantCultureIgnoreCase);
			if (!confirm)
			{
				Log.Information("Nothing was applied.");
				return output;
			}

			try
			{
				var response = await api.PostInstallationsApply(InstallBundleCommandArgs.Apply(request, plan.hash));
				output.applied = true;
				output.warnings = response.warnings.GetOrElse(Array.Empty<string>());
				output.results = SiteResultInfo.From(response.results.GetOrElse(new MapOfInstallationSite()));
				foreach (var warning in output.warnings) Log.Warning(warning);
				foreach (var result in output.results)
				{
					if (result.state == "failed") Log.Error($"{result.site}: failed. {result.error}");
					else Log.Information($"{result.site}: {result.state}");
				}
				if (output.results.Any(r => r.state != "applied"))
					Log.Warning("Not every manifest was applied. Run the same command again to retry the ones left.");
				return output;
			}
			catch (RequesterException e) when (e.Status == 409 && attempt < 3)
			{
				Log.Warning("Something changed on the zone since the plan was made, so it wasn't applied. Planning again...");
			}
		}
	}
}

