/// <summary>Uninstall a bundle from a zone: every component it put there is archived, and storage data is kept.</summary>
public class UninstallBundleCommand : AtomicCommand<UninstallBundleCommandArgs, InstallBundleCommandOutput>, ISkipManifest
{
	public UninstallBundleCommand() : base("uninstall", "Uninstall a bundle from a zone. Its components are archived; storage data is kept")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddOption(new Option<List<string>>("--detach", "An overridden component to keep as your own instead of archiving it") { AllowMultipleArgumentsPerToken = true },
			(args, i) => args.detach = i);
		ZoneInstallationArgs.AddTargetZoneOption(this);
	}

	public override async Task<InstallBundleCommandOutput> GetResult(UninstallBundleCommandArgs args)
	{
		args.uninstall = true;
		return await InstallBundleCommand.Run(args);
	}
}

[Serializable]
public class InstallationTargetInfo
{
	public long version;
	public string[] componentGroups = Array.Empty<string>();

	/// <summary>"all", "none", or the chosen realm ids.</summary>
	public string realms = "";
	public bool autoUpdate;

	public static InstallationTargetInfo From(InstallationTarget t)
	{
		if (t == null) return null;
		var realms = t.realms.GetOrElse((InstalledBundleRealms)null);
		var mode = realms?.mode.HasValue == true ? realms.mode.Value : InstallationRealmMode.All;
		return new InstallationTargetInfo
		{
			version = t.version.GetOrElse(0),
			componentGroups = t.features.GetOrElse(Array.Empty<string>()),
			realms = mode == InstallationRealmMode.Some
				? string.Join(", ", realms.ids.GetOrElse(Array.Empty<string>()))
				: mode.ToString().ToLowerInvariant(),
			autoUpdate = t.autoUpdate.GetOrElse(false),
		};
	}

	public string Describe() =>
		$"v{version} · {(componentGroups.Length == 0 ? "no component groups" : string.Join(", ", componentGroups))} · realms {realms} · auto-update {(autoUpdate ? "on" : "off")}";
}

[Serializable]
public class SitePlanInfo
{
	/// <summary>The manifest's scope: the zone id or a realm id.</summary>
	public string site;
	public bool isZone;

	/// <summary>"add Scores (service)", "upgrade", "archive", "keep" (an override stays) or "detach".</summary>
	public string[] changes = Array.Empty<string>();
}

[Serializable]
public class InstallationPlanInfo
{
	public string bundle;
	public string zoneId;
	public string change;
	public InstallationTargetInfo from;
	public InstallationTargetInfo to;
	public SitePlanInfo[] sites = Array.Empty<SitePlanInfo>();
	public string[] refusals = Array.Empty<string>();
	public string[] warnings = Array.Empty<string>();

	/// <summary>Dependencies to install, upgrade or extend first, each with why.</summary>
	public string[] blockers = Array.Empty<string>();

	/// <summary>For an upgrade: whether auto-update could apply it.</summary>
	public bool? compatible;
	public bool autoUpdateLocked;

	/// <summary>The plan's hash; apply refuses it if anything moved since.</summary>
	public string hash;

	public static InstallationPlanInfo From(InstallationPlan p) => new InstallationPlanInfo
	{
		bundle = p.bundle.GetOrElse(""),
		zoneId = p.zoneId.GetOrElse(""),
		change = p.change.HasValue ? p.change.Value.ToString() : "",
		from = InstallationTargetInfo.From(p.from.GetOrElse((InstallationTarget)null)),
		to = InstallationTargetInfo.From(p.to.GetOrElse((InstallationTarget)null)),
		sites = p.sites.GetOrElse(Array.Empty<SitePlan>()).Select(s => new SitePlanInfo
		{
			site = s.scope.GetOrElse(""),
			isZone = s.isZone.GetOrElse(false),
			changes = s.changes.GetOrElse(Array.Empty<ComponentChange>())
				.Select(c => $"{(c.change.HasValue ? c.change.Value.ToString().ToLowerInvariant() : "")} {c.name.GetOrElse("")} ({c.kind.GetOrElse("")})")
				.ToArray(),
		}).ToArray(),
		refusals = p.refusals.GetOrElse(Array.Empty<string>()),
		warnings = p.warnings.GetOrElse(Array.Empty<string>()),
		blockers = p.blockers.GetOrElse(Array.Empty<DependencyBlocker>()).Select(b =>
		{
			var range = BundleDependencyConfig.FormatRange(b.min.GetOrElse(0), b.max.HasValue ? b.max.Value : null);
			var installed = b.installedVersion.HasValue ? $", v{b.installedVersion.Value} is installed" : "";
			var kind = b.kind.HasValue ? b.kind.Value : DependencyBlockKind.Missing;
			return kind switch
			{
				DependencyBlockKind.Missing => $"{b.bundle.GetOrElse("")} {range} must be installed on the zone first",
				DependencyBlockKind.OutOfRange => $"{b.bundle.GetOrElse("")} must be {range}{installed}",
				DependencyBlockKind.Realms => $"{b.bundle.GetOrElse("")} must cover every realm this bundle uses",
				_ => $"{b.bundle.GetOrElse("")} depends on this bundle ({range}){installed}",
			};
		}).ToArray(),
		compatible = p.compatible.HasValue ? p.compatible.Value : null,
		autoUpdateLocked = p.autoUpdateLocked.GetOrElse(false),
		hash = p.hash.GetOrElse(""),
	};

	public void Print()
	{
		var sb = new StringBuilder();
		sb.AppendLine($"Plan for [{bundle}] on zone [{zoneId}]: {change}");
		if (from != null) sb.AppendLine($"  now:   {from.Describe()}");
		if (to != null) sb.AppendLine($"  after: {to.Describe()}{(autoUpdateLocked ? " (auto-update required by the publisher)" : "")}");
		if (compatible == false) sb.AppendLine("  This upgrade is breaking for at least one component, or changes data irreversibly.");
		foreach (var site in sites.OrderByDescending(s => s.isZone))
		{
			sb.AppendLine($"  {(site.isZone ? "Zone" : "Realm")} {site.site}: {(site.changes.Length == 0 ? "no changes" : "")}");
			foreach (var c in site.changes) sb.AppendLine($"   - {c}");
		}
		Log.Information(sb.ToString().TrimEnd());
		foreach (var blocker in blockers) Log.Warning($"Blocked: {blocker}");
		foreach (var warning in warnings) Log.Warning(warning);
	}
}

[Serializable]
public class SiteResultInfo
{
	public string site;

	/// <summary>"applied", "pending" or "failed".</summary>
	public string state;
	public string error;
	public string manifestId;

	public static SiteResultInfo[] From(MapOfInstallationSite results) => results
		.Select(kv => new SiteResultInfo
		{
			site = kv.Key,
			state = kv.Value.state.HasValue ? kv.Value.state.Value.ToString().ToLowerInvariant() : "",
			error = kv.Value.error.GetOrElse((string)null),
			manifestId = kv.Value.manifestId.GetOrElse((string)null),
		}).ToArray();
}
