[Serializable]
public class InstallationInfo
{
	public string bundle;
	public string zoneId;
	public InstallationTargetInfo target;

	/// <summary>"supported", "deprecated", "unsupported" or "endoflife".</summary>
	public string status;

	/// <summary>The deprecation covering the installed version, which sets <see cref="status"/>.</summary>
	public BundleNoticeInfo notice;

	/// <summary>Every unresolved notice on the installed version, of any kind, announcements included.</summary>
	public BundleNoticeInfo[] notices = Array.Empty<BundleNoticeInfo>();
	public bool uninstalling;
	public bool autoUpdateLocked;
	public SiteResultInfo[] sites = Array.Empty<SiteResultInfo>();

	/// <summary>The last automatic update's outcome, or what it waits for.</summary>
	public string update;
	public OverrideInfo[] overrides = Array.Empty<OverrideInfo>();

	public static InstallationInfo From(InstallationView v)
	{
		var update = v.update.GetOrElse((InstallationUpdate)null);
		return new InstallationInfo
		{
			bundle = v.bundle.GetOrElse(""),
			zoneId = v.zoneId.GetOrElse(""),
			target = InstallationTargetInfo.From(v.target.GetOrElse((InstallationTarget)null)),
			status = v.status.HasValue ? v.status.Value.ToString().ToLowerInvariant() : "",
			notice = BundleNoticeInfo.FromNotice(v.notice.GetOrElse((BundleNoticeView)null)),
			notices = v.notices.GetOrElse(Array.Empty<BundleNoticeView>()).Select(BundleNoticeInfo.FromNotice).ToArray(),
			uninstalling = v.uninstalling.GetOrElse(false),
			autoUpdateLocked = v.autoUpdateLocked.GetOrElse(false),
			sites = SiteResultInfo.From(v.sites.GetOrElse(new MapOfInstallationSite())),
			update = DescribeUpdate(update),
			overrides = v.overrides.GetOrElse(Array.Empty<OverrideView>()).Select(OverrideInfo.From).ToArray(),
		};
	}

	public static string DescribeUpdate(InstallationUpdate u)
	{
		if (u == null) return null;
		var state = u.state.HasValue ? u.state.Value.ToString().ToLowerInvariant() : "";
		var version = u.version.HasValue ? $" v{u.version.Value}" : "";
		var reason = u.reason.GetOrElse((string)null);
		return $"{state}{version}{(string.IsNullOrEmpty(reason) ? "" : $": {reason}")}";
	}
}

[Serializable]
public class OverrideInfo
{
	public string site;
	public string component;
	public string connectionId;
	public long baseVersion;

	/// <summary>The latest version, when it changed the component since <see cref="baseVersion"/>.</summary>
	public long? changedIn;

	public static OverrideInfo From(OverrideView o) => new OverrideInfo
	{
		site = o.site.GetOrElse(""),
		component = o.component.GetOrElse(""),
		connectionId = o.connectionId.HasValue ? o.connectionId.Value.ToString() : "",
		baseVersion = o.baseVersion.GetOrElse(0),
		changedIn = o.changedIn.HasValue ? o.changedIn.Value : null,
	};

	public string Describe() =>
		$"{component} on {site}: local build, from v{baseVersion}{(changedIn.HasValue ? $"; v{changedIn} changed it since" : "")}";
}

public class ListInstallationsCommandArgs : ZoneInstallationArgs
{
}

public class ListInstallationsCommandOutput
{
	public InstallationInfo[] installations = Array.Empty<InstallationInfo>();
}

public class ListInstallationsCommand : AtomicCommand<ListInstallationsCommandArgs, ListInstallationsCommandOutput>, ISkipManifest
{
	public ListInstallationsCommand() : base("installations", "Show the bundles installed on a zone: release, component groups, realms, deprecation and overrides")
	{
	}

	public override void Configure() => ZoneInstallationArgs.AddTargetZoneOption(this);

	public override async Task<ListInstallationsCommandOutput> GetResult(ListInstallationsCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		using var zone = await args.ZoneScope();
		var response = await api.GetInstallations();
		return new ListInstallationsCommandOutput
		{
			installations = response.records.GetOrElse(Array.Empty<InstallationView>()).Select(InstallationInfo.From).ToArray(),
		};
	}

	protected override void LogResult(object result)
	{
		if (result is not ListInstallationsCommandOutput output)
		{
			base.LogResult(result);
			return;
		}

		var table = new Table();
		table.AddColumn("Bundle");
		table.AddColumn("Installed");
		table.AddColumn("Status");
		table.AddColumn("Sites");
		table.AddColumn("Overrides");
		foreach (var i in output.installations)
		{
			var status = string.Join("\n", new[] { i.status }.Concat(i.notices.Select(n => n.description)))
			             + (i.update == null ? "" : $"\nauto-update: {i.update}");
			table.AddRow(
				Markup.Escape(i.bundle + (i.uninstalling ? " (uninstalling)" : "")),
				Markup.Escape(i.target?.Describe() ?? "-"),
				Markup.Escape(status),
				Markup.Escape(string.Join("\n", i.sites.Select(s => $"{s.site}: {s.state}{(s.error == null ? "" : $" ({s.error})")}"))),
				Markup.Escape(i.overrides.Length == 0 ? "-" : string.Join("\n", i.overrides.Select(o => o.Describe()))));
		}
		AnsiConsole.Write(table);
	}
}

public class InstallationHistoryCommandArgs : ZoneInstallationArgs
{
	public int limit;
}

[Serializable]
public class InstallationHistoryEntryInfo
{
	public DateTime at;
	public string change;
	public string actor;
	public InstallationTargetInfo from;
	public InstallationTargetInfo to;
	public SiteResultInfo[] results = Array.Empty<SiteResultInfo>();
}

public class InstallationHistoryCommandOutput
{
	public string bundle;
	public InstallationHistoryEntryInfo[] entries = Array.Empty<InstallationHistoryEntryInfo>();
}

public class InstallationHistoryCommand : AtomicCommand<InstallationHistoryCommandArgs, InstallationHistoryCommandOutput>, ISkipManifest
{
	public InstallationHistoryCommand() : base("history", "Show one installation's changes on a zone, newest first")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddOption(new Option<int>("--limit", () => 50, "How many entries to show"),
			(args, i) => args.limit = i);
		ZoneInstallationArgs.AddTargetZoneOption(this);
	}

	public override async Task<InstallationHistoryCommandOutput> GetResult(InstallationHistoryCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		using var zone = await args.ZoneScope();
		var response = await api.GetInstallationsHistory(new Optional<string>(), args.limit, fullName);
		return new InstallationHistoryCommandOutput
		{
			bundle = fullName,
			entries = response.records.GetOrElse(Array.Empty<InstallationHistoryView>()).Select(e => new InstallationHistoryEntryInfo
			{
				at = e.at.GetOrElse(default(DateTime)),
				change = e.change.HasValue ? e.change.Value.ToString() : "",
				actor = e.actor.GetOrElse(""),
				from = InstallationTargetInfo.From(e.from.GetOrElse((InstallationTarget)null)),
				to = InstallationTargetInfo.From(e.to.GetOrElse((InstallationTarget)null)),
				results = SiteResultInfo.From(e.results.GetOrElse(new MapOfInstallationSite())),
			}).ToArray(),
		};
	}

	protected override void LogResult(object result)
	{
		if (result is not InstallationHistoryCommandOutput output)
		{
			base.LogResult(result);
			return;
		}

		var table = new Table().Title(Markup.Escape(output.bundle));
		table.AddColumn("When");
		table.AddColumn("Change");
		table.AddColumn("By");
		table.AddColumn("To");
		table.AddColumn("Result");
		foreach (var e in output.entries)
		{
			table.AddRow(
				Markup.Escape(e.at.ToLocalTime().ToString("yyyy-MM-dd HH:mm")),
				Markup.Escape(e.change),
				Markup.Escape(e.actor),
				Markup.Escape(e.to?.Describe() ?? "-"),
				Markup.Escape(string.Join(", ", e.results.Select(r => $"{r.site} {r.state}"))));
		}
		AnsiConsole.Write(table);
	}
}

public class InstallationDependenciesCommandArgs : ZoneInstallationArgs
{
	public long version;
}

[Serializable]
public class DependencyStatusInfo
{
	public string name;

	/// <summary>"hard" or "soft".</summary>
	public string kind;
	public string range;
	public bool acquired;
	public long? installedVersion;
	public bool inRange;
}

public class InstallationDependenciesCommandOutput
{
	public string name;
	public long version;
	public DependencyStatusInfo[] dependencies = Array.Empty<DependencyStatusInfo>();
}

public class InstallationDependenciesCommand : AtomicCommand<InstallationDependenciesCommandArgs, InstallationDependenciesCommandOutput>, ISkipManifest
{
	public InstallationDependenciesCommand() : base("dependencies", "Show a bundle release's dependencies, and whether each is acquired and installed on the zone")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddOption(new Option<long>("--version", "The release to check. Defaults to the installed one, else latest"),
			(args, i) => args.version = i);
		ZoneInstallationArgs.AddTargetZoneOption(this);
	}

	public override async Task<InstallationDependenciesCommandOutput> GetResult(InstallationDependenciesCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		using var zone = await args.ZoneScope();
		var response = await api.GetInstallationsDependencies(fullName, args.version > 0 ? args.version : new Optional<long>());
		return new InstallationDependenciesCommandOutput
		{
			name = fullName,
			version = response.version.GetOrElse(0),
			dependencies = response.dependencies.GetOrElse(Array.Empty<DependencyStatus>()).Select(d => new DependencyStatusInfo
			{
				name = d.name.GetOrElse(""),
				kind = d.kind.HasValue ? d.kind.Value.ToString().ToLowerInvariant() : "",
				range = BundleDependencyConfig.FormatRange(d.min.GetOrElse(0), d.max.HasValue ? d.max.Value : null),
				acquired = d.acquired.GetOrElse(false),
				installedVersion = d.installedVersion.HasValue ? d.installedVersion.Value : null,
				inRange = d.inRange.GetOrElse(false),
			}).ToArray(),
		};
	}

	protected override void LogResult(object result)
	{
		if (result is not InstallationDependenciesCommandOutput output)
		{
			base.LogResult(result);
			return;
		}

		var table = new Table().Title(Markup.Escape($"{output.name} v{output.version}"));
		table.AddColumn("Dependency");
		table.AddColumn("Kind");
		table.AddColumn("Range");
		table.AddColumn("Acquired");
		table.AddColumn("On this zone");
		foreach (var d in output.dependencies)
		{
			table.AddRow(
				Markup.Escape(d.name), Markup.Escape(d.kind), Markup.Escape(d.range),
				d.acquired ? "yes" : "no",
				Markup.Escape(d.installedVersion.HasValue ? $"v{d.installedVersion}{(d.inRange ? "" : " (out of range)")}" : "not installed"));
		}
		AnsiConsole.Write(table);
	}
}

public class InstallationNoticesCommandArgs : CommandArgs
{
}

[Serializable]
public class ZoneNoticeInfo
{
	public string zoneId;
	public string bundle;
	public long version;
	public string status;
	public BundleNoticeInfo notice;

	/// <summary>The version an automatic update would move to: a deprecation's replacement, or an advisory's fix.</summary>
	public long? replacementVersion;
	public string update;
}

public class InstallationNoticesCommandOutput
{
	public ZoneNoticeInfo[] installations = Array.Empty<ZoneNoticeInfo>();
}

/// <summary>
/// Every installation of the org on a version with a notice that warns, on every zone, once per notice.
/// Announcements never show here. Works from any scope of the org.
/// </summary>
public class InstallationNoticesCommand : AtomicCommand<InstallationNoticesCommandArgs, InstallationNoticesCommandOutput>, ISkipManifest
{
	public InstallationNoticesCommand() : base("notices", "Show every installation of your org on a version with a deprecation, security advisory, known issue or retirement, by zone")
	{
	}

	public override void Configure()
	{
	}

	public override async Task<InstallationNoticesCommandOutput> GetResult(InstallationNoticesCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var response = await api.GetInstallationsNotices();
		var output = new InstallationNoticesCommandOutput
		{
			installations = response.records.GetOrElse(Array.Empty<ZoneNotices>())
				.SelectMany(z => z.installations.GetOrElse(Array.Empty<InstallationNotice>()).Select(i => new ZoneNoticeInfo
				{
					zoneId = z.zoneId.GetOrElse(""),
					bundle = i.bundle.GetOrElse(""),
					version = i.version.GetOrElse(0),
					status = i.status.HasValue ? i.status.Value.ToString().ToLowerInvariant() : "",
					notice = BundleNoticeInfo.FromNotice(i.notice.GetOrElse((BundleNoticeView)null)),
					replacementVersion = i.replacementVersion.HasValue ? i.replacementVersion.Value : null,
					update = InstallationInfo.DescribeUpdate(i.update.GetOrElse((InstallationUpdate)null)),
				}))
				// The server leaves announcements out; never show one as a warning if it does send one.
				.Where(i => i.notice?.warns ?? true)
				.ToArray(),
		};
		if (output.installations.Length == 0)
		{
			Log.Information("No installation of your org runs a version with a notice.");
		}
		return output;
	}

	protected override void LogResult(object result)
	{
		if (result is not InstallationNoticesCommandOutput output || output.installations.Length == 0)
		{
			base.LogResult(result);
			return;
		}

		var table = new Table();
		table.AddColumn("Zone");
		table.AddColumn("Bundle");
		table.AddColumn("Running");
		table.AddColumn("Notice");
		table.AddColumn("Moves to");
		foreach (var i in output.installations)
		{
			table.AddRow(
				Markup.Escape(i.zoneId), Markup.Escape(i.bundle), Markup.Escape($"v{i.version} ({i.status})"),
				Markup.Escape(i.notice?.description ?? "-"),
				Markup.Escape((i.replacementVersion.HasValue ? $"v{i.replacementVersion}" : "-") + (i.update == null ? "" : $"\n{i.update}")));
		}
		AnsiConsole.Write(table);
	}
}

public class EndOverrideCommandArgs : ZoneInstallationArgs
{
	public string component;
	public bool zone;
}

public class EndOverrideCommandOutput
{
	public string bundle;
	public string component;
	public string manifestId;
	public string[] warnings = Array.Empty<string>();
}

/// <summary>
/// Give an overridden component back to its bundle on the realm or zone in scope: the bundle's build runs
/// there again. It deploys like a manifest post. A deploy with <c>--end-override</c> does the same.
/// </summary>
public class EndOverrideCommand : AtomicCommand<EndOverrideCommandArgs, EndOverrideCommandOutput>, ISkipManifest
{
	public EndOverrideCommand() : base("end-override", "Give an overridden component back to its bundle on the current realm, or on the zone with --zone")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddArgument(new Argument<string>("component", "The overridden component"),
			(args, i) => args.component = i);
		AddOption(new Option<bool>("--zone", "End the override on the zone instead of the current realm"),
			(args, i) => args.zone = i);
		ZoneInstallationArgs.AddTargetZoneOption(this);
	}

	public override async Task<EndOverrideCommandOutput> GetResult(EndOverrideCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		using var scope = args.zone || !string.IsNullOrEmpty(args.targetZone) ? await args.ZoneScope() : null;
		var checksum = await api.DeleteInstallationsOverrides(args.component, fullName);
		var warnings = checksum.warnings.GetOrElse(Array.Empty<string>());
		foreach (var warning in warnings) Log.Warning(warning);
		Log.Information($"[{args.component}] runs the bundle's build again.");
		return new EndOverrideCommandOutput
		{
			bundle = fullName, component = args.component, manifestId = checksum.id.GetOrElse(""), warnings = warnings,
		};
	}
}
