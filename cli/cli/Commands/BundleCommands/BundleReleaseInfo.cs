using System;
using Beamable.Api.Autogenerated.Models;

namespace cli.BundleCommands;

/// <summary>
/// CLI-owned projection of one entry in a bundle's release log. After a revert the same content
/// checksum sits at several versions, so the version, not the checksum, identifies a release.
/// </summary>
[Serializable]
public class BundleReleaseInfo
{
	public long version;
	public string checksum = "";

	/// <summary>Unix timestamp (seconds).</summary>
	public long publishedAt;

	/// <summary>The account that published this release.</summary>
	public string publishedBy;

	/// <summary>A yanked version can't be installed any more; running installations keep it.</summary>
	public bool yanked;

	/// <summary>Running this version changes stored data in a way a rollback can't undo.</summary>
	public bool irreversibleDataChange;

	public static BundleReleaseInfo FromRelease(BundleRelease release)
	{
		if (release == null) return null;

		var published = release.publishedAt.GetOrElse(default(DateTime));
		return new BundleReleaseInfo
		{
			version = release.version.GetOrElse(0),
			checksum = release.checksum.GetOrElse(""),
			publishedBy = release.publishedBy.GetOrElse((string)null),
			yanked = release.yanked.GetOrElse(false),
			irreversibleDataChange = release.irreversibleDataChange.GetOrElse(false),
			publishedAt = published == default
				? 0
				: new DateTimeOffset(published.ToUniversalTime(), TimeSpan.Zero).ToUnixTimeSeconds(),
		};
	}
}
