using Beamable.Api.Autogenerated.Beamobundle;
using Beamable.Api.Autogenerated.Models;
using Beamable.Server;
using cli.Services.Bundles;
using System.CommandLine;
using System.Linq;

namespace cli.BundleCommands;

public class PinBundleCommandArgs : CommandArgs
{
	public string bundleName;
	public string tag;
	public string checksum;
}

public class PinBundleCommandOutput
{
	public string name;
	public string checksum;
}

public class PinBundleCommand : AtomicCommand<PinBundleCommandArgs, PinBundleCommandOutput>, ISkipManifest
{
	public PinBundleCommand() : base("pin", "Pin a bundle checksum into the local manifest.beam.json references")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddOption(new Option<string>("--tag", () => "latest", "Resolve the checksum from this tag"),
			(args, i) => args.tag = i);
		AddOption(new Option<string>("--checksum", "Pin this exact checksum (sha256:<checksum>) instead of a tag"),
			(args, i) => args.checksum = i);
	}

	public override async Task<PinBundleCommandOutput> GetResult(PinBundleCommandArgs args)
	{
		var (explicitNs, name) = BundleNamespace.SplitName(args.bundleName);
		BundleWorkspace.ValidateName(name);
		var ns = await BundleNamespace.Resolve(args, explicitNs);
		var fullName = BundleNamespace.Qualify(ns, name);

		var api = args.Provider.GetService<IBeamBeamobundleApi>();

		// Always fetch the bundle: we need its scope (realm/zone) to file the pin into the matching
		// manifest section, and — when no explicit checksum is given — to resolve the tag to a checksum.
		var checksum = args.checksum;
		BundleView bundle;
		if (string.IsNullOrEmpty(checksum))
		{
			var response = await api.GetBundles(name, ns);
			var match = response.tags.ToTagInfos().FirstOrDefault(t => t.tag == args.tag);
			if (match == null)
			{
				throw new CliException($"Bundle [{name}] has no tag [{args.tag}]. Use --checksum to pin an exact checksum.");
			}
			checksum = match.checksum;
			bundle = response.bundle;
		}
		else
		{
			var response = await api.GetBundlesChecksums(name, checksum, ns);
			bundle = response.bundle;
			if (bundle == null)
			{
				throw new CliException($"Bundle [{name}] has no checksum [{checksum}].");
			}
		}

		var scope = bundle?.scope.GetOrElse("");
		if (string.IsNullOrEmpty(scope))
		{
			Log.Warning($"Bundle [{fullName}] has no scope from the catalog; defaulting to the {BundleWorkspace.SCOPE_REALM} section.");
		}
		var isZone = BundleWorkspace.IsZoneScope(scope);

		var manifest = args.ConfigService.LoadManifestReferences() ?? new ManifestReferences();
		manifest.ForScope(isZone)[fullName] = checksum;
		args.ConfigService.SaveManifestReferences(manifest);

		Log.Information($"Pinned [{fullName}] → [{checksum}] into the {(isZone ? BundleWorkspace.SCOPE_ZONE : BundleWorkspace.SCOPE_REALM)} section of {ConfigService.MANIFEST_FILE_NAME}");
		return new PinBundleCommandOutput { name = fullName, checksum = checksum };
	}
}
