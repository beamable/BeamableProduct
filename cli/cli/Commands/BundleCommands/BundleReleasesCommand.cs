using Beamable.Api.Autogenerated.Beamobundle;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common.BeamCli.Contracts;
using Beamable.Common.Content;
using Beamable.Server;
using cli.Services.Bundles;
using Spectre.Console;
using System;
using System.Collections.Generic;
using System.CommandLine;
using System.Linq;

namespace cli.BundleCommands;

public class BundleReleasesCommandArgs : CommandArgs
{
	public string bundleName;
	public int limit;
	public long version;
}

public class BundleReleasesCommandOutput
{
	public string name;

	/// <summary>The bundle's releases, newest first.</summary>
	public BundleReleaseInfo[] releases = Array.Empty<BundleReleaseInfo>();

	/// <summary>The bundle's tags, latest included. A tag points at a version.</summary>
	public BundleTagInfo[] tags = Array.Empty<BundleTagInfo>();

	/// <summary>Every deprecation notice of the bundle; a version none covers is supported.</summary>
	public BundleNoticeInfo[] notices = Array.Empty<BundleNoticeInfo>();

	/// <summary>The content of the version asked for with --version; null otherwise.</summary>
	public BundleContentInfo content;
}

/// <summary>One release's content: its components, component groups and dependencies.</summary>
[Serializable]
public class BundleContentInfo
{
	public long version;
	public string checksum = "";
	public BundleComponentInfo[] components = Array.Empty<BundleComponentInfo>();
	public Dictionary<string, string[]> componentGroups = new Dictionary<string, string[]>();
	public Dictionary<string, string> dependencies = new Dictionary<string, string>();

	public static BundleContentInfo FromContent(long version, BundleContentView content) => new BundleContentInfo
	{
		version = version,
		checksum = content.checksum.GetOrElse(""),
		components = content.components.GetOrElse(Array.Empty<BundleComponent>()).Select(c => new BundleComponentInfo
		{
			name = c.name.GetOrElse(""),
			kind = c.kind.HasValue ? c.kind.Value.ToString().ToLowerInvariant() : "",
			site = c.site.HasValue ? c.site.Value.ToString().ToLowerInvariant() : "",
			source = c.sourceAvailable.GetOrElse(false),
		}).ToArray(),
		componentGroups = content.features.GetOrElse(Array.Empty<BundleFeature>())
			.ToDictionary(f => f.name.GetOrElse(""), f => f.components.GetOrElse(Array.Empty<string>())),
		dependencies = content.dependencies.GetOrElse(Array.Empty<BundleDep>()).ToDictionary(
			d => d.name.GetOrElse(""),
			d => $"{(d.kind.HasValue ? d.kind.Value.ToString().ToLowerInvariant() : "")} {BundleDependencyConfig.FormatRange(d.min.GetOrElse(0), d.max.HasValue ? d.max.Value : null)}"),
	};
}

/// <summary>
/// Show a bundle's release log. The endpoint is paged on an exclusive version cursor, so this
/// walks it to the end rather than showing a first page as if it were the whole log.
/// </summary>
public class BundleReleasesCommand
	: AtomicCommand<BundleReleasesCommandArgs, BundleReleasesCommandOutput>, ISkipManifest
{
	/// <summary>The endpoint's own maximum page size.</summary>
	private const int PageSize = 200;

	public BundleReleasesCommand() : base("releases", "Show a bundle's releases, tags and deprecation notices, or one release's content")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddOption(new Option<int>("--limit", () => 0, "Stop after this many releases, newest first. 0 (the default) walks the whole log"),
			(args, i) => args.limit = i);
		AddOption(new Option<long>("--version", "Also show this version's content: components, component groups and dependencies"),
			(args, i) => args.version = i);
	}

	public override async Task<BundleReleasesCommandOutput> GetResult(BundleReleasesCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamobundleApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);

		var output = new BundleReleasesCommandOutput { name = fullName };
		var releases = new List<BundleReleaseInfo>();
		var fromVersion = new Optional<long>();
		while (true)
		{
			var response = await api.GetReleases(fromVersion, (Optional<int>)PageSize, (Optional<string>)fullName);
			output.tags = response.tags.ToTagInfos();
			output.notices = response.notices.GetOrElse(Array.Empty<BundleNoticeView>()).Select(BundleNoticeInfo.FromNotice).ToArray();
			var page = response.releases.GetOrElse(Array.Empty<BundleRelease>())
				.Select(BundleReleaseInfo.FromRelease)
				.ToArray();
			releases.AddRange(page);

			var reachedLimit = args.limit > 0 && releases.Count >= args.limit;
			if (page.Length < PageSize || reachedLimit)
				break;
			fromVersion = (Optional<long>)page[^1].version;
		}

		if (args.limit > 0 && releases.Count > args.limit)
			releases = releases.Take(args.limit).ToList();
		output.releases = releases.ToArray();

		if (args.version > 0)
		{
			var content = await api.GetReleasesContent((Optional<string>)fullName, (Optional<long>)args.version);
			var view = content.content.GetOrElse((BundleContentView)null);
			if (view != null)
				output.content = BundleContentInfo.FromContent(args.version, view);
		}

		return output;
	}

	protected override void LogResult(object result)
	{
		if (result is not BundleReleasesCommandOutput output)
		{
			base.LogResult(result);
			return;
		}

		var tagsByVersion = output.tags
			.GroupBy(t => t.version)
			.ToDictionary(g => g.Key, g => string.Join(", ", g.Select(t => t.tag)));
		var table = new Table().Title(Markup.Escape(output.name));
		table.AddColumn("Version");
		table.AddColumn("Published At");
		table.AddColumn("Tags");
		table.AddColumn("Status");
		foreach (var release in output.releases)
		{
			var notice = output.notices.FirstOrDefault(n => release.version >= n.minVersion && release.version <= n.maxVersion);
			var status = release.yanked ? "yanked" : notice?.status ?? "supported";
			if (release.irreversibleDataChange) status += ", irreversible data change";
			table.AddRow(
				Markup.Escape($"v{release.version}"),
				Markup.Escape(BundleInfo.FormatPublishedAt(release.publishedAt)),
				Markup.Escape(tagsByVersion.TryGetValue(release.version, out var t) ? t : "-"),
				Markup.Escape(status));
		}
		AnsiConsole.Write(table);

		foreach (var notice in output.notices)
			AnsiConsole.MarkupLine($"[yellow]Notice {Markup.Escape(notice.id)}[/]: {Markup.Escape(notice.Describe())}");

		if (output.content != null)
		{
			var content = new Table().Title(Markup.Escape($"v{output.content.version} content"));
			content.AddColumn("Component");
			content.AddColumn("Kind");
			content.AddColumn("Site");
			content.AddColumn("Source");
			content.AddColumn("Component groups");
			foreach (var component in output.content.components)
			{
				content.AddRow(
					Markup.Escape(component.name),
					Markup.Escape(component.kind),
					Markup.Escape(component.site),
					component.source ? "available" : "-",
					Markup.Escape(string.Join(", ", output.content.componentGroups.Where(g => g.Value.Contains(component.name)).Select(g => g.Key))));
			}
			AnsiConsole.Write(content);
			foreach (var (dependency, range) in output.content.dependencies)
				AnsiConsole.MarkupLine($"Depends on {Markup.Escape(dependency)} ({Markup.Escape(range)})");
		}
	}
}
