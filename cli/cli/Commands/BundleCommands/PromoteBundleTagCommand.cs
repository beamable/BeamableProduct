using Beamable.Api.Autogenerated.Beamobundle;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common.BeamCli.Contracts;
using Beamable.Server;
using cli.Services.Bundles;
using System;
using System.CommandLine;

namespace cli.BundleCommands;

public class PromoteBundleTagCommandArgs : CommandArgs
{
	public string bundleName;
	public string tag;
	public long version;
}

public class PromoteBundleTagCommandOutput
{
	public string name;

	/// <summary>Every tag after the move, latest included.</summary>
	public BundleTagInfo[] tags = Array.Empty<BundleTagInfo>();
}

public class PromoteBundleTagCommand : AtomicCommand<PromoteBundleTagCommandArgs, PromoteBundleTagCommandOutput>, ISkipManifest
{
	public PromoteBundleTagCommand() : base("tag", "Point a bundle tag at a release version. latest can be moved too")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, optionally namespaced as @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
		AddArgument(new Argument<string>("tag", "The tag to move, e.g. stable or latest"),
			(args, i) => args.tag = i);
		AddArgument(new Argument<long>("version", "The release version the tag points at"),
			(args, i) => args.version = i);
	}

	public override async Task<PromoteBundleTagCommandOutput> GetResult(PromoteBundleTagCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamobundleApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		var summary = await api.PutBundlesTags(new SetBundleTagRequest
		{
			name = fullName,
			tag = args.tag,
			version = args.version,
		});
		return new PromoteBundleTagCommandOutput { name = fullName, tags = summary.tags.ToTagInfos() };
	}
}
