namespace cli.BundleCommands;

public class LibraryBundleCommandArgs : CommandArgs
{
	public string bundleName;
}

public class AcquireBundleCommandOutput
{
	public string name;
	public bool acquired;
	public string[] refusals = Array.Empty<string>();

	/// <summary>Hard dependencies to acquire first.</summary>
	public string[] missingHardDependencies = Array.Empty<string>();

	/// <summary>Soft dependencies the bundle works better with, as "name range (acquired)".</summary>
	public string[] suggestedDependencies = Array.Empty<string>();

	/// <summary>What the org should know before acquiring, such as a retirement.</summary>
	public string[] warnings = Array.Empty<string>();
}

/// <summary>
/// Add a bundle to the org's library, so it can be installed on zones. Its hard dependencies must be in
/// the library first; nothing is acquired automatically. Customer Admins only.
/// </summary>
public class AcquireBundleCommand : AtomicCommand<LibraryBundleCommandArgs, AcquireBundleCommandOutput>, ISkipManifest
{
	public AcquireBundleCommand() : base("acquire", "Add a bundle to your org's library, so it can be installed on zones")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
	}

	public override async Task<AcquireBundleCommandOutput> GetResult(LibraryBundleCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		var plan = await api.PostAcquisitionsPlan(new AcquireBundleRequest { name = fullName });
		var output = new AcquireBundleCommandOutput
		{
			name = fullName,
			refusals = plan.refusals.GetOrElse(Array.Empty<string>()),
			missingHardDependencies = plan.missingHardDependencies.GetOrElse(Array.Empty<string>()),
			suggestedDependencies = plan.suggestedDependencies.GetOrElse(Array.Empty<SuggestedDependency>())
				.Select(d => $"{d.name.GetOrElse("")} {d.range.GetOrElse("")}{(d.acquired.GetOrElse(false) ? " (acquired)" : "")}")
				.ToArray(),
			warnings = plan.warnings.GetOrElse(Array.Empty<string>()),
		};

		foreach (var warning in output.warnings)
		{
			Log.Warning(warning);
		}
		foreach (var suggestion in output.suggestedDependencies)
			Log.Information($"Suggested: {suggestion}. Optional; it is never acquired for you.");
		if (!plan.canAcquire.GetOrElse(false))
		{
			var reasons = output.refusals.Concat(output.missingHardDependencies.Select(d => $"acquire its hard dependency {d} first"));
			Log.Error($"[{fullName}] can't be acquired:\n - {string.Join("\n - ", reasons)}");
			return output;
		}

		var confirm = args.Quiet || string.Equals("yes",
			AnsiConsole.Prompt(new TextPrompt<string>($"Add {Markup.Escape(fullName)} to your org's library? Nothing is installed until you install it on a zone.\nType 'yes' to continue.")),
			StringComparison.InvariantCultureIgnoreCase);
		if (!confirm)
		{
			Log.Information("Nothing was acquired.");
			return output;
		}

		await api.PostAcquisitions(new AcquireBundleRequest { name = fullName });
		output.acquired = true;
		Log.Information($"[{fullName}] is in your org's library. Install it with `beam bundles install {fullName}`.");
		return output;
	}
}

public class RemoveBundleCommandOutput
{
	public string name;
}

/// <summary>Remove a bundle from the org's library. Refused while it is installed anywhere, or another acquired bundle needs it.</summary>
public class RemoveBundleCommand : AtomicCommand<LibraryBundleCommandArgs, RemoveBundleCommandOutput>, ISkipManifest
{
	public RemoveBundleCommand() : base("remove", "Remove a bundle from your org's library. It must not be installed on any zone")
	{
	}

	public override void Configure()
	{
		AddArgument(new Argument<string>("bundle-name", "The bundle name, @<namespace>/<bundle-name>"),
			(args, i) => args.bundleName = i);
	}

	public override async Task<RemoveBundleCommandOutput> GetResult(LibraryBundleCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var fullName = await BundleNamespace.FullName(args, args.bundleName);
		await api.DeleteAcquisitions(fullName);
		Log.Information($"Removed [{fullName}] from your org's library.");
		return new RemoveBundleCommandOutput { name = fullName };
	}
}

public class LibraryCommandArgs : CommandArgs
{
}

[Serializable]
public class LibraryEntryInfo
{
	public string bundle;
	public bool acquired;
	public bool owned;
	public DateTime? acquiredAt;
	public LibraryInstallationInfo[] installations = Array.Empty<LibraryInstallationInfo>();
}

[Serializable]
public class LibraryInstallationInfo
{
	public string zoneId;
	public long version;
	public string status;

	/// <summary>The deprecation covering the installed version, which sets <see cref="status"/>.</summary>
	public BundleNoticeInfo notice;

	/// <summary>Every unresolved notice on the installed version, of any kind, announcements included.</summary>
	public BundleNoticeInfo[] notices = Array.Empty<BundleNoticeInfo>();
	public bool uninstalling;
	public string update;
}

public class LibraryCommandOutput
{
	public LibraryEntryInfo[] bundles = Array.Empty<LibraryEntryInfo>();
}

/// <summary>The org's library: every bundle it acquired or owns, with the zones it is installed on.</summary>
public class LibraryCommand : AtomicCommand<LibraryCommandArgs, LibraryCommandOutput>, ISkipManifest
{
	public LibraryCommand() : base("library", "Show your org's library: the bundles it acquired or owns, and the zones each is installed on")
	{
	}

	public override void Configure()
	{
	}

	public override async Task<LibraryCommandOutput> GetResult(LibraryCommandArgs args)
	{
		var api = args.Provider.GetService<IBeamBeamoinstallationApi>();
		var response = await api.GetAcquisitions();
		return new LibraryCommandOutput
		{
			bundles = response.records.GetOrElse(Array.Empty<LibraryEntry>()).Select(e => new LibraryEntryInfo
			{
				bundle = e.bundle.GetOrElse(""),
				acquired = e.acquired.GetOrElse(false),
				owned = e.owned.GetOrElse(false),
				acquiredAt = e.acquiredAt.HasValue ? e.acquiredAt.Value : null,
				installations = e.installations.GetOrElse(Array.Empty<LibraryInstallation>()).Select(i => new LibraryInstallationInfo
				{
					zoneId = i.zoneId.GetOrElse(""),
					version = i.version.GetOrElse(0),
					status = i.status.HasValue ? i.status.Value.ToString().ToLowerInvariant() : "",
					notice = BundleNoticeInfo.FromNotice(i.notice.GetOrElse((BundleNoticeView)null)),
					notices = i.notices.GetOrElse(Array.Empty<BundleNoticeView>()).Select(BundleNoticeInfo.FromNotice).ToArray(),
					uninstalling = i.uninstalling.GetOrElse(false),
					update = InstallationInfo.DescribeUpdate(i.update.GetOrElse((InstallationUpdate)null)),
				}).ToArray(),
			}).ToArray(),
		};
	}

	protected override void LogResult(object result)
	{
		if (result is not LibraryCommandOutput output)
		{
			base.LogResult(result);
			return;
		}

		var table = new Table();
		table.AddColumn("Bundle");
		table.AddColumn("In library");
		table.AddColumn("Installed on");
		foreach (var b in output.bundles)
		{
			table.AddRow(
				Markup.Escape(b.bundle),
				Markup.Escape(b.owned ? "owned" : b.acquiredAt.HasValue ? $"acquired {b.acquiredAt.Value.ToLocalTime():yyyy-MM-dd}" : "acquired"),
				Markup.Escape(b.installations.Length == 0
					? "not installed"
					: string.Join("\n", b.installations.Select(i =>
						$"{i.zoneId}: v{i.version} {i.status}{(i.uninstalling ? ", uninstalling" : "")}{(i.update == null ? "" : $", auto-update {i.update}")}{string.Concat(i.notices.Select(n => $"\n  {n.description}"))}"))));
		}
		AnsiConsole.Write(table);
	}
}
