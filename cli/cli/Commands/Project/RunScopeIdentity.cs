using Beamable.Api.Autogenerated.Realms;
using Beamable.Api.Autogenerated.Zones;
using Beamable.Common.Api;
using cli.Services;

namespace cli.Commands.Project;

/// <summary>
/// The scope and secret a service started by `beam project run` authenticates with. The run command decides it
/// for every service up front, so nothing a service inherits from the CLI process (like a zone secret) can leak
/// into a service of the other scope.
/// </summary>
public class ServiceScopeIdentity
{
	public string ServiceId;
	public bool IsZone;
	public string Cid;

	/// <summary>
	/// The realm pid, or the zid for a zone service: the gateway detects a zone by the ZONE_ prefix in the pid slot.
	/// </summary>
	public string Pid;

	/// <summary>
	/// The zid for a zone service; null for a realm service.
	/// </summary>
	public string Zid;

	/// <summary>
	/// The secret to sign with, or null to leave it to the service (refresh-token auth for a realm service, or the
	/// zone secret its own generate-env provides for a zone microservice).
	/// </summary>
	public string Secret;

	public string Host;

	/// <summary>
	/// The identity as environment variables for a `dotnet run` child process. A null value removes the variable,
	/// so a value the CLI process happens to hold is never inherited.
	/// </summary>
	public Dictionary<string, string> ToProcessEnvironment() => new Dictionary<string, string>
	{
		["CID"] = Cid,
		["PID"] = Pid,
		["HOST"] = Host,
		["ZID"] = IsZone ? Zid : null,
		[RunScopeIdentity.ENV_SECRET] = string.IsNullOrEmpty(Secret) ? null : Secret,
	};
}

/// <summary>
/// Works out the <see cref="ServiceScopeIdentity"/> of every service in a `beam project run`, and validates a user's
/// SECRET override against the scopes being run. A realm secret only authenticates its realm and a zone secret
/// only its zone (the gateway picks the secret by the pid's scope), so an override can only serve one scope.
/// </summary>
public static class RunScopeIdentity
{
	public const string ENV_SECRET = "SECRET";

	public static bool HasScope(BeamoServiceDefinition definition) =>
		definition.Protocol is BeamoProtocolType.HttpMicroservice or BeamoProtocolType.PortalExtension;

	public static string GetSocketHost(string host) => host.Replace("http", "ws") + "/socket";

	/// <summary>
	/// Resolves the identity of every service in <paramref name="services"/> that authenticates (microservices and
	/// portal extensions). Throws a <see cref="CliException"/>, before anything is started, when a zone cannot be
	/// resolved or when <paramref name="secretOverride"/> is not valid for the scopes being run.
	/// </summary>
	public static async Task<Dictionary<string, ServiceScopeIdentity>> Resolve(CommandArgs args,
		IEnumerable<BeamoServiceDefinition> services, string secretOverride)
	{
		var scoped = services.Where(HasScope).ToList();
		if (scoped.Count == 0)
		{
			return new Dictionary<string, ServiceScopeIdentity>();
		}

		var cid = args.AppContext.Cid;
		var pid = args.AppContext.Pid;
		var hasOverride = !string.IsNullOrEmpty(secretOverride);
		var zoneServices = scoped.Where(s => s.IsZoneScoped).Select(s => s.BeamoId).ToList();
		var realmServices = scoped.Where(s => !s.IsZoneScoped).Select(s => s.BeamoId).ToList();

		// Nothing to look up for this one, so fail before any request.
		ThrowIfOverrideSpansScopes(hasOverride, realmServices, zoneServices);

		string zid = null;
		string zoneSecret = null;
		if (zoneServices.Count > 0)
		{
			var localZid = args.ConfigService.GetConfigString(ConfigService.CFG_JSON_FIELD_ZID);
			zid = await ZoneResolver.ResolveZid(args.DependencyProvider, cid, pid, localZid);
			if (string.IsNullOrEmpty(zid))
			{
				var reason = string.IsNullOrEmpty(pid)
					? "no realm is selected and no 'zid' is set in the .beamable config"
					: $"the selected realm [{pid}] is not bound to a zone";
				throw new CliException(
					$"The zone-scoped services [{string.Join(", ", zoneServices)}] cannot run because {reason}. " +
					$"Bind the realm to a zone (Portal > Zone Management), or set a 'zid' in the .beamable config, and retry.");
			}

			// In-process zone extensions get their secret from us; zone microservices get it from their own
			// generate-env, so only fetch it for them when there is an override to check.
			var hasZoneExtension = scoped.Any(s => s.IsZoneScoped && s.Protocol == BeamoProtocolType.PortalExtension);
			if (hasOverride || hasZoneExtension)
			{
				zoneSecret = await FetchZoneSecret(args, cid, zid);
			}
		}

		string realmSecret = null;
		if (hasOverride && realmServices.Count > 0)
		{
			realmSecret = await FetchRealmSecret(args, cid, pid);
		}

		return BuildIdentities(scoped.Select(s => (s.BeamoId, s.IsZoneScoped)), cid, pid, zid,
			GetSocketHost(args.AppContext.Host), secretOverride, realmSecret, zoneSecret);
	}

	/// <summary>
	/// Validates <paramref name="secretOverride"/> against the fetched secrets and builds each service's identity.
	/// <paramref name="realmSecret"/> and <paramref name="zoneSecret"/> are the real secrets of the realm and zone,
	/// or null when they were not needed.
	/// </summary>
	public static Dictionary<string, ServiceScopeIdentity> BuildIdentities(
		IEnumerable<(string serviceId, bool isZone)> services,
		string cid, string pid, string zid, string host,
		string secretOverride, string realmSecret, string zoneSecret)
	{
		var serviceList = services.ToList();
		var hasOverride = !string.IsNullOrEmpty(secretOverride);
		var zoneServices = serviceList.Where(s => s.isZone).Select(s => s.serviceId).ToList();
		var realmServices = serviceList.Where(s => !s.isZone).Select(s => s.serviceId).ToList();

		ThrowIfOverrideSpansScopes(hasOverride, realmServices, zoneServices);

		if (hasOverride && realmServices.Count > 0 && secretOverride != realmSecret)
		{
			throw new CliException(
				$"The SECRET override is not valid for realm [{pid}]: the realm-scoped services " +
				$"[{string.Join(", ", realmServices)}] authenticate with that realm's secret. " +
				$"Remove the SECRET override or use the realm's secret.");
		}

		if (hasOverride && zoneServices.Count > 0 && secretOverride != zoneSecret)
		{
			throw new CliException(
				$"The SECRET override is not valid for zone [{zid}]: the zone-scoped services " +
				$"[{string.Join(", ", zoneServices)}] authenticate with the zone's secret, not a realm secret. " +
				$"Remove the SECRET override or use the zone's secret.");
		}

		var identities = new Dictionary<string, ServiceScopeIdentity>();
		foreach (var (serviceId, isZone) in serviceList)
		{
			identities[serviceId] = new ServiceScopeIdentity
			{
				ServiceId = serviceId,
				IsZone = isZone,
				Cid = cid,
				Pid = isZone ? zid : pid,
				Zid = isZone ? zid : null,
				Secret = hasOverride ? secretOverride : (isZone ? zoneSecret : null),
				Host = host
			};
		}

		return identities;
	}

	static void ThrowIfOverrideSpansScopes(bool hasOverride, List<string> realmServices, List<string> zoneServices)
	{
		if (!hasOverride || realmServices.Count == 0 || zoneServices.Count == 0)
		{
			return;
		}

		throw new CliException(
			"A SECRET override cannot be used when running realm-scoped and zone-scoped services together: a realm " +
			"secret only authenticates its realm and a zone secret only its zone. " +
			$"Realm services=[{string.Join(", ", realmServices)}] zone services=[{string.Join(", ", zoneServices)}]. " +
			"Remove the SECRET override, or run only the services of the scope the secret belongs to.");
	}

	static async Task<string> FetchRealmSecret(CommandArgs args, string cid, string pid)
	{
		if (string.IsNullOrEmpty(pid))
		{
			throw new CliException("Cannot verify the SECRET override for the realm-scoped services: no realm is selected.");
		}

		try
		{
			var realmsApi = args.DependencyProvider.GetService<IRealmsApi>();
			var res = await realmsApi.GetAdminCustomer();
			var project = res.customer.projects.FirstOrDefault(p => p.name == pid);
			if (project == null)
			{
				throw new CliException($"Cannot verify the SECRET override: realm [{pid}] was not found for customer [{cid}].");
			}

			return project.secret;
		}
		catch (RequesterException ex) when (ex.Status == 401 || ex.Status == 403)
		{
			throw new CliException(
				$"Cannot verify the SECRET override for realm [{pid}]: your account cannot read that realm's secret (status=[{ex.Status}]).");
		}
	}

	static async Task<string> FetchZoneSecret(CommandArgs args, string cid, string zid)
	{
		try
		{
			var zonesApi = args.DependencyProvider.GetService<IBeamZonesApi>();
			var zoneView = await zonesApi.GetZones(cid, zid);
			var zoneSecret = (zoneView?.secret != null && zoneView.secret.HasValue) ? zoneView.secret.Value : null;
			if (string.IsNullOrEmpty(zoneSecret))
			{
				throw new CliException(
					$"Resolved zone [{zid}], but the zone returned no secret. Your account may lack permission to read the zone secret.");
			}

			return zoneSecret;
		}
		catch (RequesterException ex) when (ex.Status == 401 || ex.Status == 403)
		{
			throw new CliException(
				$"Cannot read the secret of zone [{zid}]: your account lacks permission (status=[{ex.Status}]).");
		}
	}
}
