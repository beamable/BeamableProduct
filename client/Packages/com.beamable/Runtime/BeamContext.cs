		/// <summary>
		/// After a context has been Stopped with the <see cref="Stop"/> method, this method can restart the instance.
		/// <para>
		/// If the context hasn't been stopped, this method won't do anything meaningful.
		/// </para>
		/// </summary>
		/// <returns>The same context instance</returns>
		public BeamContext Start() => Instantiate(playerCode: PlayerCode);

		/// <summary>Stops this context and disposes its services.</summary>
		/// <remarks>Context coroutines and notification subscriptions are stopped. Do not use services retained
		/// from a stopped context. Calling <see cref="Start"/>, <see cref="Instantiate"/>, or <see cref="ForPlayer"/>
		/// for the same slot restarts the existing context; await readiness again afterward.
		/// This does not clear saved credentials; use <see cref="ClearPlayerAndStop"/> to clear them.</remarks>
		/// <returns>A promise that completes after service disposal, or immediately if already stopped.</returns>
		/// <seealso cref="ForPlayer"/>
		public async Promise Stop()
		{
		
			
			if (_isStopped) return;

			// when there are no running contexts, there can be no
			//  assigned content singleton proxy. When a new context
			//  gets started, this will be re-assigned to the new context's
			//  content api.
			if (ContentApi.Instance.GetResult() == Content)
			{
				ContentApi.Instance = new Promise<IContentApi>();
			}
			
			_isStopped = true;

			// clear all events...
			OnShutdown?.Invoke();

			OnReloadUser = null;
			OnShutdown = null;
			TimeOverrideChanged = null;
			OnUserLoggedIn = null;
			OnUserLoggingOut = null;

			await _serviceScope.Dispose();

			_contentService = null;
			_announcements = null;
			_playerStats = null;

			OnShutdownComplete?.Invoke();
			OnShutdownComplete = null;
		}


		/// <summary>
		/// Clear the authorization token for the <see cref="PlayerCode"/>, then internally calls <see cref="Stop"/>
		/// </summary>
		public async Promise ClearPlayerAndStop()
		{
