		private static SKU CreateSku(string name)
		{
			var productId = "com.beamable.tests." + name;
			return new SKU { name = name, productIds = new SKUProductIDs { itunes = productId, googleplay = productId } };
		}

		[UnityTest]
		public IEnumerator RepeatedInitializationSucceeds()
		{
			TriggerContextInit();
			yield return Context.OnReady.ToYielder();
			var purchaser = Context.Api.BeamableIAP.GetResult();
			Assert.AreEqual(PurchasingInitializationStatus.Success, purchaser.InitializationStatus);

			// Initializing again (e.g. ChangeAuthorizedPlayer) used to subscribe the store handlers again and fail with
			// "FetchProducts cannot be invoked if a fetch is already in progress".
			for (var i = 0; i < 2; i++)
			{
				Exception error = null;
				yield return purchaser.Initialize(Context.ServiceProvider).Recover(err =>
				{
					error = err;
					return PromiseBase.Unit;
				}).ToYielder();

				Assert.IsNull(error, error?.Message);
				Assert.AreEqual(PurchasingInitializationStatus.Success, purchaser.InitializationStatus);
			}
			LogAssert.NoUnexpectedReceived();
		}

		[UnityTest]
		public IEnumerator StartPurchaseWithUnknownSkuFailsBeforeBeginningPurchase()
		{
			TriggerContextInit();
			yield return Context.OnReady.ToYielder();
			var purchaser = Context.Api.BeamableIAP.GetResult();

			// The second attempt checks that the failed purchase didn't leave callbacks behind,
			// which would reject it as ExistingPurchasePending.
			for (var i = 0; i < 2; i++)
			{
				LogAssert.Expect(LogType.Error, new Regex("begin purchase request"));
				Exception error = null;
				yield return purchaser.StartPurchase("listings.test", "unknown_sku").Recover(err =>
				{
					error = err;
					return null;
				}).ToYielder();

				Assert.IsInstanceOf<ErrorCode>(error);
				StringAssert.Contains("ProductUnavailable", ((ErrorCode)error).Error);
			}
			Assert.AreEqual(0, _beginPurchaseRoute.CallCount);
		}

		[UnityTest]
		public IEnumerator InitializingAgainSettlesThePurchaseInFlight()
		{
			TriggerContextInit();
			yield return Context.OnReady.ToYielder();
			var purchaser = Context.Api.BeamableIAP.GetResult();

			// The begin-purchase request never returns, so the purchase stays in flight.
			_beginPurchaseRoute.WithPendingResponse(new Promise<PurchaseResponse>());
			Exception error = null;
			var stuck = purchaser.StartPurchase("listings.test", "sku_a").Recover(err =>
			{
				error = err;
				return null;
			});

			yield return purchaser.Initialize(Context.ServiceProvider).Recover(_ => PromiseBase.Unit).ToYielder();
			yield return stuck.ToYielder();

			Assert.IsInstanceOf<ErrorCode>(error);
			Assert.AreEqual(409, ((ErrorCode)error).Code);
			// A new purchase starts instead of being rejected as ExistingPurchasePending. It stays in flight until the
			// context is disposed, which fails it, so it needs an error handler.
			var next = purchaser.StartPurchase("listings.test", "sku_a");
			next.Error(_ => { });
			Assert.IsFalse(next.IsCompleted);
		}

		[UnityTest]
		public IEnumerator RetiredPurchaseDoesNotReachTheStore()
		{
			TriggerContextInit();
			yield return Context.OnReady.ToYielder();
			var purchaser = Context.Api.BeamableIAP.GetResult();

			// The first purchase's begin request is still pending when purchasing is initialized again.
			var firstBegin = new Promise<PurchaseResponse>();
			_beginPurchaseRoute.WithPendingResponse(firstBegin);
			Exception firstError = null;
			var first = purchaser.StartPurchase("listings.test", "sku_a").Recover(err =>
			{
				firstError = err;
				return null;
			});
			yield return purchaser.Initialize(Context.ServiceProvider).Recover(_ => PromiseBase.Unit).ToYielder();
			yield return first.ToYielder();
			Assert.AreEqual(409, ((ErrorCode)firstError).Code);

			// A second purchase starts, and its begin request stays pending. Disposal fails it, so it needs an error handler.
			_beginPurchaseRoute.WithPendingResponse(new Promise<PurchaseResponse>());
			var second = purchaser.StartPurchase("listings.test", "sku_a");
			second.Error(_ => { });

			// The first begin request returns after the purchaser moved on.
			firstBegin.CompleteSuccess(new PurchaseResponse { txid = 7 });
			for (var i = 0; i < 5; i++) yield return null;

			Assert.AreEqual(1, _failRetiredPurchaseRoute.CallCount, "The retired purchase's transaction is closed.");
			Assert.AreEqual(0, _completePurchaseRoute.CallCount, "The store didn't buy the retired purchase.");
			Assert.IsFalse(second.IsCompleted);
		}
