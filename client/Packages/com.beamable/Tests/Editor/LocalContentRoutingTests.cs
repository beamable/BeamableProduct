using System;
using System.Collections.Generic;
using System.Reflection;
using System.Runtime.Serialization;
using Beamable.Api.Autogenerated.Models;
using ClientContentInfo = Beamable.Common.Content.ClientContentInfo;
using Beamable.Common;
using Beamable.Common.Api;
using Beamable.Common.Content;
using Beamable.Content;
using Beamable.Platform.Tests.Connectivity;
using NUnit.Framework;
using UnityEngine;
using RuntimeContentService = global::Beamable.Content.ContentService;

namespace Beamable.Editor.Tests
{
	// These are bounded routing tests: bypass constructor startup, coroutines and authentication.
	// Remote item/offline-cache dependencies deliberately remain null so accidental use fails.
	public class LocalContentRoutingTests
	{
		private LocalSource _local;
		private RuntimeContentService _service;
		private ManifestSubscription _subscription;
		private ChecksumSentinel _checksum;
		private ResolverSentinel _resolver;
		private LocalSourceRegressionContent _content;
		private IDisposable _testScope;

		[SetUp]
		public void SetUp()
		{
#pragma warning disable 618
			_testScope = RuntimeContentService.AllowInTests();
#pragma warning restore 618
			_content = ScriptableObject.CreateInstance<LocalSourceRegressionContent>();
			_local = new LocalSource { Content = _content };
			_checksum = new ChecksumSentinel();
			_resolver = new ResolverSentinel();
			_subscription = Subscription("global");
			_service = (RuntimeContentService)FormatterServices.GetUninitializedObject(typeof(RuntimeContentService));
			Set(_service, "_localContentSource", _local);
			Set(_service, "<CurrentDefaultManifestID>k__BackingField", "global");
			Set(_service, "<Subscribables>k__BackingField", new Dictionary<string, ManifestSubscription>
			{
				["global"] = _subscription,
				["other"] = Subscription("other")
			});
			Set(_service, "_connectivityService", new MockConnectivityService());
			Set(_service, "bakedManifest", RemoteManifest());
		}

		[TearDown]
		public void TearDown()
		{
			_testScope.Dispose();
			_content.CancelPendingEditorChangeNotification();
			UnityEngine.Object.DestroyImmediate(_content);
		}

		[TestCase(true)]
		[TestCase(false)]
		public void LocalItemsBypassRemoteManifestAndItemCacheOnlineAndOffline(bool online)
		{
			SetConnectivity(online);
			Assert.That(_service.GetContent("local.item", typeof(ContentObject)).GetResult(), Is.SameAs(_content));
			Assert.That(_local.LastNamespace, Is.EqualTo("global"));
			Assert.That(_local.LastContentId, Is.EqualTo("local.item"));
			Assert.That(_local.LastType, Is.EqualTo(typeof(ContentObject)));
			Assert.That(_local.ManifestCalls, Is.Zero);
		}

		[TestCase(0)]
		[TestCase(1)]
		[TestCase(2)]
		[TestCase(3)]
		public void EveryManifestOverloadBypassesOfflineAndBakedFallback(int overload)
		{
			SetConnectivity(false);
			Promise<ClientManifest> result;
			var query = ContentQuery.Parse("tag:draft");
			switch (overload)
			{
				case 0: result = _service.GetManifestWithID(); break;
				case 1: result = _service.GetManifest(query); break;
				case 2: result = _service.GetManifest("tag:draft", "global"); break;
				default: result = _service.GetManifest(query, "global"); break;
			}
			Assert.That(result.GetResult().entries[0].contentId, Is.EqualTo("local.item"));
			Assert.That(_local.ManifestCalls, Is.EqualTo(1));
			if (overload != 0) Assert.That(_local.LastQuery, Is.Not.Null, "Filter before copying local metadata.");
		}

		[Test]
		public void TypedContentReferenceUsesLocalItemResolution()
		{
			var reference = new ContentRef<LocalSourceRegressionContent>("localSourceRegression.unpublished");
			Assert.That(_service.GetContent<LocalSourceRegressionContent>(reference).GetResult(), Is.SameAs(_content));
			Assert.That(_local.LastContentId, Is.EqualTo(reference.Id));
			Assert.That(_local.LastType, Is.EqualTo(typeof(LocalSourceRegressionContent)));
			Assert.That(_local.ManifestCalls, Is.Zero);
		}

		[Test]
		public void GetCurrentUsesLocalSourceWithoutSubscriptionInitialization()
		{
			SetConnectivity(false);
			Assert.That(_service.GetCurrent().GetResult(), Is.SameAs(_local.Manifest));
			Assert.That(_local.ManifestCalls, Is.EqualTo(1));
		}

		[Test]
		public void SubscriptionRefreshBypassesChecksumAndRemoteResolver()
		{
			Assert.That(Execute(_subscription).GetResult(), Is.SameAs(_local.Manifest));
			Assert.That(_checksum.Calls, Is.Zero);
			Assert.That(_resolver.Calls, Is.Zero);
		}

		[TestCase(false)]
		[TestCase(true)]
		public void DisabledOrDifferentNamespaceKeepsExistingRemoteManifestPath(bool differentNamespace)
		{
			_local.Enabled = differentNamespace;
			var manifestId = differentNamespace ? "other" : "global";
			Assert.That(_service.GetManifestWithID(manifestId).GetResult().entries[0].contentId, Is.EqualTo("remote.item"));
			Assert.That(_local.ManifestCalls, Is.Zero);
			var subscription = differentNamespace ? Subscription("other") : _subscription;
			Assert.That(ObserveFailure(Execute(subscription)), Is.SameAs(SentinelError));
#if BEAMABLE_OPTOUT_MANIFEST_FILE_CACHING
			Assert.That(_resolver.Calls, Is.EqualTo(1));
#else
			Assert.That(_checksum.Calls, Is.EqualTo(1));
#endif
		}

		[Test]
		public void LocalFailuresPropagateWithoutRemoteFallbackOrPendingManifestPromise()
		{
			var error = new InvalidOperationException("local JSON is invalid");
			_local.Error = error;
			Assert.That(ObserveFailure(_service.GetManifestWithID()), Is.SameAs(error));
			Assert.That(ObserveFailure(_service.GetManifest("tag:draft")), Is.SameAs(error));
			Assert.That(ObserveFailure(_service.GetContent("local.item", typeof(ContentObject))), Is.SameAs(error));
			Assert.That(ObserveFailure(Execute(_subscription)), Is.SameAs(error));
			Assert.That(_checksum.Calls, Is.Zero);
			Assert.That(_resolver.Calls, Is.Zero);
		}

		private ManifestSubscription Subscription(string manifestId)
		{
			var subscription = (ManifestSubscription)FormatterServices.GetUninitializedObject(typeof(ManifestSubscription));
			Set(subscription, "<ManifestID>k__BackingField", manifestId);
			Set(subscription, "_localContentSource", _local);
			Set(subscription, "_contentApi", _checksum);
			Set(subscription, "_manifestResolver", _resolver);
			Set(subscription, "_latestManifiest", RemoteManifest());
			Set(subscription, "_manifestPromise", Promise<Unit>.Successful(new Unit()));
			return subscription;
		}

		private void SetConnectivity(bool online)
		{
			var connectivity = new MockConnectivityService();
			connectivity.SetHasInternet(online);
			Set(_service, "_connectivityService", connectivity);
		}

		private static Promise<ClientManifest> Execute(ManifestSubscription subscription) =>
			(Promise<ClientManifest>)typeof(ManifestSubscription).GetMethod("ExecuteRequest", BindingFlags.Instance | BindingFlags.NonPublic)
				.Invoke(subscription, new object[] { null, "/remote-manifest" });

		private static void Set(object instance, string name, object value) =>
			instance.GetType().GetField(name, BindingFlags.Instance | BindingFlags.NonPublic).SetValue(instance, value);

		private static Exception ObserveFailure<T>(Promise<T> promise)
		{
			Exception failure = null;
			promise.Error(error => failure = error);
			Assert.That(failure, Is.Not.Null, "Expected a settled error.");
			return failure;
		}

		private static ClientManifest RemoteManifest() => new ClientManifest
		{
			entries = new List<ClientContentInfo> { new ClientContentInfo { contentId = "remote.item" } }
		};

		private static readonly Exception SentinelError = new InvalidOperationException("Remote path sentinel");

		private class ChecksumSentinel : global::Beamable.Api.Autogenerated.Content.ContentApi
		{
			public int Calls;
			public ChecksumSentinel() : base(null) { }
			public override Promise<ContentBasicManifestChecksum> GetManifestChecksum(Optional<string> id, Optional<bool> omitTags,
				Optional<string> uid, bool includeAuthHeader)
			{
				Calls++;
				return Promise<ContentBasicManifestChecksum>.Failed(SentinelError);
			}
		}

		private class ResolverSentinel : IManifestResolver
		{
			public int Calls;
			public Promise<ClientManifest> ResolveManifest(IBeamableRequester requester, string url, ManifestSubscription subscription)
			{
				Calls++;
				return Promise<ClientManifest>.Failed(SentinelError);
			}
		}

		private class LocalSource : ILocalContentSource
		{
			public bool Enabled = true;
			public int ManifestCalls;
			public ContentQuery LastQuery;
			public string LastNamespace;
			public string LastContentId;
			public Type LastType;
			public IContentObject Content;
			public Exception Error;
			public readonly ClientManifest Manifest = new ClientManifest
			{
				entries = new List<ClientContentInfo>
				{
					new ClientContentInfo { contentId = "local.item", tags = new[] { "draft" } }
				}
			};
			public bool HandlesManifest(string manifestId) => Enabled && manifestId == "global";
			public Promise<ClientManifest> GetManifest(string manifestId, ContentQuery query = null)
			{
				ManifestCalls++;
				LastQuery = query;
				LastNamespace = manifestId;
				return Error == null ? Promise<ClientManifest>.Successful(query == null ? Manifest : Manifest.Filter(query)) : Promise<ClientManifest>.Failed(Error);
			}
			public Promise<IContentObject> GetContent(string contentId, Type contentType, string manifestId)
			{
				LastNamespace = manifestId;
				LastContentId = contentId;
				LastType = contentType;
				return Error == null ? Promise<IContentObject>.Successful(Content) : Promise<IContentObject>.Failed(Error);
			}
		}
	}
}
