	/// <summary>
	/// Local content mode as a game sees it: a real <see cref="BeamContext"/> and content service,
	/// with the realm replaced by a sentinel that records which namespaces asked it for a manifest.
	/// </summary>
	public class LocalContentRoutingTests : BeamContextTest
	{
		private LocalWorkingCopy _copy;
		private RealmSentinel _realm;
		private MockConnectivityService _connectivity;
		private ContentConfiguration _config;

		[SetUp]
		public void SetUpWorkingCopy()
		{
			_copy = new LocalWorkingCopy();
			_realm = new RealmSentinel();
			_connectivity = new MockConnectivityService();
			// A transient configuration, so the tests never read or change the project's settings.
			_config = ScriptableObject.CreateInstance<ContentConfiguration>();
			_config.EditorManifestID = LocalWorkingCopy.Namespace;
		}

		[TearDown]
		public void TearDownWorkingCopy()
		{
			Beam.RuntimeConfigProvider.Pid = null;
			_copy.Dispose();
			UnityEngine.Object.DestroyImmediate(_config);
		}

		[UnityTest]
		public IEnumerator EnabledModeResolvesLocalItemWithoutAskingTheRealm([Values(true, false)] bool online)
		{
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17));
			yield return StartContext(_copy.Source(), online);

			var request = Context.Content.GetContent(LocalWorkingCopy.ItemId, typeof(LocalSourceRegressionContent), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(request);

			Assert.That(((LocalSourceRegressionContent)request.GetResult()).amount, Is.EqualTo(17));
			Assert.That(_realm.RequestedNamespaces, Does.Not.Contain(LocalWorkingCopy.Namespace));
		}

		[UnityTest]
		public IEnumerator EnabledModeAnswersTagQueriesFromLocalItems()
		{
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17, "draft"));
			_copy.Write("localSourceRegression.other", LocalWorkingCopy.Json(4, "other"));
			yield return StartContext(_copy.Source());

			var request = Context.Content.GetManifest("tag:draft", LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(request);

			Assert.That(request.GetResult().entries.Select(e => e.contentId), Is.EqualTo(new[] { LocalWorkingCopy.ItemId }));
			Assert.That(_realm.RequestedNamespaces, Does.Not.Contain(LocalWorkingCopy.Namespace));
		}

		[UnityTest]
		public IEnumerator EnabledModeReportsMissingLocalItemWithoutRealmFallback()
		{
			yield return StartContext(_copy.Source());

			var request = Context.Content.GetContent(LocalWorkingCopy.ItemId, typeof(LocalSourceRegressionContent), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(request, expectError: true);

			Assert.That(LocalWorkingCopy.Failure(request), Is.InstanceOf<ContentNotFoundException>());
			Assert.That(_realm.RequestedNamespaces, Does.Not.Contain(LocalWorkingCopy.Namespace));
		}

		[UnityTest]
		public IEnumerator DisabledModeAsksTheRealm()
		{
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17));
			yield return StartContext(new DisabledLocalContentSource());

			_ = Context.Content.GetManifestWithID(LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.WaitUntil(() => _realm.RequestedNamespaces.Contains(LocalWorkingCopy.Namespace));

			Assert.That(_realm.RequestedNamespaces, Does.Contain(LocalWorkingCopy.Namespace));
		}

		[UnityTest]
		public IEnumerator EnabledModeAsksTheRealmForOtherNamespaces()
		{
			yield return StartContext(_copy.Source());

			_ = Context.Content.GetManifestWithID("other");
			yield return LocalWorkingCopy.WaitUntil(() => _realm.RequestedNamespaces.Contains("other"));

			Assert.That(_realm.RequestedNamespaces, Does.Contain("other"));
		}

		[UnityTest]
		public IEnumerator LocalContentFollowsTheRealmTheContextStartedOn()
		{
			const string switchedPid = "DE_222";
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17));
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(42), switchedPid);
			// Beam.SwitchToPid sets this override, then restarts every context.
			Beam.RuntimeConfigProvider.Pid = switchedPid;
			yield return StartContext(ForContext);

			var request = Context.Content.GetContent(LocalWorkingCopy.ItemId, typeof(LocalSourceRegressionContent), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(request);

			Assert.That(((LocalSourceRegressionContent)request.GetResult()).amount, Is.EqualTo(42));
		}

		[UnityTest]
		public IEnumerator RealmChangeWithoutRestartKeepsServingTheSameObjects()
		{
			const string switchedPid = "DE_333";
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17));
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(42), switchedPid);
			yield return StartContext(ForContext);
			var first = Context.Content.GetContent(LocalWorkingCopy.ItemId, typeof(LocalSourceRegressionContent), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(first);

			// An editor realm switch during Play Mode changes the fallback PID but does not restart contexts.
			((TestConfigProvider)Beam.RuntimeConfigProvider.Fallback).Pid = switchedPid;
			var second = Context.Content.GetContent(LocalWorkingCopy.ItemId, typeof(LocalSourceRegressionContent), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(second);

			var content = (LocalSourceRegressionContent)second.GetResult();
			Assert.That(content, Is.SameAs(first.GetResult()));
			Assert.That(content == null, Is.False, "Objects already handed to the game must stay alive.");
			Assert.That(content.amount, Is.EqualTo(17));
		}

		private EditorLocalContentSource ForContext() =>
			_copy.Track(EditorLocalContentSource.ForContext(_config, Promise<string>.Successful(_copy.Workspace)));

		private IEnumerator StartContext(ILocalContentSource local, bool online = true) => StartContext(() => local, online);

		private IEnumerator StartContext(Func<ILocalContentSource> local, bool online = true)
		{
			_connectivity.SetHasInternet(online);
			TriggerContextInit(builder =>
			{
				OnRegister(builder);
				// BeamContextTest substitutes a mock content service; these tests need the real one.
				builder.RemoveIfExists<IContentApi>();
				builder.AddSingleton<IContentApi>(provider => provider.GetService<RuntimeContentService>());
				builder.RemoveIfExists<ContentParameterProvider>();
				builder.AddSingleton(new ContentParameterProvider { manifestID = LocalWorkingCopy.Namespace });
				builder.RemoveIfExists<IContentBasicApi>();
				builder.AddSingleton<IContentBasicApi>(_realm);
				builder.RemoveIfExists<IConnectivityService>();
				builder.AddSingleton<IConnectivityService>(_connectivity);
				builder.RemoveIfExists<ILocalContentSource>();
				// A factory, so the source is created while the context is built, as in production.
				builder.AddSingleton<ILocalContentSource>(_ => local());
			});
			yield return Context.OnReady.ToYielder();
		}

		private class RealmSentinel : Beamable.Api.Autogenerated.Content.ContentApi
		{
			public readonly List<string> RequestedNamespaces = new List<string>();

			public RealmSentinel() : base(null) { }

			public override Promise<ContentBasicManifestChecksum> GetManifestChecksum(Optional<string> id, Optional<bool> omitTags,
				Optional<string> uid, bool includeAuthHeader)
			{
				RequestedNamespaces.Add(id.HasValue ? id.Value : LocalWorkingCopy.Namespace);
				return new Promise<ContentBasicManifestChecksum>();
			}
		}
	}

	/// <summary>
	/// The editor's local content source over a temporary CLI working copy, through its public API only.
	/// </summary>
	public class LocalContentSourceTests
	{
		private LocalWorkingCopy _copy;
		private readonly List<ContentObject> _callbackObjects = new List<ContentObject>();

		[SetUp]
		public void SetUp() => _copy = new LocalWorkingCopy();

		[TearDown]
		public void TearDown()
		{
			LocalReentrantRegressionContent.AfterDeserialize = null;
			_copy.Dispose();
			foreach (var content in _callbackObjects)
				if (content != null) UnityEngine.Object.DestroyImmediate(content);
			_callbackObjects.Clear();
		}

		[UnityTest]
		public IEnumerator UnpublishedItemResolvesFromTheCliWorkingCopy()
		{
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17, "draft"));
			// A same-named file outside local/content must be ignored.
			_copy.WriteOutsideWorkingCopy(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(99));
			var source = _copy.Source();

			var manifest = source.GetManifest(LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(manifest);
			var item = source.GetContent(LocalWorkingCopy.ItemId, typeof(ContentObject), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(item);

			var entry = manifest.GetResult().entries.Single();
			var content = (LocalSourceRegressionContent)item.GetResult();
			Assert.That(entry.contentId, Is.EqualTo(LocalWorkingCopy.ItemId));
			Assert.That(entry.tags, Is.EqualTo(new[] { "draft" }));
			Assert.That(content.amount, Is.EqualTo(17));
			Assert.That(content.Id, Is.EqualTo(LocalWorkingCopy.ItemId));
			Assert.That(content.ManifestID, Is.EqualTo(LocalWorkingCopy.Namespace));
			Assert.That(content.Tags, Is.EqualTo(new[] { "draft" }));
			Assert.That(content.Version, Is.EqualTo(entry.version));
		}

		[UnityTest]
		public IEnumerator RequestingAnIncompatibleTypeFails()
		{
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17));
			var request = _copy.Source().GetContent(LocalWorkingCopy.ItemId, typeof(LocalReentrantRegressionContent), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(request, expectError: true);
			Assert.That(LocalWorkingCopy.Failure(request), Is.InstanceOf<InvalidOperationException>());
		}

		[UnityTest]
		public IEnumerator EditsAfterTheFirstReadAppearOnlyInANewSource()
		{
			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17));
			var source = _copy.Source();
			yield return LocalWorkingCopy.Await(source.GetManifest(LocalWorkingCopy.Namespace));

			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(99));
			var original = source.GetContent(LocalWorkingCopy.ItemId, typeof(ContentObject), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(original);
			var fresh = _copy.Source().GetContent(LocalWorkingCopy.ItemId, typeof(ContentObject), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(fresh);

			Assert.That(((LocalSourceRegressionContent)original.GetResult()).amount, Is.EqualTo(17));
			Assert.That(((LocalSourceRegressionContent)fresh.GetResult()).amount, Is.EqualTo(99));
		}

		[UnityTest]
		public IEnumerator ChangingARuntimeObjectDoesNotWriteTheWorkingCopy()
		{
			var path = _copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17));
			var before = File.ReadAllBytes(path);
			var request = _copy.Source().GetContent(LocalWorkingCopy.ItemId, typeof(ContentObject), LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(request);

			var content = (LocalSourceRegressionContent)request.GetResult();
			content.amount = 90;
			content.Tags = new[] { "runtime-only" };

			Assert.That(File.ReadAllBytes(path), Is.EqualTo(before));
			Assert.That(Directory.GetFiles(Path.GetDirectoryName(path)), Has.Length.EqualTo(1));
		}

		private static readonly string[] MalformedFiles = { "[]", "{\"properties\":{},\"tags\":[12]}" };

		[UnityTest]
		public IEnumerator MalformedFileFailsWithItsPathAndRecoversOnceFixed([ValueSource(nameof(MalformedFiles))] string malformed)
		{
			_copy.Write("localSourceRegression.valid", LocalWorkingCopy.Json(1));
			var path = _copy.Write(LocalWorkingCopy.ItemId, malformed);
			var source = _copy.Source();

			var failed = source.GetManifest(LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(failed, expectError: true);
			Assert.That(LocalWorkingCopy.Failure(failed).Message, Does.Contain(path));

			_copy.Write(LocalWorkingCopy.ItemId, LocalWorkingCopy.Json(17));
			var retry = source.GetManifest(LocalWorkingCopy.Namespace);
			yield return LocalWorkingCopy.Await(retry);
			Assert.That(retry.GetResult().entries, Has.Count.EqualTo(2));
		}

		[UnityTest]
		public IEnumerator MissingDirectoryFailsWithoutCreatingIt()
		{
