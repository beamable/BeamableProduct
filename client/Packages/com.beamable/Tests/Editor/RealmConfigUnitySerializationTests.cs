using System.Collections.Generic;
using System.Text;
using Beamable.Api.Autogenerated.Models;
using Beamable.Common.Api.Realms;
using Beamable.Serialization.SmallerJSON;
using NUnit.Framework;
using UnityEngine;

namespace Beamable.Editor.Tests
{
	// PlatformRequester uses JsonUtility for these request bodies and default response decoding.
	// These tests record existing data loss; a decoder fix must update their expectations.
	[Category("SerializationCharacterization")]
	public class RealmConfigUnitySerializationTests
	{
		[TestCase("null")]
		[TestCase("empty")]
		[TestCase("populated")]
		public void RequestEncodingCurrentlyOmitsConfigDictionary(string state)
		{
			var config = Config(state);
			var request = new GetRealmConfigDTO { config = config };
			var json = JsonUtility.ToJson(request);
			var payload = (ArrayDict)Json.Deserialize(json);
			Assert.That(payload.ContainsKey("config"), Is.False);
			Assert.That(payload.Count, Is.Zero);
			Assert.That(JsonUtility.FromJson<GetRealmConfigDTO>(json).config, Is.Null);
			Assert.That(request.config, Is.SameAs(config));
			if (state == "populated") Assert.That(config["namespace.key"], Is.EqualTo("value"));
		}

		[TestCase("{}")]
		[TestCase("{\"config\":null}")]
		[TestCase("{\"config\":{}}")]
		[TestCase("{\"config\":{\"namespace.key\":\"value\",\"empty\":\"\",\"escaped\":\"quote\\\" and newline\\n\"}}")]
		public void ResponseDecodingCurrentlyDropsConfigDictionary(string json)
		{
			var response = JsonUtility.FromJson<GetRealmConfigDTO>(json);
			Assert.That(response, Is.Not.Null);
			Assert.That(response.config, Is.Null);
		}

		[TestCase("null")]
		[TestCase("empty")]
		[TestCase("populated")]
		public void ViewNamespaceSurvivesWhileDictionaryIsOmitted(string state)
		{
			var view = new RealmConfigView { Namespace = "test.namespace", Config = Config(state) };
			var outgoing = (ArrayDict)Json.Deserialize(JsonUtility.ToJson(view));
			Assert.That(outgoing["Namespace"], Is.EqualTo("test.namespace"));
			Assert.That(outgoing.ContainsKey("Config"), Is.False);

			// SmallerJSON constructs an incoming payload that still contains the dictionary.
			var incoming = Json.Serialize(view, new StringBuilder());
			Assert.That(((ArrayDict)Json.Deserialize(incoming)).ContainsKey("Config"), Is.True);
			var restored = JsonUtility.FromJson<RealmConfigView>(incoming);
			Assert.That(restored.Namespace, Is.EqualTo(view.Namespace));
			Assert.That(restored.Config, Is.Null);
		}

		[TestCase("ok")]
		[TestCase("error")]
		public void UpdateResponseScalarStillDecodes(string result)
		{
			var response = JsonUtility.FromJson<CommonResponse>("{\"result\":\"" + result + "\"}");
			Assert.That(response.result, Is.EqualTo(result));
		}

		private static Dictionary<string, string> Config(string state)
		{
			if (state == "null") return null;
			if (state == "empty") return new Dictionary<string, string>();
			return new Dictionary<string, string>
			{
				["namespace.key"] = "value", ["empty"] = "", ["escaped"] = "quote\" and newline\n"
			};
		}
	}
}
